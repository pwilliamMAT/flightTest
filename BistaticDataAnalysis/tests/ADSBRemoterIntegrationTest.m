classdef ADSBRemoterIntegrationTest < matlab.unittest.TestCase
    %ADSBREMOTERINTEGRATIONTEST Offline adapter and opportunity-table parity.

    properties (SetAccess = private)
        ProjectRoot
    end

    methods (TestClassSetup)
        function addAnalysisPath(testCase)
            analysis_folder = fileparts(fileparts(mfilename('fullpath')));
            testCase.ProjectRoot = string(fileparts(analysis_folder));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                analysis_folder));
        end
    end

    methods (Test)
        function testAdapterMatchesCanonicalLoader(testCase)
            fixture_path = fullfile(testCase.ProjectRoot, ...
                "external", "ADSB-remoter", "tests", "fixtures", ...
                "basestation_sample.csv");

            expected_tracks = loadADSBTruth(fixture_path, 'Verbose', false);
            [actual_tracks, import_info] = loadADSBRemoterArchive( ...
                fixture_path, 'Verbose', false);

            testCase.verifyEqual(actual_tracks, expected_tracks);
            testCase.verifyEqual(import_info.parser, "loadADSBTruth");
            testCase.verifyEqual(import_info.source_file_count, 1);
        end

        function testAdapterNormalizesCombinedDatetimeGzip(testCase)
            fixture_path = fullfile(testCase.ProjectRoot, ...
                "external", "ADSB-remoter", "tests", "fixtures", ...
                "sbs_clean", "15_adsb_20220413_060850.csv.gz");

            [actual_tracks, import_info] = loadADSBRemoterArchive( ...
                fixture_path, 'Verbose', false);

            testCase.verifyNotEmpty(actual_tracks);
            testCase.verifyGreaterThan( ...
                import_info.normalized_timestamp_line_count, 0);
            testCase.verifyGreaterThan(import_info.position_fix_count, 0);
            testCase.verifyEqual(import_info.track_count, numel(actual_tracks));

            aircraft_ids = string({actual_tracks.hex});
            track_index = find(aircraft_ids == "C01DDE", 1);
            testCase.assertNotEmpty(track_index);
            imported_track = actual_tracks(track_index);
            expected_time = posixtime(datetime( ...
                2025, 5, 1, 7, 55, 23.778, 'TimeZone', 'UTC'));
            fix_index = find(abs(imported_track.t_utc - expected_time) < ...
                1e-3, 1);
            testCase.assertNotEmpty(fix_index);
            testCase.verifyEqual( ...
                imported_track.lat_deg(fix_index), 41.65481, ...
                AbsTol=1e-10);
            testCase.verifyEqual( ...
                imported_track.lon_deg(fix_index), -73.82331, ...
                AbsTol=1e-10);
            testCase.verifyEqual( ...
                imported_track.alt_m(fix_index), 40000 * 0.3048, ...
                AbsTol=1e-9);
        end

