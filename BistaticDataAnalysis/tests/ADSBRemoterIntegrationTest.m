        function testOpportunityGeometryAndDopplerMatchProjectHelper(testCase)
            config = helperADSBRemoter599MHzConfig();
            t0 = posixtime(datetime( ...
                2026, 8, 12, 12, 0, 0, 'TimeZone', 'UTC'));
            track = localTrack( ...
                'ABC123', 'TEST123', t0 + [0; 2; 4], ...
                [42.370; 42.350; 42.330], ...
                [-71.310; -71.300; -71.290], ...
                [3200; 3200; 3200]);

            direct = adsbToBistatic( ...
                track, config.TxLLA, config.RxLLA, ...
                config.CenterFrequency_Hz);
            opportunities = buildManualADSBOpportunityTable(track, config);
            geometry = helperDeriveTxRxGeometry( ...
                config.TxLLA, config.RxLLA);
            [east_m, north_m, up_m] = geodetic2enu( ...
                direct.lat_deg, direct.lon_deg, direct.alt_m, ...
                config.RxLLA(1), config.RxLLA(2), config.RxLLA(3), ...
                geometry.spheroid);
            receiver_range_m = sqrt(east_m.^2 + north_m.^2 + up_m.^2);
            [expected_cpa_m, cpa_idx] = min(receiver_range_m);
            expected_cpa_utc = datetime( ...
                direct.t_utc(cpa_idx), ...
                'ConvertFrom', 'posixtime', 'TimeZone', 'UTC');

            testCase.verifyEqual( ...
                opportunities.CPADistance_m, expected_cpa_m, AbsTol=1e-9);
            testCase.verifyEqual( ...
                opportunities.CPATimeUTC, expected_cpa_utc);
            testCase.verifyEqual( ...
                opportunities.ExcessRange_m, ...
                direct.R_excess_m(cpa_idx), AbsTol=1e-9);
            testCase.verifyEqual( ...
                opportunities.Doppler_Hz, ...
                direct.f_D_hz(cpa_idx), AbsTol=1e-12);
            testCase.verifyEqual( ...
                opportunities.TransmitterRange_m, ...
                direct.R_excess_m(cpa_idx) + direct.L_m - expected_cpa_m, ...
                AbsTol=1e-9);
        end

        function testBiSNRAndRankMatchPinnedEquation(testCase)
            config = helperADSBRemoter599MHzConfig();
            t0 = posixtime(datetime( ...
                2026, 8, 12, 12, 0, 0, 'TimeZone', 'UTC'));
            near_lla = [42.36, -71.28, 3000];
            far_lla = [43.00, -72.00, 3000];
            tracks = [ ...
                localSingleFixTrack('ZZZ999', 'TIEZ', t0, near_lla), ...
                localSingleFixTrack('AAA111', 'TIEA', t0, near_lla), ...
                localSingleFixTrack('FFF222', 'FAR', t0, far_lla)];

            opportunities = buildManualADSBOpportunityTable(tracks, config);
            expected_bisnr_db = localPinnedBiSNR( ...
                opportunities.TransmitterRange_m, ...
                opportunities.CPADistance_m, config);

            testCase.verifyEqual( ...
                opportunities.BiSNR_dB, expected_bisnr_db, AbsTol=1e-10);
            testCase.verifyLessThanOrEqual( ...
                diff(opportunities.BiSNR_dB), zeros(2, 1));
            testCase.verifyEqual( ...
                opportunities.AircraftID, ["AAA111"; "ZZZ999"; "FFF222"]);
            testCase.verifyEqual(opportunities.BiSNRRank, (1:3).');
            testCase.verifyTrue(all(opportunities.BiSNRAssumptionBased));
            testCase.verifyEqual(opportunities.SourceID, ...
                repmat(config.SourceID, 3, 1));
            testCase.verifyEqual(opportunities.AssumptionID, ...
                repmat(config.AssumptionID, 3, 1));
        end
    end
end

function track = localTrack(hex_id, callsign, times, latitudes, longitudes, altitudes)
track = struct( ...
    'hex', hex_id, ...
    'callsign', callsign, ...
    't_utc', times(:), ...
    'lat_deg', latitudes(:), ...
    'lon_deg', longitudes(:), ...
    'alt_m', altitudes(:), ...
    'speed_mps', NaN(numel(times), 1), ...
    'track_deg', NaN(numel(times), 1), ...
    'vrate_mps', NaN(numel(times), 1));
end

function track = localSingleFixTrack(hex_id, callsign, time, lla)
track = localTrack( ...
    hex_id, callsign, time, lla(1), lla(2), lla(3));
end

function snr_db = localPinnedBiSNR(tx_range_m, rx_range_m, config)
c = physconst('LightSpeed');
k = 1.380649e-23;
wavelength_m = c ./ config.CenterFrequency_Hz;

snr_db = ...
    10 .* log10(config.EmitterEIRP_kW .* 1000) + ...
    config.ReceiverGain_dBi + ...
    20 .* log10(wavelength_m) + ...
    config.BistaticRCS_dBsm - ...
    30 .* log10(4 .* pi) - ...
    20 .* log10(tx_range_m) - ...
    20 .* log10(rx_range_m) - ...
    10 .* log10(k .* config.NoiseTemperature_K .* ...
        config.ReceiverBandwidth_Hz) - ...
    config.NoiseFigure_dB - ...
    config.PolarizationLoss_dB - ...
    config.SystemLoss_dB;
end
