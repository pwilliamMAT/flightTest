function cause_table = localBuildCrashCauseTable(visualization)
geographic_enabled = visualization.plot_ellipse_globe || ...
    visualization.plot_tracker_globe;
graphics_pressure_enabled = geographic_enabled || ...
    visualization.max_expected_open_figure_count >= 6;

cause_table = table( ...
    [1; 2; 3; 4], ...
    [ ...
        "geoglobe / uifigure / WebGL rendering"; ...
        "Per-part RDM figure fan-out"; ...
        "Combined graphics memory and GPU pressure"; ...
        "Figure export / file-save path"], ...
    [ ...
        "high"; ...
        "medium"; ...
        "medium"; ...
        "low"], ...
    [ ...
        geographic_enabled && ~visualization.force_2d_geographic_fallback; ...
        visualization.plot_per_part_rdm; ...
        graphics_pressure_enabled; ...
        false], ...
    [ ...
        "Highest-risk path when 3-D globe rendering is enabled."; ...
        "Mitigated by the single-window part viewer, but still worth gating on burst sessions."; ...
        "Multiple figures and UI controls can still compound RAM and GPU load in one run."; ...
        "Low-priority suspect; exportgraphics is not on the main-session default path."; ...
        ], ...
    'VariableNames', { ...
        'rank', ...
        'cause', ...
        'confidence', ...
        'active_in_profile', ...
        'notes'});
end

function note = localPerPartRDMNote(expected_part_count)
if isfinite(expected_part_count) && expected_part_count >= 1
    note = sprintf([ ...
        'Single-window slider viewer replaces the legacy %d-window ' ...
        'per-part fan-out.'], round(expected_part_count));
else
    note = 'Single-window slider viewer replaces the legacy per-part fan-out.';
end
end

function label = localGeographicRendererLabel(force_2d, include_color_scale)
if force_2d
    label = "figure + geoaxes";
else
    label = "uifigure + geoglobe";
end

if include_color_scale
    label = label + " + classic color-scale figure";
end
end

function tf = localIsVisualizationProfile(value)
value = string(value);
value = lower(strtrim(value));
if strlength(value) == 0
    tf = true;
    return
end

tf = any(strcmp(value, ["full", "core", "headless"]));
end

function tf = localIsOptionalLogicalScalar(value)
tf = isempty(value) || ...
    (islogical(value) && isscalar(value)) || ...
    (isnumeric(value) && isscalar(value) && any(value == [0, 1]));
end
