function [session_root, stage_dir, session_id] = localTempSession(testCase)
session_root = string(tempname(char(testCase.TriggerRoot)));
stage_dir = string(tempname(char(testCase.TriggerRoot)));
mkdir(session_root);
mkdir(stage_dir);
session_id = "trigger_test_" + string(datetime('now', 'Format', 'yyyyMMddHHmmssSSS')) + "_" + string(randi([1 1e6]));

testCase.addTeardown(@() localSafeRemoveFolder(session_root));
testCase.addTeardown(@() localSafeRemoveFolder(stage_dir));
end

function localWriteScenario(stage_dir, session_id, varargin)
p = inputParser;
addParameter(p, 'include_decoy', true, @islogical);
parse(p, varargin{:});
opts = p.Results;

rx_lla = [42.2999333, -71.349333, 15.0];
spheroid = wgs84Ellipsoid('meter');
now_utc = datetime('now', 'TimeZone', 'UTC');

aircraft = struct( ...
    'hex', {'ABC123'}, ...
    'callsign', {'WEST1'}, ...
    'ranges_m', {[26e3, 27e3, 28e3]}, ...
    'azimuth_deg', {270.0}, ...
    'altitude_m', {2500}, ...
    'groundspeed_mps', {180}, ...
    'track_deg', {270}, ...
    'vertical_rate_mps', {0});

if opts.include_decoy
    aircraft(2) = struct( ...
        'hex', 'DEF456', ...
        'callsign', 'EASTDEC', ...
        'ranges_m', {[24e3, 24.5e3, 25e3]}, ...
        'azimuth_deg', 75.0, ...
        'altitude_m', 2500, ...
        'groundspeed_mps', 160, ...
        'track_deg', 75, ...
        'vertical_rate_mps', 0);
end

file_name = fullfile(stage_dir, "000_" + string(datetime('now', 'Format', 'yyyyMMdd_HHmmss')) + "_adsb_" + session_id + ".txt");
file_id = fopen(file_name, 'w');
if file_id == -1
    error('ADSBTriggeredCaptureSessionTest:fileOpenFailed', ...
        'Could not create %s.', file_name);
end
cleanup_file = onCleanup(@() fclose(file_id));

for idx = 1:numel(aircraft)
    ac = aircraft(idx);
    timestamps = now_utc + seconds([-10, -5, 0]);
    fprintf(file_id, 'MSG,1,1,1,%s,1,%s,%s,%s,%s,%s,,,,,,,,,,\n', ...
        ac.hex, ...
        localDateString(timestamps(1)), localTimeString(timestamps(1)), ...
        localDateString(timestamps(1)), localTimeString(timestamps(1)), ...
        ac.callsign);

    for fix_idx = 1:numel(timestamps)
        range_m = ac.ranges_m(fix_idx);
        east_m = range_m .* sind(ac.azimuth_deg);
        north_m = range_m .* cosd(ac.azimuth_deg);
        up_m = ac.altitude_m - rx_lla(3);
        [lat_deg, lon_deg, alt_m] = enu2geodetic( ...
            east_m, north_m, up_m, ...
            rx_lla(1), rx_lla(2), rx_lla(3), spheroid);

        fprintf(file_id, 'MSG,3,1,1,%s,1,%s,%s,%s,%s,,%d,,,%s,%s,,,,0\n', ...
            ac.hex, ...
            localDateString(timestamps(fix_idx)), localTimeString(timestamps(fix_idx)), ...
            localDateString(timestamps(fix_idx)), localTimeString(timestamps(fix_idx)), ...
            round(alt_m ./ 0.3048), ...
            sprintf('%.6f', lat_deg), ...
            sprintf('%.6f', lon_deg));

        fprintf(file_id, 'MSG,4,1,1,%s,1,%s,%s,%s,%s,,,%d,%d,,0,,%d\n', ...
            ac.hex, ...
            localDateString(timestamps(fix_idx)), localTimeString(timestamps(fix_idx)), ...
            localDateString(timestamps(fix_idx)), localTimeString(timestamps(fix_idx)), ...
            round(ac.groundspeed_mps ./ 0.5144444), ...
            round(ac.track_deg), ...
            round(ac.vertical_rate_mps ./ 0.00508));
    end
end
end

function capture_info = localCaptureStub(capture_root, varargin)
p = inputParser;
addParameter(p, 'SessionID', "", @(x) ischar(x) || isstring(x));
addParameter(p, 'CaptureDuration_s', 30, @(x) isnumeric(x) && isscalar(x));
addParameter(p, 'CaptureFile', "n320_hdtv_capture", @(x) ischar(x) || isstring(x));
addParameter(p, 'RadioName', "Stub", @(x) ischar(x) || isstring(x));
addParameter(p, 'CenterFrequency_Hz', 540e6, @(x) isnumeric(x) && isscalar(x));
addParameter(p, 'SampleRate_Hz', 6.144e6, @(x) isnumeric(x) && isscalar(x));
addParameter(p, 'LOOffset_Hz', 200e3, @(x) isnumeric(x) && isscalar(x));
addParameter(p, 'Gain', [30 50], @isnumeric);
addParameter(p, 'Repetitions', 1, @(x) isnumeric(x) && isscalar(x));
addParameter(p, 'RepetitionSpacing_s', 1.0, @(x) isnumeric(x) && isscalar(x));
parse(p, varargin{:});
opts = p.Results;

capture_path = fullfile(capture_root, string(opts.CaptureFile) + "_" + string(opts.SessionID) + ".bb");
file_id = fopen(capture_path, 'w');
if file_id == -1
    error('ADSBTriggeredCaptureSessionTest:captureCreateFailed', ...
        'Could not create %s.', capture_path);
end
fclose(file_id);

capture_info = struct( ...
    'session_id', string(opts.SessionID), ...
    'capture_duration_s', double(opts.CaptureDuration_s), ...
    'capture_repetitions', double(opts.Repetitions), ...
    'capture_repetition_spacing_s', double(opts.RepetitionSpacing_s), ...
    'radar_active_window_s', double(opts.CaptureDuration_s) .* double(opts.Repetitions), ...
    'radar_recorded_iq_seconds_s', double(opts.CaptureDuration_s) .* double(opts.Repetitions), ...
    'capture_file_base', string(opts.CaptureFile), ...
    'radio_name', string(opts.RadioName), ...
    'center_frequency_hz', double(opts.CenterFrequency_Hz), ...
    'sample_rate_hz', double(opts.SampleRate_Hz), ...
    'lo_offset_hz', double(opts.LOOffset_Hz), ...
    'header_center_frequency_hz', double(opts.CenterFrequency_Hz), ...
    'header_lo_offset_hz', double(opts.LOOffset_Hz), ...
    'header_tune_frequency_hz', double(opts.CenterFrequency_Hz + opts.LOOffset_Hz), ...
    'header_sample_rate_hz', double(opts.SampleRate_Hz), ...
    'gain', double(opts.Gain(:).'), ...
    'recording_utc', posixtime(datetime('now', 'TimeZone', 'UTC')), ...
    'local_capture_files', string(capture_path));
end

function capture_info = localCaptureFailureStub(varargin)
capture_info = struct(); %#ok<NASGU>
error('ADSBTriggeredCaptureSessionTest:stubFailure', ...
    'Capture failed in the injected stub.');
end

function context = localLoadTriggerContext(result)
loaded = load(char(result.artifacts.trigger_context_mat), 'context');
context = loaded.context;
end

function east_support_m = localQualifiedEastSupport(preview)
[~, east_idx] = find(preview.qualified_grid);
east_support_m = double(preview.east_axis_m(east_idx));
east_support_m = east_support_m(:);
end

function value = localDateString(time_value)
value = sprintf('%04d/%02d/%02d', year(time_value), month(time_value), day(time_value));
end

function value = localTimeString(time_value)
value = sprintf('%02d:%02d:%06.3f', hour(time_value), minute(time_value), second(time_value));
end

function localSafeRemoveFolder(folder_path)
folder_path = char(string(folder_path));
if isfolder(folder_path)
    rmdir(folder_path, 's');
end
end
