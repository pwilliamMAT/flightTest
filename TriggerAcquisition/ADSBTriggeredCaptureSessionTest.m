                'ShowTriggerPreviewMap', false, ...
                'SaveTriggerPreviewMap', false, ...
                'WatchTimeout_s', 0.05, ...
                'PollPeriod_s', 0.01, ...
                'TailSeconds_s', 0, ...
                'Verbose', false);

            testCase.verifyEqual(result.final_status, "timeout");
            testCase.verifyFalse(result.trigger_fired);
            testCase.verifyEqual(result.capture_info.status, "not_run");
            testCase.verifyTrue(isfile(char(result.artifacts.trigger_summary_txt)));
            testCase.verifyTrue(isfile(char(result.artifacts.trigger_decisions_csv)));
            testCase.verifyTrue(isfile(char(result.artifacts.trigger_context_mat)));
            testCase.verifyEqual(strlength(result.artifacts.session_manifest), 0);
        end

        function testDefaultSessionGeometryResolvesWestFacingAzimuths(testCase)
