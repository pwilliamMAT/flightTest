        TriggerRoot string
    end

    methods (TestClassSetup)
        function addSourcePath(testCase)
            triggerRoot = string(fileparts(mfilename('fullpath')));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture(char(triggerRoot)));
            testCase.TriggerRoot = triggerRoot;
            helperTriggerAddProjectPaths();
        end
    end

    methods (TestMethodSetup)
        function resetRandomState(testCase)
            original_rng = rng;
            testCase.addTeardown(@() rng(original_rng));
