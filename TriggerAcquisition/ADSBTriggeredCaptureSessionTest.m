        function testShadowRecommendationRanksWestTargetAndRejectsEastDecoy(testCase)
            [session_root, stage_dir, session_id] = localTempSession(testCase);
            localWriteScenario(stage_dir, session_id, 'include_decoy', true);

            result = runADSBTriggeredCaptureSession( ...
                'SessionID', session_id, ...
                'SessionRoot', session_root, ...
                'ADSBStageDir', stage_dir, ...
                'Mode', 'shadow', ...
                'ShowTriggerPreviewMap', false, ...
                'SaveTriggerPreviewMap', false, ...
                'MinConsecutiveQualifiedPolls', 1, ...
                'WatchTimeout_s', 0.05, ...
                'PollPeriod_s', 0.01, ...
                'TailSeconds_s', 0, ...
                'Verbose', false);

            testCase.verifyEqual(result.final_status, "shadow_recommendation");
            testCase.verifyFalse(result.trigger_fired);
            testCase.verifyGreaterThanOrEqual(height(result.candidate_table), 1);
            testCase.verifyEqual(result.candidate_table.hex(1), "ABC123");
            testCase.verifyTrue(contains(result.trigger_reason, "Shadow recommendation"));
            testCase.verifyLessThan(abs(result.candidate_table.azimuth_deg(1) - 270.0), 10.0);
            testCase.verifyTrue(result.candidate_table.qualified(1));

            decoy_row = result.candidate_table(result.candidate_table.hex == "DEF456", :);

            testCase.verifyEqual(height(decoy_row), 1);
            testCase.verifyFalse(decoy_row.qualified(1));
            testCase.verifyFalse(decoy_row.corridor_gate_pass(1));
            testCase.verifyGreaterThan(result.candidate_table.trigger_score(1), decoy_row.trigger_score(1));
        end

