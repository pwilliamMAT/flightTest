function localValidateSourceInputs(reportRoot,reports)
for index = 1:numel(reports)
    sourcePath = fullfile(reportRoot,reports(index).Filename);
    if ~isfile(sourcePath)
        error("TechnicalSummaryFamily:MissingReport", ...
            "Accepted canonical report is unavailable: %s",sourcePath);
    end
end
end

