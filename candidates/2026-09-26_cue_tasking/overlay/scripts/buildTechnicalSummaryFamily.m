    mkdir(folder);
end
end

function hashTable = localSourceHashTable(reportRoot,reports)
count = numel(reports);
ids = strings(count,1);
filenames = strings(count,1);
paths = strings(count,1);
hashes = strings(count,1);
for index = 1:count
    path = fullfile(reportRoot,reports(index).Filename);
    ids(index) = reports(index).Id;
    filenames(index) = reports(index).Filename;
    paths(index) = path;
    hashes(index) = string(localSha256(path));
end
hashTable = table(ids,filenames,paths,hashes, ...
    'VariableNames',{'ReportID','Filename','SourcePath','SourceSHA256'});
end

function integrity = localSourceIntegrityBaseline(reportRoot,reports)
% Record every report-local source image plus all source PowerPoint files.
% The release may read these files but never modifies them.
assetPaths = strings(0,1);
for index = 1:numel(reports)
    content = string(fileread(fullfile(reportRoot,reports(index).Filename)));
    sources = localExtractLinks(content,"src");
    for sourceIndex = 1:numel(sources)
        sourceLink = sources(sourceIndex);
        if localIsExternalOrFragment(sourceLink)
            continue;
        end
        sourcePath = fullfile(reportRoot, ...
            string(urldecode(char(localStripFragment(sourceLink)))));
        if isfile(sourcePath)
            assetPaths(end+1,1) = string(sourcePath); %#ok<AGROW>
        end
    end
end
assetPaths = unique(assetPaths,"stable");

powerPointListing = dir(fullfile(reportRoot,"**","*.pptx"));
powerPointPaths = strings(numel(powerPointListing),1);
for index = 1:numel(powerPointListing)
    powerPointPaths(index) = fullfile(powerPointListing(index).folder, ...
        powerPointListing(index).name);
end

paths = [assetPaths;powerPointPaths];
kind = [repmat("Asset",numel(assetPaths),1); ...
    repmat("PowerPoint",numel(powerPointPaths),1)];
relativePath = strings(numel(paths),1);
hashes = strings(numel(paths),1);
for index = 1:numel(paths)
    relativePath(index) = extractAfter(paths(index),reportRoot + filesep);
    hashes(index) = string(localSha256(paths(index)));
end
integrity = table(kind,relativePath,paths,hashes, ...
    'VariableNames',{'Kind','RelativePath','SourcePath','SourceSHA256'});
end

