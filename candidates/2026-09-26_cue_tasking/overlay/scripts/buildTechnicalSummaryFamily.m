function [content,copyInfo] = localCopyCompanionDependencies(content,reportRoot,folders,copyInfo)
links = localExtractLinks(content,"href");
for index = 1:numel(links)
    link = links(index);
    if localIsExternalOrFragment(link) || endsWith(lower(link),".html")
        continue;
    end
    decoded = string(urldecode(char(localStripFragment(link))));
    sourcePath = fullfile(reportRoot,decoded);
    [~,name,extension] = fileparts(sourcePath);
    if ~isfile(sourcePath) || ~ismember(lower(extension), ...
            [".csv",".md",".yaml",".yml",".json",".txt"])
        continue;
    end
    destinationName = string(name) + string(extension);
    destinationPath = fullfile(folders.Companions,destinationName);
    if ~isfile(destinationPath)
        copyfile(sourcePath,destinationPath);
    end
    content = replace(content,link,"../companions/" + destinationName);
    copyInfo.Companions(end+1,1) = destinationName; %#ok<AGROW>
end
end

function [content,copyInfo] = localCopyAssetDependencies(content,reportRoot,folders,copyInfo)
sources = localExtractLinks(content,"src");
for index = 1:numel(sources)
    sourceLink = sources(index);
    if startsWith(sourceLink,"data:") || startsWith(sourceLink,"http") || startsWith(sourceLink,"file:")
        if startsWith(sourceLink,"file:")
            copyInfo.ExternalDependencies(end+1,1) = sourceLink; %#ok<AGROW>
        end
        continue;
    end
    decoded = string(urldecode(char(localStripFragment(sourceLink))));
    sourcePath = fullfile(reportRoot,decoded);
    if ~isfile(sourcePath)
        continue;
    end

    if startsWith(sourceLink,"../HardwarePhotos/")
        destinationFolder = fullfile(folders.Assets,"HardwarePhotos");
        localEnsureFolder(destinationFolder);
        [~,name,extension] = fileparts(sourcePath);
        destinationName = string(name) + string(extension);
        copyfile(sourcePath,fullfile(destinationFolder,destinationName));
        content = replace(content,sourceLink, ...
            "../assets/HardwarePhotos/" + localUrlEncodeFilename(destinationName));
        copyInfo.Assets(end+1,1) = "HardwarePhotos/" + destinationName; %#ok<AGROW>
    elseif contains(sourceLink,"_assets/")
        sourceFolderName = extractBefore(sourceLink,"/");
        sourceFolder = fullfile(reportRoot,string(urldecode(char(sourceFolderName))));
        destinationFolder = fullfile(folders.Assets,sourceFolderName);
        if ~isfolder(destinationFolder)
            copyfile(sourceFolder,destinationFolder);
        end
        content = replace(content,sourceFolderName + "/", ...
            "../assets/" + sourceFolderName + "/");
        copyInfo.Assets(end+1,1) = sourceFolderName; %#ok<AGROW>
    else
        destinationFolder = fullfile(folders.Assets,"misc");
        localEnsureFolder(destinationFolder);
        [~,name,extension] = fileparts(sourcePath);
        destinationName = string(name) + string(extension);
        copyfile(sourcePath,fullfile(destinationFolder,destinationName));
        content = replace(content,sourceLink, ...
            "../assets/misc/" + localUrlEncodeFilename(destinationName));
        copyInfo.Assets(end+1,1) = "misc/" + destinationName; %#ok<AGROW>
    end
end
end

function [content,copyInfo] = localNormalizeRelativeEvidenceLinks(content,reportRoot,copyInfo,reports)
links = localExtractLinks(content,"href");
for index = 1:numel(links)
    link = links(index);
    if localIsExternalOrFragment(link) || startsWith(link,"../companions/") || ...
            localIsFamilyReportReference(link,reports)
        continue;
    end
    decoded = string(urldecode(char(localStripFragment(link))));
    sourcePath = fullfile(reportRoot,decoded);
    if isfile(sourcePath) || isfolder(sourcePath)
        externalUri = localFileUri(sourcePath);
        fragment = extractAfter(link,"#");
        if strlength(fragment) > 0
            externalUri = externalUri + "#" + fragment;
        end
        content = replace(content,link,externalUri);
        copyInfo.ExternalDependencies(end+1,1) = externalUri; %#ok<AGROW>
    end
end
end

