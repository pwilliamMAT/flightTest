function localPromoteImmutableRelease(immutableRoot,releaseRoot,releaseHistoryRoot)
nextRoot = releaseRoot + "_next";
if isfolder(nextRoot)
    error("TechnicalSummaryFamily:PendingPromotionExists", ...
        "Refusing to replace a retained pending promotion folder: %s",nextRoot);
end
copyfile(immutableRoot,nextRoot);
if isfolder(releaseRoot)
    legacyId = "superseded_current_" + string(datetime("now","Format","yyyyMMdd_HHmmss"));
    legacyRoot = fullfile(releaseHistoryRoot,legacyId);
    movefile(releaseRoot,legacyRoot,"f");
end
movefile(nextRoot,releaseRoot,"f");
end

