function priorId = localPriorReleaseId(releaseHistoryRoot)
priorId = "";
if ~isfolder(releaseHistoryRoot)
    return;
end
listing = dir(releaseHistoryRoot);
names = string({listing([listing.isdir]).name});
names = names(~ismember(names,[".",".."]));
isImmutableRelease = ~cellfun(@isempty, ...
    regexp(cellstr(names),'^\d{8}_\d{6}$','once'));
names = names(isImmutableRelease);
if ~isempty(names)
    names = sort(names);
    priorId = names(end);
end
end

