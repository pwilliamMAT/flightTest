function result = buildTechnicalSummaryFamily(reportRoot)
% buildTechnicalSummaryFamily Audit and package the technical-summary family.
%
% This builder never edits the nine source reports or their source assets. It
% writes audit outputs and release copies to TechnicalSummaryFamily_Releases,
% then promotes a validated immutable release to TechnicalSummaryFamily.

arguments
    reportRoot (1,1) string = string(fileparts(mfilename("fullpath")))
end

reportRoot = string(char(reportRoot));
flightTestRoot = string(fileparts(reportRoot));
agenticRoot = "C:\Users\pwilliam\agenticProjects";
releaseRoot = fullfile(reportRoot,"TechnicalSummaryFamily");
releaseHistoryRoot = fullfile(reportRoot,"TechnicalSummaryFamily_Releases");
releaseId = string(datetime("now","Format","yyyyMMdd_HHmmss"));
stageRoot = fullfile(releaseHistoryRoot,releaseId + "_staging");
immutableRoot = fullfile(releaseHistoryRoot,releaseId);

reports = localReportDefinitions(flightTestRoot,agenticRoot);
result = struct( ...
    "ReleaseId",releaseId, ...
    "StageRoot",stageRoot, ...
    "ReleaseRoot",releaseRoot, ...
    "Status","FAILED", ...
    "Message","Build did not start.");

localEnsureFolder(releaseHistoryRoot);
priorReleaseId = localPriorReleaseId(releaseHistoryRoot);
if isfolder(stageRoot)
    error("TechnicalSummaryFamily:StageExists", ...
        "Staging folder already exists: %s",stageRoot);
end

mkdir(stageRoot);
cleanupStage = onCleanup(@()localWriteFailureMarker(stageRoot,result)); %#ok<NASGU>

try
    localValidateSourceInputs(reportRoot,reports);
    sourceHashes = localSourceHashTable(reportRoot,reports);
    sourceIntegrity = localSourceIntegrityBaseline(reportRoot,reports);

    folders = localReleaseFolders(stageRoot);
    localCreateReleaseFolders(folders);

    audit = localBuildPhaseZeroAudit( ...
        folders.Metadata,reportRoot,flightTestRoot,agenticRoot,reports,sourceHashes);

    if any(audit.Priority == "P0" & ...
            audit.RecommendedDisposition == "Blocked from Canonical Release")
        error("TechnicalSummaryFamily:BlockedByAudit", ...
            "The Phase 0 audit contains unresolved P0 blockers.");
    end

    copyInfo = localCreateReleaseCopies( ...
        folders,reportRoot,flightTestRoot,reports,sourceHashes,audit);
    localWriteCanonicalMetadata(folders,reportRoot,releaseRoot,releaseId, ...
        immutableRoot,priorReleaseId,reports,sourceHashes,sourceIntegrity,audit,copyInfo);
    localWriteReleaseReadme(folders.Root,releaseId);

    verification = verifyTechnicalSummaryFamily(folders.Root);
    if ~verification.Passed
        error("TechnicalSummaryFamily:ValidationFailed", ...
            "Release validation failed. See %s", ...
            fullfile(folders.Validation,"release_validation.md"));
    end

    localAssertSourceIntegrity(sourceIntegrity);
    movefile(stageRoot,immutableRoot,"f");
    result.StageRoot = immutableRoot;

    localRecordPromotion(immutableRoot,stageRoot,releaseRoot,priorReleaseId);
    localPromoteImmutableRelease(immutableRoot,releaseRoot,releaseHistoryRoot);
    localAssertSourceIntegrity(sourceIntegrity);

    result.Status = verification.Status;
    result.Message = "Phase 0 audit, release-local stabilization, and promotion completed.";
    result.CurrentRelease = releaseRoot;
    result.ImmutableRelease = immutableRoot;
    result.Validation = verification;
catch exception
    result.Status = "FAILED";
    result.Message = string(getReport(exception,"extended","hyperlinks","off"));
    localWriteBuildFailure(stageRoot,result,exception);
    rethrow(exception);
end
end

