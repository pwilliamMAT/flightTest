function localAssertSourceIntegrity(sourceIntegrity)
for index = 1:height(sourceIntegrity)
    sourcePath = sourceIntegrity.SourcePath(index);
    if ~isfile(sourcePath)
        error("TechnicalSummaryFamily:SourceMissing", ...
            "Source file disappeared during build: %s",sourcePath);
    end
    actualHash = string(localSha256(sourcePath));
    if actualHash ~= sourceIntegrity.SourceSHA256(index)
        error("TechnicalSummaryFamily:SourceChanged", ...
            "Source report changed during build: %s",sourcePath);
    end
end
end

function links = localExtractLinks(content,attribute)
expression = "(?i)" + attribute + "\s*=\s*[""']([^""']+)[""']";
matches = regexp(content,expression,"tokens");
if isempty(matches)
    links = strings(0,1);
else
    links = string(cellfun(@(item)item{1},matches,'UniformOutput',false));
end
end

function value = localStripFragment(link)
hashIndex = strfind(link,"#");
if isempty(hashIndex)
    value = link;
else
    value = extractBefore(link,hashIndex(1));
end
end

function tf = localIsExternalOrFragment(link)
tf = startsWith(link,"#") || startsWith(link,"http:") || startsWith(link,"https:") || ...
    startsWith(link,"file:") || startsWith(link,"mailto:") || startsWith(link,"javascript:") || ...
    startsWith(link,"data:");
end

