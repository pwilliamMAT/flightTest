%[text] Step 4: Run the readiness gate to check whether the generated IQ landed where the scenario predicted in range and Doppler and whether the seeded waveform preserved the expected signal structure.
%[text] Step 5: Run the existing detector and compare detections to truth in measurement space so you can decide whether the dataset is useful for intermediate validation.
%[text] The range-error and Doppler-error summaries are the numbers behind the bottom histograms from the legacy figure: mean near zero indicates low bias, and sigma or RMS tells you how tightly the true-positive detections cluster around truth.
