function tableOut = localBuildReadinessOverviewTable(validationSummary)
if isempty(validationSummary) || ~isfield(validationSummary, 'readiness')
    tableOut = localBuildKeyValueTable("Signal-physics readiness", "Not run.");
    return
end
readiness = validationSummary.readiness;
labels = [ ...
    "Overall readiness"; ...
    "Failure classes"; ...
    "Parts validated"; ...
    "Parts passed"; ...
    "Packaging integrity"; ...
    "Seed preservation"; ...
    "Direct-path gate"; ...
    "Median direct-path residual"; ...
    "Worst direct-path residual"; ...
    "Target placement"; ...
    "Strength ordering"; ...
    "Qualified strength-ordering pairs"; ...
    "Vertical columns clear"; ...
    "Target echo dataset"; ...
    "Recommended intermediate mode"];
values = [ ...
    localFormatPassFail(readiness.overall_pass); ...
    localJoinStringArray(readiness.failure_classes); ...
    compose("%d", readiness.n_parts_validated); ...
    compose("%d", readiness.n_parts_passed); ...
    localFormatPassFail(readiness.packaging_integrity_pass); ...
    localFormatPassFail(readiness.seed_preservation.overall_pass); ...
    localFormatPassFail(readiness.direct_path.overall_pass); ...
    compose("%.3f [samples]", readiness.direct_path.median_abs_residual_samples); ...
    compose("%.3f [samples]", readiness.direct_path.worst_abs_residual_samples); ...
    localFormatPassFail(readiness.target_placement_pass); ...
    localFormatPassFail(readiness.target_strength_ordering.overall_pass); ...
    compose("%d", readiness.target_strength_ordering.n_qualified_pairs); ...
    localFormatPassFail(readiness.vertical_column.overall_pass); ...
    string(readiness.target_echo_dataset_label); ...
    localFormatYesNo(readiness.recommended_intermediate_algorithm_test_mode)];
tableOut = localBuildKeyValueTable(labels, values);
end
function tableOut = localBuildReadinessPartTable(validationSummary)
tableOut = table();
if isempty(validationSummary) || ~isfield(validationSummary, 'per_part') || isempty(validationSummary.per_part)
    return
end
partResults = validationSummary.per_part;
nParts = numel(partResults);
partIndex = zeros(nParts, 1);
overallReadiness = strings(nParts, 1);
failureClasses = strings(nParts, 1);
seedPreservation = strings(nParts, 1);
referenceSpectrumCorr = NaN(nParts, 1);
surveillanceSpectrumCorr = NaN(nParts, 1);
directPathResidualSamples = NaN(nParts, 1);
medianProminenceDB = NaN(nParts, 1);
verticalColumnsClear = strings(nParts, 1);
for idx = 1 : nParts
    partResult = partResults(idx);
    partIndex(idx) = partResult.part_index;
    overallReadiness(idx) = localFormatPassFail(partResult.readiness.overall_pass);
    failureClasses(idx) = localJoinStringArray(partResult.readiness.failure_classes);
    seedPreservation(idx) = localFormatPassFail(partResult.seed_preservation.overall_pass);
    referenceSpectrumCorr(idx) = partResult.seed_preservation.reference_spectrum_correlation;
    surveillanceSpectrumCorr(idx) = partResult.seed_preservation.surveillance_spectrum_correlation;
    directPathResidualSamples(idx) = partResult.direct_path.residual_samples_fractional;
    medianProminenceDB(idx) = partResult.target_prominence_summary.median_prominence_db;
    verticalColumnsClear(idx) = localFormatPassFail(partResult.doppler_column_advisory.all_targets_clear);
end
