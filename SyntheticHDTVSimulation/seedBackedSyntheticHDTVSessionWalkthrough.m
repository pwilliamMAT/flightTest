function tableOut = localBuildValidationInterpretationTable(validationSummary, truthDiagOutput, runSignalPhysicsReadinessCheck, runWrapperReplay)
questions = [ ...
    "Is the generated IQ internally consistent with the requested scene?"; ...
    "Did the synthetic targets land where truth predicted?"; ...
    "Does the downstream detector recover truth-aligned targets?"; ...
    "What validation claim does this run support?"];
answers = strings(size(questions));
evidence = strings(size(questions));
if ~runSignalPhysicsReadinessCheck || isempty(validationSummary)
    answers(1) = "Not assessed in this run.";
    evidence(1) = "Set runSignalPhysicsReadinessCheck = true to run the session-level readiness gate.";
    answers(2) = "Not assessed in this run.";
    evidence(2) = "Target-placement evidence comes from the readiness gate.";
else
    answers(1) = localTernary(validationSummary.readiness.overall_pass, "Yes.", "No.");
    evidence(1) = "Failure classes: " + localJoinStringArray(validationSummary.readiness.failure_classes) + ".";
    answers(2) = localTernary(validationSummary.readiness.target_placement_pass, "Yes at the current readiness thresholds.", "No, at least one target missed the placement thresholds.");
    evidence(2) = localBuildTargetPlacementEvidence(validationSummary.readiness.per_target);
end
if ~runWrapperReplay
    answers(3) = "Not assessed in this run.";
    evidence(3) = "Set runWrapperReplay = true to run the packaged-session workflow and truth comparison.";
elseif ~localHasTruthDiagnostics(truthDiagOutput)
    answers(3) = "Wrapper replay ran, but no truth-diagnostic bundle was available.";
    evidence(3) = "Check whether runBistaticAnalysisSession returned truth_diag_input.";
else
    metrics = truthDiagOutput.truth_metrics;
    answers(3) = localTernary(metrics.n_tp > 0, "Yes, the detector produced truth-matched hits.", "No true positives under the current gates.");
    evidence(3) = compose("TP=%d, FA=%d, missed truth CPIs=%d.", metrics.n_tp, metrics.n_fa, metrics.n_miss);
end
[answers(4), evidence(4)] = localClassifyValidationUsefulness(validationSummary, truthDiagOutput, runSignalPhysicsReadinessCheck, runWrapperReplay);
tableOut = table(questions, answers, evidence, 'VariableNames', {'Question', 'Answer', 'Evidence'});
end
function [label, evidence] = localClassifyValidationUsefulness(validationSummary, truthDiagOutput, runSignalPhysicsReadinessCheck, runWrapperReplay)
if ~runSignalPhysicsReadinessCheck || isempty(validationSummary)
    if runWrapperReplay && localHasTruthDiagnostics(truthDiagOutput)
        label = "Exploratory only.";
        evidence = "Downstream truth metrics exist, but the signal-physics readiness gate was skipped.";
    else
        label = "Configuration only.";
        evidence = "Neither the readiness gate nor downstream truth replay completed in this run.";
    end
    return
end
failureClasses = string(validationSummary.readiness.failure_classes);
failureClasses = failureClasses(strlength(failureClasses) > 0);
onlyVerticalColumnFailure = numel(failureClasses) == 1 && failureClasses(1) == "vertical_column_defect";
hasTruthDiagnostics = localHasTruthDiagnostics(truthDiagOutput);
nTP = 0;
nFA = 0;
nMiss = 0;
if hasTruthDiagnostics
    nTP = truthDiagOutput.truth_metrics.n_tp;
    nFA = truthDiagOutput.truth_metrics.n_fa;
    nMiss = truthDiagOutput.truth_metrics.n_miss;
end
if validationSummary.readiness.overall_pass
    if hasTruthDiagnostics && nTP > 0
        label = "Useful for intermediate workflow validation.";
        evidence = "Readiness PASS and the downstream detector produced truth-matched hits. This is still not a field-equivalent benchmark.";
    elseif hasTruthDiagnostics
        label = "Internally consistent, but downstream recovery was not demonstrated in this run.";
        evidence = compose("Readiness PASS, but TP=%d, FA=%d, and missed truth CPIs=%d under the current gates.", nTP, nFA, nMiss);
    else
        label = "Internally consistent; downstream usefulness was not checked in this run.";
        evidence = "Readiness PASS and wrapper replay was skipped or did not return truth metrics.";
    end
elseif onlyVerticalColumnFailure
    if hasTruthDiagnostics && nTP > 0
        label = "Useful for debugging and controlled comparisons, but not for benchmark scoring.";
        evidence = "Target placement is usable and truth-matched detections exist, but vertical Doppler-column artifacts remain.";
    else
        label = "Useful only for signal-chain debugging.";
        evidence = "The main remaining failure is vertical_column_defect and downstream evidence is limited.";
    end
else
    label = "Not ready for downstream validation.";
    evidence = "Readiness failed on " + localJoinStringArray(failureClasses) + ".";
end
if ~runWrapperReplay && validationSummary.readiness.overall_pass
    evidence = evidence + " Wrapper replay was skipped in this run.";
end
end
function evidence = localBuildTargetPlacementEvidence(perTargetSummary)
if isempty(perTargetSummary)
    evidence = "No per-target readiness summary was produced.";
    return
end
parts = strings(numel(perTargetSummary), 1);
for idx = 1 : numel(perTargetSummary)
    target = perTargetSummary(idx);
    parts(idx) = string(target.target_id) + " R " + compose("%.2f/%.2f bins", target.median_abs_range_residual_bins, target.worst_abs_range_residual_bins) + ", fd " + compose("%.2f/%.2f bins", target.median_abs_doppler_residual_bins, target.worst_abs_doppler_residual_bins);
end
evidence = strjoin(parts, " | ");
end
function match = localFindByTargetId(items, targetId)
match = struct([]);
if isempty(items)
    return
end
targetIds = string({items.target_id});
matchIdx = find(targetIds == string(targetId), 1, 'first');
if ~isempty(matchIdx)
    match = items(matchIdx);
end
end
function count = localCountAlignedTruthTracks(analysisOutput)
count = 0;
