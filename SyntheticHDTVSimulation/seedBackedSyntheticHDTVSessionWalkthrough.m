    return
end
count = sum(arrayfun(@(track) any(isfinite(track.R_excess_m)), analysisOutput.adsb_aligned));
end
function tf = localHasTruthDiagnostics(truthDiagOutput)
tf = isstruct(truthDiagOutput) && ~isempty(truthDiagOutput) && isfield(truthDiagOutput, 'truth_metrics') && ~isempty(truthDiagOutput.truth_metrics);
end
function [countValue, meanValue, sigmaValue, medianValue, rmsValue] = localComputeErrorStats(values)
values = double(values(:));
values = values(isfinite(values));
countValue = numel(values);
if isempty(values)
    meanValue = NaN;
    sigmaValue = NaN;
    medianValue = NaN;
    rmsValue = NaN;
    return
end
meanValue = mean(values, 'omitnan');
sigmaValue = std(values, 0, 'omitnan');
medianValue = median(values, 'omitnan');
rmsValue = sqrt(mean(values .^ 2, 'omitnan'));
end
