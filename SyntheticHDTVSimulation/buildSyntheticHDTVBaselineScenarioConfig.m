        seed_path = char(string(seed_path_in));
        if ~localIsAbsolutePath(seed_path)
            seed_path = fullfile(repo_root, seed_path);
        end
    end
end
end

function truth_source_mode = localResolveTruthSourceMode( ...
    truth_source_mode_in, seed_session_context)
requested_mode = lower(char(string(truth_source_mode_in)));
valid_modes = {'auto', 'synthetic_waypoints_v1', 'capture_adsb_v1'};
if ~ismember(requested_mode, valid_modes)
    error('buildSyntheticHDTVBaselineScenarioConfig:badTruthSourceMode', ...
        'TruthSourceMode must be "auto", "synthetic_waypoints_v1", or "capture_adsb_v1".');
end

switch requested_mode
    case 'auto'
        if seed_session_context.is_manifest_backed && ...
                seed_session_context.has_adsb && ...
                seed_session_context.input_kind ~= "baseband_file"
            truth_source_mode = 'capture_adsb_v1';
        else
            truth_source_mode = 'synthetic_waypoints_v1';
        end

    case 'capture_adsb_v1'
        if ~seed_session_context.is_manifest_backed || ~seed_session_context.has_adsb
            error('buildSyntheticHDTVBaselineScenarioConfig:captureTruthRequiresADSB', ...
                ['TruthSourceMode="capture_adsb_v1" requires a packaged session ' ...
                 'with at least one ADS-B truth file.']);
        end
        truth_source_mode = 'capture_adsb_v1';

    otherwise
        truth_source_mode = 'synthetic_waypoints_v1';
end
end

function timing_plan = localResolveTimingPlan(opts, truth_source_mode, seed_session_context)
requested_active_window_s = double(opts.CaptureDurationS) * double(opts.CaptureRepetitions) + ...
    max(double(opts.CaptureRepetitions) - 1, 0) * double(opts.CaptureRepetitionSpacingS);

timing_plan = struct( ...
    'part_duration_s', double(opts.CaptureDurationS), ...
    'capture_repetitions', double(opts.CaptureRepetitions), ...
    'capture_repetition_spacing_s', double(opts.CaptureRepetitionSpacingS), ...
    'radar_active_window_s', requested_active_window_s, ...
    'selected_truth_window_s', requested_active_window_s, ...
    'mode_id', 'synthetic_timing_v1');

if ~strcmp(truth_source_mode, 'capture_adsb_v1')
    return
end

full_capture_window_s = double(seed_session_context.radar_active_window_s);
if ~(isfinite(full_capture_window_s) && full_capture_window_s > 0)
    error('buildSyntheticHDTVBaselineScenarioConfig:missingCaptureWindow', ...
        'The packaged capture session does not expose a finite radar_active_window_s.');
end

selected_window_s = localResolveSelectedWindow( ...
    opts.TruthWindowMaxS, ...
    full_capture_window_s);
timing_plan.selected_truth_window_s = selected_window_s;
timing_plan.radar_active_window_s = selected_window_s;

[use_manifest_timing, included_parts] = localResolveManifestTimingCrop( ...
    selected_window_s, ...
    seed_session_context);

if use_manifest_timing
    timing_plan.part_duration_s = double(seed_session_context.capture_duration_s);
    timing_plan.capture_repetitions = double(numel(included_parts));
    timing_plan.capture_repetition_spacing_s = double(seed_session_context.capture_repetition_spacing_s);
    timing_plan.mode_id = 'capture_manifest_timing_v1';
else
    timing_plan.part_duration_s = selected_window_s;
    timing_plan.capture_repetitions = 1;
    timing_plan.capture_repetition_spacing_s = 0;
    timing_plan.mode_id = 'capture_cropped_single_part_v1';
end
end

function selected_window_s = localResolveSelectedWindow(truth_window_max_s_in, full_capture_window_s)
if isempty(truth_window_max_s_in)
    selected_window_s = full_capture_window_s;
else
    selected_window_s = min(double(truth_window_max_s_in), full_capture_window_s);
end
end

function [use_manifest_timing, included_parts] = localResolveManifestTimingCrop( ...
    selected_window_s, seed_session_context)
use_manifest_timing = false;
included_parts = 1 : max(numel(seed_session_context.radar_files), 0);

capture_duration_s = double(seed_session_context.capture_duration_s);
capture_spacing_s = double(seed_session_context.capture_repetition_spacing_s);
n_parts = numel(seed_session_context.radar_files);
if ~(isfinite(capture_duration_s) && isfinite(capture_spacing_s) && n_parts >= 1)
    return
end

part_start_offsets_s = (0 : n_parts - 1).' .* (capture_duration_s + capture_spacing_s);
part_end_offsets_s = part_start_offsets_s + capture_duration_s;
boundary_tolerance_s = 1e-9;

if abs(selected_window_s - double(seed_session_context.radar_active_window_s)) <= boundary_tolerance_s
    use_manifest_timing = true;
    included_parts = 1 : n_parts;
    return
end

included_mask = part_end_offsets_s <= selected_window_s + boundary_tolerance_s;
included_parts = find(included_mask).';
if isempty(included_parts)
    return
end

if abs(part_end_offsets_s(included_parts(end)) - selected_window_s) <= boundary_tolerance_s
    use_manifest_timing = true;
end
end

function radar_epoch_utc = localResolveRadarEpoch( ...
    requested_epoch_in, truth_source_mode, seed_session_context)
requested_epoch_utc = localNormalizeEpoch(requested_epoch_in);
if strcmp(truth_source_mode, 'capture_adsb_v1') && ...
        isfinite(seed_session_context.radar_epoch_utc)
    radar_epoch_utc = double(seed_session_context.radar_epoch_utc);
else
    radar_epoch_utc = requested_epoch_utc;
end
end

