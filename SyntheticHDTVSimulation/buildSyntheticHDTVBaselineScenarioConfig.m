function seed_echo_conditioning = localBuildSeedEchoConditioning( ...
    signal_mode, sample_rate_hz, enabled_in, comparison_reference_mode)
seed_backed_mode = strcmp(char(string(signal_mode)), 'seed_backed_bistatic_v1');
conditioning_enabled = logical(enabled_in) && seed_backed_mode;

seed_echo_conditioning = struct( ...
    'enabled', conditioning_enabled, ...
    'reference_source', 'full_seed', ...
    'direct_path_source', 'full_seed', ...
    'target_echo_source', 'full_seed', ...
    'method', 'dominant_line_notch_then_rms_match_v1', ...
    'minimum_prominence_db', 10, ...
    'notch_half_width_hz', min(50e3, 0.01 * double(sample_rate_hz)), ...
    'dc_highpass_cutoff_hz', min(50e3, 0.01 * double(sample_rate_hz)), ...
    'max_analysis_samples', 65536, ...
    'baseline_span_bins', 129, ...
    'note', '');

if conditioning_enabled
    seed_echo_conditioning.target_echo_source = 'conditioned_seed';
    seed_echo_conditioning.note = ['Recommended intermediate algorithm-test output. ' ...
        'Reference and direct-path channels keep the full seed while target ' ...
        'echoes use a lightly conditioned seed copy so the dominant pilot-like ' ...
        'line is less likely to create truth-aligned vertical Doppler columns.'];
elseif seed_backed_mode && comparison_reference_mode
    seed_echo_conditioning.note = ['Full-seed comparison/reference output. ' ...
        'Reference, direct-path, and target echoes all reuse the unmodified ' ...
        'seed so users can study seed preservation and vertical-column artifacts.'];
elseif seed_backed_mode
    seed_echo_conditioning.note = ['Full-seed comparison/reference output. ' ...
        'This mode is retained for A/B comparison and is not the recommended ' ...
        'algorithm-test dataset while the vertical-column artifact persists.'];
end

if ~seed_backed_mode
    seed_echo_conditioning.enabled = false;
    seed_echo_conditioning.target_echo_source = 'not_applicable';
    seed_echo_conditioning.note = 'Zero-channel mode does not synthesize seed-backed target echoes.';
end
end

function echo_generation_model = localResolveEchoGenerationModel(echo_generation_model_in, signal_mode)
if ~strcmp(char(string(signal_mode)), 'seed_backed_bistatic_v1')
    echo_generation_model = 'not_applicable';
    return
end

echo_generation_model = char(string(echo_generation_model_in));
if strlength(string(echo_generation_model)) == 0
    echo_generation_model = 'toolbox_wideband_free_space_v1';
end
end

function comparison_echo_generation_model = localResolveComparisonEchoGenerationModel( ...
    comparison_model_in, legacy_diagnostic_model_in, primary_echo_generation_model, signal_mode)
if ~strcmp(char(string(signal_mode)), 'seed_backed_bistatic_v1')
    comparison_echo_generation_model = 'not_applicable';
    return
end

comparison_model = string(comparison_model_in);
if strlength(comparison_model) == 0
    comparison_model = string(legacy_diagnostic_model_in);
end
if strlength(comparison_model) == 0
    comparison_model = string(primary_echo_generation_model);
end

comparison_echo_generation_model = char(comparison_model);
end

function full_seed_comparison_enabled = localResolveFullSeedComparisonEnabled( ...
    full_seed_comparison_in, legacy_diagnostic_in, signal_mode)
