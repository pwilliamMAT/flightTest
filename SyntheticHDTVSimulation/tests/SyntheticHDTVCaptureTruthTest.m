        function testCaptureTruthWindowMaxSCropsTimeline(testCase)
            fixture = testCase.applyFixture(matlab.unittest.fixtures.TemporaryFolderFixture);
            capture_fixture = SyntheticHDTVCaptureTruthTest.localCreateCaptureTruthFixture( ...
                fixture.Folder, ...
                'capture_truth_crop_fixture');

            cfg = buildSyntheticHDTVBaselineScenarioConfig( ...
                'OutputRoot', fixture.Folder, ...
                'SeedSourcePath', capture_fixture.manifest_path, ...
                'TruthWindowMaxS', 1.25, ...
                'TruthSamplePeriodS', 0.25);
            truth_bundle = helperSyntheticGenerateTruth(cfg);

            testCase.verifyEqual(cfg.selected_truth_window_s, 1.25, AbsTol=1e-12);
            testCase.verifyEqual(truth_bundle.selected_truth_window_s, 1.25, AbsTol=1e-12);
            testCase.verifyEqual(truth_bundle.sample_times_s(end), 1.25, AbsTol=1e-12);
            testCase.verifyLessThanOrEqual(max(truth_bundle.targets(1).t_rel_s), 1.25 + 1e-12);
