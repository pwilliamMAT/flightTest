classdef SyntheticHDTVCaptureTruthTest < matlab.unittest.TestCase
    %SYNTHETICHDTVCAPTURETRUTHTEST Coverage for capture-backed truth flow.

    methods (TestClassSetup)
        function addProjectPaths(testCase)
            tests_folder = fileparts(mfilename('fullpath'));
            src_folder = fileparts(tests_folder);
            repo_root = fileparts(src_folder);

            testCase.applyFixture(matlab.unittest.fixtures.PathFixture(src_folder));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                fullfile(repo_root, 'BistaticDataAnalysis')));
        end
    end

    methods (TestMethodSetup)
        function suppressFigures(testCase)
            original_visibility = get(groot, 'DefaultFigureVisible');
            set(groot, 'DefaultFigureVisible', 'off');
            testCase.addTeardown(@() set(groot, 'DefaultFigureVisible', original_visibility));
        end
    end

    methods (Test)
        function testAutoTruthModeSelectsCaptureADSBForManifestSeed(testCase)
            fixture = testCase.applyFixture(matlab.unittest.fixtures.TemporaryFolderFixture);
            capture_fixture = SyntheticHDTVCaptureTruthTest.localCreateCaptureTruthFixture( ...
                fixture.Folder, ...
                'capture_truth_auto_fixture');

            cfg = buildSyntheticHDTVBaselineScenarioConfig( ...
                'OutputRoot', fixture.Folder, ...
                'SeedSourcePath', capture_fixture.manifest_path);

            testCase.verifyEqual(cfg.truth_source_mode, 'capture_adsb_v1');
            testCase.verifyEqual(cfg.seed_source_kind, 'session_manifest');
            testCase.verifyEqual(cfg.capture_manifest_path, capture_fixture.manifest_path);
        end

