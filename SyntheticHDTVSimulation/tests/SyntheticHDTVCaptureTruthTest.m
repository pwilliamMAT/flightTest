        function testCaptureTruthSelectionTableReportsRetainAndExcludeReasons(testCase)
            fixture = testCase.applyFixture(matlab.unittest.fixtures.TemporaryFolderFixture);
            capture_fixture = SyntheticHDTVCaptureTruthTest.localCreateCaptureTruthFixture( ...
                fixture.Folder, ...
                'capture_truth_filter_fixture');

            cfg = buildSyntheticHDTVBaselineScenarioConfig( ...
                'OutputRoot', fixture.Folder, ...
                'SeedSourcePath', capture_fixture.manifest_path, ...
                'TruthSamplePeriodS', 0.25);
            truth_bundle = helperSyntheticGenerateTruth(cfg);
            selection_table = truth_bundle.selection_table;

            testCase.verifyEqual(sum(selection_table.Include), 1);
            testCase.verifyTrue(any(selection_table.Reason == "retained_overlap_geometry_inclusive_v1"));
            testCase.verifyTrue(any(selection_table.Reason == "fewer_than_2_in_window_adsb_fixes"));
            testCase.verifyTrue(any(selection_table.Reason == "below_5km_near_range_guard"));
            testCase.verifyEqual(numel(truth_bundle.targets), 1);
            testCase.verifyEqual(numel(truth_bundle.bistatic_tracks), 1);
        end

        function testCaptureTruthRetainedTracksShareGeneratorTimeline(testCase)
            fixture = testCase.applyFixture(matlab.unittest.fixtures.TemporaryFolderFixture);
            capture_fixture = SyntheticHDTVCaptureTruthTest.localCreateCaptureTruthFixture( ...
                fixture.Folder, ...
                'capture_truth_timeline_fixture');

            cfg = buildSyntheticHDTVBaselineScenarioConfig( ...
                'OutputRoot', fixture.Folder, ...
                'SeedSourcePath', capture_fixture.manifest_path, ...
                'TruthSamplePeriodS', 0.25);
            truth_bundle = helperSyntheticGenerateTruth(cfg);

            retained_target = truth_bundle.targets(1);
            retained_track = truth_bundle.bistatic_tracks(1);
            valid_mask = isfinite(retained_track.R_excess_m(:)) & ...
                isfinite(retained_track.f_D_hz(:));

            testCase.verifyEqual(retained_target.t_rel_s, truth_bundle.sample_times_s(valid_mask), AbsTol=1e-12);
            testCase.verifyEqual(numel(retained_track.t_utc), numel(truth_bundle.sample_times_s));
            testCase.verifyEqual(max(retained_target.t_rel_s), cfg.selected_truth_window_s, AbsTol=1e-12);
        end

        function testCaptureTruthGainHeuristicIsRecordedAndDeterministic(testCase)
            fixture = testCase.applyFixture(matlab.unittest.fixtures.TemporaryFolderFixture);
            capture_fixture = SyntheticHDTVCaptureTruthTest.localCreateCaptureTruthFixture( ...
                fixture.Folder, ...
                'capture_truth_gain_fixture');

            cfg = buildSyntheticHDTVBaselineScenarioConfig( ...
                'OutputRoot', fixture.Folder, ...
                'SeedSourcePath', capture_fixture.manifest_path, ...
                'TruthSamplePeriodS', 0.25);
            truth_a = helperSyntheticGenerateTruth(cfg);
            truth_b = helperSyntheticGenerateTruth(cfg);

            gains_a = [truth_a.track_metadata.echo_gain_db];
            gains_b = [truth_b.track_metadata.echo_gain_db];
            policies = string({truth_a.track_metadata.echo_gain_policy});

            testCase.verifyEqual(gains_a, gains_b, AbsTol=1e-12);
            testCase.verifyTrue(all(policies == "range_only_heuristic_v1"));
        end

