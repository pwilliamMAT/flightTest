function value = localAxisSpacing(axis_values)
axis_values = double(axis_values(:));
if numel(axis_values) < 2
    value = NaN;
    return
end
value = mean(diff(axis_values));
end

function value = localMetadataScalar(metadata, field_name, default_value)
value = default_value;
if ~isstruct(metadata) || ~isfield(metadata, field_name)
    return
end

raw_value = metadata.(field_name);
if isempty(raw_value)
    return
end

candidate = double(raw_value);
if isscalar(candidate) && isfinite(candidate)
    value = candidate;
end
end

function value = localNestedScalar(data, field_path, default_value)
value = default_value;
cursor = data;

for idx = 1 : numel(field_path)
    if ~isstruct(cursor) || ~isfield(cursor, field_path{idx})
        return
    end
    cursor = cursor.(field_path{idx});
end

if isempty(cursor)
    return
end

candidate = double(cursor);
if isscalar(candidate) && isfinite(candidate)
    value = candidate;
end
end

function txt = localPassString(tf)
if tf
    txt = 'PASS';
else
    txt = 'WARN';
end
end

function txt = localYesNo(tf)
if tf
    txt = 'yes';
else
    txt = 'no';
end
end
