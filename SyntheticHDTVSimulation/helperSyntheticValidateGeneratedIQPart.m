    rdm_before_db, ...
    range_axis_m, ...
    doppler_axis_hz, ...
    range_bin_spacing_m, ...
    doppler_bin_spacing_hz, ...
    opts)
truth_targets = truth_bundle.targets;
truth_adsb_tracks = truth_bundle.adsb_tracks;
n_targets = numel(truth_targets);
time_tolerance_s = max(eps(max(abs(double(spot_check_query_time_s)), 1)), 1e-12);
selected_indices = zeros(0, 1);

for idx = 1 : n_targets
    if idx > numel(target_summaries) || ~target_summaries(idx).present_in_dwell
        continue
    end

    track_hex = string(truth_adsb_tracks(idx).hex);
    row_mask = projected_truth_table.hex == track_hex & ...
        abs(projected_truth_table.query_time_s - double(spot_check_query_time_s)) <= time_tolerance_s;
    if ~any(row_mask)
        continue
    end

    row_idx = find(row_mask, 1, 'first');
    if ~projected_truth_table.valid(row_idx)
        continue
    end

    selected_indices(end + 1, 1) = idx; %#ok<AGROW>
    if numel(selected_indices) >= 5
        break
    end
end

n_selected = numel(selected_indices);
spot_check_targets = repmat(struct( ...
    'target_id', '', ...
    'callsign', '', ...
    'hex', '', ...
    'display_label', '', ...
    'truth_range_m', NaN, ...
    'truth_doppler_hz', NaN, ...
    'observed_range_m', NaN, ...
    'observed_doppler_hz', NaN, ...
    'range_residual_m', NaN, ...
    'doppler_residual_hz', NaN, ...
    'local_prominence_db', NaN, ...
    'pass_within_gate', false, ...
    'search_window_range_m', [NaN, NaN], ...
    'search_window_doppler_hz', [NaN, NaN]), 1, n_selected);

for write_idx = 1 : n_selected
    target_idx = selected_indices(write_idx);
    truth_target = truth_targets(target_idx);
    truth_adsb_track = truth_adsb_tracks(target_idx);
    row_mask = projected_truth_table.hex == string(truth_adsb_track.hex) & ...
        abs(projected_truth_table.query_time_s - double(spot_check_query_time_s)) <= time_tolerance_s;
    row_idx = find(row_mask, 1, 'first');

    truth_range_m = double(projected_truth_table.R_excess_m(row_idx));
    truth_doppler_hz = double(projected_truth_table.f_D_hz(row_idx));
    search_range_m = truth_range_m + [-1, 1] .* opts.RangeGateExpansionBins * range_bin_spacing_m;
    search_doppler_hz = truth_doppler_hz + [-1, 1] .* opts.DopplerGateExpansionBins * doppler_bin_spacing_hz;

    [observed_range_m, observed_doppler_hz, observed_power_db] = localFindObservedPeak( ...
        rdm_before_db, ...
        range_axis_m, ...
        doppler_axis_hz, ...
        search_range_m, ...
        search_doppler_hz);
    [local_prominence_db, ~, ~] = localEstimateTargetProminence( ...
        rdm_before_db, ...
        range_axis_m, ...
        doppler_axis_hz, ...
        search_range_m, ...
        search_doppler_hz, ...
        observed_range_m, ...
        observed_doppler_hz, ...
        observed_power_db);

    spot_check_targets(write_idx) = struct( ...
        'target_id', char(string(truth_target.target_id)), ...
        'callsign', char(string(truth_target.callsign)), ...
        'hex', char(string(truth_adsb_track.hex)), ...
        'display_label', char("Raw Spot Check: " + ...
            string(truth_target.target_id) + " (" + string(truth_target.callsign) + ")"), ...
        'truth_range_m', truth_range_m, ...
        'truth_doppler_hz', truth_doppler_hz, ...
        'observed_range_m', observed_range_m, ...
        'observed_doppler_hz', observed_doppler_hz, ...
        'range_residual_m', observed_range_m - truth_range_m, ...
        'doppler_residual_hz', observed_doppler_hz - truth_doppler_hz, ...
        'local_prominence_db', local_prominence_db, ...
        'pass_within_gate', isfinite(observed_range_m) && isfinite(observed_doppler_hz), ...
        'search_window_range_m', search_range_m, ...
        'search_window_doppler_hz', search_doppler_hz);
end

spot_check_table = localBuildSpotCheckTable(spot_check_targets);
end

