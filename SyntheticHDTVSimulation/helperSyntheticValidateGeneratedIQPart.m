function [observed_peak_range_m, observed_peak_doppler_hz, observed_peak_power_db] = localFindObservedPeak( ...
    rdm_db, range_axis_m, doppler_axis_hz, search_range_m, search_doppler_hz)
observed_peak_range_m = NaN;
observed_peak_doppler_hz = NaN;
observed_peak_power_db = NaN;

range_idx = find(range_axis_m >= search_range_m(1) & range_axis_m <= search_range_m(2));
doppler_idx = find(doppler_axis_hz >= search_doppler_hz(1) & doppler_axis_hz <= search_doppler_hz(2));
if isempty(range_idx) || isempty(doppler_idx)
    return
end

rdm_region_db = rdm_db(range_idx, doppler_idx);
[observed_peak_power_db, linear_idx] = max(rdm_region_db(:));
[range_local_idx, doppler_local_idx] = ind2sub(size(rdm_region_db), linear_idx);
observed_peak_range_m = range_axis_m(range_idx(range_local_idx));
observed_peak_doppler_hz = doppler_axis_hz(doppler_idx(doppler_local_idx));
end

function [local_prominence_db, local_background_level_db, local_background_cell_count] = ...
    localEstimateTargetProminence( ...
    rdm_db, ...
    range_axis_m, ...
    doppler_axis_hz, ...
    search_range_m, ...
    search_doppler_hz, ...
    observed_peak_range_m, ...
    observed_peak_doppler_hz, ...
    observed_peak_power_db)
% This is a local raw CAF prominence metric, not a calibrated RF SNR
% estimate. The target gate is excluded from the background estimate so
% the table reports whether a visible local peak exists near the truth.
local_prominence_db = NaN;
local_background_level_db = NaN;
local_background_cell_count = 0;

if ~isfinite(observed_peak_range_m) || ...
        ~isfinite(observed_peak_doppler_hz) || ...
        ~isfinite(observed_peak_power_db)
    return
end

target_range_idx = find(range_axis_m >= search_range_m(1) & range_axis_m <= search_range_m(2));
target_doppler_idx = find(doppler_axis_hz >= search_doppler_hz(1) & doppler_axis_hz <= search_doppler_hz(2));
if isempty(target_range_idx) || isempty(target_doppler_idx)
    return
end

range_pad_bins = max(8, numel(target_range_idx) + 4);
doppler_pad_bins = max(6, numel(target_doppler_idx) + 4);
background_range_idx = max(1, min(target_range_idx) - range_pad_bins) : ...
    min(numel(range_axis_m), max(target_range_idx) + range_pad_bins);
background_doppler_idx = max(1, min(target_doppler_idx) - doppler_pad_bins) : ...
    min(numel(doppler_axis_hz), max(target_doppler_idx) + doppler_pad_bins);

rdm_mag = 10 .^ (rdm_db(background_range_idx, background_doppler_idx) ./ 20);
background_mask = true(size(rdm_mag));
target_range_local_idx = target_range_idx - background_range_idx(1) + 1;
target_doppler_local_idx = target_doppler_idx - background_doppler_idx(1) + 1;
background_mask(target_range_local_idx, target_doppler_local_idx) = false;

background_cells = rdm_mag(background_mask);
background_cells = background_cells(isfinite(background_cells) & background_cells > 0);
if isempty(background_cells)
    return
end

background_level_mag = median(background_cells, 'omitnan');
if ~(isfinite(background_level_mag) && background_level_mag > 0)
    return
end

peak_level_mag = 10 ^ (double(observed_peak_power_db) / 20);
local_prominence_db = 20 * log10(peak_level_mag / max(background_level_mag, eps));
local_background_level_db = 20 * log10(background_level_mag + eps);
local_background_cell_count = numel(background_cells);
end

