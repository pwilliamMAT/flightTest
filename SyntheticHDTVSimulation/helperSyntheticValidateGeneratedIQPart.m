function validation_summary = helperSyntheticValidateGeneratedIQPart(session_artifact, varargin)
%HELPERSYNTHETICVALIDATEGENERATEDIQPART Validate one written synthetic IQ part against truth.
%
% Plain language:
% The synthetic workflow intentionally reuses one truth source end to end.
% User-edited waypoints define synthetic aircraft motion. That motion is
% sampled into traceability truth, converted into ADS-B-compatible structs
% for workflow compatibility, converted again into bistatic range/Doppler
% truth, and then used to synthesize delayed and Doppler-shifted echoes.
% This helper closes the loop by reading the written `.bb` file back and
% checking that the recovered measurement-space content still matches the
% same synthetic truth that drove synthesis.
%
helperSyntheticEnsureProjectPaths();
repo_root = fileparts(fileparts(mfilename('fullpath')));
analysis_folder = fullfile(repo_root, 'BistaticDataAnalysis');
original_folder = pwd;
cleanup_folder = onCleanup(@() cd(original_folder));
cd(analysis_folder);

p = inputParser;
p.FunctionName = mfilename;
addRequired(p, 'session_artifact', @(x) isstruct(x) && isscalar(x));
addParameter(p, 'PartIndex', 1, @(x) isnumeric(x) && isscalar(x) && x >= 1 && mod(x, 1) == 0);
addParameter(p, 'PlotFigures', true, @(x) islogical(x) && isscalar(x));
addParameter(p, 'PrecheckFigures', false, @(x) islogical(x) && isscalar(x));
addParameter(p, 'FigureVisibility', 'on', @(x) any(strcmpi(string(x), ["on", "off"])));
addParameter(p, 'RangeGateExpansionBins', 3, @(x) isnumeric(x) && isscalar(x) && x >= 0);
addParameter(p, 'DopplerGateExpansionBins', 2, @(x) isnumeric(x) && isscalar(x) && x >= 0);
addParameter(p, 'MaxDisplayRangeM', 30e3, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0);
addParameter(p, 'ReferenceSpectrumCorrelationMin', 0.98, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0 && x <= 1);
addParameter(p, 'SurveillanceSpectrumCorrelationMin', 0.90, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0 && x <= 1);
addParameter(p, 'DirectPathResidualMaxSamples', 0.50, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0);
addParameter(p, 'Verbose', false, @(x) islogical(x) && isscalar(x));
parse(p, session_artifact, varargin{:});
opts = p.Results;

localValidateArtifact(session_artifact);

if opts.PartIndex > numel(session_artifact.radar_files)
    error('helperSyntheticValidateGeneratedIQ:partIndexOutOfRange', ...
        'PartIndex %d exceeds the %d radar file(s) in this artifact.', ...
        opts.PartIndex, numel(session_artifact.radar_files));
end

scenario_config = session_artifact.scenario_config;
truth_bundle = session_artifact.truth_bundle;
manifest = helperLoadSessionManifest(session_artifact.manifest_path);
radar_file_path = localResolveRadarFilePath(session_artifact, opts.PartIndex);
part_start_offset_s = localResolvePartStartOffset(session_artifact, opts.PartIndex);
part_synthesis_summary = localResolvePartSynthesisSummary(session_artifact, opts.PartIndex);

integrity = localValidateBasebandIntegrity(radar_file_path, scenario_config, manifest);
validation_config = localBuildValidationConfig(integrity.header.sample_rate_hz);

% Use the same CPI duration and first-chunk dwell that the current passive
% radar processor uses, but stop after one chunk so validation stays cheap.
validation_sample_count = min( ...
    integrity.header.samples_in_file, ...
    round(validation_config.validation_dwell_s * integrity.header.sample_rate_hz));
[reference_channel, surveillance_channel, reference_cube, surveillance_cube] = loadIQData( ...
    radar_file_path, ...
    validation_sample_count, ...
    validation_config.cpi_duration_s, ...
    integrity.header.sample_rate_hz, ...
    struct('swap_channels', false, 'verbose', opts.Verbose));
[seed_waveform, ~] = helperSyntheticLoadSeedWaveform( ...
    scenario_config, ...
    validation_sample_count, ...
    part_start_offset_s);

n_slow_used = size(surveillance_cube, 2);
if n_slow_used < 1
    error('helperSyntheticValidateGeneratedIQ:noValidationCPIs', ...
        'The selected file does not contain enough samples for one validation CPI.');
end

surveillance_cube = surveillance_cube(:, 1:n_slow_used);
reference_cube = reference_cube(:, 1:n_slow_used);
validation_dwell_s = n_slow_used * validation_config.cpi_duration_s;
validation_query_time_s = part_start_offset_s + ...
    (((0 : n_slow_used - 1).' + 0.5) * validation_config.cpi_duration_s);
spot_check_query_time_s = validation_query_time_s(ceil(numel(validation_query_time_s) / 2));

[~, projected_aligned_tracks, projected_truth_table] = ...
    helperProjectADSBTruthToRangeDoppler( ...
    truth_bundle.adsb_tracks, ...
    scenario_config.tx_lla_deg_m, ...
    scenario_config.rx_lla_deg_m, ...
    double(scenario_config.center_frequency_hz), ...
    double(scenario_config.radar_epoch_utc), ...
    validation_query_time_s);

[rdm_before_db, doppler_axis_hz, range_axis_m, measured_direct_path_lag_samples] = createRDM( ...
    surveillance_cube, ...
    reference_cube, ...
    integrity.header.sample_rate_hz, ...
    validation_config.prf_hz, ...
    [], ...
    opts.Verbose);

range_bin_spacing_m = localAxisSpacing(range_axis_m);
doppler_bin_spacing_hz = localAxisSpacing(doppler_axis_hz);
direct_path_delay_samples_expected = double(scenario_config.direct_path_delay_samples);
max_lag_samples = max(500, ceil(direct_path_delay_samples_expected) + 64);
fractional_lag_summary = localMeasureFractionalLag( ...
    surveillance_channel, ...
    reference_channel, ...
    integrity.header.sample_rate_hz, ...
    max_lag_samples);

% Keep the direct-path precheck in the loop, but treat its pilot/coherence
% outputs as advisory only for this synthetic-validation pass.
precheck_summary = localRunAdvisoryPrecheck( ...
    radar_file_path, ...
    validation_config, ...
    integrity.header.part_duration_header_s, ...
    direct_path_delay_samples_expected, ...
    opts);
seed_preservation_summary = localBuildSeedPreservationSummary( ...
    seed_waveform, ...
    reference_channel, ...
    surveillance_channel, ...
    precheck_summary, ...
    opts);

[target_summaries] = localBuildTargetValidationSummaries( ...
    truth_bundle, ...
    scenario_config, ...
    projected_aligned_tracks, ...
    part_synthesis_summary, ...
    validation_query_time_s, ...
    range_axis_m, ...
    doppler_axis_hz, ...
    rdm_before_db, ...
    range_bin_spacing_m, ...
    doppler_bin_spacing_hz, ...
    opts);
[spot_check_targets, spot_check_table] = localBuildRawSpotCheckSummary( ...
    truth_bundle, ...
    projected_truth_table, ...
    target_summaries, ...
    spot_check_query_time_s, ...
    rdm_before_db, ...
    range_axis_m, ...
    doppler_axis_hz, ...
    range_bin_spacing_m, ...
    doppler_bin_spacing_hz, ...
    opts);

readiness_summary = localBuildReadinessSummary( ...
    target_summaries, ...
    validation_config, ...
    range_bin_spacing_m, ...
    doppler_bin_spacing_hz);
strength_ordering_summary = localBuildTargetStrengthOrderingSummary( ...
    target_summaries, ...
    truth_bundle, ...
    scenario_config);

direct_path_summary = struct( ...
    'configured_delay_samples', double(scenario_config.direct_path_delay_samples), ...
    'comparison_delay_samples', double(direct_path_delay_samples_expected), ...
    'measured_lag_samples_integer', double(measured_direct_path_lag_samples), ...
    'measured_lag_samples_fractional', double(fractional_lag_summary.peak_lag_samples), ...
    'residual_samples_fractional', double(fractional_lag_summary.peak_lag_samples - direct_path_delay_samples_expected), ...
    'residual_samples_integer', double(measured_direct_path_lag_samples - direct_path_delay_samples_expected), ...
    'peak_to_median_db', double(fractional_lag_summary.peak_to_median_db), ...
    'peak_to_second_db', double(fractional_lag_summary.peak_to_second_db), ...
    'max_residual_samples', double(opts.DirectPathResidualMaxSamples), ...
    'pass', abs(double(fractional_lag_summary.peak_lag_samples - direct_path_delay_samples_expected)) <= ...
        double(opts.DirectPathResidualMaxSamples), ...
    'comparison_note', 'Configured fractional direct-path delay is compared directly against a sub-sample lag estimate.');

target_echo_dataset_mode = helperSyntheticDescribeTargetEchoDatasetMode( ...
    char(string(scenario_config.signal_mode)), ...
    localResolvePartSeedEchoSourceMode(part_synthesis_summary, scenario_config));
readiness_summary.seed_preservation = seed_preservation_summary;
readiness_summary.direct_path_pass = direct_path_summary.pass;
readiness_summary.target_strength_ordering = strength_ordering_summary;
readiness_summary.target_echo_dataset_mode = target_echo_dataset_mode.mode_id;
readiness_summary.target_echo_dataset_label = target_echo_dataset_mode.label;
readiness_summary.recommended_intermediate_algorithm_test_mode = ...
    target_echo_dataset_mode.recommended_intermediate_algorithm_test_mode;
readiness_summary.comparison_reference_mode = ...
    target_echo_dataset_mode.comparison_reference_mode;
readiness_summary.failure_classes = localBuildPartFailureClasses( ...
    seed_preservation_summary, ...
    direct_path_summary, ...
    target_summaries, ...
    strength_ordering_summary);
readiness_summary.overall_pass = isempty(readiness_summary.failure_classes);

figure_handles = struct('validation', [], 'precheck', [], 'raw_spot_check', []);
if opts.PlotFigures
    figure_handles.validation = localPlotValidationFigure( ...
        session_artifact, ...
        opts.PartIndex, ...
        integrity.header.sample_rate_hz, ...
        surveillance_channel, ...
        reference_channel, ...
        rdm_before_db, ...
        range_axis_m, ...
        doppler_axis_hz, ...
        direct_path_summary, ...
        precheck_summary, ...
        target_summaries, ...
        spot_check_query_time_s, ...
        spot_check_targets, ...
        opts);
    figure_handles.raw_spot_check = figure_handles.validation;
end
if isstruct(precheck_summary) && isfield(precheck_summary, 'figure_handles')
    figure_handles.precheck = precheck_summary.figure_handles;
end

validation_summary = struct( ...
    'session_id', string(session_artifact.session_id), ...
    'part_index', double(opts.PartIndex), ...
    'radar_file_path', string(radar_file_path), ...
    'manifest_path', string(session_artifact.manifest_path), ...
    'echo_generation_model', string(part_synthesis_summary.echo_generation_model), ...
    'seed_echo_source_mode', string(part_synthesis_summary.seed_echo_source_mode), ...
    'target_echo_dataset_mode', string(target_echo_dataset_mode.mode_id), ...
    'target_echo_dataset_label', string(target_echo_dataset_mode.label), ...
    'integrity', integrity, ...
    'validation_config', validation_config, ...
    'seed_preservation', seed_preservation_summary, ...
    'direct_path', direct_path_summary, ...
    'advisory_precheck', precheck_summary, ...
    'rdm', struct( ...
        'before_db', rdm_before_db, ...
        'range_axis_m', range_axis_m, ...
        'doppler_axis_hz', doppler_axis_hz, ...
        'dwell_start_s', double(part_start_offset_s), ...
        'dwell_duration_s', double(validation_dwell_s)), ...
    'target_summaries', {target_summaries(:).'}, ...
    'spot_check_query_time_s', double(spot_check_query_time_s), ...
    'spot_check_targets', {spot_check_targets(:).'}, ...
    'spot_check_table', spot_check_table, ...
    'readiness', readiness_summary, ...
    'assumptions', struct( ...
        'direct_path_fractional_comparison', ...
            'Measured lag is compared against the configured fractional direct-path delay using parabolic interpolation.', ...
        'precheck_policy', ...
            'Pilot/coherence outputs from runDirectPathPrecheck contribute to seed-preservation evidence but are not the only gate.', ...
        'target_observation_policy', ...
            'Target placement and strength-ordering checks use the raw pre-ECA-C read-back RDM, not a clutter-mitigated detector product.', ...
        'spot_check_metric', ...
            'LocalProminenceDB in the midpoint-CPI spot-check table is a raw local-gate prominence metric for read-back consistency, not calibrated RF receive-power SNR.'), ...
    'figure_handles', figure_handles);

localPrintValidationSummary(validation_summary);
end

function localValidateArtifact(session_artifact)
required_fields = { ...
    'scenario_config', ...
    'session_id', ...
    'session_folder', ...
    'manifest_path', ...
    'radar_files', ...
    'truth_bundle'};

for idx = 1 : numel(required_fields)
    if ~isfield(session_artifact, required_fields{idx})
        error('helperSyntheticValidateGeneratedIQ:missingArtifactField', ...
            'The artifact struct is missing required field "%s".', required_fields{idx});
    end
end
end

function radar_file_path = localResolveRadarFilePath(session_artifact, part_index)
radar_rel_path = char(string(session_artifact.radar_files{part_index}));
radar_file_path = fullfile(session_artifact.session_folder, strrep(radar_rel_path, '/', filesep));
if exist(radar_file_path, 'file') ~= 2
    error('helperSyntheticValidateGeneratedIQ:missingRadarFile', ...
        'Radar file not found for validation: %s', radar_file_path);
end
end

function part_start_offset_s = localResolvePartStartOffset(session_artifact, part_index)
part_start_offset_s = 0;
if isfield(session_artifact, 'part_start_offsets_s') && ...
        numel(session_artifact.part_start_offsets_s) >= part_index
    part_start_offset_s = double(session_artifact.part_start_offsets_s(part_index));
end
end

