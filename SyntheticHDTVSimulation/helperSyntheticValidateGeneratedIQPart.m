end

function seed_echo_source_mode = localResolvePartSeedEchoSourceMode(part_synthesis_summary, scenario_config)
seed_echo_source_mode = "";
if isfield(part_synthesis_summary, 'seed_echo_source_mode') && ...
        strlength(string(part_synthesis_summary.seed_echo_source_mode)) > 0
    seed_echo_source_mode = string(part_synthesis_summary.seed_echo_source_mode);
elseif isfield(scenario_config, 'seed_echo_source_mode') && ...
        strlength(string(scenario_config.seed_echo_source_mode)) > 0
    seed_echo_source_mode = string(scenario_config.seed_echo_source_mode);
end
end

function integrity = localValidateBasebandIntegrity(radar_file_path, scenario_config, manifest)
reader = comm.BasebandFileReader(radar_file_path, 'SamplesPerFrame', 65536);
cleanup_reader = onCleanup(@() release(reader));
header_info = info(reader);
metadata = reader.Metadata;

sample_rate_hz = double(reader.SampleRate);
center_frequency_hz = double(reader.CenterFrequency);
lo_offset_hz = localMetadataScalar(metadata, 'LOOffset', NaN);
part_duration_header_s = localMetadataScalar(metadata, 'Duration_s', NaN);
recording_utc = localMetadataScalar(metadata, 'RecordingUTC', NaN);
samples_in_file = double(header_info.NumSamplesInData);

channel_count_observed = NaN;
total_samples_counted = 0;
all_finite = true;
nonzero_channels = false(1, 2);
sum_abs_sq = zeros(1, 2);
peak_abs = zeros(1, 2);
sum_diff_sq = 0;

while total_samples_counted < samples_in_file
    frame = reader();
    if isempty(frame)
        break
    end

    samples_remaining = samples_in_file - total_samples_counted;
    frame = frame(1:min(size(frame, 1), samples_remaining), :);
    frame = double(frame);
    frame_rows = size(frame, 1);
    frame_channels = size(frame, 2);
    total_samples_counted = total_samples_counted + frame_rows;

    if isnan(channel_count_observed)
        channel_count_observed = frame_channels;
    end

    all_finite = all_finite && all(isfinite(real(frame(:)))) && all(isfinite(imag(frame(:))));
    n_channels_to_check = min(frame_channels, 2);
    for ch_idx = 1 : n_channels_to_check
        channel_data = frame(:, ch_idx);
        sum_abs_sq(ch_idx) = sum_abs_sq(ch_idx) + sum(abs(channel_data) .^ 2);
        peak_abs(ch_idx) = max(peak_abs(ch_idx), max(abs(channel_data)));
        nonzero_channels(ch_idx) = nonzero_channels(ch_idx) || any(channel_data ~= 0);
    end

    if frame_channels >= 2
        sum_diff_sq = sum_diff_sq + sum(abs(frame(:, 1) - frame(:, 2)) .^ 2);
    end
end

surveillance_rms = sqrt(sum_abs_sq(1) / max(total_samples_counted, 1));
reference_rms = sqrt(sum_abs_sq(2) / max(total_samples_counted, 1));
channel_difference_rms = sqrt(sum_diff_sq / max(total_samples_counted, 1));

duration_from_samples_s = total_samples_counted / max(sample_rate_hz, eps);
duration_tolerance_s = max(1 / max(sample_rate_hz, 1), 1e-9);
sample_rate_pass = abs(sample_rate_hz - double(scenario_config.sample_rate_hz)) <= 1e-9;
center_frequency_pass = abs(center_frequency_hz - double(scenario_config.center_frequency_hz)) <= 1e-6;
lo_offset_pass = abs(lo_offset_hz - double(scenario_config.lo_offset_hz)) <= 1e-9;
duration_header_pass = abs(part_duration_header_s - double(scenario_config.part_duration_s)) <= duration_tolerance_s;
duration_samples_pass = abs(duration_from_samples_s - double(scenario_config.part_duration_s)) <= duration_tolerance_s;
channel_count_pass = (channel_count_observed == 2);
finite_pass = all_finite;
nonzero_pass = all(nonzero_channels);
channels_distinct_pass = channel_difference_rms > (1e-6 * max([surveillance_rms, reference_rms, eps]));

manifest_center_hz = localNestedScalar(manifest, {'sdr_defaults', 'center_frequency_hz'}, NaN);
manifest_sample_rate_hz = localNestedScalar(manifest, {'sdr_defaults', 'sample_rate_hz'}, NaN);
manifest_lo_offset_hz = localNestedScalar(manifest, {'sdr_defaults', 'lo_offset_hz'}, NaN);
manifest_header_center_hz = localNestedScalar(manifest, {'header_readback', 'center_frequency_hz'}, NaN);
manifest_header_sample_rate_hz = localNestedScalar(manifest, {'header_readback', 'sample_rate_hz'}, NaN);
manifest_header_lo_offset_hz = localNestedScalar(manifest, {'header_readback', 'lo_offset_hz'}, NaN);

manifest_match_pass = true;
if isfinite(manifest_center_hz)
    manifest_match_pass = manifest_match_pass && abs(manifest_center_hz - center_frequency_hz) <= 1e-6;
end
if isfinite(manifest_sample_rate_hz)
    manifest_match_pass = manifest_match_pass && abs(manifest_sample_rate_hz - sample_rate_hz) <= 1e-9;
end
if isfinite(manifest_lo_offset_hz)
    manifest_match_pass = manifest_match_pass && abs(manifest_lo_offset_hz - lo_offset_hz) <= 1e-9;
end
if isfinite(manifest_header_center_hz)
    manifest_match_pass = manifest_match_pass && abs(manifest_header_center_hz - center_frequency_hz) <= 1e-6;
end
if isfinite(manifest_header_sample_rate_hz)
    manifest_match_pass = manifest_match_pass && abs(manifest_header_sample_rate_hz - sample_rate_hz) <= 1e-9;
end
if isfinite(manifest_header_lo_offset_hz)
    manifest_match_pass = manifest_match_pass && abs(manifest_header_lo_offset_hz - lo_offset_hz) <= 1e-9;
end

overall_pass = sample_rate_pass && center_frequency_pass && lo_offset_pass && ...
    duration_header_pass && duration_samples_pass && channel_count_pass && ...
    finite_pass && nonzero_pass && channels_distinct_pass && manifest_match_pass;

integrity = struct( ...
    'overall_pass', overall_pass, ...
    'checks', struct( ...
        'sample_rate_pass', sample_rate_pass, ...
        'center_frequency_pass', center_frequency_pass, ...
        'lo_offset_pass', lo_offset_pass, ...
        'duration_header_pass', duration_header_pass, ...
        'duration_samples_pass', duration_samples_pass, ...
        'channel_count_pass', channel_count_pass, ...
        'finite_pass', finite_pass, ...
        'nonzero_pass', nonzero_pass, ...
        'channels_distinct_pass', channels_distinct_pass, ...
        'manifest_match_pass', manifest_match_pass), ...
    'header', struct( ...
        'sample_rate_hz', sample_rate_hz, ...
        'center_frequency_hz', center_frequency_hz, ...
        'lo_offset_hz', lo_offset_hz, ...
        'part_duration_header_s', part_duration_header_s, ...
        'recording_utc', recording_utc, ...
        'samples_in_file', total_samples_counted, ...
        'channel_count', channel_count_observed), ...
    'measured_duration_s', duration_from_samples_s, ...
    'surveillance', struct( ...
        'rms', surveillance_rms, ...
        'peak', peak_abs(1), ...
        'rms_dbfs', 20 * log10(surveillance_rms + eps), ...
        'peak_dbfs', 20 * log10(peak_abs(1) + eps)), ...
    'reference', struct( ...
        'rms', reference_rms, ...
        'peak', peak_abs(2), ...
        'rms_dbfs', 20 * log10(reference_rms + eps), ...
        'peak_dbfs', 20 * log10(peak_abs(2) + eps)), ...
    'channel_difference_rms', channel_difference_rms);
end

function validation_config = localBuildValidationConfig(sample_rate_hz)
% Mirror the current downstream processor dwell settings without calling
% the full pipeline. Keep this helper in sync with analyzeBistaticData.
validation_config = struct( ...
    'sample_rate_hz', double(sample_rate_hz), ...
    'cpi_duration_s', 0.5e-3, ...
    'prf_hz', 1 / 0.5e-3, ...
    'n_slow_cpi', 200, ...
    'max_nci_looks', 2, ...
    'cfar_min_range_m', 5e3, ...
    'validation_dwell_s', 200 * 0.5e-3);
end

function precheck_summary = localRunAdvisoryPrecheck( ...
    radar_file_path, validation_config, part_duration_s, expected_delay_samples, opts)
precheck_slice_s = min(double(part_duration_s), max(validation_config.validation_dwell_s, validation_config.cpi_duration_s));
max_lag_samples = max(500, double(expected_delay_samples) + 64);

try
    precheck_summary = runDirectPathPrecheck( ...
        radar_file_path, ...
        'SliceDurationS', precheck_slice_s, ...
        'CPIDurationS', validation_config.cpi_duration_s, ...
        'MaxLagSamples', max_lag_samples, ...
        'PlotFigures', opts.PrecheckFigures, ...
        'FigureVisibility', char(string(opts.FigureVisibility)), ...
        'Verbose', opts.Verbose);
    precheck_summary.policy_note = 'Pilot/coherence outputs are advisory only in this helper.';
catch ME
    precheck_summary = struct( ...
        'policy_note', 'Pilot/coherence outputs are advisory only in this helper.', ...
        'error_message', ME.message, ...
        'figure_handles', struct('reference', [], 'cross_correlation', [], 'zero_doppler', []));
end
end

function lag_summary = localMeasureFractionalLag( ...
    surveillance_channel, reference_channel, sample_rate_hz, max_lag_samples)
surveillance_channel = double(surveillance_channel(:));
reference_channel = double(reference_channel(:));
n_samples = numel(surveillance_channel);
n_fft = 2 ^ nextpow2(2 * n_samples - 1);

surveillance_channel = surveillance_channel - mean(surveillance_channel);
reference_channel = reference_channel - mean(reference_channel);
surveillance_channel = surveillance_channel ./ max(rms(surveillance_channel), eps);
reference_channel = reference_channel ./ max(rms(reference_channel), eps);

cpsd = fft(surveillance_channel, n_fft) .* conj(fft(reference_channel, n_fft));
xc_full = fftshift(ifft(cpsd ./ max(abs(cpsd), eps)));
lags_full = (-n_fft / 2 : n_fft / 2 - 1).';
lag_mask = abs(lags_full) <= max_lag_samples;
lags = double(lags_full(lag_mask));
xc_mag = abs(xc_full(lag_mask));
[peak_value, peak_idx] = max(xc_mag);

if peak_idx > 1 && peak_idx < numel(xc_mag)
    y_left = xc_mag(peak_idx - 1);
    y_mid = xc_mag(peak_idx);
    y_right = xc_mag(peak_idx + 1);
    curvature = y_left - 2 * y_mid + y_right;
    if abs(curvature) > eps
        fractional_offset = 0.5 * (y_left - y_right) / curvature;
    else
        fractional_offset = 0;
    end
else
    fractional_offset = 0;
end

guard_bins = max(2, round(0.01 * numel(lags)));
secondary_mask = true(size(xc_mag));
secondary_mask(max(1, peak_idx - guard_bins) : min(numel(xc_mag), peak_idx + guard_bins)) = false;
if any(secondary_mask)
    second_value = max(xc_mag(secondary_mask));
else
    second_value = median(xc_mag);
end

peak_lag_samples = lags(peak_idx) + fractional_offset;
peak_to_median_db = 20 * log10(peak_value / max(median(xc_mag), eps));
peak_to_second_db = 20 * log10(peak_value / max(second_value, eps));

lag_summary = struct( ...
    'peak_lag_samples', double(peak_lag_samples), ...
    'peak_lag_us', double(peak_lag_samples / sample_rate_hz * 1e6), ...
    'peak_to_median_db', double(peak_to_median_db), ...
    'peak_to_second_db', double(peak_to_second_db), ...
    'max_lag_samples', double(max_lag_samples));
end

function seed_preservation_summary = localBuildSeedPreservationSummary( ...
    seed_waveform, reference_channel, surveillance_channel, precheck_summary, opts)
correlation_sample_count = min([numel(seed_waveform), numel(reference_channel), numel(surveillance_channel), 65536]);
nfft = 4096;
[seed_psd, freq_hz] = periodogram( ...
    double(seed_waveform(1:correlation_sample_count)), [], nfft, 1, 'centered', 'power');
[reference_psd, ~] = periodogram( ...
    double(reference_channel(1:correlation_sample_count)), [], nfft, 1, 'centered', 'power');
[surveillance_psd, ~] = periodogram( ...
    double(surveillance_channel(1:correlation_sample_count)), [], nfft, 1, 'centered', 'power');

seed_psd_db = 10 * log10(seed_psd + eps);
reference_psd_db = 10 * log10(reference_psd + eps);
surveillance_psd_db = 10 * log10(surveillance_psd + eps);

reference_spectrum_correlation = corr(seed_psd_db, reference_psd_db);
surveillance_spectrum_correlation = corr(seed_psd_db, surveillance_psd_db);
reference_spectrum_pass = reference_spectrum_correlation >= opts.ReferenceSpectrumCorrelationMin;
surveillance_spectrum_pass = surveillance_spectrum_correlation >= opts.SurveillanceSpectrumCorrelationMin;
pilot_pass = isstruct(precheck_summary) && isfield(precheck_summary, 'reference_quality') && ...
    precheck_summary.reference_quality.pass;
lag_peak_pass = isstruct(precheck_summary) && isfield(precheck_summary, 'cross_correlation') && ...
    precheck_summary.cross_correlation.pass;

seed_preservation_summary = struct( ...
    'frequency_axis_normalized_hz', freq_hz, ...
    'reference_spectrum_correlation', double(reference_spectrum_correlation), ...
    'surveillance_spectrum_correlation', double(surveillance_spectrum_correlation), ...
    'reference_spectrum_correlation_min', double(opts.ReferenceSpectrumCorrelationMin), ...
    'surveillance_spectrum_correlation_min', double(opts.SurveillanceSpectrumCorrelationMin), ...
    'reference_spectrum_pass', reference_spectrum_pass, ...
    'surveillance_spectrum_pass', surveillance_spectrum_pass, ...
    'pilot_pass', pilot_pass, ...
    'lag_peak_pass', lag_peak_pass, ...
    'overall_pass', reference_spectrum_pass && surveillance_spectrum_pass && pilot_pass && lag_peak_pass);
end

function strength_ordering_summary = localBuildTargetStrengthOrderingSummary( ...
    target_summaries, truth_bundle, scenario_config)
max_pair_count = max(numel(target_summaries) * (numel(target_summaries) - 1) / 2, 0);
pair_details = repmat(struct( ...
    'target_pair', '', ...
    'expected_stronger_target', '', ...
    'expected_delta_gain_db', NaN, ...
    'observed_delta_power_db', NaN, ...
    'pass', true, ...
    'applicable', false), 1, max_pair_count);
pair_write_idx = 0;

expected_gain_map = localResolveExpectedTargetGainMap( ...
    truth_bundle, ...
    scenario_config);

for idx = 1 : numel(target_summaries)
    for jdx = idx + 1 : numel(target_summaries)
        target_a = target_summaries(idx);
        target_b = target_summaries(jdx);
        if ~target_a.present_in_dwell || ~target_b.present_in_dwell
            continue
        end
        if ~isfinite(target_a.observed_peak_power_db) || ~isfinite(target_b.observed_peak_power_db)
            continue
        end

        if ~isKey(expected_gain_map, target_a.target_id) || ...
                ~isKey(expected_gain_map, target_b.target_id)
            continue
        end

        gain_a_db = expected_gain_map(target_a.target_id);
        gain_b_db = expected_gain_map(target_b.target_id);
        gain_delta_db = gain_a_db - gain_b_db;
        if abs(gain_delta_db) < 3
            continue
        end

        expected_stronger_target = target_a.target_id;
        if gain_delta_db < 0
            expected_stronger_target = target_b.target_id;
        end

        observed_delta_power_db = target_a.observed_peak_power_db - target_b.observed_peak_power_db;
        pass = sign(observed_delta_power_db) == sign(gain_delta_db);
        pair_write_idx = pair_write_idx + 1;
        pair_details(pair_write_idx) = struct( ...
            'target_pair', char(string(target_a.target_id) + " vs " + string(target_b.target_id)), ...
            'expected_stronger_target', expected_stronger_target, ...
            'expected_delta_gain_db', double(abs(gain_delta_db)), ...
            'observed_delta_power_db', double(observed_delta_power_db), ...
            'pass', pass, ...
            'applicable', true);
    end
end

pair_details = pair_details(1:pair_write_idx);

strength_ordering_summary = struct( ...
    'n_qualified_pairs', pair_write_idx, ...
    'pass', all([pair_details.pass]) || isempty(pair_details), ...
    'pair_details', {pair_details});
end

function expected_gain_map = localResolveExpectedTargetGainMap( ...
    truth_bundle, scenario_config)
expected_gain_map = containers.Map('KeyType', 'char', 'ValueType', 'double');

if isfield(truth_bundle, 'track_metadata') && ~isempty(truth_bundle.track_metadata)
    for idx = 1 : numel(truth_bundle.track_metadata)
        track_metadata = truth_bundle.track_metadata(idx);
        if ~isfield(track_metadata, 'target_id') || ...
                strlength(string(track_metadata.target_id)) == 0
            continue
        end
        if ~isfield(track_metadata, 'echo_gain_db') || ...
                ~isfinite(double(track_metadata.echo_gain_db))
            continue
        end

        expected_gain_map(char(string(track_metadata.target_id))) = ...
            double(track_metadata.echo_gain_db);
    end
end

if ~isfield(scenario_config, 'targets') || isempty(scenario_config.targets)
    return
end

for idx = 1 : numel(scenario_config.targets)
    target_def = scenario_config.targets(idx);
    target_id = char(string(target_def.target_id));
    if isKey(expected_gain_map, target_id)
        continue
    end
    if ~isfinite(double(target_def.echo_gain_db))
        continue
    end

    expected_gain_map(target_id) = double(target_def.echo_gain_db);
end
end

function failure_classes = localBuildPartFailureClasses( ...
    seed_preservation_summary, direct_path_summary, target_summaries, ...
    strength_ordering_summary)
failure_classes = strings(0, 1);

if ~seed_preservation_summary.overall_pass
    failure_classes(end + 1, 1) = "seed_preservation_failure";
end
if ~direct_path_summary.pass
    failure_classes(end + 1, 1) = "direct_path_failure";
end
if any(arrayfun(@(target) target.present_in_dwell && ...
        (~isfinite(target.range_residual_bins) || abs(target.range_residual_bins) > 2 || ...
        ~isfinite(target.doppler_residual_bins) || abs(target.doppler_residual_bins) > 2), target_summaries))
    failure_classes(end + 1, 1) = "target_placement_failure";
end
if ~strength_ordering_summary.pass
    failure_classes(end + 1, 1) = "target_strength_ordering_failure";
end

failure_classes = unique(failure_classes, 'stable');
failure_classes = cellstr(failure_classes).';
end

function target_summaries = localBuildTargetValidationSummaries( ...
    truth_bundle, ...
    scenario_config, ...
    projected_aligned_tracks, ...
    part_synthesis_summary, ...
    ~, ...
    range_axis_m, ...
    doppler_axis_hz, ...
    rdm_raw_db, ...
    range_bin_spacing_m, ...
    doppler_bin_spacing_hz, ...
    opts)
truth_targets = truth_bundle.targets;
truth_adsb_tracks = truth_bundle.adsb_tracks;
n_targets = numel(truth_targets);
target_summaries = repmat(struct( ...
    'target_id', '', ...
    'callsign', '', ...
    'hex', '', ...
    'display_label', '', ...
    'present_in_dwell', false, ...
    'predicted_trace_time_s', zeros(0, 1), ...
    'predicted_trace_range_m', zeros(0, 1), ...
    'predicted_trace_doppler_hz', zeros(0, 1), ...
    'predicted_mid_range_m', NaN, ...
    'predicted_mid_doppler_hz', NaN, ...
    'expected_delay_samples_range', [NaN, NaN], ...
    'expected_doppler_hz_range', [NaN, NaN], ...
    'observed_peak_range_m', NaN, ...
    'observed_peak_doppler_hz', NaN, ...
    'observed_peak_power_db', NaN, ...
    'search_window_range_m', [NaN, NaN], ...
    'search_window_doppler_hz', [NaN, NaN], ...
    'range_residual_m', NaN, ...
    'doppler_residual_hz', NaN, ...
    'range_residual_bins', NaN, ...
    'doppler_residual_bins', NaN, ...
    'combined_residual_bins', NaN, ...
    'alignment_label', 'not_in_dwell'), 1, n_targets);

for idx = 1 : n_targets
    truth_target = truth_targets(idx);
    truth_adsb_track = truth_adsb_tracks(idx);
    projected_track = localFindProjectedTrack(projected_aligned_tracks, truth_adsb_track.hex);

    target_summaries(idx).target_id = char(string(truth_target.target_id));
    target_summaries(idx).callsign = char(string(truth_target.callsign));
    target_summaries(idx).hex = char(string(truth_adsb_track.hex));
    target_summaries(idx).display_label = char("Synthetic Truth: " + ...
        string(truth_target.target_id) + " (" + string(truth_target.callsign) + ")");

    if isempty(projected_track)
        continue
    end

    predicted_range_m = double(projected_track.R_excess_m(:));
    predicted_doppler_hz = double(projected_track.f_D_hz(:));
    valid_mask = isfinite(predicted_range_m) & isfinite(predicted_doppler_hz);

    if ~any(valid_mask)
        continue
    end

    predicted_trace_time_s = double(projected_track.t_abs_s(valid_mask));
    predicted_trace_range_m = predicted_range_m(valid_mask);
    predicted_trace_doppler_hz = predicted_doppler_hz(valid_mask);
    predicted_mid_idx = ceil(numel(predicted_trace_time_s) / 2);

    target_summaries(idx).present_in_dwell = true;
    target_summaries(idx).predicted_trace_time_s = predicted_trace_time_s;
    target_summaries(idx).predicted_trace_range_m = predicted_trace_range_m;
    target_summaries(idx).predicted_trace_doppler_hz = predicted_trace_doppler_hz;
    target_summaries(idx).predicted_mid_range_m = predicted_trace_range_m(predicted_mid_idx);
    target_summaries(idx).predicted_mid_doppler_hz = predicted_trace_doppler_hz(predicted_mid_idx);

    synthesis_track_summary = localFindTrackSummary(part_synthesis_summary, truth_adsb_track.hex);
    if ~isempty(synthesis_track_summary)
        target_summaries(idx).expected_delay_samples_range = synthesis_track_summary.delay_samples_range;
        target_summaries(idx).expected_doppler_hz_range = synthesis_track_summary.doppler_hz_range;
    else
        target_summaries(idx).expected_delay_samples_range = localRangeToDelayRange( ...
            predicted_trace_range_m, ...
            double(scenario_config.direct_path_delay_samples), ...
            double(scenario_config.sample_rate_hz));
        target_summaries(idx).expected_doppler_hz_range = [ ...
            min(predicted_trace_doppler_hz), ...
            max(predicted_trace_doppler_hz)];
    end

    search_range_m = [ ...
        min(predicted_trace_range_m) - opts.RangeGateExpansionBins * range_bin_spacing_m, ...
        max(predicted_trace_range_m) + opts.RangeGateExpansionBins * range_bin_spacing_m];
    search_doppler_hz = [ ...
        min(predicted_trace_doppler_hz) - opts.DopplerGateExpansionBins * doppler_bin_spacing_hz, ...
        max(predicted_trace_doppler_hz) + opts.DopplerGateExpansionBins * doppler_bin_spacing_hz];
    target_summaries(idx).search_window_range_m = search_range_m;
    target_summaries(idx).search_window_doppler_hz = search_doppler_hz;

    [observed_peak_range_m, observed_peak_doppler_hz, observed_peak_power_db] = localFindObservedPeak( ...
        rdm_raw_db, ...
        range_axis_m, ...
        doppler_axis_hz, ...
        search_range_m, ...
        search_doppler_hz);

    target_summaries(idx).observed_peak_range_m = observed_peak_range_m;
    target_summaries(idx).observed_peak_doppler_hz = observed_peak_doppler_hz;
    target_summaries(idx).observed_peak_power_db = observed_peak_power_db;

    if ~isfinite(observed_peak_range_m) || ~isfinite(observed_peak_doppler_hz)
        target_summaries(idx).alignment_label = 'no_peak_in_gate';
        continue
    end

    range_residual_trace_m = observed_peak_range_m - predicted_trace_range_m;
    doppler_residual_trace_hz = observed_peak_doppler_hz - predicted_trace_doppler_hz;
    combined_residual_trace_bins = hypot( ...
        range_residual_trace_m ./ max(range_bin_spacing_m, eps), ...
        doppler_residual_trace_hz ./ max(doppler_bin_spacing_hz, eps));

    [min_combined_residual_bins, best_match_idx] = min(combined_residual_trace_bins);
    target_summaries(idx).range_residual_m = range_residual_trace_m(best_match_idx);
    target_summaries(idx).doppler_residual_hz = doppler_residual_trace_hz(best_match_idx);
    target_summaries(idx).range_residual_bins = ...
        target_summaries(idx).range_residual_m / max(range_bin_spacing_m, eps);
    target_summaries(idx).doppler_residual_bins = ...
        target_summaries(idx).doppler_residual_hz / max(doppler_bin_spacing_hz, eps);
    target_summaries(idx).combined_residual_bins = min_combined_residual_bins;
    target_summaries(idx).alignment_label = localDescribeAlignment(min_combined_residual_bins);
end
end

