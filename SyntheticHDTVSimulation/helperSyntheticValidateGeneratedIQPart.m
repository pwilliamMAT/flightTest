function [display_range_min_km, display_range_max_km] = localResolveDisplayRangeLimitsKm( ...
    target_summaries, spot_check_targets, range_axis_m, max_display_range_m)
truth_ranges_m = zeros(0, 1);

for idx = 1 : numel(target_summaries)
    if ~target_summaries(idx).present_in_dwell
        continue
    end

    predicted_trace_range_m = double(target_summaries(idx).predicted_trace_range_m(:));
    predicted_trace_range_m = predicted_trace_range_m(isfinite(predicted_trace_range_m));
    truth_ranges_m = [truth_ranges_m; predicted_trace_range_m]; %#ok<AGROW>
end

if isempty(truth_ranges_m) && ~isempty(spot_check_targets)
    spot_check_truth_range_m = double([spot_check_targets.truth_range_m]);
    spot_check_truth_range_m = spot_check_truth_range_m(isfinite(spot_check_truth_range_m));
    truth_ranges_m = spot_check_truth_range_m(:);
end

if isempty(truth_ranges_m)
    display_range_min_km = min(double(range_axis_m)) / 1e3;
    display_range_max_km = min(max(double(range_axis_m)), double(max_display_range_m)) / 1e3;
else
    display_range_min_km = min(truth_ranges_m) / 1e3 - 10;
    display_range_max_km = max(truth_ranges_m) / 1e3 + 10;
end

if ~(isfinite(display_range_min_km) && isfinite(display_range_max_km))
    display_range_min_km = min(double(range_axis_m)) / 1e3;
    display_range_max_km = min(max(double(range_axis_m)), double(max_display_range_m)) / 1e3;
end

if display_range_max_km <= display_range_min_km
    display_range_max_km = display_range_min_km + 1;
end
end

