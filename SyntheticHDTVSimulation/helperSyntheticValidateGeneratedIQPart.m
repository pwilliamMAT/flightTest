function [minimum_range_separation_bins, minimum_doppler_separation_bins, minimum_combined_separation_bins] = ...
    localMinimumPairSeparation(target_a, target_b, range_bin_spacing_m, doppler_bin_spacing_hz)
common_time_s = intersect(target_a.predicted_trace_time_s, target_b.predicted_trace_time_s);
if isempty(common_time_s)
    minimum_range_separation_bins = NaN;
    minimum_doppler_separation_bins = NaN;
    minimum_combined_separation_bins = NaN;
    return
end

range_a_m = interp1(target_a.predicted_trace_time_s, target_a.predicted_trace_range_m, common_time_s, 'linear', NaN);
range_b_m = interp1(target_b.predicted_trace_time_s, target_b.predicted_trace_range_m, common_time_s, 'linear', NaN);
doppler_a_hz = interp1(target_a.predicted_trace_time_s, target_a.predicted_trace_doppler_hz, common_time_s, 'linear', NaN);
doppler_b_hz = interp1(target_b.predicted_trace_time_s, target_b.predicted_trace_doppler_hz, common_time_s, 'linear', NaN);

valid_mask = isfinite(range_a_m) & isfinite(range_b_m) & isfinite(doppler_a_hz) & isfinite(doppler_b_hz);
if ~any(valid_mask)
    minimum_range_separation_bins = NaN;
    minimum_doppler_separation_bins = NaN;
    minimum_combined_separation_bins = NaN;
    return
end

range_delta_bins = abs(range_a_m(valid_mask) - range_b_m(valid_mask)) ./ max(range_bin_spacing_m, eps);
doppler_delta_bins = abs(doppler_a_hz(valid_mask) - doppler_b_hz(valid_mask)) ./ max(doppler_bin_spacing_hz, eps);
combined_delta_bins = hypot(range_delta_bins, doppler_delta_bins);

minimum_range_separation_bins = min(range_delta_bins);
minimum_doppler_separation_bins = min(doppler_delta_bins);
minimum_combined_separation_bins = min(combined_delta_bins);
end

