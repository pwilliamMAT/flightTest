part_synthesis_summary = struct( ...
    'part_idx', double(part_index), ...
    'part_start_offset_s', NaN, ...
    'signal_mode', '', ...
    'seed_echo_source_mode', '', ...
    'track_summaries', {repmat(struct( ...
        'hex', '', ...
        'callsign', '', ...
        'echo_gain_db', NaN, ...
        'valid_samples', 0, ...
        'delay_samples_range', [NaN, NaN], ...
        'doppler_hz_range', [NaN, NaN]), 1, 0)});

if isfield(session_artifact, 'part_synthesis_summaries') && ...
        numel(session_artifact.part_synthesis_summaries) >= part_index && ...
        ~isempty(session_artifact.part_synthesis_summaries{part_index})
    part_synthesis_summary = session_artifact.part_synthesis_summaries{part_index};
