frozenPositionError = frozenPredictedNextState(:, positionColumns) - dataset.nextState(:, positionColumns);
frozenVelocityError = frozenPredictedNextState(:, velocityColumns) - dataset.nextState(:, velocityColumns);

pairErrorTable = table( ...
    (1:pairCount).', ...
    dataset.metadata.sessionID, ...
    dataset.metadata.sourceFile, ...
    dataset.metadata.hex, ...
    dataset.metadata.callsign, ...
    dataset.metadata.split, ...
    dataset.metadata.timeUtcK, ...
    dataset.metadata.timeUtcNext, ...
    dataset.dtSeconds, ...
    maneuverPairTable.maneuverClass, ...
    maneuverPairTable.verticalStatus, ...
    maneuverPairTable.dtRegime, ...
    vecnorm(constvelPositionError, 2, 2), ...
    vecnorm(constvelVelocityError, 2, 2), ...
    vecnorm(frozenPositionError, 2, 2), ...
    vecnorm(frozenVelocityError, 2, 2), ...
    'VariableNames', [ ...
        "pairIndex", ...
        "sessionID", ...
        "sourceFile", ...
        "hex", ...
        "callsign", ...
        "split", ...
        "timeUtcK", ...
        "timeUtcNext", ...
        "dtSeconds", ...
        "maneuverClass", ...
        "verticalStatus", ...
        "dtRegime", ...
        "constvelPositionErrorMeters", ...
        "constvelVelocityErrorMetersPerSecond", ...
        "frozenStage3APositionErrorMeters", ...
        "frozenStage3AVelocityErrorMetersPerSecond"]);

end

function metricComparisonTable = localBuildMetricComparisonTable(aggregate)
%LOCALBUILDMETRICCOMPARISONTABLE Add interpretation to aggregate metrics.

interpretation = strings(height(aggregate), 1);

for rowIdx = 1:height(aggregate)
    methodName = string(aggregate.method(rowIdx));

    if methodName == "constvel baseline"
        interpretation(rowIdx) = "Native Sensor Fusion constant-velocity prediction on the exact Stage 3B samples.";
    else
        interpretation(rowIdx) = "Frozen Stage 3A delta-target MLP reconstructed as previousState + predictedDelta.";
    end
end

metricComparisonTable = table( ...
    aggregate.method, ...
    aggregate.sampleCount, ...
    aggregate.positionRMSEMeters, ...
    aggregate.velocityRMSEMetersPerSecond, ...
    aggregate.positionMedianErrorMeters, ...
    aggregate.positionP95ErrorMeters, ...
    interpretation, ...
    'VariableNames', [ ...
        "method", ...
        "sampleCount", ...
        "positionRMSEMeters", ...
        "velocityRMSEMetersPerSecond", ...
        "positionMedianErrorMeters", ...
        "positionP95ErrorMeters", ...
        "interpretation"]);

end

function trackSummary = localBuildTrackSummary(pairErrorTable)
%LOCALBUILDTRACKSUMMARY Summarize coverage and error by aircraft track.

trackInput = table( ...
    pairErrorTable.sessionID, ...
    pairErrorTable.hex, ...
    pairErrorTable.callsign, ...
    pairErrorTable.dtSeconds, ...
    double(string(pairErrorTable.maneuverClass) == "constvel_like"), ...
    double(string(pairErrorTable.maneuverClass) == "constacc_like"), ...
    double(string(pairErrorTable.maneuverClass) == "constturn_like"), ...
    double(string(pairErrorTable.maneuverClass) == "mixed_or_sparse"), ...
    double(string(pairErrorTable.verticalStatus) == "climb"), ...
    double(string(pairErrorTable.verticalStatus) == "descent"), ...
    double(string(pairErrorTable.dtRegime) == "sparse_update"), ...
    pairErrorTable.constvelPositionErrorMeters, ...
    pairErrorTable.frozenStage3APositionErrorMeters, ...
    'VariableNames', [ ...
        "sessionID", ...
        "hex", ...
        "callsign", ...
        "dtSeconds", ...
        "constvelLikePairCount", ...
        "constaccLikePairCount", ...
        "constturnLikePairCount", ...
        "mixedOrSparsePairCount", ...
        "climbPairCount", ...
        "descentPairCount", ...
        "sparseUpdatePairCount", ...
        "constvelPositionErrorMeters", ...
        "frozenStage3APositionErrorMeters"]);

[groupID, sessionID, hex, callsign] = findgroups( ...
    trackInput.sessionID, ...
    trackInput.hex, ...
    trackInput.callsign);

pairCount = splitapply(@numel, trackInput.dtSeconds, groupID);
medianDtSeconds = splitapply(@median, trackInput.dtSeconds, groupID);
constvelLikePairCount = splitapply(@sum, trackInput.constvelLikePairCount, groupID);
constaccLikePairCount = splitapply(@sum, trackInput.constaccLikePairCount, groupID);
constturnLikePairCount = splitapply(@sum, trackInput.constturnLikePairCount, groupID);
mixedOrSparsePairCount = splitapply(@sum, trackInput.mixedOrSparsePairCount, groupID);
climbPairCount = splitapply(@sum, trackInput.climbPairCount, groupID);
descentPairCount = splitapply(@sum, trackInput.descentPairCount, groupID);
sparseUpdatePairCount = splitapply(@sum, trackInput.sparseUpdatePairCount, groupID);
constvelPositionRMSEMeters = splitapply(@localRmse, trackInput.constvelPositionErrorMeters, groupID);
frozenStage3APositionRMSEMeters = splitapply(@localRmse, trackInput.frozenStage3APositionErrorMeters, groupID);

trackSummary = table( ...
    sessionID, ...
    hex, ...
    callsign, ...
    pairCount, ...
    medianDtSeconds, ...
    constvelLikePairCount, ...
    constaccLikePairCount, ...
    constturnLikePairCount, ...
