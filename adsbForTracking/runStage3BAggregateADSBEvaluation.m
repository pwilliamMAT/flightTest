stage3BSummary.labelSummary = labelSummary;
stage3BSummary.featureData = featureData;
stage3BSummary.predictions = predictions;
stage3BSummary.metrics = metrics;
stage3BSummary.metricComparisonTable = metricComparisonTable;
stage3BSummary.pairErrorTable = pairErrorTable;
stage3BSummary.trackSummary = trackSummary;
stage3BSummary.selectedTrack = selectedTrack;
stage3BSummary.dataReadiness = dataReadiness;
stage3BSummary.verificationTable = verificationTable;
stage3BSummary.figurePaths = struct();

if config.CreatePlots
    stage3BSummary.figurePaths = helperWriteStage3BFigures( ...
        config.OutputFolder, ...
        stage3BSummary);
end

if config.CreateGlobeSnapshot
    stage3BSummary = localTryWriteGlobeSnapshot(stage3BSummary);
end

helperWriteStage3BReport(config.ReportPath, stage3BSummary);
localSaveArtifact(stage3BSummary);

if config.Verbose
    localPrintSummary(stage3BSummary);
end

end

