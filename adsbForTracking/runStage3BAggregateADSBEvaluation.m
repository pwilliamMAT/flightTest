function metricTable = localScoreBothByGroup(groupValues, groupVariableName, pairErrorTable)
%LOCALSCOREBOTHBYGROUP Score constvel and frozen MLP for group values.

groupValues = string(groupValues(:));
groupNames = unique(groupValues, "stable");
metricTable = table();

for groupIdx = 1:numel(groupNames)
    groupName = groupNames(groupIdx);
    groupMask = groupValues == groupName;
    constvelRow = localBuildMetricRow( ...
        groupMask, ...
        groupVariableName, ...
        groupName, ...
        "constvel baseline", ...
        pairErrorTable.constvelPositionErrorMeters, ...
        pairErrorTable.constvelVelocityErrorMetersPerSecond);
    mlpRow = localBuildMetricRow( ...
        groupMask, ...
        groupVariableName, ...
        groupName, ...
        "Frozen Stage 3A delta MLP", ...
        pairErrorTable.frozenStage3APositionErrorMeters, ...
        pairErrorTable.frozenStage3AVelocityErrorMetersPerSecond);
    metricTable = [metricTable; constvelRow; mlpRow]; %#ok<AGROW>
end

end

function metricRow = localBuildMetricRow(mask, groupVariableName, groupName, methodName, positionErrorMeters, velocityErrorMetersPerSecond)
%LOCALBUILDMETRICROW Return one physical-unit metric row.

positionError = positionErrorMeters(mask);
velocityError = velocityErrorMetersPerSecond(mask);
sampleCount = numel(positionError);

metricRow = table( ...
    string(methodName), ...
    string(groupVariableName), ...
    string(groupName), ...
    sampleCount, ...
    sqrt(mean(positionError .^ 2, "omitnan")), ...
    sqrt(mean(velocityError .^ 2, "omitnan")), ...
    median(positionError, "omitnan"), ...
    median(velocityError, "omitnan"), ...
    prctile(positionError, 95), ...
    prctile(velocityError, 95), ...
    'VariableNames', [ ...
        "method", ...
        "groupVariable", ...
        "groupName", ...
        "sampleCount", ...
        "positionRMSEMeters", ...
        "velocityRMSEMetersPerSecond", ...
        "positionMedianErrorMeters", ...
        "velocityMedianErrorMetersPerSecond", ...
        "positionP95ErrorMeters", ...
        "velocityP95ErrorMetersPerSecond"]);

end

function pairErrorTable = localBuildPairErrorTable(dataset, maneuverPairTable, constvelPredictedNextState, frozenPredictedNextState)
