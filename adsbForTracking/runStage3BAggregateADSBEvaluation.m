if isempty(sourceFiles)
    error("Stage3B:NoSourceFiles", ...
        "No local ADS-B truth files were found for Stage 3B aggregation.");
end

end

function dataset = localBuildOrLoadAggregateDataset(config, sourceFiles)
%LOCALBUILDORLOADAGGREGATEDATASET Build the Stage 3B derived dataset.

if ~config.RebuildAggregateDataset && exist(config.AggregateDatasetPath, "file") == 2
    dataset = localLoadAggregateDataset(config.AggregateDatasetPath);
    return;
end

try
    dataset = buildLocalADSBStatePairDataset( ...
        "SourceFiles", sourceFiles, ...
        "SearchRoot", config.SearchRoot, ...
        "ParserFolder", config.ParserFolder, ...
        "OutputPath", config.AggregateDatasetPath, ...
        "ReportPath", config.AggregateDatasetReportPath, ...
        "SmokeTest", false, ...
        "Verbose", config.Verbose);
