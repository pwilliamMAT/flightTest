function stage3BSummary = runStage3BAggregateADSBEvaluation(varargin)
%RUNSTAGE3BAGGREGATEADSBEVALUATION Compare frozen Stage 3A MLP and constvel.
% Stage 3B aggregates the local ADS-B truth currently available, rebuilds a
% derived state-pair dataset under artifacts/stage3B, and evaluates the
% frozen Stage 3A network without retraining.

projectRoot = fileparts(mfilename("fullpath"));
flightTestRoot = fileparts(projectRoot);
defaultSearchRoot = fullfile(flightTestRoot, "BistaticDataAnalysis", "captures");
defaultParserFolder = fullfile(flightTestRoot, "BistaticDataAnalysis");
defaultOutputFolder = fullfile(projectRoot, "artifacts", "stage3B");
defaultAggregateDatasetPath = fullfile(defaultOutputFolder, "localADSBAggregateStatePairDataset.mat");
defaultAggregateDatasetReportPath = fullfile(defaultOutputFolder, "stage3BAggregateStatePairDatasetSummary.md");
defaultStage3AArtifactPath = fullfile(projectRoot, "artifacts", "stage3", "localADSBMLPStage3Training.mat");
defaultArtifactPath = fullfile(defaultOutputFolder, "localADSBAggregateStage3BEvaluation.mat");
defaultReportPath = fullfile(defaultOutputFolder, "stage3BAggregateADSBEvaluationReport.md");

parser = inputParser;
parser.FunctionName = mfilename;
addParameter(parser, "ProjectRoot", projectRoot);
addParameter(parser, "SourceFiles", strings(0, 1));
addParameter(parser, "SearchRoot", defaultSearchRoot);
addParameter(parser, "ParserFolder", defaultParserFolder);
addParameter(parser, "OutputFolder", defaultOutputFolder);
addParameter(parser, "AggregateDatasetPath", defaultAggregateDatasetPath);
addParameter(parser, "AggregateDatasetReportPath", defaultAggregateDatasetReportPath);
addParameter(parser, "Stage3AArtifactPath", defaultStage3AArtifactPath);
addParameter(parser, "ArtifactPath", defaultArtifactPath);
addParameter(parser, "ReportPath", defaultReportPath);
addParameter(parser, "RebuildAggregateDataset", true);
addParameter(parser, "CreatePlots", true);
addParameter(parser, "CreateGlobeSnapshot", false);
addParameter(parser, "MinimumSessionsForRetraining", 3);
addParameter(parser, "MinimumSourceFilesForRetraining", 3);
addParameter(parser, "MinimumAircraftForRetraining", 20);
addParameter(parser, "MinimumNonConstvelManeuverClasses", 2);
addParameter(parser, "MinimumConstaccPairs", 100);
addParameter(parser, "MinimumConstturnPairs", 100);
addParameter(parser, "MinimumSparseUpdatePairs", 100);
addParameter(parser, "MinimumClimbPairs", 100);
addParameter(parser, "MinimumDescentPairs", 100);
addParameter(parser, "Verbose", true);
parse(parser, varargin{:});

config = localBuildConfig(parser.Results);
localValidateConfig(config);

if config.Verbose
    fprintf("Stage 3B aggregate ADS-B evaluation\n");
    fprintf("Search root:\t%s\n", config.SearchRoot);
    fprintf("Stage 3A artifact:\t%s\n", config.Stage3AArtifactPath);
end

sourceFiles = localResolveSourceFiles(config);
dataset = localBuildOrLoadAggregateDataset(config, sourceFiles);
inventoryTable = localBuildInventoryTable(sourceFiles, dataset.sourceManifest);

stage3A = localLoadStage3AArtifact(config.Stage3AArtifactPath);

constvelBaseline = helperScoreConstVelBaseline( ...
    dataset.previousState, ...
    dataset.nextState, ...
    dataset.dtSeconds);
constvelPredictedNextState = constvelBaseline.predictedState;

[maneuverPairTable, labelSummary] = helperAssignADSBManeuverLabels( ...
    dataset.previousState, ...
    dataset.nextState, ...
    dataset.dtSeconds);

featureData = localBuildFrozenFeatureData( ...
    dataset, ...
    constvelPredictedNextState, ...
    stage3A.normalization);
frozenPrediction = localPredictFrozenStage3A( ...
    stage3A.net, ...
    featureData.featuresNormalized, ...
    dataset.previousState, ...
    stage3A.normalization.target);
frozenStage3APredictedNextState = frozenPrediction.predictedNextState;

constvelMetrics = helperScoreStage3APredictions( ...
    dataset.nextState, ...
    constvelPredictedNextState, ...
    dataset.metadata, ...
    maneuverPairTable, ...
    "constvel baseline");
frozenStage3AMetrics = helperScoreStage3APredictions( ...
    dataset.nextState, ...
    frozenStage3APredictedNextState, ...
    dataset.metadata, ...
    maneuverPairTable, ...
    "Frozen Stage 3A delta MLP");

pairErrorTable = localBuildPairErrorTable( ...
    dataset, ...
    maneuverPairTable, ...
    constvelPredictedNextState, ...
    frozenStage3APredictedNextState);
metrics = localBuildMetricsStruct( ...
    dataset, ...
    pairErrorTable, ...
    constvelMetrics, ...
    frozenStage3AMetrics);
metricComparisonTable = localBuildMetricComparisonTable(metrics.aggregate);
trackSummary = localBuildTrackSummary(pairErrorTable);
selectedTrack = localSelectRepresentativeTrack(dataset.metadata, trackSummary);
dataReadiness = localBuildDataReadinessAssessment( ...
    config, ...
    dataset, ...
    inventoryTable, ...
    labelSummary, ...
    trackSummary);
verificationTable = localBuildVerificationTable( ...
    dataset, ...
    frozenPrediction, ...
    metrics);

predictions = struct();
predictions.constvelPredictedNextState = constvelPredictedNextState;
predictions.frozenStage3APredictedNextState = frozenStage3APredictedNextState;
predictions.frozenStage3APredictedDeltaNormalized = frozenPrediction.predictedDeltaNormalized;
predictions.frozenStage3APredictedDelta = frozenPrediction.predictedDelta;
predictions.reconstructedNextState = frozenPrediction.reconstructedNextState;

stage3BSummary = struct();
stage3BSummary.generatedAt = datetime("now", "TimeZone", "UTC");
stage3BSummary.projectRoot = config.ProjectRoot;
stage3BSummary.outputFolder = config.OutputFolder;
stage3BSummary.aggregateDatasetPath = config.AggregateDatasetPath;
stage3BSummary.aggregateDatasetReportPath = config.AggregateDatasetReportPath;
stage3BSummary.stage3AArtifactPath = config.Stage3AArtifactPath;
stage3BSummary.artifactPath = config.ArtifactPath;
stage3BSummary.reportPath = config.ReportPath;
stage3BSummary.config = config;
stage3BSummary.configTable = localBuildConfigTable(config);
stage3BSummary.inventoryTable = inventoryTable;
stage3BSummary.sourceManifest = dataset.sourceManifest;
stage3BSummary.buildSummary = dataset.buildSummary;
stage3BSummary.stateOrder = dataset.stateOrder;
stage3BSummary.previousState = dataset.previousState;
stage3BSummary.nextState = dataset.nextState;
stage3BSummary.dtSeconds = dataset.dtSeconds;
stage3BSummary.previousCovarianceDiag = dataset.previousCovarianceDiag;
stage3BSummary.metadata = dataset.metadata;
