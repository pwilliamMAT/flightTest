function localValidateConfig(config)
%LOCALVALIDATECONFIG Validate Stage 3B scalar options.

if strlength(config.OutputFolder) == 0
    error("Stage3B:MissingOutputFolder", ...
        "OutputFolder must not be empty.");
end

if exist(config.Stage3AArtifactPath, "file") ~= 2
    error("Stage3B:MissingStage3AArtifact", ...
        "Stage 3A artifact was not found: %s", config.Stage3AArtifactPath);
end

numericFields = [ ...
    "MinimumSessionsForRetraining", ...
    "MinimumSourceFilesForRetraining", ...
    "MinimumAircraftForRetraining", ...
    "MinimumNonConstvelManeuverClasses", ...
    "MinimumConstaccPairs", ...
    "MinimumConstturnPairs", ...
    "MinimumSparseUpdatePairs", ...
    "MinimumClimbPairs", ...
    "MinimumDescentPairs"];

for fieldIdx = 1:numel(numericFields)
    fieldName = numericFields(fieldIdx);
    validateattributes(config.(fieldName), {'numeric'}, {'scalar', 'real', 'finite', 'nonnegative'}, ...
        mfilename, fieldName);
end

end

function sourceFiles = localResolveSourceFiles(config)
