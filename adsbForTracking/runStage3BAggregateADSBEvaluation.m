    error("Stage3B:AggregateDatasetBuildFailed", ...
        "Failed to build Stage 3B aggregate dataset: %s", err.message);
end

end

function dataset = localLoadAggregateDataset(datasetPath)
%LOCALLOADAGGREGATEDATASET Load a saved Stage 2B-compatible dataset.

try
    loaded = load(datasetPath, "dataset");
catch err
    error("Stage3B:AggregateDatasetLoadFailed", ...
        "Failed to load Stage 3B aggregate dataset: %s", err.message);
end

if ~isfield(loaded, "dataset")
    error("Stage3B:MissingAggregateDataset", ...
        "The aggregate dataset artifact does not contain the variable dataset.");
end

dataset = loaded.dataset;

end

function inventoryTable = localBuildInventoryTable(sourceFiles, sourceManifest)
%LOCALBUILDINVENTORYTABLE Record every discovered source file.

sourceFiles = string(sourceFiles(:));
fileExists = false(numel(sourceFiles), 1);
fileSizeBytes = NaN(numel(sourceFiles), 1);
modifiedTime = NaT(numel(sourceFiles), 1);

for fileIdx = 1:numel(sourceFiles)
    fileInfo = dir(sourceFiles(fileIdx));

    if ~isempty(fileInfo)
        fileExists(fileIdx) = true;
        fileSizeBytes(fileIdx) = fileInfo.bytes;
        modifiedTime(fileIdx) = datetime(fileInfo.datenum, "ConvertFrom", "datenum");
    end
end

manifestSourceFiles = string(sourceManifest.sourceFile);
usedInDataset = ismember(sourceFiles, manifestSourceFiles(sourceManifest.parseStatus == "parsed"));
usablePairCount = zeros(numel(sourceFiles), 1);
parseStatus = strings(numel(sourceFiles), 1);
sessionID = strings(numel(sourceFiles), 1);

for fileIdx = 1:numel(sourceFiles)
    manifestIdx = find(manifestSourceFiles == sourceFiles(fileIdx), 1, "first");

    if isempty(manifestIdx)
        parseStatus(fileIdx) = "not_in_manifest";
        continue;
    end

    parseStatus(fileIdx) = string(sourceManifest.parseStatus(manifestIdx));
    usablePairCount(fileIdx) = sourceManifest.usablePairCount(manifestIdx);
    sessionID(fileIdx) = string(sourceManifest.sessionID(manifestIdx));
end

inventoryTable = table( ...
    sourceFiles, ...
    fileExists, ...
    fileSizeBytes, ...
    modifiedTime, ...
    parseStatus, ...
    usedInDataset, ...
    usablePairCount, ...
    sessionID, ...
    'VariableNames', [ ...
        "sourceFile", ...
        "fileExists", ...
        "fileSizeBytes", ...
        "modifiedTime", ...
        "parseStatus", ...
        "usedInDataset", ...
        "usablePairCount", ...
        "sessionID"]);

end

function stage3A = localLoadStage3AArtifact(stage3AArtifactPath)
%LOCALLOADSTAGE3AARTIFACT Load the frozen Stage 3A network and transforms.

try
    loaded = load(stage3AArtifactPath, ...
        "net", ...
        "normalization", ...
        "stage3Summary");
catch err
    error("Stage3B:Stage3ALoadFailed", ...
        "Failed to load Stage 3A artifact: %s", err.message);
end

requiredFields = ["net", "normalization", "stage3Summary"];

for fieldIdx = 1:numel(requiredFields)
    fieldName = requiredFields(fieldIdx);

    if ~isfield(loaded, fieldName)
        error("Stage3B:MissingStage3AField", ...
            "The Stage 3A artifact is missing required variable: %s", fieldName);
    end
end

if isempty(loaded.net)
    error("Stage3B:EmptyStage3ANetwork", ...
        "The Stage 3A artifact does not contain a trained network.");
end

stage3A = loaded;

end

function featureData = localBuildFrozenFeatureData(dataset, constvelPredictedNextState, normalization)
%LOCALBUILDFROZENFEATUREDATA Build Stage 3A features using saved scaling.

featureSets = helperBuildStage3AFeatures( ...
    dataset.previousState, ...
    dataset.previousCovarianceDiag, ...
    dataset.dtSeconds, ...
    constvelPredictedNextState, ...
    string(dataset.metadata.split));
featureSet = featureSets.physics;
savedNormalization = normalization.physicsFeatures;
featureNames = string(featureSet.featureNames(:));
savedFeatureNames = localSavedFeatureNames(savedNormalization, featureNames);

if numel(featureNames) ~= numel(savedFeatureNames) || any(featureNames ~= savedFeatureNames)
    error("Stage3B:FeatureContractMismatch", ...
        "Stage 3B physics feature names do not match the saved Stage 3A normalization.");
end

featureMean = double(savedNormalization.featureMean);
featureStd = double(savedNormalization.featureStd);
featuresNormalized = (featureSet.features - featureMean) ./ featureStd;

featureData = struct();
featureData.featureMode = featureSet.featureMode;
featureData.featureNames = featureNames;
featureData.features = featureSet.features;
featureData.featuresNormalized = featuresNormalized;
featureData.savedNormalization = savedNormalization;
featureData.recomputedNormalization = featureSet.normalization;
featureData.excludedDefaultFeatures = featureSets.excludedDefaultFeatures;

end

function featureNames = localSavedFeatureNames(savedNormalization, fallbackFeatureNames)
%LOCALSAVEDFEATURENAMES Recover saved feature names if present.

if isfield(savedNormalization, "featureNames")
    featureNames = string(savedNormalization.featureNames(:));
else
    featureNames = string(fallbackFeatureNames(:));
end

end

function prediction = localPredictFrozenStage3A(net, featuresNormalized, previousState, targetNormalization)
%LOCALPREDICTFROZENSTAGE3A Run frozen MLP inference and reconstruct state.

predictedDeltaNormalized = minibatchpredict(net, featuresNormalized);
predictedDeltaNormalized = double(gather(extractdata(predictedDeltaNormalized)));

if size(predictedDeltaNormalized, 1) ~= size(featuresNormalized, 1) && ...
        size(predictedDeltaNormalized, 2) == size(featuresNormalized, 1)
    predictedDeltaNormalized = predictedDeltaNormalized.';
end

if size(predictedDeltaNormalized, 2) > 6
    predictedDeltaNormalized = predictedDeltaNormalized(:, 1:6);
end

if size(predictedDeltaNormalized, 1) ~= size(featuresNormalized, 1) || ...
        size(predictedDeltaNormalized, 2) ~= 6
    error("Stage3B:PredictionShapeMismatch", ...
        "Frozen Stage 3A predictions must be N-by-6 after inference.");
end

predictedDelta = predictedDeltaNormalized .* targetNormalization.targetStd + ...
    targetNormalization.targetMean;
predictedNextState = previousState + predictedDelta;

prediction = struct();
prediction.predictedDeltaNormalized = predictedDeltaNormalized;
prediction.predictedDelta = predictedDelta;
prediction.predictedNextState = predictedNextState;
prediction.reconstructedNextState = previousState + predictedDelta;

end

