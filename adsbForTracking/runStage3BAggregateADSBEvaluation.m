function selectedTrack = localSelectRepresentativeTrack(metadata, trackSummary)
%LOCALSELECTREPRESENTATIVETRACK Pick one readable trajectory for plots.

if isempty(trackSummary) || height(trackSummary) == 0
    rows = (1:min(80, height(metadata))).';
    selectedTrack = struct("sessionID", "", "hex", "", "rows", rows);
    return;
end

constvelShare = trackSummary.constvelLikePairCount ./ trackSummary.pairCount;
candidateMask = trackSummary.pairCount >= 40 & constvelShare >= 0.70;

if any(candidateMask)
    candidateTable = trackSummary(candidateMask, :);
else
    candidateTable = trackSummary;
end

[~, bestIdx] = min(candidateTable.constvelPositionRMSEMeters);
sessionID = string(candidateTable.sessionID(bestIdx));
trackHex = string(candidateTable.hex(bestIdx));
rows = find(string(metadata.sessionID) == sessionID & string(metadata.hex) == trackHex);

if isempty(rows)
    rows = (1:min(80, height(metadata))).';
else
    [~, sortIdx] = sort(metadata.timeUtcNext(rows));
    rows = rows(sortIdx);
    rows = rows(1:min(80, numel(rows)));
end

selectedTrack = struct();
selectedTrack.sessionID = sessionID;
selectedTrack.hex = trackHex;
selectedTrack.rows = rows(:);

end

function dataReadiness = localBuildDataReadinessAssessment(config, dataset, inventoryTable, labelSummary, trackSummary)
%LOCALBUILDDATAREADINESSASSESSMENT Gate future training on data diversity.

sessionCount = numel(unique(string(dataset.metadata.sessionID)));
sourceFileCount = sum(inventoryTable.usedInDataset);
aircraftCount = height(trackSummary);
constaccCount = localLookupCount(labelSummary.countsByManeuverClass, "maneuverClass", "constacc_like");
constturnCount = localLookupCount(labelSummary.countsByManeuverClass, "maneuverClass", "constturn_like");
sparseUpdateCount = localLookupCount(labelSummary.countsByDtRegime, "dtRegime", "sparse_update");
climbCount = localLookupCount(labelSummary.countsByVerticalStatus, "verticalStatus", "climb");
descentCount = localLookupCount(labelSummary.countsByVerticalStatus, "verticalStatus", "descent");
nonConstvelClassCount = localCountNonConstvelManeuverClasses(labelSummary.countsByManeuverClass);

gateName = [ ...
    "distinct ADS-B sessions"; ...
    "local truth files used"; ...
    "distinct aircraft tracks"; ...
    "non-constvel maneuver classes"; ...
    "constacc-like pairs"; ...
    "constturn-like pairs"; ...
    "sparse-update pairs"; ...
    "climb pairs"; ...
    "descent pairs"];
observedValue = [ ...
    sessionCount; ...
    sourceFileCount; ...
    aircraftCount; ...
    nonConstvelClassCount; ...
    constaccCount; ...
    constturnCount; ...
    sparseUpdateCount; ...
    climbCount; ...
    descentCount];
requiredValue = [ ...
    config.MinimumSessionsForRetraining; ...
    config.MinimumSourceFilesForRetraining; ...
    config.MinimumAircraftForRetraining; ...
    config.MinimumNonConstvelManeuverClasses; ...
    config.MinimumConstaccPairs; ...
    config.MinimumConstturnPairs; ...
    config.MinimumSparseUpdatePairs; ...
    config.MinimumClimbPairs; ...
    config.MinimumDescentPairs];
passed = observedValue >= requiredValue;
details = localBuildGateDetails(observedValue, requiredValue, passed);

gateTable = table( ...
    gateName, ...
    observedValue, ...
    requiredValue, ...
    passed, ...
    details, ...
    'VariableNames', [ ...
        "gate", ...
        "observedValue", ...
        "requiredValue", ...
        "passed", ...
        "details"]);

isReadyForRetraining = all(passed);
recommendation = localBuildReadinessRecommendation( ...
    isReadyForRetraining, ...
    sessionCount, ...
    sourceFileCount, ...
    aircraftCount, ...
    constturnCount, ...
    sparseUpdateCount);

dataReadiness = struct();
dataReadiness.isReadyForRetraining = isReadyForRetraining;
dataReadiness.gateTable = gateTable;
dataReadiness.recommendation = recommendation;
dataReadiness.sessionCount = sessionCount;
dataReadiness.sourceFileCount = sourceFileCount;
dataReadiness.aircraftCount = aircraftCount;
dataReadiness.nonConstvelManeuverClassCount = nonConstvelClassCount;
dataReadiness.constaccLikePairCount = constaccCount;
dataReadiness.constturnLikePairCount = constturnCount;
dataReadiness.sparseUpdatePairCount = sparseUpdateCount;
dataReadiness.climbPairCount = climbCount;
dataReadiness.descentPairCount = descentCount;

end

function details = localBuildGateDetails(observedValue, requiredValue, passed)
%LOCALBUILDGATEDETAILS Format readiness gate table details.

details = strings(numel(observedValue), 1);

for rowIdx = 1:numel(observedValue)
    if passed(rowIdx)
        details(rowIdx) = sprintf("Observed %d; requirement met.", observedValue(rowIdx));
    else
        details(rowIdx) = sprintf( ...
            "Observed %d; need at least %d before retraining.", ...
            observedValue(rowIdx), ...
            requiredValue(rowIdx));
    end
end

end

function recommendation = localBuildReadinessRecommendation(isReadyForRetraining, sessionCount, sourceFileCount, aircraftCount, constturnCount, sparseUpdateCount)
%LOCALBUILDREADINESSRECOMMENDATION Convert gate result into a direct answer.

if isReadyForRetraining
    recommendation = "Ready for a future gated retraining experiment. Keep Stage 3A frozen for this report and start retraining as a new stage.";
    return;
end

if sessionCount < 3 || sourceFileCount < 3
    recommendation = sprintf( ...
        "Not ready for retraining. Stage 3B found %d ADS-B session(s) and %d usable truth file(s); collect more local SBS-1 ADS-B sessions first.", ...
        sessionCount, ...
        sourceFileCount);
    return;
end

if aircraftCount < 20
    recommendation = sprintf( ...
        "Not ready for retraining. Only %d aircraft tracks are present after filtering; add more local ADS-B tracks first.", ...
        aircraftCount);
    return;
end

if constturnCount < 100 || sparseUpdateCount < 100
    recommendation = sprintf( ...
        "Not ready for retraining. Maneuver coverage is weak, with %d constturn-like pairs and %d sparse-update pairs.", ...
        constturnCount, ...
        sparseUpdateCount);
    return;
end

recommendation = "Not ready for retraining. At least one configured Stage 3B diversity gate failed.";

end

function countValue = localLookupCount(countTable, variableName, categoryName)
%LOCALLOOKUPCOUNT Return a category count from a count table.

categoryValues = string(countTable.(variableName));
categoryMask = categoryValues == categoryName;

if any(categoryMask)
    countValue = countTable.pairCount(find(categoryMask, 1, "first"));
else
    countValue = 0;
end

end

function nonConstvelClassCount = localCountNonConstvelManeuverClasses(countTable)
%LOCALCOUNTNONCONSTVELMANEUVERCLASSES Count observed non-constvel labels.

classNames = string(countTable.maneuverClass);
classCounts = countTable.pairCount;
nonConstvelMask = classNames ~= "constvel_like";
nonConstvelClassCount = sum(nonConstvelMask & classCounts > 0);

end

function verificationTable = localBuildVerificationTable(dataset, frozenPrediction, metrics)
%LOCALBUILDVERIFICATIONTABLE Verify frozen-evaluation invariants.

reconstructionMaxAbsError = max( ...
    abs(frozenPrediction.reconstructedNextState - frozenPrediction.predictedNextState), ...
    [], ...
    "all");
sameSampleCount = all(metrics.aggregate.sampleCount == size(dataset.nextState, 1));
finitePrediction = all(isfinite(frozenPrediction.predictedNextState), "all");
sameRowsScored = metrics.constvel.aggregate.sampleCount(1) == ...
    metrics.frozenStage3A.aggregate.sampleCount(1);

checkName = [ ...
    "frozen delta reconstruction"; ...
    "same sample count for constvel and MLP"; ...
    "finite frozen MLP predictions"; ...
    "all aggregate metrics use dataset row count"];
passed = [ ...
    reconstructionMaxAbsError <= 1e-10; ...
    sameRowsScored; ...
    finitePrediction; ...
    sameSampleCount];
details = [ ...
    sprintf("max abs reconstruction error = %.3g", reconstructionMaxAbsError); ...
    sprintf("constvel rows = %d, MLP rows = %d", metrics.constvel.aggregate.sampleCount(1), metrics.frozenStage3A.aggregate.sampleCount(1)); ...
    sprintf("finite prediction rows = %d", sum(all(isfinite(frozenPrediction.predictedNextState), 2))); ...
    sprintf("dataset rows = %d", size(dataset.nextState, 1))];

verificationTable = table( ...
    checkName, ...
    passed, ...
    details, ...
    'VariableNames', [ ...
        "check", ...
        "passed", ...
        "details"]);

end

function configTable = localBuildConfigTable(config)
%LOCALBUILDCONFIGTABLE Convert config struct to a report table.

fieldNames = string(fieldnames(config));
values = strings(numel(fieldNames), 1);

for fieldIdx = 1:numel(fieldNames)
    fieldName = fieldNames(fieldIdx);
    values(fieldIdx) = localConfigValueToString(config.(fieldName));
end

configTable = table(fieldNames, values, ...
    'VariableNames', ["setting", "value"]);

end

function valueText = localConfigValueToString(value)
%LOCALCONFIGVALUETOSTRING Format config values.

if isstring(value)
    valueText = strjoin(value, ", ");
elseif ischar(value)
    valueText = string(value);
elseif isnumeric(value) || islogical(value)
    valueText = string(mat2str(value));
else
    valueText = string(value);
end

end

