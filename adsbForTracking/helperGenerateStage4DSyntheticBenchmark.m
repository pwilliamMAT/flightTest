function audit = localAuditPairs(pairSet)
%LOCALAUDITPAIRS Verify the observation-to-target pair contract.

rowCount = size(pairSet.previousState, 1);
alignedRowCounts = [ ...
    size(pairSet.targetState, 1), ...
    size(pairSet.previousCovarianceDiag, 1), ...
    numel(pairSet.dtSeconds), ...
    numel(pairSet.timeKSeconds), ...
    numel(pairSet.timeNextSeconds), ...
    numel(pairSet.eventID), ...
    numel(pairSet.profile)];
audit = struct();
audit.rowCount = rowCount;
audit.alignedRows = all(alignedRowCounts == rowCount);
audit.finiteObservedStates = all(isfinite(pairSet.previousState), "all");
audit.finiteTargets = all(isfinite(pairSet.targetState), "all");
audit.positiveDt = all(pairSet.dtSeconds > 0);
audit.monotonicPairs = all(pairSet.timeNextSeconds > pairSet.timeKSeconds);
audit.latentTruthTargets = all( ...
    pairSet.targetReference == "latent_kinematic_truth");
audit.passed = audit.alignedRows && ...
    audit.finiteObservedStates && ...
    audit.finiteTargets && ...
    audit.positiveDt && ...
    audit.monotonicPairs && ...
    audit.latentTruthTargets;

end

