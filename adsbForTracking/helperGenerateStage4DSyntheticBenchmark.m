%LOCALVALIDATEOPTIONALPOSITIVESCALAR Validate an optional scalar override.

if isempty(value)
    return;
end

validateattributes(value, ...
    {'numeric'}, ...
    {'scalar', 'real', 'positive', 'finite'}, ...
    mfilename, ...
    argumentName);

end
