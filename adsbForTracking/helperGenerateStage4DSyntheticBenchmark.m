function [pieces, truthAuditTable, caseTable] = localGenerateCanonical( ...
        config, profileTable, stream, empiricalDtSeconds, previousCovarianceDiag)
%LOCALGENERATECANONICAL Build seven motions under three observation profiles.

scenarioNames = [ ...
    "cv_level"; ...
    "cv_climb"; ...
    "horizontal_acceleration"; ...
    "vertical_acceleration"; ...
    "left_turn"; ...
    "right_turn"; ...
    "motion_transitions"];
profileCount = height(profileTable);
pieceCount = numel(scenarioNames) * profileCount;
pieces = repmat(localEmptyPiece(), pieceCount, 1);
truthAuditRows = cell(numel(scenarioNames), 1);
caseRows = cell(pieceCount, 1);
pieceIdx = 0;

for scenarioIdx = 1:numel(scenarioNames)
    scenarioName = scenarioNames(scenarioIdx);
    truth = localCreateCanonicalTruth( ...
        scenarioName, ...
        config.durationSeconds, ...
        config.sampleRateHz, ...
        stream);
    truthAuditRows{scenarioIdx} = localTruthAuditRow( ...
        scenarioName, ...
        truth);
    empiricalIndices = localEmpiricalObservationIndices( ...
        truth.timeSeconds, ...
        empiricalDtSeconds, ...
        stream);

    for profileIdx = 1:profileCount
        pieceIdx = pieceIdx + 1;
        profileName = profileTable.profile(profileIdx);
        caseID = scenarioName + "__" + profileName;
        pieces(pieceIdx) = localObserveTruth( ...
            truth, ...
            profileName, ...
            empiricalIndices, ...
            stream, ...
            previousCovarianceDiag, ...
            pieceIdx, ...
            caseID, ...
            scenarioName);
        caseRows{pieceIdx} = table( ...
            caseID, ...
            scenarioName, ...
            profileName, ...
            config.durationSeconds, ...
            height(pieces(pieceIdx).previousState), ...
            "latent_kinematic_truth", ...
            'VariableNames', [ ...
                "caseID", ...
                "motionScenario", ...
                "observationProfile", ...
                "durationSeconds", ...
                "pairCount", ...
                "targetReference"]);
    end
end

truthAuditTable = vertcat(truthAuditRows{:});
caseTable = vertcat(caseRows{:});

end

