function benchmark = helperGenerateStage4DSyntheticBenchmark(groupName, varargin)
%HELPERGENERATESTAGE4DSYNTHETICBENCHMARK Generate independent Stage 4D truth.
% Truth is generated with kinematicTrajectory on a uniform internal time
% grid. Observation profiles then sample and perturb that latent truth.

parser = inputParser;
parser.FunctionName = mfilename;
addRequired(parser, "groupName");
addParameter(parser, "BenchmarkMode", "smoke");
addParameter(parser, "Seed", 123);
addParameter(parser, "EmpiricalDtSeconds", 1);
addParameter(parser, "PreviousCovarianceDiag", [10000, 100, 10000, 100, 22500, 25]);
addParameter(parser, "TrajectoryCount", []);
addParameter(parser, "DurationSeconds", []);
addParameter(parser, "SampleRateHz", []);
parse(parser, groupName, varargin{:});

groupName = lower(strtrim(string(parser.Results.groupName)));
benchmarkMode = lower(strtrim(string(parser.Results.BenchmarkMode)));
seed = double(parser.Results.Seed);
empiricalDtSeconds = double(parser.Results.EmpiricalDtSeconds(:));
previousCovarianceDiag = double(parser.Results.PreviousCovarianceDiag(:).');
trajectoryCount = parser.Results.TrajectoryCount;
durationSeconds = parser.Results.DurationSeconds;
sampleRateHz = parser.Results.SampleRateHz;
localValidateInputs( ...
    groupName, ...
    benchmarkMode, ...
    seed, ...
    empiricalDtSeconds, ...
    previousCovarianceDiag, ...
    trajectoryCount, ...
    durationSeconds, ...
    sampleRateHz);

config = localBuildConfig( ...
    groupName, ...
    benchmarkMode, ...
    trajectoryCount, ...
    durationSeconds, ...
    sampleRateHz);
stream = RandStream("mt19937ar", "Seed", seed + config.seedOffset);
profileTable = localSyntheticProfileTable();

if groupName == "canonical"
    [pieces, truthAuditTable, caseTable] = localGenerateCanonical( ...
        config, ...
        profileTable, ...
        stream, ...
        empiricalDtSeconds, ...
        previousCovarianceDiag);
else
    [pieces, truthAuditTable, caseTable] = localGenerateMixed( ...
        config, ...
        profileTable, ...
        stream, ...
        empiricalDtSeconds, ...
        previousCovarianceDiag);
end

pairSet = localConcatenatePieces(pieces, groupName);
pairAudit = localAuditPairs(pairSet);

benchmark = struct();
benchmark.groupName = groupName;
benchmark.benchmarkMode = benchmarkMode;
benchmark.seed = seed + config.seedOffset;
benchmark.config = config;
benchmark.profileTable = profileTable;
benchmark.caseTable = caseTable;
benchmark.pairSet = pairSet;
benchmark.sequences = pieces;
benchmark.truthAuditTable = truthAuditTable;
benchmark.pairAudit = pairAudit;
benchmark.truthTrajectoryCount = config.truthTrajectoryCount;
benchmark.observedCaseCount = numel(pieces);

end

function config = localBuildConfig( ...
        groupName, benchmarkMode, trajectoryCount, durationSeconds, sampleRateHz)
%LOCALBUILDCONFIG Define smoke and full benchmark sizes.

config = struct();
config.sampleRateHz = 2;
config.groupName = groupName;

if benchmarkMode == "full"
    config.canonicalDurationSeconds = 240;
    config.mixedDurationSeconds = 600;
    config.inDistributionTrajectoryCount = 100;
    config.outOfDistributionTrajectoryCount = 50;
else
    config.canonicalDurationSeconds = 90;
    config.mixedDurationSeconds = 120;
    config.inDistributionTrajectoryCount = 4;
    config.outOfDistributionTrajectoryCount = 2;
end

switch groupName
    case "canonical"
        config.truthTrajectoryCount = 7;
        config.durationSeconds = config.canonicalDurationSeconds;
        config.seedOffset = 101;
    case "in_distribution"
        config.truthTrajectoryCount = config.inDistributionTrajectoryCount;
        config.durationSeconds = config.mixedDurationSeconds;
        config.seedOffset = 1001;
    case "out_of_distribution"
        config.truthTrajectoryCount = config.outOfDistributionTrajectoryCount;
        config.durationSeconds = config.mixedDurationSeconds;
        config.seedOffset = 2001;
    otherwise
        error("Stage4D:UnknownSyntheticGroup", ...
            "Synthetic group must be canonical, in_distribution, or out_of_distribution.");
end

if ~isempty(trajectoryCount)
    config.truthTrajectoryCount = double(trajectoryCount);
end

if ~isempty(durationSeconds)
    config.durationSeconds = double(durationSeconds);
end

if ~isempty(sampleRateHz)
    config.sampleRateHz = double(sampleRateHz);
end

end

