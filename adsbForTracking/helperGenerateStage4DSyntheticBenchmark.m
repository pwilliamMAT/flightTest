function mask = localTimeMask(timeSeconds, startFraction, endFraction)
%LOCALTIMEMASK Select a fractional interval from a trajectory duration.

durationSeconds = timeSeconds(end);
mask = timeSeconds >= startFraction*durationSeconds & ...
    timeSeconds < endFraction*durationSeconds;

end

function value = localUniformDraw(stream, bounds)
%LOCALUNIFORMDRAW Draw one scalar uniformly between two bounds.

value = bounds(1) + diff(bounds)*rand(stream);

end

function localValidateInputs( ...
        groupName, ...
        benchmarkMode, ...
        seed, ...
        empiricalDtSeconds, ...
        previousCovarianceDiag, ...
        trajectoryCount, ...
        durationSeconds, ...
        sampleRateHz)
%LOCALVALIDATEINPUTS Validate public helper arguments.

if ~ismember(groupName, ...
        ["canonical", "in_distribution", "out_of_distribution"])
    error("Stage4D:UnknownSyntheticGroup", ...
        "Synthetic group must be canonical, in_distribution, or out_of_distribution.");
end

if ~ismember(benchmarkMode, ["smoke", "full"])
    error("Stage4D:InvalidBenchmarkMode", ...
        "BenchmarkMode must be smoke or full.");
end

validateattributes(seed, ...
    {'numeric'}, {'scalar', 'integer', 'nonnegative', 'finite'}, ...
    mfilename, "Seed");
validateattributes(empiricalDtSeconds, ...
    {'numeric'}, {'column', 'real', 'finite', 'positive', 'nonempty'}, ...
    mfilename, "EmpiricalDtSeconds");
validateattributes(previousCovarianceDiag, ...
    {'numeric'}, {'row', 'numel', 6, 'real', 'finite', 'positive'}, ...
    mfilename, "PreviousCovarianceDiag");

localValidateOptionalPositiveInteger(trajectoryCount, "TrajectoryCount");
localValidateOptionalPositiveScalar(durationSeconds, "DurationSeconds");
localValidateOptionalPositiveScalar(sampleRateHz, "SampleRateHz");

end

function localValidateOptionalPositiveInteger(value, argumentName)
%LOCALVALIDATEOPTIONALPOSITIVEINTEGER Validate an optional count override.

if isempty(value)
    return;
end

validateattributes(value, ...
    {'numeric'}, ...
    {'scalar', 'integer', 'positive', 'finite'}, ...
    mfilename, ...
    argumentName);

end

