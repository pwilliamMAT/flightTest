function resolvedPath = localResolvePath(projectRoot, suppliedPath, defaultPath)
%LOCALRESOLVEPATH Resolve optional paths relative to the project root.

suppliedPath = string(suppliedPath);

if strlength(suppliedPath) == 0
    suppliedPath = string(defaultPath);
end

if localIsAbsolutePath(suppliedPath)
    resolvedPath = suppliedPath;
else
    resolvedPath = string(fullfile(projectRoot, suppliedPath));
end

end

function tf = localIsAbsolutePath(pathValue)
%LOCALISABSOLUTEPATH Recognize Windows, UNC, and rooted paths.

pathValue = char(string(pathValue));
tf = ~isempty(regexp(pathValue, '^[A-Za-z]:[\\/]', 'once')) || ...
    startsWith(pathValue, "\\") || ...
    startsWith(pathValue, "/");

end

