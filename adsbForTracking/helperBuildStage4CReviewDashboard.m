function dashboard = helperBuildStage4CReviewDashboard(varargin)
%HELPERBUILDSTAGE4CREVIEWDASHBOARD Build the frozen Stage 4C review data.
% The helper loads the Expanded-3Day dataset and completed Stage 4C
% comparison, but it does not train, smooth, clip, or write artifacts.
% Neural inference is limited to the three representative test events.

projectRoot = string(fileparts(mfilename("fullpath")));
parser = inputParser;
parser.FunctionName = mfilename;
addParameter(parser, "ProjectRoot", projectRoot);
addParameter(parser, "DatasetPath", "");
addParameter(parser, "SplitManifestPath", "");
addParameter(parser, "ComparisonArtifactPath", "");
addParameter(parser, "Stage3AArtifactPath", "");
addParameter(parser, "ScratchArtifactPath", "");
addParameter(parser, "WarmArtifactPath", "");
addParameter(parser, "PredictionMiniBatchSize", 8192);
parse(parser, varargin{:});

config = localBuildConfig(parser.Results);
localValidateFiles(config);
dataset = localLoadDataset(config.DatasetPath);
stage4CSummary = localLoadComparison(config.ComparisonArtifactPath);
sourceHashes = localValidateFrozenProvenance(config, stage4CSummary);
split = localLoadFrozenSplit(dataset.metadata, config.SplitManifestPath);
maneuverPairTable = helperAssignADSBManeuverLabels( ...
    dataset.previousState, ...
    dataset.nextState, ...
    dataset.dtSeconds);

splitSummaryTable = localBuildSplitSummary(split);
motionClassSplitTable = localBuildMotionClassSplitTable( ...
    maneuverPairTable.maneuverClass, ...
    split);
rmseTable = localBuildRMSETable(stage4CSummary);

models = localLoadModels(config);
motionClasses = [ ...
    "constvel_like"; ...
    "constacc_like"; ...
    "constturn_like"];
nativeModelIDs = ["constvel"; "constacc"; "constturn"];
representatives = repmat(localEmptyRepresentative(), 3, 1);

for classIdx = 1:numel(motionClasses)
    candidateRows = localEligibleTestRows( ...
        motionClasses(classIdx), ...
        split, ...
        maneuverPairTable, ...
        stage4CSummary.nativeManeuverBaseline.selectionTable);
    eventTable = localBuildEventTable(candidateRows, dataset.metadata);
    representatives(classIdx) = localBuildRepresentative( ...
        motionClasses(classIdx), ...
        nativeModelIDs(classIdx), ...
        eventTable, ...
        dataset, ...
        split, ...
        models, ...
        config.PredictionMiniBatchSize);
end

localValidateDashboard( ...
    dataset, ...
    splitSummaryTable, ...
    motionClassSplitTable, ...
    rmseTable, ...
    representatives);

dashboard = struct();
dashboard.datasetName = "Expanded-3Day";
dashboard.datasetVariantID = "expanded_post3day_v2";
dashboard.datasetPairCount = size(dataset.previousState, 1);
dashboard.stateOrder = string(dataset.stateOrder);
dashboard.splitSummaryTable = splitSummaryTable;
dashboard.motionClassSplitTable = motionClassSplitTable;
dashboard.rmseTable = rmseTable;
dashboard.representatives = representatives;
dashboard.modelIdentityTable = localBuildModelIdentityTable( ...
    config, ...
    stage4CSummary);
dashboard.metricDefinition = ...
    "Pair-weighted aggregate 3-D error, reported separately for position and velocity.";
dashboard.trajectoryDefinition = ...
    "Sequences of one-step predictions from observed previous states; not recursive forecasts or tracker outputs.";
dashboard.trainingPerformed = false;
dashboard.clippingApplied = false;
dashboard.smoothingApplied = false;
dashboard.sourcePaths = struct( ...
    "dataset", config.DatasetPath, ...
    "splitManifest", config.SplitManifestPath, ...
    "comparisonArtifact", config.ComparisonArtifactPath);
dashboard.sourceHashes = sourceHashes;
dashboard.predictionMiniBatchSize = config.PredictionMiniBatchSize;

end

