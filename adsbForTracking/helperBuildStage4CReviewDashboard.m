function split = localLoadFrozenSplit(metadata, splitManifestPath)
%LOCALLOADFROZENSPLIT Apply the global ICAO-disjoint split manifest.

manifest = readtable(splitManifestPath, TextType="string");
requiredVariables = ["icao24", "split"];

if any(~ismember(requiredVariables, ...
        string(manifest.Properties.VariableNames)))
    error( ...
        "StageReview:InvalidStage4CSplitManifest", ...
        "The frozen split manifest must contain icao24 and split.");
end

manifest.icao24 = lower(strtrim(string(manifest.icao24)));
manifest.split = lower(strtrim(string(manifest.split)));

if numel(unique(manifest.icao24)) ~= height(manifest)
    error( ...
        "StageReview:DuplicateStage4CICAO", ...
        "Every ICAO must occur exactly once in the frozen split manifest.");
end

[found, manifestRow] = ismember( ...
    lower(strtrim(string(metadata.hex))), ...
    manifest.icao24);

if ~all(found)
    error( ...
        "StageReview:Stage4CSplitMembershipMismatch", ...
        "Every Expanded-3Day ICAO must occur in the frozen split manifest.");
end

split = manifest.split(manifestRow);
expectedCounts = [277959, 86420, 93524];
actualCounts = [ ...
    sum(split == "train"), ...
    sum(split == "validation"), ...
    sum(split == "test")];

if ~isequal(actualCounts, expectedCounts)
    error( ...
        "StageReview:Stage4CSplitCountMismatch", ...
        "The frozen train/validation/test pair counts have changed.");
end

end

