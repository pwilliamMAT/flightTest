function identityTable = localBuildModelIdentityTable(config, stage4CSummary)
%LOCALBUILDMODELIDENTITYTABLE Record every frozen neural artifact.

modelID = [ ...
    "legacy_stage3a_v1"; ...
    "expanded_scratch_mean_v1"; ...
    "expanded_warm_mean_v1"];
artifactPath = [ ...
    config.Stage3AArtifactPath; ...
    config.ScratchArtifactPath; ...
    config.WarmArtifactPath];
trainingRole = [ ...
    "Stage 3A legacy"; ...
    "Expanded-3Day scratch"; ...
    "Expanded-3Day normalization-rebased warm start"];
frozen = true(3, 1);
sha256 = strings(3, 1);
integrity = ...
    stage4CSummary.nativeManeuverBaseline.frozenArtifactIntegrity;

for modelIdx = 1:numel(modelID)
    expectedRow = integrity.artifactID == modelID(modelIdx);

    if sum(expectedRow) ~= 1
        error( ...
            "StageReview:MissingStage4CModelIntegrity", ...
            "No unique frozen hash is recorded for %s.", ...
            modelID(modelIdx));
    end

    sha256(modelIdx) = helperComputeFileSHA256(artifactPath(modelIdx));

    if ~strcmpi(sha256(modelIdx), integrity.beforeSHA256(expectedRow))
        error( ...
            "StageReview:Stage4CFrozenModelHashMismatch", ...
            "Frozen model %s differs from the evaluated artifact.", ...
            modelID(modelIdx));
    end
end

identityTable = table( ...
    modelID, ...
    artifactPath, ...
    trainingRole, ...
    frozen, ...
    sha256);

end

