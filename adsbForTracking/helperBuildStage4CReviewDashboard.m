function localValidateDashboard( ...
        dataset, ...
        splitSummaryTable, ...
        motionClassSplitTable, ...
        rmseTable, ...
        representatives)
%LOCALVALIDATEDASHBOARD Enforce the supplied Stage 4C review contract.

pairCount = size(dataset.previousState, 1);

if sum(splitSummaryTable.pairCount) ~= pairCount || ...
        motionClassSplitTable.total(end) ~= pairCount
    error( ...
        "StageReview:Stage4CCountCoverageMismatch", ...
        "Split and motion-class counts must cover all Expanded-3Day rows.");
end

sectionCounts = groupsummary( ...
    rmseTable, ...
    ["motionClass", "split"], ...
    ["min", "max"], ...
    "sampleCount");

if height(rmseTable) ~= 24 || ...
        any(sectionCounts.min_sampleCount ~= sectionCounts.max_sampleCount)
    error( ...
        "StageReview:Stage4CRMSEMatchingFailed", ...
        "Every RMSE section must compare four models on matched rows.");
end

expectedClasses = [ ...
    "constvel_like"; ...
    "constacc_like"; ...
    "constturn_like"];

if any(string({representatives.motionClass}).' ~= expectedClasses)
    error( ...
        "StageReview:Stage4CRepresentativeOrderMismatch", ...
        "Representative trajectories must follow the three dashboard rows.");
end

for representativeIdx = 1:numel(representatives)
    representative = representatives(representativeIdx);
    llaValues = [ ...
        representative.truthLLA; ...
        representative.nativeLLA; ...
        representative.legacyLLA; ...
        representative.scratchLLA; ...
        representative.warmLLA];

    if representative.selectedTrajectory ~= 1 || ...
            representative.pairCount ~= ...
            max(representative.eventTable.pairCount) || ...
            any(diff(representative.timeSeconds) <= 0) || ...
            any(~isfinite(llaValues), "all") || ...
            height(representative.legendTable) ~= 5
        error( ...
            "StageReview:InvalidStage4CRepresentative", ...
            "A representative trajectory failed continuity or finiteness checks.");
    end
end

end
