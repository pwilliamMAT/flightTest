function candidateRows = localEligibleTestRows( ...
        motionClass, split, maneuverPairTable, selectionTable)
%LOCALELIGIBLETESTROWS Resolve each class's exact eligible test rows.

if motionClass == "constvel_like"
    candidateRows = find( ...
        split == "test" & ...
        string(maneuverPairTable.maneuverClass) == motionClass);
    return;
end

selectionMask = ...
    selectionTable.split == "test" & ...
    selectionTable.maneuverSlice == motionClass;

if sum(selectionMask) ~= 1
    error( ...
        "StageReview:Stage4CSelectionMismatch", ...
        "Expected one frozen test selection for %s.", ...
        motionClass);
end

candidateRows = selectionTable.datasetRowIndices{selectionMask};
candidateRows = candidateRows(:);

end

function eventTable = localBuildEventTable(candidateRows, metadata)
%LOCALBUILDEVENTTABLE Segment contiguous rows and rank longest first.

candidateRows = unique(double(candidateRows(:)), "stable");

if isempty(candidateRows)
    error( ...
        "StageReview:NoEligibleStage4CTrajectory", ...
        "No eligible test rows are available for a representative trajectory.");
end

ordering = table( ...
    string(metadata.sessionID(candidateRows)), ...
    lower(strtrim(string(metadata.hex(candidateRows)))), ...
    metadata.timeUtcK(candidateRows), ...
    metadata.timeUtcNext(candidateRows), ...
    candidateRows, ...
    'VariableNames', [ ...
        "sessionID", ...
        "icao24", ...
        "timeUtcK", ...
        "timeUtcNext", ...
        "datasetRow"]);
ordering = sortrows( ...
    ordering, ...
    ["sessionID", "icao24", "timeUtcK", "timeUtcNext", "datasetRow"]);
newEvent = true(height(ordering), 1);

if height(ordering) > 1
    sameTrack = ...
        ordering.sessionID(2:end) == ordering.sessionID(1:end - 1) & ...
        ordering.icao24(2:end) == ordering.icao24(1:end - 1);
    adjacentPair = abs(seconds( ...
        ordering.timeUtcK(2:end) - ...
        ordering.timeUtcNext(1:end - 1))) <= 1e-6;
    newEvent(2:end) = ~(sameTrack & adjacentPair);
end

eventID = cumsum(newEvent);
eventCount = eventID(end);
sessionID = strings(eventCount, 1);
icao24 = strings(eventCount, 1);
callsign = strings(eventCount, 1);
startTimeUtc = NaT(eventCount, 1, "TimeZone", "UTC");
endTimeUtc = NaT(eventCount, 1, "TimeZone", "UTC");
pairCount = zeros(eventCount, 1);
firstDatasetRow = zeros(eventCount, 1);
datasetRowIndices = cell(eventCount, 1);

for eventIdx = 1:eventCount
    rows = ordering.datasetRow(eventID == eventIdx);
    datasetRowIndices{eventIdx} = rows;
    sessionID(eventIdx) = string(metadata.sessionID(rows(1)));
    icao24(eventIdx) = lower(strtrim(string(metadata.hex(rows(1)))));
    callsign(eventIdx) = string(metadata.callsign(rows(1)));
    startTimeUtc(eventIdx) = metadata.timeUtcK(rows(1));
    endTimeUtc(eventIdx) = metadata.timeUtcNext(rows(end));
    pairCount(eventIdx) = numel(rows);
    firstDatasetRow(eventIdx) = rows(1);
end

eventTable = table( ...
    sessionID, ...
    icao24, ...
    callsign, ...
    startTimeUtc, ...
    endTimeUtc, ...
    pairCount, ...
    firstDatasetRow, ...
    datasetRowIndices);
eventTable = sortrows( ...
    eventTable, ...
    [ ...
        "pairCount", ...
        "sessionID", ...
        "icao24", ...
        "startTimeUtc", ...
        "firstDatasetRow"], ...
    [ ...
        "descend", ...
        "ascend", ...
        "ascend", ...
        "ascend", ...
        "ascend"]);

end

function representative = localBuildRepresentative( ...
        motionClass, ...
        nativeModelID, ...
        eventTable, ...
        dataset, ...
        split, ...
        models, ...
        miniBatchSize)
%LOCALBUILDREPRESENTATIVE Build five one-step trajectory sequences.

selectedEvent = eventTable(1, :);
selectedRows = selectedEvent.datasetRowIndices{1};
previousState = double(dataset.previousState(selectedRows, :));
constvelPrediction = double( ...
    dataset.baselineConstVelMetrics.predictedState(selectedRows, :));
featureData = helperBuildStage4CFeatures( ...
    previousState, ...
    dataset.previousCovarianceDiag(selectedRows, :), ...
    dataset.dtSeconds(selectedRows), ...
    constvelPrediction);
neuralPredictions = cell(3, 1);

for modelIdx = 1:numel(models)
    neuralPredictions{modelIdx} = localPredictState( ...
        models(modelIdx), ...
        featureData.features, ...
        previousState, ...
        miniBatchSize);
end

nativePrediction = localBuildNativePrediction( ...
    nativeModelID, ...
    selectedRows, ...
    dataset, ...
    split);
timeUtc = [ ...
    dataset.metadata.timeUtcK(selectedRows(1)); ...
    dataset.metadata.timeUtcNext(selectedRows)];
timeSeconds = seconds(timeUtc - timeUtc(1));
truthState = [ ...
    previousState(1, :); ...
    double(dataset.nextState(selectedRows, :))];
nativeState = [previousState(1, :); nativePrediction];
legacyState = [previousState(1, :); neuralPredictions{1}];
scratchState = [previousState(1, :); neuralPredictions{2}];
warmState = [previousState(1, :); neuralPredictions{3}];
receiverOriginLLA = dataset.metadata.receiverOriginLLA(selectedRows(1), :);

truthLLA = localStateToLLA(truthState, receiverOriginLLA);
nativeLLA = localStateToLLA(nativeState, receiverOriginLLA);
legacyLLA = localStateToLLA(legacyState, receiverOriginLLA);
scratchLLA = localStateToLLA(scratchState, receiverOriginLLA);
warmLLA = localStateToLLA(warmState, receiverOriginLLA);

trajectory = struct();
trajectory.truth = geoTrajectory( ...
    truthLLA, timeSeconds, ReferenceFrame="ENU");
trajectory.native = geoTrajectory( ...
    nativeLLA, timeSeconds, ReferenceFrame="ENU");
trajectory.legacy = geoTrajectory( ...
    legacyLLA, timeSeconds, ReferenceFrame="ENU");
trajectory.scratch = geoTrajectory( ...
    scratchLLA, timeSeconds, ReferenceFrame="ENU");
trajectory.warm = geoTrajectory( ...
    warmLLA, timeSeconds, ReferenceFrame="ENU");

timeSpanUTC = localTimeSpan( ...
    selectedEvent.startTimeUtc, ...
    selectedEvent.endTimeUtc);
label = sprintf( ...
    "Representative trajectory—1 of %d eligible trajectories | session %s | ICAO %s | %s | %d pairs", ...
    height(eventTable), ...
    selectedEvent.sessionID, ...
    selectedEvent.icao24, ...
    timeSpanUTC, ...
    selectedEvent.pairCount);
summaryTable = table( ...
    motionClass, ...
    nativeModelID, ...
    1, ...
    height(eventTable), ...
    selectedEvent.sessionID, ...
    selectedEvent.icao24, ...
    selectedEvent.callsign, ...
    selectedEvent.startTimeUtc, ...
    selectedEvent.endTimeUtc, ...
    selectedEvent.pairCount, ...
    string(label), ...
    'VariableNames', [ ...
        "motionClass", ...
        "nativeModelID", ...
        "selectedTrajectory", ...
