function dataset = localLoadDataset(datasetPath)
%LOCALLOADDATASET Load only fields needed by the review dashboard.

try
    dataset = load( ...
        datasetPath, ...
        "previousState", ...
        "nextState", ...
        "dtSeconds", ...
        "previousCovarianceDiag", ...
        "metadata", ...
        "baselineConstVelMetrics", ...
        "stateOrder");
catch err
    error( ...
        "StageReview:Stage4CDatasetLoadFailed", ...
        "Unable to load the Expanded-3Day dataset: %s", ...
        err.message);
end

requiredFields = [ ...
    "previousState"; ...
    "nextState"; ...
    "dtSeconds"; ...
    "previousCovarianceDiag"; ...
    "metadata"; ...
    "baselineConstVelMetrics"; ...
    "stateOrder"];

if any(~isfield(dataset, requiredFields))
    error( ...
        "StageReview:InvalidStage4CDataset", ...
        "The Expanded-3Day dataset is missing a required field.");
end

pairCount = size(dataset.previousState, 1);
expectedStateOrder = ["x", "vx", "y", "vy", "z", "vz"];

if pairCount ~= 457903 || ...
        ~isequal(size(dataset.previousState), [pairCount, 6]) || ...
        ~isequal(size(dataset.nextState), [pairCount, 6]) || ...
        ~isequal(size(dataset.previousCovarianceDiag), [pairCount, 6]) || ...
        numel(dataset.dtSeconds) ~= pairCount || ...
        height(dataset.metadata) ~= pairCount || ...
        any(string(dataset.stateOrder(:).') ~= expectedStateOrder)
    error( ...
        "StageReview:Stage4CDatasetContractMismatch", ...
        "The frozen Expanded-3Day dataset contract has changed.");
end

if ~isfield(dataset.baselineConstVelMetrics, "predictedState") || ...
        ~isequal( ...
        size(dataset.baselineConstVelMetrics.predictedState), ...
        [pairCount, 6])
    error( ...
        "StageReview:MissingStage4CConstvelPrediction", ...
        "The dataset lacks aligned native constvel predictions.");
end

end

