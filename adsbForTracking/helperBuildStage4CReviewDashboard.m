function rmseTable = localBuildRMSETable(stage4CSummary)
%LOCALBUILDRMSETABLE Select the 3-by-2 dashboard's matched comparisons.

motionClasses = [ ...
    "constvel_like"; ...
    "constacc_like"; ...
    "constturn_like"];
nativeModelIDs = ["constvel"; "constacc"; "constturn"];
neuralModelIDs = [ ...
    "legacy_stage3a_v1"; ...
    "expanded_scratch_mean_v1"; ...
    "expanded_warm_mean_v1"];
splitNames = ["validation"; "test"];
outputRows = cell(24, 1);
outputRow = 0;
baseMetrics = stage4CSummary.metrics.table;
nativeMetrics = stage4CSummary.nativeManeuverBaseline.metrics.table;

for classIdx = 1:numel(motionClasses)
    modelIDs = [nativeModelIDs(classIdx); neuralModelIDs];

    for splitIdx = 1:numel(splitNames)
        if motionClasses(classIdx) == "constvel_like"
            source = baseMetrics( ...
                baseMetrics.groupDimension == "maneuver_class" & ...
                baseMetrics.groupName == motionClasses(classIdx) & ...
                baseMetrics.weighting == "pair_weighted" & ...
                baseMetrics.split == splitNames(splitIdx), :);
        else
            source = nativeMetrics( ...
                nativeMetrics.groupName == motionClasses(classIdx) & ...
                nativeMetrics.weighting == "pair_weighted" & ...
                nativeMetrics.split == splitNames(splitIdx), :);
        end

        for modelIdx = 1:numel(modelIDs)
            selected = source(source.modelID == modelIDs(modelIdx), :);

            if height(selected) ~= 1
                error( ...
                    "StageReview:Stage4CRMSEIdentityMismatch", ...
                    "Expected one %s/%s/%s metric row.", ...
                    motionClasses(classIdx), ...
                    splitNames(splitIdx), ...
                    modelIDs(modelIdx));
            end

            outputRow = outputRow + 1;
            outputRows{outputRow} = table( ...
                motionClasses(classIdx), ...
                nativeModelIDs(classIdx), ...
                selected.modelID, ...
                localModelDisplayName( ...
                selected.modelID, ...
                nativeModelIDs(classIdx)), ...
                selected.split, ...
                selected.sampleCount, ...
                selected.eventCount, ...
                selected.positionRMSEMeters, ...
                selected.velocityRMSEMetersPerSecond, ...
                'VariableNames', [ ...
                    "motionClass", ...
                    "nativeModelID", ...
                    "modelID", ...
                    "modelDisplayName", ...
                    "split", ...
                    "sampleCount", ...
                    "eventCount", ...
                    "positionRMSEMeters", ...
                    "velocityRMSEMetersPerSecond"]);
        end
    end
end

rmseTable = vertcat(outputRows{:});

end

