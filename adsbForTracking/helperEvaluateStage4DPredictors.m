function [weights, eventCount] = localIndependentEventWeights(eventID)
%LOCALINDEPENDENTEVENTWEIGHTS Give every event equal total pair weight.

if isempty(eventID)
    weights = zeros(0, 1);
    eventCount = 0;
    return;
end

[eventGroup, ~] = findgroups(eventID);
eventLength = accumarray(eventGroup, 1);
weights = 1 ./ eventLength(eventGroup);
eventCount = numel(eventLength);

end

function interval = localPairedMeanConfidenceInterval( ...
        differences, confidenceLevel)
%LOCALPAIREDMEANCONFIDENCEINTERVAL Compute a paired Student t interval.

differences = differences(isfinite(differences));
sampleCount = numel(differences);
meanDifference = mean(differences);

if sampleCount < 2
    interval = [meanDifference, meanDifference];
    return;
end

alpha = 1 - confidenceLevel;
criticalValue = tinv(1 - alpha / 2, sampleCount - 1);
halfWidth = criticalValue*std(differences, 0) / sqrt(sampleCount);
interval = meanDifference + [-halfWidth, halfWidth];

end

