    [metricRows, rowIdx] = localAppendFamilyMetrics( ...
        metricRows, ...
        rowIdx, ...
        pairSet, ...
        models, ...
        positionErrors, ...
        velocityErrors, ...
        caseMask, ...
        "same_information", ...
        [1, 2], ...
        profileName, ...
        caseID);
    [metricRows, rowIdx] = localAppendFamilyMetrics( ...
        metricRows, ...
        rowIdx, ...
        pairSet, ...
        models, ...
        positionErrors, ...
        velocityErrors, ...
        caseMask & causalMask, ...
        "causal_history", ...
        1:4, ...
        profileName, ...
        caseID);
end

metricTable = vertcat(metricRows{1:rowIdx});

end

function [metricRows, rowIdx] = localAppendFamilyMetrics( ...
        metricRows, ...
        rowIdx, ...
        pairSet, ...
        models, ...
        positionErrors, ...
        velocityErrors, ...
        rowMask, ...
        comparisonFamily, ...
        modelIndices, ...
        profileName, ...
        caseID)
%LOCALAPPENDFAMILYMETRICS Add both weighting policies for selected models.

if nargin < 11
    caseID = "all";
end

[eventWeights, eventCount] = localIndependentEventWeights( ...
    pairSet.eventID(rowMask));
pairWeights = ones(sum(rowMask), 1);

for modelIdx = modelIndices
    rowIdx = rowIdx + 1;
    metricRows{rowIdx} = localMetricRow( ...
        pairSet, ...
        models(modelIdx).modelID, ...
        profileName, ...
        comparisonFamily, ...
        "pair_weighted", ...
        caseID, ...
        positionErrors(rowMask, modelIdx), ...
        velocityErrors(rowMask, modelIdx), ...
        pairWeights, ...
        eventCount);
    rowIdx = rowIdx + 1;
    metricRows{rowIdx} = localMetricRow( ...
        pairSet, ...
        models(modelIdx).modelID, ...
        profileName, ...
        comparisonFamily, ...
        "independent_event_weighted", ...
        caseID, ...
        positionErrors(rowMask, modelIdx), ...
        velocityErrors(rowMask, modelIdx), ...
        eventWeights, ...
        eventCount);
end

end

