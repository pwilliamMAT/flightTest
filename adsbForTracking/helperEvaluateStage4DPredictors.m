function evaluation = helperEvaluateStage4DPredictors( ...
        pairSet, warmModel, varargin)
%HELPEREVALUATESTAGE4DPREDICTORS Compare the frozen warm model and native models.
% Warm and constvel share the current observation and dt. Constacc and
% constturn are reported separately because they also use one predecessor.

parser = inputParser;
parser.FunctionName = mfilename;
addRequired(parser, "pairSet");
addRequired(parser, "warmModel");
addParameter(parser, "PredictionMiniBatchSize", 8192);
addParameter(parser, "ConfidenceLevel", 0.95);
addParameter(parser, "RetainPredictions", false);
parse(parser, pairSet, warmModel, varargin{:});

miniBatchSize = double(parser.Results.PredictionMiniBatchSize);
confidenceLevel = double(parser.Results.ConfidenceLevel);
retainPredictions = localLogicalScalar( ...
    parser.Results.RetainPredictions, ...
    "RetainPredictions");
localValidateInputs(pairSet, warmModel, miniBatchSize, confidenceLevel);

rowCount = size(pairSet.previousState, 1);
constvelTimer = tic;
constvelPrediction = localPredictConstvel( ...
    pairSet.previousState, ...
    pairSet.dtSeconds);
constvelSeconds = toc(constvelTimer);

warmTimer = tic;
warmPrediction = localPredictWarm( ...
    pairSet.previousState, ...
    pairSet.previousCovarianceDiag, ...
    pairSet.dtSeconds, ...
    constvelPrediction, ...
    warmModel, ...
    miniBatchSize);
warmSeconds = toc(warmTimer);

[causalPrediction, causalRuntime] = localPredictCausalNative(pairSet);
models = localBuildModels( ...
    warmPrediction, ...
    constvelPrediction, ...
    causalPrediction);
positionErrors = localStateErrors( ...
    models, ...
    pairSet.targetState, ...
    [1, 3, 5]);
velocityErrors = localStateErrors( ...
    models, ...
    pairSet.targetState, ...
    [2, 4, 6]);

metricTable = localScoreProfiles( ...
    pairSet, ...
    models, ...
    positionErrors, ...
    velocityErrors, ...
    causalPrediction.eligibleMask);
canonicalMetricTable = localScoreCanonicalCases( ...
    pairSet, ...
    models, ...
    positionErrors, ...
    velocityErrors, ...
    causalPrediction.eligibleMask);
[eventWinRateTable, pairedConfidenceIntervalTable] = ...
    localCompareEvents( ...
    pairSet, ...
    positionErrors, ...
    velocityErrors, ...
    causalPrediction.eligibleMask, ...
    confidenceLevel);
transitionMetricTable = localScoreTransitions( ...
    pairSet, ...
    models, ...
    positionErrors, ...
    velocityErrors, ...
    causalPrediction.eligibleMask);

runtimeTable = table( ...
    repmat(string(pairSet.domain), 5, 1), ...
    [ ...
        "expanded_warm_mean_v1"; ...
        "constvel"; ...
        "constacc"; ...
        "constturn"; ...
        "causal_history_initialization"], ...
    [ ...
        rowCount; ...
        rowCount; ...
        sum(causalPrediction.eligibleMask); ...
        sum(causalPrediction.eligibleMask); ...
        rowCount], ...
    [ ...
        warmSeconds; ...
        constvelSeconds; ...
        causalRuntime.constaccSeconds; ...
        causalRuntime.constturnSeconds; ...
        causalRuntime.initializationSeconds], ...
    'VariableNames', [ ...
        "domain", ...
        "modelID", ...
        "pairCount", ...
        "elapsedSeconds"]);
runtimeTable.microsecondsPerPair = ...
    1e6*runtimeTable.elapsedSeconds ./ max(runtimeTable.pairCount, 1);

matchedGroups = groupsummary( ...
    metricTable, ...
    ["domain", "profile", "comparisonFamily", "weighting"], ...
    ["min", "max"], ...
    "sampleCount");
audit = struct();
audit.rowCount = rowCount;
audit.sameInformationRowCount = rowCount;
audit.causalHistoryRowCount = sum(causalPrediction.eligibleMask);
audit.finiteWarmPrediction = all(isfinite(warmPrediction), "all");
audit.finiteConstvelPrediction = all(isfinite(constvelPrediction), "all");
audit.finiteCausalPredictions = all(isfinite( ...
    causalPrediction.constaccPrediction(causalPrediction.eligibleMask, :)), ...
    "all") && all(isfinite( ...
    causalPrediction.constturnPrediction(causalPrediction.eligibleMask, :)), ...
    "all");
audit.matchedComparisonRows = all( ...
    matchedGroups.min_sampleCount == matchedGroups.max_sampleCount);
audit.warmUsesPredecessorHistory = false;
audit.constvelUsesPredecessorHistory = false;
audit.constaccUsesPredecessorHistory = true;
audit.constturnUsesPredecessorHistory = true;
audit.targetStateUsedForPrediction = false;
audit.motionLabelUsedForPrediction = false;
audit.passed = audit.finiteWarmPrediction && ...
    audit.finiteConstvelPrediction && ...
    audit.finiteCausalPredictions && ...
    audit.matchedComparisonRows && ...
    ~audit.targetStateUsedForPrediction && ...
    ~audit.motionLabelUsedForPrediction;

evaluation = struct();
evaluation.domain = string(pairSet.domain);
evaluation.metricTable = metricTable;
evaluation.canonicalMetricTable = canonicalMetricTable;
evaluation.eventWinRateTable = eventWinRateTable;
evaluation.pairedConfidenceIntervalTable = pairedConfidenceIntervalTable;
evaluation.transitionMetricTable = transitionMetricTable;
evaluation.runtimeTable = runtimeTable;
evaluation.audit = audit;
evaluation.causalPolicy = causalPrediction.policy;
evaluation.confidenceIntervalMethod = ...
    "Paired event-RMSE mean difference with a two-sided Student t interval.";
evaluation.errorDifferenceConvention = ...
    "Warm minus comparator; negative values favor the warm model.";

if retainPredictions
    evaluation.predictionReview = struct( ...
        "warm", warmPrediction, ...
        "constvel", constvelPrediction, ...
        "constacc", causalPrediction.constaccPrediction, ...
        "constturn", causalPrediction.constturnPrediction, ...
        "causalEligibleMask", causalPrediction.eligibleMask, ...
        "predecessorRow", causalPrediction.predecessorRow);
end

end

function predictedState = localPredictConstvel(previousState, dtSeconds)
%LOCALPREDICTCONSTVEL Apply native constvel for every distinct interval.

predictedState = NaN(size(previousState));
[uniqueDtSeconds, ~, dtGroup] = unique(dtSeconds);

for groupIdx = 1:numel(uniqueDtSeconds)
    rowMask = dtGroup == groupIdx;
    predicted = constvel( ...
        previousState(rowMask, :).', ...
        uniqueDtSeconds(groupIdx));
    predictedState(rowMask, :) = predicted.';
end

end

function predictedState = localPredictWarm( ...
        previousState, ...
        previousCovarianceDiag, ...
        dtSeconds, ...
        constvelPrediction, ...
        warmModel, ...
        miniBatchSize)
%LOCALPREDICTWARM Run the frozen warm network in physical units.

featureData = helperBuildStage4CFeatures( ...
    previousState, ...
    previousCovarianceDiag, ...
    dtSeconds, ...
    constvelPrediction);
featureNormalization = warmModel.featureNormalization;
targetNormalization = warmModel.targetNormalization;
normalizedFeatures = ...
    (featureData.features - featureNormalization.featureMean) ./ ...
    featureNormalization.featureStd;
normalizedDelta = minibatchpredict( ...
    warmModel.net, ...
    single(normalizedFeatures), ...
    MiniBatchSize=min(miniBatchSize, size(normalizedFeatures, 1)));
normalizedDelta = gather(extractdata(normalizedDelta));

if size(normalizedDelta, 1) ~= size(previousState, 1) && ...
        size(normalizedDelta, 2) == size(previousState, 1)
    normalizedDelta = normalizedDelta.';
end

if ~isequal(size(normalizedDelta), size(previousState))
    error("Stage4D:WarmPredictionShapeMismatch", ...
        "The frozen warm model must return one six-state delta per input row.");
end

physicalDelta = double(normalizedDelta) .* ...
    targetNormalization.targetStd + ...
    targetNormalization.targetMean;
predictedState = previousState + physicalDelta;

end

function [prediction, runtime] = localPredictCausalNative(pairSet)
%LOCALPREDICTCAUSALNATIVE Initialize CA and CT from one predecessor.

initializationTimer = tic;
rowCount = size(pairSet.previousState, 1);
predecessorRow = zeros(rowCount, 1);

if rowCount > 1
    sameEvent = pairSet.eventID(2:end) == pairSet.eventID(1:end - 1);
    adjacentTime = abs( ...
        pairSet.timeKSeconds(2:end) - ...
        pairSet.timeNextSeconds(1:end - 1)) <= 1e-9;
    hasPredecessor = sameEvent & adjacentTime;
    predecessorRow(find(hasPredecessor) + 1) = find(hasPredecessor);
end

eligibleMask = predecessorRow > 0;
eligibleRows = find(eligibleMask);
priorRows = predecessorRow(eligibleRows);
priorDtSeconds = ...
    pairSet.timeKSeconds(eligibleRows) - ...
    pairSet.timeKSeconds(priorRows);
currentVelocity = pairSet.previousState(eligibleRows, [2, 4, 6]);
priorVelocity = pairSet.previousState(priorRows, [2, 4, 6]);
rawAcceleration = ...
    (currentVelocity - priorVelocity) ./ priorDtSeconds;
currentHeadingDegrees = atan2d(currentVelocity(:, 2), currentVelocity(:, 1));
priorHeadingDegrees = atan2d(priorVelocity(:, 2), priorVelocity(:, 1));
rawTurnRateDegreesPerSecond = ...
    wrapTo180(currentHeadingDegrees - priorHeadingDegrees) ./ priorDtSeconds;
finiteInitialization = ...
    all(isfinite(rawAcceleration), 2) & ...
    isfinite(rawTurnRateDegreesPerSecond) & ...
    isfinite(priorDtSeconds) & ...
    priorDtSeconds > 0;
eligibleMask(eligibleRows(~finiteInitialization)) = false;
eligibleRows = find(eligibleMask);
priorRows = predecessorRow(eligibleRows);
priorDtSeconds = ...
    pairSet.timeKSeconds(eligibleRows) - ...
    pairSet.timeKSeconds(priorRows);
currentVelocity = pairSet.previousState(eligibleRows, [2, 4, 6]);
priorVelocity = pairSet.previousState(priorRows, [2, 4, 6]);
rawAcceleration = ...
    (currentVelocity - priorVelocity) ./ priorDtSeconds;
currentHeadingDegrees = atan2d(currentVelocity(:, 2), currentVelocity(:, 1));
priorHeadingDegrees = atan2d(priorVelocity(:, 2), priorVelocity(:, 1));
rawTurnRateDegreesPerSecond = ...
    wrapTo180(currentHeadingDegrees - priorHeadingDegrees) ./ priorDtSeconds;
constaccInitialState = [ ...
    pairSet.previousState(eligibleRows, 1), ...
    pairSet.previousState(eligibleRows, 2), ...
    rawAcceleration(:, 1), ...
    pairSet.previousState(eligibleRows, 3), ...
    pairSet.previousState(eligibleRows, 4), ...
    rawAcceleration(:, 2), ...
    pairSet.previousState(eligibleRows, 5), ...
    pairSet.previousState(eligibleRows, 6), ...
    rawAcceleration(:, 3)];
constturnInitialState = [ ...
    pairSet.previousState(eligibleRows, 1), ...
    pairSet.previousState(eligibleRows, 2), ...
    pairSet.previousState(eligibleRows, 3), ...
    pairSet.previousState(eligibleRows, 4), ...
    rawTurnRateDegreesPerSecond, ...
    pairSet.previousState(eligibleRows, 5), ...
    pairSet.previousState(eligibleRows, 6)];
runtime = struct();
runtime.initializationSeconds = toc(initializationTimer);

constaccTimer = tic;
constaccState = localPropagateByDt( ...
    constaccInitialState, ...
    pairSet.dtSeconds(eligibleRows), ...
    "constacc");
runtime.constaccSeconds = toc(constaccTimer);
constturnTimer = tic;
constturnState = localPropagateByDt( ...
    constturnInitialState, ...
    pairSet.dtSeconds(eligibleRows), ...
    "constturn");
runtime.constturnSeconds = toc(constturnTimer);

constaccPrediction = NaN(rowCount, 6);
constturnPrediction = NaN(rowCount, 6);
constaccPrediction(eligibleRows, :) = ...
    constaccState(:, [1, 2, 4, 5, 7, 8]);
constturnPrediction(eligibleRows, :) = ...
    constturnState(:, [1, 2, 3, 4, 6, 7]);
finitePrediction = ...
    all(isfinite(constaccPrediction), 2) & ...
    all(isfinite(constturnPrediction), 2);
eligibleMask = eligibleMask & finitePrediction;

prediction = struct();
prediction.eligibleMask = eligibleMask;
prediction.constaccPrediction = constaccPrediction;
prediction.constturnPrediction = constturnPrediction;
prediction.predecessorRow = predecessorRow;
prediction.policy = table( ...
    ["constacc"; "constturn"], ...
    ["raw 3-D velocity finite difference"; "wrapped ENU heading finite difference"], ...
    [true; true], ...
    [false; false], ...
    [false; false], ...
    'VariableNames', [ ...
        "modelID", ...
        "causalInitialization", ...
        "usesPredecessorHistory", ...
        "usesTargetState", ...
        "usesMotionLabel"]);

end

function predictedState = localPropagateByDt(initialState, dtSeconds, modelName)
%LOCALPROPAGATEBYDT Apply one native motion function per distinct interval.

predictedState = NaN(size(initialState));
[uniqueDtSeconds, ~, dtGroup] = unique(dtSeconds);

for groupIdx = 1:numel(uniqueDtSeconds)
    rowMask = dtGroup == groupIdx;

    if modelName == "constacc"
        predicted = constacc( ...
            initialState(rowMask, :).', ...
            uniqueDtSeconds(groupIdx));
    elseif modelName == "constturn"
        predicted = constturn( ...
            initialState(rowMask, :).', ...
            uniqueDtSeconds(groupIdx));
    else
        error("Stage4D:UnknownNativeModel", ...
            "Native model must be constacc or constturn.");
    end

    predictedState(rowMask, :) = predicted.';
end

end

function models = localBuildModels( ...
        warmPrediction, constvelPrediction, causalPrediction)
%LOCALBUILDMODELS Preserve the fixed Stage 4D comparison order.

models = repmat(struct( ...
    "modelID", "", ...
    "prediction", []), ...
    4, ...
    1);
models(1).modelID = "expanded_warm_mean_v1";
models(1).prediction = warmPrediction;
models(2).modelID = "constvel";
models(2).prediction = constvelPrediction;
models(3).modelID = "constacc";
models(3).prediction = causalPrediction.constaccPrediction;
models(4).modelID = "constturn";
models(4).prediction = causalPrediction.constturnPrediction;

end

function errors = localStateErrors(models, targetState, stateColumns)
%LOCALSTATEERRORS Compute Euclidean state-subvector errors for each model.

errors = NaN(size(targetState, 1), numel(models));

for modelIdx = 1:numel(models)
    errors(:, modelIdx) = vecnorm( ...
        models(modelIdx).prediction(:, stateColumns) - ...
        targetState(:, stateColumns), ...
        2, ...
        2);
end

end

function metricTable = localScoreProfiles( ...
        pairSet, models, positionErrors, velocityErrors, causalMask)
%LOCALSCOREPROFILES Score pair- and event-weighted profile metrics.

profiles = unique(pairSet.profile, "stable");
metricRows = cell(numel(profiles)*12, 1);
rowIdx = 0;

for profileIdx = 1:numel(profiles)
    profileName = profiles(profileIdx);
    profileMask = pairSet.profile == profileName;
    [metricRows, rowIdx] = localAppendFamilyMetrics( ...
        metricRows, ...
        rowIdx, ...
        pairSet, ...
        models, ...
        positionErrors, ...
        velocityErrors, ...
        profileMask, ...
        "same_information", ...
        [1, 2], ...
        profileName);
    [metricRows, rowIdx] = localAppendFamilyMetrics( ...
        metricRows, ...
        rowIdx, ...
        pairSet, ...
        models, ...
        positionErrors, ...
        velocityErrors, ...
        profileMask & causalMask, ...
        "causal_history", ...
        1:4, ...
        profileName);
end

metricTable = vertcat(metricRows{1:rowIdx});

end

