function value = localWeightedRMSE(errors, weights)
%LOCALWEIGHTEDRMSE Compute weighted root mean square error.

value = sqrt(sum(weights .* errors .^ 2) / sum(weights));

end

function value = localWeightedQuantile(values, weights, probability)
%LOCALWEIGHTEDQUANTILE Return a left-continuous weighted quantile.

[values, order] = sort(values);
weights = weights(order);
cumulativeWeight = cumsum(weights);
threshold = probability*cumulativeWeight(end);
quantileIndex = find(cumulativeWeight >= threshold, 1, "first");
value = values(quantileIndex);

end

