function localValidateInputs(pairSet, warmModel, miniBatchSize, confidenceLevel)
%LOCALVALIDATEINPUTS Enforce aligned inputs and frozen warm-model fields.

requiredPairFields = [ ...
    "domain", ...
    "previousState", ...
    "targetState", ...
    "previousCovarianceDiag", ...
    "dtSeconds", ...
    "timeKSeconds", ...
    "timeNextSeconds", ...
    "eventID", ...
    "caseID", ...
    "profile", ...
    "targetReference", ...
    "transitionOffsetSeconds"];
requiredWarmFields = [ ...
    "net", ...
    "featureNormalization", ...
    "targetNormalization"];

if ~isstruct(pairSet) || any(~isfield(pairSet, requiredPairFields))
    error("Stage4D:InvalidPairSet", ...
        "The Stage 4D pair set is missing required aligned fields.");
end

if ~isstruct(warmModel) || any(~isfield(warmModel, requiredWarmFields))
    error("Stage4D:InvalidWarmModel", ...
        "The warm model must contain net and feature/target normalization.");
end

rowCount = size(pairSet.previousState, 1);

if rowCount == 0 || ...
        ~isequal(size(pairSet.previousState), [rowCount, 6]) || ...
        ~isequal(size(pairSet.targetState), [rowCount, 6]) || ...
        ~isequal(size(pairSet.previousCovarianceDiag), [rowCount, 6]) || ...
        numel(pairSet.dtSeconds) ~= rowCount || ...
        numel(pairSet.timeKSeconds) ~= rowCount || ...
        numel(pairSet.timeNextSeconds) ~= rowCount || ...
        numel(pairSet.eventID) ~= rowCount || ...
        numel(pairSet.profile) ~= rowCount
    error("Stage4D:PairSetAlignmentMismatch", ...
        "All Stage 4D pair fields must describe identical N-by-6 rows.");
end

validateattributes(pairSet.previousState, ...
    {'numeric'}, {'2d', 'real', 'finite'}, mfilename, "previousState");
validateattributes(pairSet.targetState, ...
    {'numeric'}, {'2d', 'real', 'finite'}, mfilename, "targetState");
validateattributes(pairSet.previousCovarianceDiag, ...
    {'numeric'}, {'2d', 'real', 'finite', 'positive'}, ...
    mfilename, "previousCovarianceDiag");
validateattributes(pairSet.dtSeconds, ...
    {'numeric'}, {'column', 'real', 'finite', 'positive'}, ...
    mfilename, "dtSeconds");
validateattributes(miniBatchSize, ...
    {'numeric'}, {'scalar', 'integer', 'positive'}, ...
    mfilename, "PredictionMiniBatchSize");
validateattributes(confidenceLevel, ...
    {'numeric'}, {'scalar', 'real', '>', 0, '<', 1}, ...
    mfilename, "ConfidenceLevel");

end

function value = localLogicalScalar(value, argumentName)
%LOCALLOGICALSCALAR Accept scalar logical or numeric zero/one.

isLogicalScalar = islogical(value) && isscalar(value);
isBinaryNumericScalar = isnumeric(value) && isscalar(value) && ...
    isfinite(value) && (value == 0 || value == 1);

if ~isLogicalScalar && ~isBinaryNumericScalar
    error("Stage4D:InvalidLogicalOption", ...
        "%s must be a scalar logical value.", argumentName);
end

value = logical(value);

end
