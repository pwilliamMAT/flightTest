function [winTable, confidenceTable] = localCompareEvents( ...
        pairSet, positionErrors, velocityErrors, causalMask, confidenceLevel)
%LOCALCOMPAREEVENTS Compare paired event RMSE values against the warm model.

profiles = unique(pairSet.profile, "stable");
winRows = cell(numel(profiles)*4, 1);
confidenceRows = cell(numel(profiles)*4, 1);
rowIdx = 0;

for profileIdx = 1:numel(profiles)
    profileName = profiles(profileIdx);
    profileMask = pairSet.profile == profileName;
    [winRows, confidenceRows, rowIdx] = localAppendEventComparisons( ...
        winRows, ...
        confidenceRows, ...
        rowIdx, ...
        pairSet, ...
        positionErrors, ...
        velocityErrors, ...
        profileMask, ...
        profileName, ...
        "same_information", ...
        2, ...
        confidenceLevel);
    [winRows, confidenceRows, rowIdx] = localAppendEventComparisons( ...
        winRows, ...
        confidenceRows, ...
        rowIdx, ...
        pairSet, ...
        positionErrors, ...
        velocityErrors, ...
        profileMask & causalMask, ...
        profileName, ...
        "causal_history", ...
        2:4, ...
        confidenceLevel);
end

winTable = vertcat(winRows{1:rowIdx});
confidenceTable = vertcat(confidenceRows{1:rowIdx});

end

function [winRows, confidenceRows, rowIdx] = localAppendEventComparisons( ...
        winRows, ...
        confidenceRows, ...
        rowIdx, ...
        pairSet, ...
        positionErrors, ...
        velocityErrors, ...
        rowMask, ...
        profileName, ...
        comparisonFamily, ...
        comparatorIndices, ...
        confidenceLevel)
%LOCALAPPENDEVENTCOMPARISONS Add warm-versus-comparator event statistics.

selectedEventID = pairSet.eventID(rowMask);
[eventGroup, eventValues] = findgroups(selectedEventID);
warmPositionRMSE = splitapply( ...
    @(values) sqrt(mean(values .^ 2)), ...
    positionErrors(rowMask, 1), ...
    eventGroup);
warmVelocityRMSE = splitapply( ...
    @(values) sqrt(mean(values .^ 2)), ...
    velocityErrors(rowMask, 1), ...
    eventGroup);

for comparatorIdx = comparatorIndices
    comparatorPositionRMSE = splitapply( ...
        @(values) sqrt(mean(values .^ 2)), ...
        positionErrors(rowMask, comparatorIdx), ...
        eventGroup);
    comparatorVelocityRMSE = splitapply( ...
        @(values) sqrt(mean(values .^ 2)), ...
        velocityErrors(rowMask, comparatorIdx), ...
        eventGroup);
    positionDifference = warmPositionRMSE - comparatorPositionRMSE;
    velocityDifference = warmVelocityRMSE - comparatorVelocityRMSE;
    positionCI = localPairedMeanConfidenceInterval( ...
        positionDifference, ...
        confidenceLevel);
    velocityCI = localPairedMeanConfidenceInterval( ...
        velocityDifference, ...
        confidenceLevel);
    rowIdx = rowIdx + 1;
    comparatorID = localModelID(comparatorIdx);
    winRows{rowIdx} = table( ...
        string(pairSet.domain), ...
        string(profileName), ...
        string(comparisonFamily), ...
        comparatorID, ...
        numel(eventValues), ...
        mean(positionDifference < 0), ...
        mean(abs(positionDifference) <= 1e-12), ...
        mean(velocityDifference < 0), ...
        mean(abs(velocityDifference) <= 1e-12), ...
        'VariableNames', [ ...
            "domain", ...
            "profile", ...
            "comparisonFamily", ...
            "comparatorModelID", ...
            "eventCount", ...
            "warmPositionWinRate", ...
            "positionTieRate", ...
            "warmVelocityWinRate", ...
            "velocityTieRate"]);
    confidenceRows{rowIdx} = table( ...
        string(pairSet.domain), ...
        string(profileName), ...
        string(comparisonFamily), ...
        comparatorID, ...
        numel(eventValues), ...
        confidenceLevel, ...
        mean(positionDifference), ...
        positionCI(1), ...
        positionCI(2), ...
        mean(velocityDifference), ...
        velocityCI(1), ...
        velocityCI(2), ...
        'VariableNames', [ ...
            "domain", ...
            "profile", ...
            "comparisonFamily", ...
            "comparatorModelID", ...
            "eventCount", ...
            "confidenceLevel", ...
            "meanPositionRMSEDifferenceMeters", ...
            "positionDifferenceLower", ...
            "positionDifferenceUpper", ...
            "meanVelocityRMSEDifferenceMetersPerSecond", ...
            "velocityDifferenceLower", ...
            "velocityDifferenceUpper"]);
end

end

function transitionTable = localScoreTransitions( ...
        pairSet, models, positionErrors, velocityErrors, causalMask)
%LOCALSCORETRANSITIONS Summarize error relative to the nearest motion change.

transitionEdges = [-30, -10, 0, 10, 30, 60];
transitionLabels = [ ...
    "minus30_to_minus10"; ...
    "minus10_to_0"; ...
    "0_to_10"; ...
    "10_to_30"; ...
    "30_to_60"];
transitionBin = discretize( ...
    pairSet.transitionOffsetSeconds, ...
    transitionEdges);

if all(isnan(transitionBin))
    transitionTable = localEmptyTransitionTable();
    return;
end

profiles = unique(pairSet.profile, "stable");
transitionRows = cell(numel(profiles)*numel(transitionLabels)*6, 1);
rowIdx = 0;

for profileIdx = 1:numel(profiles)
    profileName = profiles(profileIdx);

    for binIdx = 1:numel(transitionLabels)
        baseMask = pairSet.profile == profileName & transitionBin == binIdx;
        [transitionRows, rowIdx] = localAppendTransitionRows( ...
            transitionRows, ...
            rowIdx, ...
            pairSet, ...
            models, ...
            positionErrors, ...
            velocityErrors, ...
            baseMask, ...
            profileName, ...
            "same_information", ...
            [1, 2], ...
            transitionLabels(binIdx), ...
            mean(transitionEdges(binIdx:(binIdx + 1))));
        [transitionRows, rowIdx] = localAppendTransitionRows( ...
            transitionRows, ...
            rowIdx, ...
            pairSet, ...
            models, ...
            positionErrors, ...
            velocityErrors, ...
            baseMask & causalMask, ...
            profileName, ...
            "causal_history", ...
            1:4, ...
            transitionLabels(binIdx), ...
            mean(transitionEdges(binIdx:(binIdx + 1))));
    end
end

transitionTable = vertcat(transitionRows{1:rowIdx});

end

function [transitionRows, rowIdx] = localAppendTransitionRows( ...
        transitionRows, ...
        rowIdx, ...
        pairSet, ...
        models, ...
        positionErrors, ...
        velocityErrors, ...
        rowMask, ...
        profileName, ...
        comparisonFamily, ...
        modelIndices, ...
        transitionBin, ...
        transitionBinCenterSeconds)
%LOCALAPPENDTRANSITIONROWS Add pair-weighted errors for one time bin.

for modelIdx = modelIndices
    positionError = positionErrors(rowMask, modelIdx);
    velocityError = velocityErrors(rowMask, modelIdx);
    rowIdx = rowIdx + 1;
    transitionRows{rowIdx} = table( ...
        string(pairSet.domain), ...
        string(profileName), ...
        string(comparisonFamily), ...
        string(models(modelIdx).modelID), ...
        string(transitionBin), ...
        transitionBinCenterSeconds, ...
        numel(positionError), ...
