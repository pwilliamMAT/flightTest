function localValidateConfig(config)
%LOCALVALIDATECONFIG Validate modes, files, and protected outputs.

if ~ismember(config.BenchmarkMode, ["smoke", "full"])
    error("Stage4E:InvalidBenchmarkMode", ...
        "BenchmarkMode must be smoke or full.");
end

validateattributes(config.Seed, ...
    {'numeric'}, {'scalar', 'integer', 'nonnegative', 'finite'}, ...
    mfilename, "Seed");
requiredPaths = [ ...
    config.WarmArtifactPath; ...
    config.DatasetPath; ...
    config.SplitManifestPath];

for pathIdx = 1:numel(requiredPaths)
    if exist(requiredPaths(pathIdx), "file") ~= 2
        error("Stage4E:MissingInputFile", ...
            "Required frozen input was not found: %s", requiredPaths(pathIdx));
    end
end

protectedPaths = lower(requiredPaths);

if ismember(lower(config.ResultsPath), protectedPaths) || ...
        ismember(lower(config.TuningPath), protectedPaths)
    error("Stage4E:ProtectedArtifactCollision", ...
        "Stage 4E outputs cannot overwrite frozen Stage 4C inputs.");
end

end

function [dataset, split, audit] = localLoadFrozenInputs(config)
%LOCALLOADFROZENINPUTS Load the fixed Expanded-3Day data and split.

dataset = load( ...
    config.DatasetPath, ...
    "previousState", ...
    "nextState", ...
    "dtSeconds", ...
    "previousCovarianceDiag", ...
    "covarianceStdAssumed", ...
    "metadata", ...
    "stateOrder");
rowCount = size(dataset.previousState, 1);
expectedStateOrder = ["x", "vx", "y", "vy", "z", "vz"];

if rowCount ~= 457903 || ...
        ~isequal(size(dataset.previousState), [rowCount, 6]) || ...
        ~isequal(size(dataset.nextState), [rowCount, 6]) || ...
        ~isequal(size(dataset.previousCovarianceDiag), [rowCount, 6]) || ...
        height(dataset.metadata) ~= rowCount || ...
        numel(dataset.dtSeconds) ~= rowCount || ...
        any(string(dataset.stateOrder(:).') ~= expectedStateOrder)
    error("Stage4E:DatasetContractMismatch", ...
        "The frozen Expanded-3Day dataset contract has changed.");
end

manifest = readtable(config.SplitManifestPath, TextType="string");
[found, manifestRows] = ismember( ...
    lower(strtrim(string(dataset.metadata.hex))), ...
    lower(strtrim(string(manifest.icao24))));

if ~all(found)
    error("Stage4E:SplitMembershipMismatch", ...
        "Every dataset ICAO must occur in the frozen split manifest.");
end

split = lower(strtrim(string(manifest.split(manifestRows))));
splitCounts = [ ...
    sum(split == "train"), ...
    sum(split == "validation"), ...
    sum(split == "test")];

if ~isequal(splitCounts, [277959, 86420, 93524])
    error("Stage4E:SplitCountMismatch", ...
        "The frozen train/validation/test pair counts have changed.");
end

audit = struct();
audit.datasetSHA256 = helperComputeFileSHA256(config.DatasetPath);
audit.splitSHA256 = helperComputeFileSHA256(config.SplitManifestPath);
audit.splitCounts = splitCounts;
audit.stateOrder = expectedStateOrder;
audit.fixedTrainingCovarianceDiag = ...
    double(dataset.covarianceStdAssumed(:).').^2;

end

