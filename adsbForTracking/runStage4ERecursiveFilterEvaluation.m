function value = localTextScalar(value, argumentName, allowEmpty)
%LOCALTEXTSCALAR Normalize a text option.

isCharacterVector = ischar(value) && (isrow(value) || isempty(value));
isStringScalar = isstring(value) && isscalar(value);

if ~isCharacterVector && ~isStringScalar
    error("Stage4E:InvalidTextOption", ...
        "%s must be a character vector or string scalar.", argumentName);
end

value = strtrim(string(value));

if ismissing(value) || (~allowEmpty && strlength(value) == 0)
    error("Stage4E:InvalidTextOption", ...
        "%s must not be empty.", argumentName);
end

end

function value = localLogicalScalar(value, argumentName)
%LOCALLOGICALSCALAR Validate a scalar logical-like option.

if ~(islogical(value) || isnumeric(value)) || ...
        ~isscalar(value) || ...
        ~isfinite(double(value))
    error("Stage4E:InvalidLogicalOption", ...
        "%s must be a finite scalar logical value.", argumentName);
end

value = logical(value);

end

function resolvedPath = localResolvePath(projectRoot, value, defaultPath)
%LOCALRESOLVEPATH Resolve optional paths relative to the project.

value = localTextScalar(value, "path", true);

if strlength(value) == 0
    value = string(defaultPath);
end

if localIsAbsolutePath(value)
    resolvedPath = localCanonicalPath(value);
else
    resolvedPath = localCanonicalPath(fullfile(projectRoot, value));
end

end

function canonicalPath = localCanonicalPath(pathValue)
%LOCALCANONICALPATH Normalize a path without requiring it to exist.

try
    canonicalPath = string(java.io.File(char(pathValue)).getCanonicalPath());
catch err
    error("Stage4E:PathResolutionFailed", ...
        "Unable to resolve path %s: %s", pathValue, err.message);
end

end

function tf = localIsAbsolutePath(pathValue)
%LOCALISABSOLUTEPATH Identify Windows or UNC absolute paths.

pathValue = char(pathValue);
tf = ~isempty(regexp(pathValue, '^[A-Za-z]:[\\/]', 'once')) || ...
    startsWith(pathValue, "\\") || ...
    startsWith(pathValue, "/");

end

function text = localBooleanText(value)
%LOCALBOOLEANTEXT Convert a scalar logical to lowercase text.

if value
    text = "true";
else
    text = "false";
end

end
