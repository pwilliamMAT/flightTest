function [detectionLogs, truthTables, summary] = ...
        localBuildValidationTuningData(dataset, split, config)
%LOCALBUILDVALIDATIONTUNINGDATA Reserve validation events for tuner use.

[orderedRows, eventID, eventTable] = localFindEvents( ...
    dataset, ...
    split, ...
    "validation");
eventTable = sortrows( ...
    eventTable, ...
    ["pairCount", "sessionID", "icao24", "startTime"], ...
    ["descend", "ascend", "ascend", "ascend"]);
tuningEventCount = min(3, height(eventTable));
eventTable = eventTable(1:tuningEventCount, :);
maximumTuningPairsPerEvent = 120;
detectionLogs = cell(tuningEventCount, 1);
truthTables = cell(tuningEventCount, 1);
eventKeys = strings(tuningEventCount, 1);

for selectedIdx = 1:tuningEventCount
    selectedEventID = eventTable.originalEventID(selectedIdx);
    eventRows = orderedRows(eventID == selectedEventID);
    eventRows = eventRows(1:min(maximumTuningPairsPerEvent, numel(eventRows)));
    state = [ ...
        double(dataset.previousState(eventRows, :)); ...
        double(dataset.nextState(eventRows(end), :))];
    eventStart = dataset.metadata.timeUtcK(eventRows(1));
    timeSeconds = [ ...
        seconds(dataset.metadata.timeUtcK(eventRows) - eventStart); ...
        seconds(dataset.metadata.timeUtcNext(eventRows(end)) - eventStart)];
    measurementNoise = diag([30, 30, 45].^2);
    covarianceDiag = double(dataset.previousCovarianceDiag(eventRows(1), :));
    detectionLog = cell(numel(timeSeconds), 1);

    for sampleIdx = 1:numel(timeSeconds)
        attributes = struct( ...
            "InitialVelocity", state(1, [2, 4, 6]), ...
            "InitialCovarianceDiag", covarianceDiag);
        detectionLog{sampleIdx} = objectDetection( ...
            timeSeconds(sampleIdx), ...
            state(sampleIdx, [1, 3, 5]).', ...
            MeasurementNoise=measurementNoise, ...
            ObjectAttributes={attributes});
    end

    detectionLogs{selectedIdx} = detectionLog;
    truthTables{selectedIdx} = timetable( ...
        seconds(timeSeconds), ...
        state, ...
        'VariableNames', {'State'});
    eventKeys(selectedIdx) = ...
        string(eventTable.sessionID(selectedIdx)) + "::" + ...
        string(eventTable.icao24(selectedIdx));
end

summary = struct();
summary.split = "validation";
summary.eventCount = tuningEventCount;
summary.eventKeys = eventKeys;
summary.detectionCount = sum(cellfun(@numel, detectionLogs));
summary.maximumPairsPerEvent = maximumTuningPairsPerEvent;
summary.testRowsUsed = false;
summary.seed = config.Seed;

end

function tuning = localResolveTuning( ...
        detectionLogs, ...
        truthTables, ...
        validationSummary, ...
        config, ...
        warmAudit, ...
        inputAudit)
%LOCALRESOLVETUNING Create or load the frozen validation-only tuning result.

if config.RetuneFilters
    tuning = helperTuneStage4EFilters( ...
        detectionLogs, ...
        truthTables, ...
        Seed=config.Seed + 4001, ...
        Verbose=config.Verbose);
    tuning.validationSummary = validationSummary;
    tuning.datasetSHA256 = inputAudit.datasetSHA256;
    tuning.splitSHA256 = inputAudit.splitSHA256;
    tuning.warmSHA256 = warmAudit.sha256;
    tuning.frozenAt = datetime("now", "TimeZone", "UTC");
    tuningPathFolder = string(fileparts(config.TuningPath));

    if ~isfolder(tuningPathFolder)
        mkdir(tuningPathFolder);
    end

    stage4ETuning = tuning;
    save(config.TuningPath, "stage4ETuning", "-v7.3");
elseif exist(config.TuningPath, "file") == 2
    loaded = load(config.TuningPath, "stage4ETuning");
    tuning = loaded.stage4ETuning;
else
    error("Stage4E:MissingFrozenTuning", ...
        "No frozen Stage 4E tuning exists. Run once with RetuneFilters=true.");
end

requiredFields = [ ...
    "completed", ...
    "validationOnly", ...
    "networkTrainingPerformed", ...
    "parameters", ...
    "datasetSHA256", ...
    "splitSHA256", ...
    "warmSHA256", ...
    "frozenAt", ...
    "validationSummary"];

if any(~isfield(tuning, requiredFields)) || ...
        ~tuning.completed || ...
        ~tuning.validationOnly || ...
        tuning.networkTrainingPerformed || ...
        ~strcmpi(tuning.datasetSHA256, inputAudit.datasetSHA256) || ...
        ~strcmpi(tuning.splitSHA256, inputAudit.splitSHA256) || ...
        ~strcmpi(tuning.warmSHA256, warmAudit.sha256)
    error("Stage4E:InvalidFrozenTuning", ...
        "Frozen tuning must match validation-only data and Stage 4C hashes.");
end

end

function [sequences, summary] = localBuildSyntheticSequences( ...
        dataset, split, config)
%LOCALBUILDSYNTHETICSEQUENCES Generate full-grid recursive test sequences.

trainMask = split == "train";
empiricalDtSeconds = double(dataset.dtSeconds(trainMask));
fixedCovarianceDiag = median( ...
    double(dataset.previousCovarianceDiag(trainMask, :)), ...
    1);

if config.BenchmarkMode == "full"
    canonicalDurationSeconds = 120;
    mixedDurationSeconds = 600;
    inDistributionCount = 6;
    outOfDistributionCount = 3;
else
    canonicalDurationSeconds = 30;
    mixedDurationSeconds = 60;
    inDistributionCount = 2;
    outOfDistributionCount = 1;
end

canonical = helperGenerateStage4DSyntheticBenchmark( ...
    "canonical", ...
    BenchmarkMode=config.BenchmarkMode, ...
    Seed=config.Seed, ...
    EmpiricalDtSeconds=empiricalDtSeconds, ...
    PreviousCovarianceDiag=fixedCovarianceDiag, ...
    DurationSeconds=canonicalDurationSeconds, ...
    SampleRateHz=2);
inDistribution = helperGenerateStage4DSyntheticBenchmark( ...
    "in_distribution", ...
    BenchmarkMode=config.BenchmarkMode, ...
    Seed=config.Seed, ...
    EmpiricalDtSeconds=empiricalDtSeconds, ...
    PreviousCovarianceDiag=fixedCovarianceDiag, ...
    TrajectoryCount=inDistributionCount, ...
    DurationSeconds=mixedDurationSeconds, ...
    SampleRateHz=2);
outOfDistribution = helperGenerateStage4DSyntheticBenchmark( ...
    "out_of_distribution", ...
    BenchmarkMode=config.BenchmarkMode, ...
    Seed=config.Seed, ...
    EmpiricalDtSeconds=empiricalDtSeconds, ...
    PreviousCovarianceDiag=fixedCovarianceDiag, ...
    TrajectoryCount=outOfDistributionCount, ...
    DurationSeconds=mixedDurationSeconds, ...
    SampleRateHz=2);
sequences = [ ...
    localConvertSyntheticBenchmark(canonical, "synthetic_canonical"); ...
    localConvertSyntheticBenchmark( ...
    inDistribution, ...
    "synthetic_in_distribution"); ...
    localConvertSyntheticBenchmark( ...
    outOfDistribution, ...
    "synthetic_out_of_distribution")];
summary = struct();
summary.canonicalTrajectoryCount = 7;
summary.inDistributionTrajectoryCount = inDistributionCount;
summary.outOfDistributionTrajectoryCount = outOfDistributionCount;
summary.profileCount = height(canonical.profileTable);
summary.sequenceCount = numel(sequences);
summary.sampleRateHz = 2;
summary.canonicalDurationSeconds = canonicalDurationSeconds;
summary.mixedDurationSeconds = mixedDurationSeconds;
summary.fullLatentGridScored = all(arrayfun( ...
    @(sequence) all(sequence.scoringMask(2:end)), ...
    sequences));
summary.motionScenarios = unique(string({sequences.motionScenario}));
summary.profiles = unique(string({sequences.profile}));

end

function sequences = localConvertSyntheticBenchmark(benchmark, domain)
%LOCALCONVERTSYNTHETICBENCHMARK Build recursive sequence records.

sourceSequences = benchmark.sequences;
sequences = repmat(localEmptySequence(), numel(sourceSequences), 1);

for sequenceIdx = 1:numel(sourceSequences)
    source = sourceSequences(sequenceIdx);
    sampleCount = numel(source.truthTimeSeconds);
    measurementState = NaN(sampleCount, 6);
    measurementState(source.observationTruthIndex, :) = ...
        source.observationState;
    updateMask = false(sampleCount, 1);
    updateMask(source.observationTruthIndex) = true;
    scoringMask = true(sampleCount, 1);
    scoringMask(1) = false;

    if source.profile(1) == "degraded"
        measurementNoise = diag([30, 30, 45].^2);
    else
        measurementNoise = eye(3);
    end

    sequences(sequenceIdx) = localEmptySequence();
    sequences(sequenceIdx).domain = string(domain);
    sequences(sequenceIdx).profile = source.profile(1);
    sequences(sequenceIdx).caseID = source.caseID(1);
    sequences(sequenceIdx).eventID = ...
        string(domain) + "::" + source.caseID(1);
    sequences(sequenceIdx).motionScenario = source.motionScenario(1);
    sequences(sequenceIdx).timeSeconds = source.truthTimeSeconds;
    sequences(sequenceIdx).referenceState = source.truthState;
    sequences(sequenceIdx).measurementState = measurementState;
    sequences(sequenceIdx).updateMask = updateMask;
    sequences(sequenceIdx).scoringMask = scoringMask;
    sequences(sequenceIdx).measurementNoise = measurementNoise;
    sequences(sequenceIdx).initialCovarianceDiag = ...
        source.previousCovarianceDiag(1, :);
    sequences(sequenceIdx).motionMode = source.truthMotionMode;
    sequences(sequenceIdx).targetReference = "latent_kinematic_truth";
    sequences(sequenceIdx).receiverOriginLLA = ...
        [42.2999333, -71.349333, 15.0];
end

end

function [sequences, protocol] = localBuildRealSequences( ...
        dataset, split, splitName, config)
%LOCALBUILDREALSEQUENCES Reserve score rows before applying update dropout.

[orderedRows, eventID, eventTable] = localFindEvents( ...
    dataset, ...
    split, ...
    splitName);
eventTable = sortrows( ...
    eventTable, ...
    ["pairCount", "sessionID", "icao24", "startTime"], ...
    ["descend", "ascend", "ascend", "ascend"]);

if splitName == "validation"
    eventLimit = 3;
elseif config.BenchmarkMode == "full"
    eventLimit = 40;
else
    eventLimit = 4;
end

if config.BenchmarkMode == "smoke"
    maximumPairsPerEvent = 240;
else
    maximumPairsPerEvent = Inf;
end

eventTable = eventTable(1:min(eventLimit, height(eventTable)), :);
profileNames = [ ...
    "baseline"; ...
    "random_dropout_10"; ...
    "random_dropout_25"; ...
    "burst_outage"];
sequences = repmat( ...
    localEmptySequence(), ...
    height(eventTable)*numel(profileNames), ...
    1);
stream = RandStream("mt19937ar", "Seed", config.Seed + 5001);
sequenceIndex = 0;

for selectedIdx = 1:height(eventTable)
    selectedEventID = eventTable.originalEventID(selectedIdx);
    eventRows = orderedRows(eventID == selectedEventID);

    if isfinite(maximumPairsPerEvent)
        eventRows = eventRows( ...
            1:min(maximumPairsPerEvent, numel(eventRows)));
    end

    state = [ ...
        double(dataset.previousState(eventRows, :)); ...
        double(dataset.nextState(eventRows(end), :))];
    eventStart = dataset.metadata.timeUtcK(eventRows(1));
    timeSeconds = [ ...
        seconds(dataset.metadata.timeUtcK(eventRows) - eventStart); ...
        seconds(dataset.metadata.timeUtcNext(eventRows(end)) - eventStart)];
    scoringMask = false(numel(timeSeconds), 1);
    scoringMask(3:5:end) = true;

    if ~any(scoringMask)
        scoringMask(end) = true;
    end

    updateCandidateMask = ~scoringMask;
    updateCandidateMask(1) = true;
    eventKey = ...
        string(eventTable.sessionID(selectedIdx)) + "::" + ...
        string(eventTable.icao24(selectedIdx)) + "::" + ...
        string(eventTable.startTime(selectedIdx), "yyyyMMdd'T'HHmmss");

    for profileIdx = 1:numel(profileNames)
        profileName = profileNames(profileIdx);
        updateMask = localApplyRealDropout( ...
            updateCandidateMask, ...
            profileName, ...
            stream);
        sequenceIndex = sequenceIndex + 1;
        sequences(sequenceIndex) = localEmptySequence();
        sequences(sequenceIndex).domain = "real_adsb";
        sequences(sequenceIndex).profile = profileName;
        sequences(sequenceIndex).caseID = ...
            eventKey + "__" + profileName;
        sequences(sequenceIndex).eventID = eventKey;
        sequences(sequenceIndex).motionScenario = "observed_adsb";
        sequences(sequenceIndex).timeSeconds = timeSeconds;
        sequences(sequenceIndex).referenceState = state;
        sequences(sequenceIndex).measurementState = state;
        sequences(sequenceIndex).updateMask = updateMask;
        sequences(sequenceIndex).scoringMask = scoringMask;
        sequences(sequenceIndex).measurementNoise = diag([30, 30, 45].^2);
        sequences(sequenceIndex).initialCovarianceDiag = ...
            double(dataset.previousCovarianceDiag(eventRows(1), :));
        sequences(sequenceIndex).motionMode = ...
            repmat("unlabeled_real_adsb", numel(timeSeconds), 1);
        sequences(sequenceIndex).targetReference = "adsb_scoring_proxy";
        sequences(sequenceIndex).receiverOriginLLA = ...
            double(dataset.metadata.receiverOriginLLA(eventRows(1), :));
    end
end

protocol = struct();
protocol.split = string(splitName);
protocol.eventCount = height(eventTable);
protocol.profileNames = profileNames;
protocol.scoringStride = 5;
protocol.scoringRowsReservedBeforeDropout = true;
protocol.scoringReportsUsedForCorrection = any(arrayfun( ...
    @(sequence) any(sequence.scoringMask & sequence.updateMask), ...
    sequences));
protocol.sameScoringRowsAcrossProfiles = ...
    localSameScoringRowsAcrossProfiles(sequences);
protocol.targetReference = "adsb_scoring_proxy";
protocol.maximumPairsPerEvent = maximumPairsPerEvent;

end

function updateMask = localApplyRealDropout( ...
        updateCandidateMask, profileName, stream)
%LOCALAPPLYREALDROPOUT Drop only non-scoring update candidates.

updateMask = updateCandidateMask;
candidateRows = find(updateCandidateMask);
candidateRows(candidateRows == 1) = [];

switch profileName
    case "baseline"
        % Keep every non-scoring update candidate.
    case "random_dropout_10"
        dropped = rand(stream, numel(candidateRows), 1) < 0.10;
        updateMask(candidateRows(dropped)) = false;
    case "random_dropout_25"
        dropped = rand(stream, numel(candidateRows), 1) < 0.25;
        updateMask(candidateRows(dropped)) = false;
    case "burst_outage"
        outageCount = min( ...
            numel(candidateRows), ...
            max(1, round(0.20*numel(candidateRows))));

        if outageCount > 0
            maximumStart = numel(candidateRows) - outageCount + 1;
            outageStart = randi(stream, maximumStart);
            droppedRows = candidateRows( ...
                outageStart:(outageStart + outageCount - 1));
            updateMask(droppedRows) = false;
        end
    otherwise
        error("Stage4E:UnknownRealProfile", ...
            "Unknown real ADS-B profile: %s", profileName);
end

updateMask(1) = true;
updateMask(~updateCandidateMask) = false;

end

function [orderedRows, eventID, eventTable] = ...
        localFindEvents(dataset, split, splitName)
%LOCALFINDEVENTS Identify contiguous events from one frozen split.

selectedRows = find(split == splitName);
ordering = table( ...
    string(dataset.metadata.sessionID(selectedRows)), ...
    lower(strtrim(string(dataset.metadata.hex(selectedRows)))), ...
    dataset.metadata.timeUtcK(selectedRows), ...
    dataset.metadata.timeUtcNext(selectedRows), ...
    selectedRows, ...
    'VariableNames', [ ...
        "sessionID", ...
        "icao24", ...
        "timeUtcK", ...
        "timeUtcNext", ...
        "datasetRow"]);
ordering = sortrows( ...
    ordering, ...
    ["sessionID", "icao24", "timeUtcK", "timeUtcNext", "datasetRow"]);
orderedRows = ordering.datasetRow;
newEvent = true(height(ordering), 1);

if height(ordering) > 1
    sameTrack = ...
        ordering.sessionID(2:end) == ordering.sessionID(1:end - 1) & ...
        ordering.icao24(2:end) == ordering.icao24(1:end - 1);
    adjacentTime = abs(seconds( ...
        ordering.timeUtcK(2:end) - ...
        ordering.timeUtcNext(1:end - 1))) <= 1e-6;
    newEvent(2:end) = ~(sameTrack & adjacentTime);
end

eventID = cumsum(newEvent);
eventCount = max(eventID);
firstIndex = accumarray(eventID, (1:numel(eventID)).', [], @min);
lastIndex = accumarray(eventID, (1:numel(eventID)).', [], @max);
firstRows = orderedRows(firstIndex);
lastRows = orderedRows(lastIndex);
eventTable = table( ...
    (1:eventCount).', ...
    string(dataset.metadata.sessionID(firstRows)), ...
    lower(strtrim(string(dataset.metadata.hex(firstRows)))), ...
    dataset.metadata.timeUtcK(firstRows), ...
    dataset.metadata.timeUtcNext(lastRows), ...
    accumarray(eventID, 1), ...
    'VariableNames', [ ...
        "originalEventID", ...
        "sessionID", ...
        "icao24", ...
        "startTime", ...
        "endTime", ...
        "pairCount"]);

end

function same = localSameScoringRowsAcrossProfiles(sequences)
%LOCALSAMESCORINGROWSACROSSPROFILES Check profile-independent score rows.

same = true;
eventIDs = unique(string({sequences.eventID}), "stable");

for eventIdx = 1:numel(eventIDs)
    selected = sequences( ...
        string({sequences.eventID}) == eventIDs(eventIdx));
    referenceTime = selected(1).timeSeconds(selected(1).scoringMask);

    for profileIdx = 2:numel(selected)
        same = same && isequal( ...
            selected(profileIdx).timeSeconds( ...
            selected(profileIdx).scoringMask), ...
            referenceTime);
    end
end

end

