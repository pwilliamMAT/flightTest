function results = runStage4ERecursiveFilterEvaluation(varargin)
%RUNSTAGE4ERECURSIVEFILTEREVALUATION Benchmark complete recursive filters.
% Stage 4E compares native CV, CA, CT, and IMM estimators with a trackingUKF
% whose state transition is the frozen Stage 4C warm network.

projectRoot = string(fileparts(mfilename("fullpath")));
parser = inputParser;
parser.FunctionName = mfilename;
addParameter(parser, "BenchmarkMode", "smoke");
addParameter(parser, "Seed", 123);
addParameter(parser, "OutputFolder", "");
addParameter(parser, "ResultsPath", "");
addParameter(parser, "RetuneFilters", false);
addParameter(parser, "CreatePlots", true);
addParameter(parser, "Verbose", true);
parse(parser, varargin{:});

config = localBuildConfig(projectRoot, parser.Results);
localValidateConfig(config);
benchmarkTimer = tic;

if config.Verbose
    fprintf("Stage 4E recursive filter evaluation\n");
    fprintf("Benchmark mode:\t%s\n", config.BenchmarkMode);
    fprintf("Retune filters:\t%s\n", string(config.RetuneFilters));
end

warmHashBefore = helperComputeFileSHA256(config.WarmArtifactPath);
[dataset, split, inputAudit] = localLoadFrozenInputs(config);
warmAudit = localAuditWarmArtifact(config, warmHashBefore);
[validationDetectionLogs, validationTruthTables, validationSummary] = ...
    localBuildValidationTuningData( ...
    dataset, ...
    split, ...
    config);
tuning = localResolveTuning( ...
    validationDetectionLogs, ...
    validationTruthTables, ...
    validationSummary, ...
    config, ...
    warmAudit, ...
    inputAudit);
tuningFrozenBeforeTest = exist(config.TuningPath, "file") == 2;

[syntheticSequences, syntheticSummary] = localBuildSyntheticSequences( ...
    dataset, ...
    split, ...
    config);
[realSequences, realProtocol] = localBuildRealSequences( ...
    dataset, ...
    split, ...
    "test", ...
    config);
[realRepeat, ~] = localBuildRealSequences( ...
    dataset, ...
    split, ...
    "test", ...
    config);
deterministicRealDropout = localSequencesEqual( ...
    realSequences, ...
    realRepeat);
clear realRepeat
allSequences = [syntheticSequences(:); realSequences(:)];
evaluationStartedAt = datetime("now", "TimeZone", "UTC");
evaluation = helperEvaluateStage4ESequences( ...
    allSequences, ...
    tuning, ...
    Verbose=config.Verbose);
clear allSequences syntheticSequences realSequences dataset

warmHashAfter = helperComputeFileSHA256(config.WarmArtifactPath);
artifactAudit = localBuildArtifactAudit( ...
    config, ...
    warmAudit, ...
    inputAudit, ...
    tuning, ...
    warmHashBefore, ...
    warmHashAfter);
verificationTable = localBuildVerificationTable( ...
    evaluation, ...
    realProtocol, ...
    syntheticSummary, ...
    tuning, ...
    config, ...
    tuningFrozenBeforeTest, ...
    evaluationStartedAt, ...
    deterministicRealDropout, ...
    warmHashBefore, ...
    warmHashAfter);

if ~isfolder(config.OutputFolder)
    mkdir(config.OutputFolder);
end

resultsFolder = string(fileparts(config.ResultsPath));

if strlength(resultsFolder) > 0 && ~isfolder(resultsFolder)
    mkdir(resultsFolder);
end

results = struct();
results.generatedAt = datetime("now", "TimeZone", "UTC");
results.stage = "4E";
results.completed = all(verificationTable.passed);
results.benchmarkMode = config.BenchmarkMode;
results.randomSeed = config.Seed;
results.interpretation = ...
    "Recursive filter behavior with position-only updates; real ADS-B is a scoring proxy.";
results.config = localBuildConfigurationTable( ...
    config, ...
    syntheticSummary, ...
    realProtocol, ...
    validationSummary);
results.nativeFunctionAudit = localBuildNativeFunctionAudit();
results.artifactAudit = artifactAudit;
results.verificationTable = verificationTable;
results.tuningSummary = rmfield(tuning, 'parameters');
results.metricTable = evaluation.metricTable;
results.eventMetricTable = evaluation.eventMetricTable;
results.motionMetricTable = evaluation.motionMetricTable;
results.outageAgeMetricTable = evaluation.outageAgeMetricTable;
results.eventWinRateTable = evaluation.eventWinRateTable;
results.consistencyTable = evaluation.consistencyTable;
results.runtimeTable = evaluation.runtimeTable;
results.inputAuditTable = evaluation.inputAuditTable;
results.syntheticSummary = syntheticSummary;
results.realProtocol = realProtocol;
results.representativePaths = evaluation.representativePaths;
results.trainingPerformed = false;
results.networkPredictsCovariance = false;
results.associationEvaluated = false;
results.passiveRadarPerformanceEvaluated = false;
results.paths = localBuildOutputPaths(config);
results.figurePaths = struct("summary", "");
results.elapsedSeconds = toc(benchmarkTimer);

if config.CreatePlots
    plotOutput = helperPlotStage4ERecursiveEvaluation( ...
        results, ...
        SavePath=results.paths.summaryFigure);
    results.figurePaths.summary = plotOutput.savePath;
end

localWriteResults(results);

if config.Verbose
    fprintf("Stage 4E complete:\t%s\n", string(results.completed));
    fprintf("Results:\t%s\n", results.paths.results);
end

end

