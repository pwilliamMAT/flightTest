function equal = localSequencesEqual(first, second)
%LOCALSEQUENCESEQUAL Compare deterministic real dropout and score masks.

equal = numel(first) == numel(second);

if ~equal
    return;
end

for sequenceIdx = 1:numel(first)
    equal = equal && ...
        first(sequenceIdx).caseID == second(sequenceIdx).caseID && ...
        isequal(first(sequenceIdx).timeSeconds, second(sequenceIdx).timeSeconds) && ...
        isequal(first(sequenceIdx).updateMask, second(sequenceIdx).updateMask) && ...
        isequal(first(sequenceIdx).scoringMask, second(sequenceIdx).scoringMask);
end

end

