function analysis = helperAnalyzeADSBDatasetMotionDiversity(stageSummary, variantID)
%HELPERANALYZEADSBDATASETMOTIONDIVERSITY Measure independent motion coverage.
% Pair-level distributions are retained for compatibility, but readiness is
% based on sustained events, contributor concentration, and leakage-resistant
% prospective splits.

variantID = string(variantID);
stage3BSummary = localResolveStage3BSummary(stageSummary);
localValidateInputs(stage3BSummary, variantID);

pairTable = localBuildMotionPairTable(stage3BSummary, variantID);
continuousSummary = localBuildContinuousSummary(pairTable);
continuousHistogram = localBuildContinuousHistogram(pairTable);
pairRegimeSummary = localBuildPairRegimeSummary(pairTable);
jointRegimeOccupancy = localBuildJointRegimeOccupancy(pairTable);
eventTable = helperSegmentADSBMotionEvents(pairTable, variantID);
eventSummary = localBuildEventSummary(eventTable);
splitAudit = helperAuditADSBProspectiveSplits(pairTable, eventTable);
sourceSummary = localBuildSourceSummary(stageSummary, stage3BSummary);

analysis = struct();
analysis.generatedAt = datetime("now", "TimeZone", "UTC");
analysis.variantID = variantID;
analysis.sourceSummary = sourceSummary;
analysis.pairTable = pairTable;
analysis.continuousSummary = continuousSummary;
analysis.continuousHistogram = continuousHistogram;
analysis.pairRegimeSummary = pairRegimeSummary;
analysis.jointRegimeOccupancy = jointRegimeOccupancy;
analysis.eventTable = eventTable;
analysis.eventSummary = eventSummary;
analysis.splitAudit = splitAudit;
analysis.motionThresholds = stage3BSummary.labelSummary.thresholds;
analysis.retrainingRun = false;

end

