function localValidateConfig(config)
%LOCALVALIDATECONFIG Reject missing inputs and Stage 4C output collisions.

if ~ismember(config.BenchmarkMode, ["smoke", "full"])
    error("Stage4D:InvalidBenchmarkMode", ...
        "BenchmarkMode must be smoke or full.");
end

requiredFiles = [ ...
    config.WarmArtifactPath, ...
    config.DatasetPath, ...
    config.SplitManifestPath];

for pathIdx = 1:numel(requiredFiles)
    if exist(requiredFiles(pathIdx), "file") ~= 2
        error("Stage4D:MissingInputFile", ...
            "Required frozen input was not found: %s", requiredFiles(pathIdx));
    end
end

validateattributes(config.Seed, ...
    {'numeric'}, {'scalar', 'integer', 'nonnegative', 'finite'}, ...
    mfilename, "Seed");
validateattributes(config.PredictionMiniBatchSize, ...
    {'numeric'}, {'scalar', 'integer', 'positive'}, ...
    mfilename, "PredictionMiniBatchSize");
validateattributes(config.ConfidenceLevel, ...
    {'numeric'}, {'scalar', 'real', '>', 0, '<', 1}, ...
    mfilename, "ConfidenceLevel");

protectedPaths = lower([ ...
    config.WarmArtifactPath, ...
    config.DatasetPath, ...
    config.SplitManifestPath]);

if ismember(lower(config.ResultsPath), protectedPaths)
    error("Stage4D:ProtectedArtifactCollision", ...
        "Stage 4D results cannot overwrite a frozen input.");
end

stage4CFolder = lower(localCanonicalPath(fullfile( ...
    config.ProjectRoot, ...
    "artifacts", ...
    "stage4CRetrain")));

if startsWith(lower(config.OutputFolder), stage4CFolder)
    error("Stage4D:Stage4COutputCollision", ...
        "Stage 4D outputs must not be written beneath the Stage 4C folder.");
end

end

function [warmModel, audit] = localLoadAndAuditWarmModel(artifactPath, artifactHash)
%LOCALLOADANDAUDITWARMMODEL Load only the frozen warm Stage 4C artifact.

try
    loaded = load(artifactPath, "net", "normalization", "modelArtifact");
catch err
    error("Stage4D:WarmArtifactLoadFailed", ...
        "Unable to load the frozen warm artifact: %s", err.message);
end

if ~isfield(loaded, "net") || ...
        ~isfield(loaded, "normalization") || ...
        ~isfield(loaded, "modelArtifact") || ...
        isempty(loaded.net)
    error("Stage4D:InvalidWarmArtifact", ...
        "The warm artifact lacks its network, normalization, or identity record.");
end

modelID = string(loaded.modelArtifact.modelID);

if modelID ~= "expanded_warm_mean_v1"
    error("Stage4D:WrongModelIdentity", ...
        "Stage 4D requires expanded_warm_mean_v1, not %s.", modelID);
end

expectedFeatureNames = [ ...
    "vx"; ...
    "vy"; ...
    "z"; ...
    "vz"; ...
    "dtSeconds"; ...
    "previousCovarianceDiag_x"; ...
    "previousCovarianceDiag_vx"; ...
    "previousCovarianceDiag_y"; ...
    "previousCovarianceDiag_vy"; ...
    "previousCovarianceDiag_z"; ...
    "previousCovarianceDiag_vz"; ...
    "vxTimesDt"; ...
    "vyTimesDt"; ...
    "vzTimesDt"; ...
    "constvelDelta_x"; ...
    "constvelDelta_vx"; ...
    "constvelDelta_y"; ...
    "constvelDelta_vy"; ...
    "constvelDelta_z"; ...
    "constvelDelta_vz"];
featureNames = string(loaded.normalization.features.featureNames(:));
layers = loaded.net.Layers;
fullyConnectedMask = arrayfun( ...
    @(layer) isa(layer, "nnet.cnn.layer.FullyConnectedLayer"), ...
    layers);
fullyConnectedLayers = layers(fullyConnectedMask);
fullyConnectedSizes = arrayfun( ...
    @(layer) layer.OutputSize, ...
    fullyConnectedLayers);
architecturePassed = ...
    layers(1).InputSize == 20 && ...
    isequal(fullyConnectedSizes(:).', [64, 64, 6]);
identityPassed = ...
    modelID == "expanded_warm_mean_v1" && ...
    logical(loaded.modelArtifact.exploratory) && ...
    ~logical(loaded.modelArtifact.promoted);
featureContractPassed = isequal(featureNames, expectedFeatureNames);

if ~identityPassed || ~architecturePassed || ~featureContractPassed
    error("Stage4D:WarmArtifactContractMismatch", ...
        "The frozen warm artifact no longer matches the 20-64-64-6 Stage 4C contract.");
end

warmModel = struct();
warmModel.net = loaded.net;
warmModel.featureNormalization = loaded.normalization.features;
warmModel.targetNormalization = loaded.normalization.target;

audit = struct();
audit.path = string(artifactPath);
audit.sha256 = string(artifactHash);
audit.modelID = modelID;
audit.exploratory = logical(loaded.modelArtifact.exploratory);
audit.promoted = logical(loaded.modelArtifact.promoted);
audit.identityPassed = identityPassed;
audit.architecturePassed = architecturePassed;
audit.featureContractPassed = featureContractPassed;
audit.datasetProvenance = loaded.modelArtifact.datasetProvenance;
audit.splitProvenance = loaded.modelArtifact.splitProvenance;
audit.loadedModelArtifactPaths = string(artifactPath);
audit.loadedScratchArtifact = false;
audit.loadedStage3AArtifact = false;

end

function [dataset, split, audit] = localLoadAndAuditFrozenInputs(config, warmAudit)
%LOCALLOADANDAUDITFROZENINPUTS Verify dataset and global split provenance.

try
    dataset = load( ...
        config.DatasetPath, ...
        "previousState", ...
        "nextState", ...
        "dtSeconds", ...
        "previousCovarianceDiag", ...
        "metadata", ...
        "stateOrder");
catch err
    error("Stage4D:DatasetLoadFailed", ...
        "Unable to load the frozen Expanded-3Day dataset: %s", err.message);
end

rowCount = size(dataset.previousState, 1);
expectedStateOrder = ["x", "vx", "y", "vy", "z", "vz"];

if rowCount ~= 457903 || ...
        ~isequal(size(dataset.previousState), [rowCount, 6]) || ...
        ~isequal(size(dataset.nextState), [rowCount, 6]) || ...
        ~isequal(size(dataset.previousCovarianceDiag), [rowCount, 6]) || ...
        numel(dataset.dtSeconds) ~= rowCount || ...
        height(dataset.metadata) ~= rowCount || ...
        any(string(dataset.stateOrder(:).') ~= expectedStateOrder)
    error("Stage4D:DatasetContractMismatch", ...
        "The frozen Expanded-3Day dataset contract has changed.");
end

manifest = readtable(config.SplitManifestPath, TextType="string");
[found, manifestRow] = ismember( ...
    lower(strtrim(string(dataset.metadata.hex))), ...
    lower(strtrim(string(manifest.icao24))));

if ~all(found)
    error("Stage4D:SplitMembershipMismatch", ...
        "Every dataset ICAO must occur in the frozen split manifest.");
end

split = lower(strtrim(string(manifest.split(manifestRow))));
splitCounts = [ ...
    sum(split == "train"), ...
    sum(split == "validation"), ...
    sum(split == "test")];

if ~isequal(splitCounts, [277959, 86420, 93524])
    error("Stage4D:SplitCountMismatch", ...
        "The frozen train/validation/test pair counts have changed.");
end

datasetHash = helperComputeFileSHA256(config.DatasetPath);
splitHash = helperComputeFileSHA256(config.SplitManifestPath);
recordedDatasetHash = string(warmAudit.datasetProvenance.datasetSHA256);
recordedSplitHash = string(warmAudit.splitProvenance.splitManifestSHA256);
hashesMatch = ...
    strcmpi(datasetHash, recordedDatasetHash) && ...
    strcmpi(splitHash, recordedSplitHash);

if config.VerifyInputHashes && ~hashesMatch
    error("Stage4D:FrozenInputHashMismatch", ...
        "Dataset or split hash differs from the warm model's Stage 4C provenance.");
end

audit = struct();
audit.datasetPath = config.DatasetPath;
audit.datasetSHA256 = datasetHash;
audit.recordedDatasetSHA256 = recordedDatasetHash;
audit.splitManifestPath = config.SplitManifestPath;
audit.splitManifestSHA256 = splitHash;
audit.recordedSplitManifestSHA256 = recordedSplitHash;
audit.hashesMatchWarmProvenance = hashesMatch;
audit.splitCounts = splitCounts;
audit.stateOrder = expectedStateOrder;
audit.finiteStates = ...
    all(isfinite(dataset.previousState), "all") && ...
    all(isfinite(dataset.nextState), "all");
audit.positiveDt = all(dataset.dtSeconds > 0);

end

function equal = localPairSetsEqual(firstPairSet, secondPairSet)
%LOCALPAIRSETSEQUAL Verify exact seeded canonical regeneration.

numericFields = [ ...
    "previousState", ...
    "targetState", ...
    "previousCovarianceDiag", ...
    "dtSeconds", ...
    "timeKSeconds", ...
    "timeNextSeconds", ...
    "eventID", ...
    "transitionOffsetSeconds"];
textFields = [ ...
    "caseID", ...
    "profile", ...
    "motionScenario", ...
    "motionMode", ...
    "targetReference"];
equal = true;

for fieldIdx = 1:numel(numericFields)
    fieldName = numericFields(fieldIdx);
    equal = equal && isequaln( ...
        firstPairSet.(fieldName), ...
        secondPairSet.(fieldName));
end

for fieldIdx = 1:numel(textFields)
    fieldName = textFields(fieldIdx);
    equal = equal && isequal( ...
        firstPairSet.(fieldName), ...
        secondPairSet.(fieldName));
end

end

function robustnessTable = localBuildRobustnessTable(metricTable)
%LOCALBUILDROBUSTNESSTABLE Express profile degradation relative to baseline.

robustnessTable = metricTable( ...
    metricTable.weighting == "pair_weighted" & ...
    metricTable.caseID == "all", :);
rowCount = height(robustnessTable);
positionReference = NaN(rowCount, 1);
velocityReference = NaN(rowCount, 1);

for rowIdx = 1:rowCount
    if robustnessTable.domain(rowIdx) == "real_adsb"
        referenceProfile = "baseline";
    else
        referenceProfile = "ideal";
    end

    referenceMask = ...
        robustnessTable.domain == robustnessTable.domain(rowIdx) & ...
        robustnessTable.profile == referenceProfile & ...
        robustnessTable.comparisonFamily == ...
        robustnessTable.comparisonFamily(rowIdx) & ...
        robustnessTable.modelID == robustnessTable.modelID(rowIdx);
    positionReference(rowIdx) = ...
        robustnessTable.positionRMSEMeters(referenceMask);
    velocityReference(rowIdx) = ...
        robustnessTable.velocityRMSEMetersPerSecond(referenceMask);
end

robustnessTable.referencePositionRMSEMeters = positionReference;
robustnessTable.positionRMSEChangePercent = ...
    100*(robustnessTable.positionRMSEMeters - positionReference) ./ ...
    positionReference;
robustnessTable.referenceVelocityRMSEMetersPerSecond = velocityReference;
robustnessTable.velocityRMSEChangePercent = ...
    100*(robustnessTable.velocityRMSEMetersPerSecond - velocityReference) ./ ...
    velocityReference;

end

