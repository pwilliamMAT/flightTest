function results = runStage4DFrozenWarmCharacterization(varargin)
%RUNSTAGE4DFROZENWARMCHARACTERIZATION Characterize the frozen warm predictor.
% The benchmark compares one-step predictions from the Stage 4C warm
% network with constvel on identical information. Constacc and constturn
% are reported separately because they use one causal predecessor.

projectRoot = string(fileparts(mfilename("fullpath")));
parser = inputParser;
parser.FunctionName = mfilename;
addParameter(parser, "ProjectRoot", projectRoot);
addParameter(parser, "BenchmarkMode", "smoke");
addParameter(parser, "Seed", 123);
addParameter(parser, "WarmArtifactPath", "");
addParameter(parser, "DatasetPath", "");
addParameter(parser, "SplitManifestPath", "");
addParameter(parser, "OutputFolder", "");
addParameter(parser, "ResultsPath", "");
addParameter(parser, "PredictionMiniBatchSize", 8192);
addParameter(parser, "ConfidenceLevel", 0.95);
addParameter(parser, "VerifyInputHashes", true);
addParameter(parser, "CreatePlots", true);
addParameter(parser, "Verbose", true);
parse(parser, varargin{:});

config = localBuildConfig(parser.Results);
localValidateConfig(config);
benchmarkTimer = tic;

if config.Verbose
    fprintf("Stage 4D frozen-warm characterization\n");
    fprintf("Benchmark mode:\t%s\n", config.BenchmarkMode);
    fprintf("Warm artifact:\t%s\n", config.WarmArtifactPath);
end

warmHashBefore = helperComputeFileSHA256(config.WarmArtifactPath);
[warmModel, warmAudit] = localLoadAndAuditWarmModel( ...
    config.WarmArtifactPath, ...
    warmHashBefore);
[dataset, split, inputAudit] = localLoadAndAuditFrozenInputs(config, warmAudit);
trainMask = split == "train";
empiricalDtSeconds = dataset.dtSeconds(trainMask);
previousCovarianceDiag = median( ...
    dataset.previousCovarianceDiag(trainMask, :), ...
    1);

canonicalBenchmark = helperGenerateStage4DSyntheticBenchmark( ...
    "canonical", ...
    BenchmarkMode=config.BenchmarkMode, ...
    Seed=config.Seed, ...
    EmpiricalDtSeconds=empiricalDtSeconds, ...
    PreviousCovarianceDiag=previousCovarianceDiag);
canonicalRepeat = helperGenerateStage4DSyntheticBenchmark( ...
    "canonical", ...
    BenchmarkMode=config.BenchmarkMode, ...
    Seed=config.Seed, ...
    EmpiricalDtSeconds=empiricalDtSeconds, ...
    PreviousCovarianceDiag=previousCovarianceDiag);
deterministicGeneration = localPairSetsEqual( ...
    canonicalBenchmark.pairSet, ...
    canonicalRepeat.pairSet);
clear canonicalRepeat
canonicalEvaluation = helperEvaluateStage4DPredictors( ...
    canonicalBenchmark.pairSet, ...
    warmModel, ...
    PredictionMiniBatchSize=config.PredictionMiniBatchSize, ...
    ConfidenceLevel=config.ConfidenceLevel);
canonicalEvidence = rmfield(canonicalBenchmark, ["pairSet", "sequences"]);
clear canonicalBenchmark

inDistributionBenchmark = helperGenerateStage4DSyntheticBenchmark( ...
    "in_distribution", ...
    BenchmarkMode=config.BenchmarkMode, ...
    Seed=config.Seed, ...
    EmpiricalDtSeconds=empiricalDtSeconds, ...
    PreviousCovarianceDiag=previousCovarianceDiag);
inDistributionEvaluation = helperEvaluateStage4DPredictors( ...
    inDistributionBenchmark.pairSet, ...
    warmModel, ...
    PredictionMiniBatchSize=config.PredictionMiniBatchSize, ...
    ConfidenceLevel=config.ConfidenceLevel);
inputPreview = localBuildInputPreview(inDistributionBenchmark.sequences);
inDistributionEvidence = rmfield( ...
    inDistributionBenchmark, ...
    ["pairSet", "sequences"]);
clear inDistributionBenchmark

outOfDistributionBenchmark = helperGenerateStage4DSyntheticBenchmark( ...
    "out_of_distribution", ...
    BenchmarkMode=config.BenchmarkMode, ...
    Seed=config.Seed, ...
    EmpiricalDtSeconds=empiricalDtSeconds, ...
    PreviousCovarianceDiag=previousCovarianceDiag);
outOfDistributionEvaluation = helperEvaluateStage4DPredictors( ...
    outOfDistributionBenchmark.pairSet, ...
    warmModel, ...
    PredictionMiniBatchSize=config.PredictionMiniBatchSize, ...
    ConfidenceLevel=config.ConfidenceLevel);
outOfDistributionEvidence = rmfield( ...
    outOfDistributionBenchmark, ...
    ["pairSet", "sequences"]);
clear outOfDistributionBenchmark

realBenchmark = helperBuildStage4DRealDropoutBenchmark( ...
    dataset, ...
    split, ...
    BenchmarkMode=config.BenchmarkMode, ...
    Seed=config.Seed, ...
    PreviousCovarianceDiag=previousCovarianceDiag);
realEvaluation = helperEvaluateStage4DPredictors( ...
    realBenchmark.pairSet, ...
    warmModel, ...
    PredictionMiniBatchSize=config.PredictionMiniBatchSize, ...
    ConfidenceLevel=config.ConfidenceLevel);
realEvidence = rmfield(realBenchmark, "pairSet");
clear realBenchmark dataset warmModel

metricTable = vertcat( ...
    canonicalEvaluation.metricTable, ...
    inDistributionEvaluation.metricTable, ...
    outOfDistributionEvaluation.metricTable, ...
    realEvaluation.metricTable);
canonicalMetricTable = canonicalEvaluation.canonicalMetricTable;
eventWinRateTable = vertcat( ...
    canonicalEvaluation.eventWinRateTable, ...
    inDistributionEvaluation.eventWinRateTable, ...
    outOfDistributionEvaluation.eventWinRateTable, ...
    realEvaluation.eventWinRateTable);
pairedConfidenceIntervalTable = vertcat( ...
    canonicalEvaluation.pairedConfidenceIntervalTable, ...
    inDistributionEvaluation.pairedConfidenceIntervalTable, ...
    outOfDistributionEvaluation.pairedConfidenceIntervalTable, ...
    realEvaluation.pairedConfidenceIntervalTable);
transitionMetricTable = vertcat( ...
    canonicalEvaluation.transitionMetricTable, ...
    inDistributionEvaluation.transitionMetricTable, ...
    outOfDistributionEvaluation.transitionMetricTable);
runtimeTable = vertcat( ...
    canonicalEvaluation.runtimeTable, ...
    inDistributionEvaluation.runtimeTable, ...
    outOfDistributionEvaluation.runtimeTable, ...
    realEvaluation.runtimeTable);
robustnessTable = localBuildRobustnessTable(metricTable);
headlineMetricTable = localBuildHeadlineMetricTable(metricTable);
headlineComparisonTable = localBuildHeadlineComparisonTable( ...
    pairedConfidenceIntervalTable, ...
    eventWinRateTable);
mixedMotionTable = localBuildMixedMotionTable(metricTable);
realDropoutTable = localBuildRealDropoutTable(metricTable);
nativeFunctionAudit = localBuildNativeFunctionAudit();

warmHashAfter = helperComputeFileSHA256(config.WarmArtifactPath);
artifactAudit = localBuildArtifactAudit( ...
    config, ...
    warmAudit, ...
    inputAudit, ...
    warmHashBefore, ...
    warmHashAfter);
verificationTable = localBuildVerificationTable( ...
    config, ...
    canonicalEvidence, ...
    inDistributionEvidence, ...
    outOfDistributionEvidence, ...
    realEvidence, ...
    canonicalEvaluation, ...
    inDistributionEvaluation, ...
    outOfDistributionEvaluation, ...
    realEvaluation, ...
    deterministicGeneration, ...
    artifactAudit);
limitationsTable = localBuildLimitationsTable();
nextDecision = localBuildNextDecision(headlineComparisonTable);
benchmarkElapsedSeconds = toc(benchmarkTimer);
runtimeTable = [ ...
    runtimeTable; ...
    table( ...
        "all", ...
        "complete_benchmark", ...
        sum(metricTable( ...
        metricTable.comparisonFamily == "same_information" & ...
        metricTable.weighting == "pair_weighted" & ...
        metricTable.modelID == "expanded_warm_mean_v1", ...
        :).sampleCount), ...
        benchmarkElapsedSeconds, ...
        1e6*benchmarkElapsedSeconds / max(1, sum(metricTable( ...
        metricTable.comparisonFamily == "same_information" & ...
        metricTable.weighting == "pair_weighted" & ...
        metricTable.modelID == "expanded_warm_mean_v1", ...
        :).sampleCount)), ...
        'VariableNames', runtimeTable.Properties.VariableNames)];

if ~isfolder(config.OutputFolder)
    mkdir(config.OutputFolder);
end

results = struct();
results.generatedAt = datetime("now", "TimeZone", "UTC");
results.stage = "4D";
results.completed = all(verificationTable.passed);
results.benchmarkMode = config.BenchmarkMode;
results.randomSeed = config.Seed;
results.interpretation = ...
    "Frozen one-step warm-model characterization; not a deployed tracker replacement.";
results.config = localBuildConfigurationTable( ...
    config, ...
    canonicalEvidence, ...
    inDistributionEvidence, ...
    outOfDistributionEvidence, ...
    realEvidence);
results.syntheticObservationProfiles = canonicalEvidence.profileTable;
results.realObservationProfiles = realEvidence.profileTable;
results.inputPreview = inputPreview;
results.nativeFunctionAudit = nativeFunctionAudit;
results.artifactAudit = artifactAudit;
results.verificationTable = verificationTable;
results.canonicalCaseTable = canonicalEvidence.caseTable;
results.canonicalMetricTable = canonicalMetricTable;
results.metricTable = metricTable;
results.headlineMetricTable = headlineMetricTable;
results.headlineComparisonTable = headlineComparisonTable;
results.mixedMotionTable = mixedMotionTable;
results.realDropoutTable = realDropoutTable;
results.eventWinRateTable = eventWinRateTable;
results.pairedConfidenceIntervalTable = pairedConfidenceIntervalTable;
results.transitionMetricTable = transitionMetricTable;
results.robustnessTable = robustnessTable;
results.runtimeTable = runtimeTable;
results.confidenceIntervalMethod = ...
    canonicalEvaluation.confidenceIntervalMethod;
results.errorDifferenceConvention = ...
    canonicalEvaluation.errorDifferenceConvention;
results.causalPolicy = canonicalEvaluation.causalPolicy;
results.syntheticEvidence = struct( ...
    "canonical", canonicalEvidence, ...
    "inDistribution", inDistributionEvidence, ...
    "outOfDistribution", outOfDistributionEvidence);
results.realEvidence = realEvidence;
results.limitationsTable = limitationsTable;
results.nextDecision = nextDecision;
results.trainingPerformed = false;
results.modelPromoted = false;
results.recursiveTrackingEvaluated = false;
results.paths = localBuildOutputPaths(config);
results.figurePaths = struct( ...
    "inputPreview", "", ...
    "motionComparison", "", ...
    "characterization", "");

if config.CreatePlots
    inputPlotOutput = helperPlotStage4DInputPreview( ...
        results.inputPreview, ...
        SavePath=results.paths.inputPreviewFigure);
    motionPlotOutput = helperPlotStage4DMotionComparison( ...
        results, ...
        SavePath=results.paths.motionComparisonFigure);
    plotOutput = helperPlotStage4DCharacterization( ...
        results, ...
        SavePath=results.paths.characterizationFigure);
    results.figurePaths.inputPreview = inputPlotOutput.savePath;
    results.figurePaths.motionComparison = motionPlotOutput.savePath;
    results.figurePaths.characterization = plotOutput.savePath;
end

localWriteResults(results);

if config.Verbose
    fprintf("Stage 4D complete:\t%s\n", string(results.completed));
    fprintf("Results:\t%s\n", results.paths.results);
    fprintf("Decision:\t%s\n", results.nextDecision);
end

end

function preview = localBuildInputPreview(sequences)
%LOCALBUILDINPUTPREVIEW Select one deterministic input-only trajectory.

profileNames = strings(numel(sequences), 1);

for sequenceIdx = 1:numel(sequences)
    profileNames(sequenceIdx) = sequences(sequenceIdx).profile(1);
end
selectedIndex = find(profileNames == "degraded", 1, "first");

if isempty(selectedIndex)
    error("Stage4D:MissingInputPreview", ...
        "The in-distribution benchmark does not contain a degraded sequence.");
end

selected = sequences(selectedIndex);
preview = struct();
preview.caseID = selected.caseID(1);
preview.profile = selected.profile(1);
preview.motionScenario = selected.motionScenario(1);
preview.observationTimeSeconds = selected.observationTimeSeconds;
preview.observationState = selected.observationState;
preview.retainedIntervalSeconds = [ ...
    NaN; ...
    diff(selected.observationTimeSeconds)];
preview.nominalTruthIntervalSeconds = median(diff(selected.truthTimeSeconds));
preview.nominalDropoutFraction = 0.25;
preview.containsPredictions = false;
preview.source = "seeded degraded in-distribution synthetic observations";

end

