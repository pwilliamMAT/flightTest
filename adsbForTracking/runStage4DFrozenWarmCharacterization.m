function comparisonTable = localBuildHeadlineComparisonTable( ...
        confidenceTable, eventWinRateTable)
%LOCALBUILDHEADLINECOMPARISONTABLE Join paired intervals and event win rates.

comparisonTable = confidenceTable( ...
    confidenceTable.comparisonFamily == "same_information" & ...
    confidenceTable.comparatorModelID == "constvel", :);
winRows = eventWinRateTable( ...
    eventWinRateTable.comparisonFamily == "same_information" & ...
    eventWinRateTable.comparatorModelID == "constvel", :);
joinKeys = [ ...
    "domain", ...
    "profile", ...
    "comparisonFamily", ...
    "comparatorModelID", ...
    "eventCount"];
comparisonTable = innerjoin( ...
    comparisonTable, ...
    winRows, ...
    Keys=joinKeys);

end

