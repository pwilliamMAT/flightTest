        function testRepresentativeSelectionAndTrajectoryContracts(testCase)
            representatives = testCase.Stage4CDashboard.representatives;
            selectedPairCounts = [representatives.pairCount].';
            maximumEventCounts = arrayfun( ...
                @(value) max(value.eventTable.pairCount), ...
                representatives);
            monotonicTime = arrayfun( ...
                @(value) all(diff(value.timeSeconds) > 0), ...
                representatives);
            finiteLLA = arrayfun( ...
                @(value) all(isfinite([ ...
                value.truthLLA; ...
                value.nativeLLA; ...
                value.legacyLLA; ...
                value.scratchLLA; ...
                value.warmLLA]), ...
                "all"), ...
                representatives);
            expectedNeuralIDs = [ ...
                "expanded_scratch_mean_v1"; ...
                "expanded_warm_mean_v1"; ...
                "legacy_stage3a_v1"; ...
                "truth"];

            testCase.verifyEqual( ...
                string({representatives.motionClass}).', ...
                ["constvel_like"; "constacc_like"; "constturn_like"]);
            testCase.verifyEqual( ...
                [representatives.selectedTrajectory].', ...
                ones(3, 1));
            testCase.verifyEqual( ...
                [representatives.eligibleTrajectoryCount].', ...
                [12537; 10340; 1242]);
            testCase.verifyEqual(selectedPairCounts, [176; 40; 25]);
            testCase.verifyEqual( ...
                selectedPairCounts, ...
                maximumEventCounts(:));
            testCase.verifyTrue(all(monotonicTime));
            testCase.verifyTrue(all(finiteLLA));
            testCase.verifyTrue(all(startsWith( ...
                string({representatives.label}).', ...
                "Representative trajectory—1 of ")));
            testCase.verifyEqual( ...
                sort(representatives(1).legendTable.modelID), ...
                sort([expectedNeuralIDs; "constvel"]));
            testCase.verifyEqual( ...
                sort(representatives(2).legendTable.modelID), ...
                sort([expectedNeuralIDs; "constacc"]));
            testCase.verifyEqual( ...
                sort(representatives(3).legendTable.modelID), ...
                sort([expectedNeuralIDs; "constturn"]));
            testCase.verifyEqual( ...
                [ ...
                    height(representatives(1).legendTable); ...
                    height(representatives(2).legendTable); ...
                    height(representatives(3).legendTable)], ...
                repmat(5, 3, 1));
        end

        function testTrajectoryCollectionCountsAndRanking( ...
                testCase, stage4CTrajectoryCount)
            representative = testCase.Stage4CDashboard.representatives(1);
            collection = helperBuildStage4CTrajectoryCollection( ...
                testCase.Stage4CDashboard, ...
                "constvel_like", ...
                TrajectoryCount=stage4CTrajectoryCount);
            expectedEvents = representative.eventTable( ...
                1:stage4CTrajectoryCount, :);
            actualEvents = collection.eventTable( ...
                :, ...
                expectedEvents.Properties.VariableNames);
            trajectoryCounts = cellfun( ...
                @numel, ...
                struct2cell(collection.trajectories));

            testCase.verifyEqual( ...
                collection.requestedTrajectoryCount, ...
                stage4CTrajectoryCount);
            testCase.verifyEqual( ...
                collection.plottedTrajectoryCount, ...
                stage4CTrajectoryCount);
            testCase.verifyEqual( ...
                collection.trajectoryPathCount, ...
                5 * stage4CTrajectoryCount);
            testCase.verifyEqual(collection.plotCallCount, 5);
            testCase.verifyEqual( ...
                trajectoryCounts, ...
                repmat(stage4CTrajectoryCount, 5, 1));
            testCase.verifyEqual(actualEvents, expectedEvents);
            testCase.verifyTrue(all( ...
                collection.validationTable{:, 2:end}, ...
                "all"));
        end

