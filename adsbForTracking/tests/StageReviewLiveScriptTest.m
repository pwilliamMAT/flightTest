            testCase.verifyEqual(height(stage4CNativeMetrics), 40);
            testCase.verifyTrue(exist("stage4CDashboard", "var") == 1);
            testCase.verifyTrue(exist( ...
                "expandedMotionClassAllocation", ...
                "var") == 1);
            testCase.verifyTrue(exist( ...
