            loaded = load(results.paths.results, "stage4EResults");

            testCase.verifyEqual(exist(results.paths.results, "file"), 2);
            testCase.verifyEqual(exist(results.paths.metrics, "file"), 2);
            testCase.verifyEqual(exist(results.paths.eventMetrics, "file"), 2);
            testCase.verifyEqual(exist(results.paths.motionMetrics, "file"), 2);
            testCase.verifyEqual(exist(results.paths.outageMetrics, "file"), 2);
            testCase.verifyEqual(exist(results.paths.eventWinRates, "file"), 2);
            testCase.verifyEqual(exist(results.paths.consistency, "file"), 2);
            testCase.verifyEqual(exist(results.paths.runtime, "file"), 2);
            testCase.verifyEqual(exist(results.paths.inputAudit, "file"), 2);
            testCase.verifyEqual(exist(results.paths.verification, "file"), 2);
            testCase.verifyEqual(exist(plotOutput.savePath, "file"), 2);
            testCase.verifyTrue(loaded.stage4EResults.completed);
        end

        function testRepresentativeGlobeReviews(testCase)
            syntheticReview = testCase.SyntheticGlobeReview;
            realReview = testCase.RealGlobeReview;

            testCase.verifyEqual( ...
                syntheticReview.summaryTable.trajectoryPathCount, ...
                7);
            testCase.verifyEqual( ...
                realReview.summaryTable.trajectoryPathCount, ...
                7);
            testCase.verifyEqual( ...
                syntheticReview.summaryTable.scoringReference, ...
                "Latent kinematic truth");
            testCase.verifyEqual( ...
                realReview.summaryTable.scoringReference, ...
                "ADS-B scoring proxy");
            testCase.verifyTrue(all( ...
                syntheticReview.validationTable{:, 2:end}, ...
                "all"));
            testCase.verifyTrue(all( ...
                realReview.validationTable{:, 2:end}, ...
                "all"));
            testCase.verifyTrue(syntheticReview.recursiveEvaluation);
            testCase.verifyFalse(realReview.trainingPerformed);
        end

        function testGlobeReviewRejectsUnknownView(testCase)
            testCase.verifyError( ...
                @() helperBuildStage4EGlobeReview( ...
                    testCase.Results, ...
                    ViewType="unknown"), ...
                "Stage4EGlobe:UnknownViewType");
        end

        function testLiveScriptRunsHeadlessly(testCase)
            scriptPath = fullfile( ...
                testCase.ProjectRoot, ...
                "stage4ERecursiveFilterEvaluationLiveScript.m"); %#ok<NASGU>
            previousFigureVisibility = get(groot, "defaultFigureVisible");
            testCase.addTeardown(@() close("all"));
            testCase.addTeardown(@() set( ...
                groot, ...
                "defaultFigureVisible", ...
                previousFigureVisibility));
            set(groot, "defaultFigureVisible", "off");
            stage4EBenchmarkMode = "smoke"; %#ok<NASGU>
            regenerateStage4EResults = false; %#ok<NASGU>
            retuneStage4EFilters = false; %#ok<NASGU>
            stage4ERandomSeed = 123; %#ok<NASGU>
            generateStage4EPlots = false; %#ok<NASGU>
            enableStage4EInteractiveGlobe = false; %#ok<NASGU>
            stage4EOutputFolder = testCase.OutputFolder; %#ok<NASGU>
            commandWindowOutput = evalc("run(scriptPath);"); %#ok<NASGU>

            testCase.verifyTrue(exist("stage4EResults", "var") == 1);
            testCase.verifyTrue(exist("stage4EMetrics", "var") == 1);
            testCase.verifyTrue(exist("stage4EEventMetrics", "var") == 1);
            testCase.verifyTrue(exist("stage4EConsistency", "var") == 1);
            testCase.verifyTrue(exist("stage4ESyntheticGlobeReview", "var") == 1);
            testCase.verifyTrue(exist("stage4ERealGlobeReview", "var") == 1);
            testCase.verifyTrue(exist("stage4ESyntheticGlobeStatus", "var") == 1);
            testCase.verifyTrue(exist("stage4ERealGlobeStatus", "var") == 1);
            testCase.verifyTrue(stage4EResults.completed);
        end

        function testPlainTextLiveScriptAndScopeBoundary(testCase)
            scriptPath = fullfile( ...
                testCase.ProjectRoot, ...
                "stage4ERecursiveFilterEvaluationLiveScript.m");
            runnerPath = fullfile( ...
                testCase.ProjectRoot, ...
                "runStage4ERecursiveFilterEvaluation.m");
            evaluatorPath = fullfile( ...
                testCase.ProjectRoot, ...
                "helperEvaluateStage4ESequences.m");
            scriptText = string(fileread(scriptPath));
            implementationText = ...
                string(fileread(runnerPath)) + ...
                string(fileread(evaluatorPath));
            lines = splitlines(scriptText);

            testCase.verifyTrue(contains(scriptText, "%[text:tableOfContents]"));
            testCase.verifyTrue(contains( ...
                scriptText, ...
                "%[appendix]{""version"":""1.0""}"));
            testCase.verifyFalse(contains(scriptText, "mfilename"));
            testCase.verifyFalse(contains(scriptText, "figure("));
            testCase.verifyFalse(contains(scriptText, "%[output:"));
            testCase.verifyFalse(any(strlength(lines(1:end - 1)) == 0));
            testCase.verifyFalse(contains(implementationText, "trainnet("));
            testCase.verifyFalse(contains(implementationText, "trainingOptions("));
            testCase.verifyFalse(contains(implementationText, "trackerGNN("));
            testCase.verifyFalse(contains(implementationText, "trackerJPDA("));
            testCase.verifyFalse(contains(implementationText, "trackerTOMHT("));
        end
    end
