classdef Stage4ERecursiveFilterEvaluationTest < matlab.unittest.TestCase
    %STAGE4ERECURSIVEFILTEREVALUATIONTEST Verify recursive filter evaluation.

    properties
        ProjectRoot
        OutputFolder
        Results
        WarmHashBefore
        SyntheticGlobeReview
        RealGlobeReview
    end

    methods (TestClassSetup)
        function runSmokeBenchmark(testCase)
            testFolder = fileparts(mfilename("fullpath"));
            testCase.ProjectRoot = fileparts(testFolder);
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture(testCase.ProjectRoot));
            tempFixture = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture);
            testCase.OutputFolder = tempFixture.Folder;
            tuningPath = fullfile( ...
                testCase.ProjectRoot, ...
                "artifacts", ...
                "stage4ERecursiveFilterEvaluation", ...
                "stage4EFilterTuning.mat");
            testCase.assertEqual(exist(tuningPath, "file"), 2, ...
                "Generate the frozen validation-only Stage 4E tuning artifact first.");
            warmPath = fullfile( ...
                testCase.ProjectRoot, ...
                "artifacts", ...
                "stage4CRetrain", ...
                "expandedPost3DayWarmStartMeanMLP_v1.mat");
            testCase.WarmHashBefore = helperComputeFileSHA256(warmPath);
            testCase.Results = runStage4ERecursiveFilterEvaluation( ...
                BenchmarkMode="smoke", ...
                Seed=123, ...
                OutputFolder=testCase.OutputFolder, ...
                CreatePlots=false, ...
                Verbose=false);
            testCase.SyntheticGlobeReview = helperBuildStage4EGlobeReview( ...
                testCase.Results, ...
                ViewType="synthetic");
            testCase.RealGlobeReview = helperBuildStage4EGlobeReview( ...
                testCase.Results, ...
                ViewType="real_adsb");
        end
    end

    methods (Test)
        function testFilterTypesAndCommonInitialization(testCase)
            initialState = [100; 21; -40; 7; 1800; -2];
            covarianceDiag = [900; 25; 900; 25; 1600; 9];
            attributes = struct( ...
                "InitialVelocity", initialState([2, 4, 6]).', ...
                "InitialCovarianceDiag", covarianceDiag.');
            detection = objectDetection( ...
                0, ...
                initialState([1, 3, 5]), ...
                MeasurementNoise=diag([30, 30, 45].^2), ...
                ObjectAttributes={attributes});

            cvFilter = helperInitializeStage4EFilter(detection, "cv_ekf");
            caFilter = helperInitializeStage4EFilter(detection, "ca_ekf");
            ctFilter = helperInitializeStage4EFilter(detection, "ct_ekf");
            immFilter = helperInitializeStage4EFilter(detection, "native_imm");
            warmFilter = helperInitializeStage4EFilter(detection, "warm_ukf");

            testCase.verifyClass(cvFilter, "trackingEKF");
            testCase.verifyClass(caFilter, "trackingEKF");
            testCase.verifyClass(ctFilter, "trackingEKF");
            testCase.verifyClass(immFilter, "trackingIMM");
            testCase.verifyClass(warmFilter, "trackingUKF");
            testCase.verifyEqual(cvFilter.State, initialState, AbsTol=0);
            testCase.verifyEqual( ...
                caFilter.State([1, 2, 4, 5, 7, 8]), ...
                initialState, ...
                AbsTol=0);
            testCase.verifyEqual( ...
                ctFilter.State([1, 2, 3, 4, 6, 7]), ...
                initialState, ...
                AbsTol=0);
            testCase.verifyEqual( ...
                immFilter.State, ...
                initialState, ...
                AbsTol=1e-10);
            testCase.verifyEqual(warmFilter.State, initialState, AbsTol=0);
            testCase.verifyEqual( ...
                diag(cvFilter.StateCovariance), ...
                covarianceDiag, ...
                AbsTol=0);
            testCase.verifyEqual(string(func2str(cvFilter.MeasurementFcn)), "cvmeas");
            testCase.verifyEqual(string(func2str(caFilter.MeasurementFcn)), "cameas");
            testCase.verifyEqual(string(func2str(ctFilter.MeasurementFcn)), "ctmeas");
            testCase.verifyEqual(string(func2str(warmFilter.MeasurementFcn)), "cvmeas");
        end

        function testMatchedInputsAndCorrectionProtocol(testCase)
            results = testCase.Results;
            requiredChecks = [ ...
                "identical_filter_inputs"; ...
                "identical_filter_initialization"; ...
                "scheduled_corrections_applied"; ...
                "real_scoring_reports_never_corrected"; ...
                "same_real_scoring_rows_across_profiles"; ...
                "deterministic_real_dropout"; ...
                "monotonic_time"; ...
                "coasting_during_outages"];
            selected = results.verificationTable( ...
                ismember(results.verificationTable.check, requiredChecks), :);

            testCase.verifyEqual(height(selected), numel(requiredChecks));
            testCase.verifyTrue(all(selected.passed));
            testCase.verifyFalse(results.realProtocol.scoringReportsUsedForCorrection);
            testCase.verifyTrue(results.realProtocol.sameScoringRowsAcrossProfiles);
            testCase.verifyTrue(all( ...
                results.inputAuditTable.actualCorrectionCount == ...
                results.inputAuditTable.scheduledCorrectionCount));
        end

        function testSyntheticMotionAndConsistencyMetrics(testCase)
            results = testCase.Results;
            syntheticRows = startsWith( ...
                results.metricTable.domain, ...
                "synthetic_");
            syntheticMetrics = results.metricTable(syntheticRows, :);
            requiredMotions = [ ...
                "cv_level"; ...
                "cv_climb"; ...
                "horizontal_acceleration"; ...
                "vertical_acceleration"; ...
                "left_turn"; ...
                "right_turn"; ...
                "motion_transitions"];
            canonicalRows = results.eventMetricTable.domain == ...
                "synthetic_canonical";
            canonicalMotions = unique( ...
                results.eventMetricTable.motionScenario(canonicalRows));

            testCase.verifyTrue(all(ismember(requiredMotions, canonicalMotions)));
            testCase.verifyTrue(all(isfinite( ...
                syntheticMetrics.positionRMSEMeters)));
            testCase.verifyTrue(all(isfinite( ...
                syntheticMetrics.velocityRMSEMetersPerSecond)));
            testCase.verifyTrue(all(isfinite(syntheticMetrics.meanNEES)));
            testCase.verifyTrue(all(isfinite(syntheticMetrics.stateCoverage95)));
            testCase.verifyTrue(all(isfinite( ...
                syntheticMetrics.positionCoverage95)));
            testCase.verifyGreaterThanOrEqual( ...
                syntheticMetrics.stateCoverage95, ...
                zeros(height(syntheticMetrics), 1));
            testCase.verifyLessThanOrEqual( ...
                syntheticMetrics.stateCoverage95, ...
                ones(height(syntheticMetrics), 1));
        end

        function testRealADSBProxyMetrics(testCase)
            results = testCase.Results;
            realRows = results.metricTable.domain == "real_adsb";
            realMetrics = results.metricTable(realRows, :);
            profileNames = unique(realMetrics.profile);

            testCase.verifyEqual( ...
                sort(profileNames), ...
                sort([ ...
                    "baseline"; ...
                    "random_dropout_10"; ...
                    "random_dropout_25"; ...
                    "burst_outage"]));
            testCase.verifyTrue(all( ...
                realMetrics.targetReference == "adsb_scoring_proxy"));
            testCase.verifyTrue(all(isfinite( ...
                realMetrics.positionRMSEMeters)));
            testCase.verifyTrue(all(isfinite( ...
                realMetrics.velocityRMSEMetersPerSecond)));
            testCase.verifyTrue(all(isnan(realMetrics.meanNEES)));
            testCase.verifyTrue(all(isnan(realMetrics.stateCoverage95)));
            testCase.verifyGreaterThan( ...
                height(results.eventWinRateTable), ...
                0);
        end

        function testFiniteStatesCovarianceAndNIS(testCase)
            results = testCase.Results;
            requiredChecks = [ ...
                "finite_recursive_states"; ...
                "positive_definite_covariance"];
            selected = results.verificationTable( ...
                ismember(results.verificationTable.check, requiredChecks), :);

            testCase.verifyTrue(all(selected.passed));
            testCase.verifyEqual( ...
                sum(results.eventMetricTable.divergenceCount), ...
                0);
            testCase.verifyEqual( ...
                sum(results.eventMetricTable.invalidCovarianceCount), ...
                0);
            testCase.verifyTrue(all(strlength( ...
                results.inputAuditTable.errorIdentifier) == 0));
            testCase.verifyTrue(all(isfinite( ...
                results.consistencyTable.meanNIS)));
            testCase.verifyTrue(all(isfinite( ...
                results.consistencyTable.nisCoverage95)));
        end

        function testFrozenWarmArtifactAndTuningBoundary(testCase)
            results = testCase.Results;
            warmPath = fullfile( ...
                testCase.ProjectRoot, ...
                "artifacts", ...
                "stage4CRetrain", ...
                "expandedPost3DayWarmStartMeanMLP_v1.mat");
            warmHashAfter = helperComputeFileSHA256(warmPath);
            requiredChecks = [ ...
                "tuning_validation_only"; ...
                "tuning_frozen_before_test"; ...
                "no_neural_training"; ...
                "warm_hash_unchanged"; ...
                "warm_hash_matches_expected"];
            selected = results.verificationTable( ...
                ismember(results.verificationTable.check, requiredChecks), :);

            testCase.verifyEqual( ...
                testCase.WarmHashBefore, ...
                "1999F972DBDABE67F45953C52CD4CDB1620F1FECF1716C075F391064D3B32FFE");
            testCase.verifyEqual(warmHashAfter, testCase.WarmHashBefore);
            testCase.verifyTrue(all(selected.passed));
            testCase.verifyFalse(results.trainingPerformed);
            testCase.verifyFalse(results.networkPredictsCovariance);
            testCase.verifyFalse(results.associationEvaluated);
            testCase.verifyFalse(results.passiveRadarPerformanceEvaluated);
            testCase.verifyLessThanOrEqual( ...
                results.tuningSummary.validationSummary.maximumPairsPerEvent, ...
                120);
        end

