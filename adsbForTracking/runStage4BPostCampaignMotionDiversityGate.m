end

function summary = localResolveVariantSummary(config, variantID)
%LOCALRESOLVEVARIANTSUMMARY Rebuild or load one versioned Stage 3C result.

outputFolder = fullfile( ...
    config.ProjectRoot, ...
    "artifacts", ...
    "stage4BPostCampaign", ...
    variantID);
artifactPath = fullfile(outputFolder, "stage3CArchiveADSBEvaluation.mat");

if config.RebuildVariantEvaluations || exist(artifactPath, "file") ~= 2
    summary = runADSBDatasetVariantEvaluation( ...
        variantID, ...
        "ProjectRoot", ...
        config.ProjectRoot, ...
        "OutputFolder", ...
        outputFolder, ...
        "CreatePlots", ...
        config.CreateVariantPlots, ...
        "Verbose", ...
        config.Verbose);
    return;
end

loaded = load(artifactPath, "stage3CSummary");

if ~isfield(loaded, "stage3CSummary") || ...
        string(loaded.stage3CSummary.datasetVariantID) ~= variantID
    error("Stage4BPost:InvalidVariantArtifact", ...
        "Saved artifact does not match variant %s: %s", ...
        variantID, ...
        artifactPath);
end

summary = loaded.stage3CSummary;

end

function summaryTable = localBuildVariantSummaryTable( ...
        variantIDs, displayNames, variantSummaries, analyses)
%LOCALBUILDVARIANTSUMMARYTABLE Put source, motion, and model counts together.

variantCount = numel(variantIDs);
sourceFileCount = zeros(variantCount, 1);
usableSourceFileCount = zeros(variantCount, 1);
sessionCount = zeros(variantCount, 1);
aircraftCount = zeros(variantCount, 1);
aircraftTrackCount = zeros(variantCount, 1);
pairCount = zeros(variantCount, 1);
eventCount = zeros(variantCount, 1);
occupiedJointRegimeCellCount = zeros(variantCount, 1);
constvelPositionRMSEMeters = NaN(variantCount, 1);
frozenMLPPositionRMSEMeters = NaN(variantCount, 1);

for variantIdx = 1:variantCount
    variantID = variantIDs(variantIdx);
    source = analyses.(variantID).sourceSummary;
    metrics = variantSummaries.(variantID).metricComparisonTable;
    sourceFileCount(variantIdx) = source.sourceFileCount;
    usableSourceFileCount(variantIdx) = source.usableSourceFileCount;
    sessionCount(variantIdx) = source.sessionCount;
    aircraftCount(variantIdx) = source.aircraftCount;
    aircraftTrackCount(variantIdx) = source.aircraftTrackCount;
    pairCount(variantIdx) = source.pairCount;
    eventCount(variantIdx) = height(analyses.(variantID).eventTable);
    occupiedJointRegimeCellCount(variantIdx) = sum( ...
        analyses.(variantID).jointRegimeOccupancy.occupied);
    constvelPositionRMSEMeters(variantIdx) = metrics.positionRMSEMeters( ...
        metrics.method == "constvel baseline");
    frozenMLPPositionRMSEMeters(variantIdx) = metrics.positionRMSEMeters( ...
        metrics.method == "Frozen Stage 3A delta MLP");
end

summaryTable = table( ...
    variantIDs, ...
    displayNames, ...
    sourceFileCount, ...
    usableSourceFileCount, ...
    sessionCount, ...
    aircraftCount, ...
    aircraftTrackCount, ...
    pairCount, ...
    eventCount, ...
    occupiedJointRegimeCellCount, ...
    constvelPositionRMSEMeters, ...
    frozenMLPPositionRMSEMeters, ...
    'VariableNames', [ ...
        "variantID", ...
        "displayName", ...
        "sourceFileCount", ...
        "usableSourceFileCount", ...
        "sessionCount", ...
        "aircraftCount", ...
        "aircraftTrackCount", ...
        "pairCount", ...
        "eventCount", ...
        "occupiedJointRegimeCellCount", ...
        "constvelPositionRMSEMeters", ...
        "frozenMLPPositionRMSEMeters"]);

end

