function summaryTable = localAppendVariantDifference(summaryTable, difference)
%LOCALAPPENDVARIANTDIFFERENCE Add the named expanded-minus-legacy row.

differenceRow = summaryTable(1, :);
differenceRow.variantID = "expanded_minus_legacy";
differenceRow.displayName = difference.name;
differenceRow.sourceFileCount = ...
    summaryTable.sourceFileCount(summaryTable.variantID == "expanded_post3day_v2") - ...
    summaryTable.sourceFileCount(summaryTable.variantID == "legacy_pre3day_v1");
differenceRow.usableSourceFileCount = ...
    summaryTable.usableSourceFileCount(summaryTable.variantID == "expanded_post3day_v2") - ...
    summaryTable.usableSourceFileCount(summaryTable.variantID == "legacy_pre3day_v1");
differenceRow.sessionCount = ...
    summaryTable.sessionCount(summaryTable.variantID == "expanded_post3day_v2") - ...
    summaryTable.sessionCount(summaryTable.variantID == "legacy_pre3day_v1");
differenceRow.aircraftCount = difference.aircraftCount;
differenceRow.aircraftTrackCount = difference.aircraftTrackCount;
differenceRow.pairCount = difference.pairCount;
differenceRow.eventCount = difference.eventCount;
differenceRow.occupiedJointRegimeCellCount = difference.occupiedJointRegimeCellCount;
differenceRow.constvelPositionRMSEMeters = NaN;
differenceRow.frozenMLPPositionRMSEMeters = NaN;
summaryTable = [summaryTable; differenceRow];

end

function combined = localAppendTableDifference( ...
        combined, dimensionVariable, keyVariable)
%LOCALAPPENDTABLEDIFFERENCE Add expanded-minus-legacy rows to count tables.

legacy = combined(combined.variantID == "legacy_pre3day_v1", :);
expanded = combined(combined.variantID == "expanded_post3day_v2", :);
keyVariables = string(keyVariable);

if strlength(dimensionVariable) > 0
    keyVariables = [string(dimensionVariable), keyVariables];
end

differenceRows = expanded;
differenceRows.variantID(:) = "expanded_minus_legacy";
differenceRows.displayName(:) = "Expanded-3Day minus Legacy-16";
variableNames = string(differenceRows.Properties.VariableNames);

for rowIdx = 1:height(differenceRows)
    legacyMask = true(height(legacy), 1);

    for keyIdx = 1:numel(keyVariables)
        variableName = keyVariables(keyIdx);
        legacyMask = legacyMask & ...
            string(legacy.(variableName)) == string(differenceRows.(variableName)(rowIdx));
    end

    if any(legacyMask)
        for variableIdx = 1:numel(variableNames)
            variableName = variableNames(variableIdx);

            if isnumeric(differenceRows.(variableName))
                differenceRows.(variableName)(rowIdx, :) = ...
                    differenceRows.(variableName)(rowIdx, :) - ...
                    legacy.(variableName)(legacyMask, :);
            end
        end
    end
end

combined = [combined; differenceRows];

end

function combined = localCombineSplitCoverage( ...
        variantIDs, displayNames, analyses)
%LOCALCOMBINESPLITCOVERAGE Stack prospective split evidence.

combined = table();

for variantIdx = 1:numel(variantIDs)
    variantID = variantIDs(variantIdx);
    current = analyses.(variantID).splitAudit.eventCoverage;
    current = addvars( ...
        current, ...
        repmat(variantID, height(current), 1), ...
        repmat(displayNames(variantIdx), height(current), 1), ...
        'Before', ...
        1, ...
        'NewVariableNames', ...
        ["variantID", "displayName"]);
    combined = [combined; current]; %#ok<AGROW>
end

end

