function difference = localBuildDifferenceSummary(legacy, expanded)
%LOCALBUILDDIFFERENCESUMMARY Name the incremental evidence explicitly.

legacyEvents = sum(legacy.eventSummary.eventCount);
expandedEvents = sum(expanded.eventSummary.eventCount);
difference = struct();
difference.name = "Expanded-3Day minus Legacy-16";
