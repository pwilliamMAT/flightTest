function gateTable = localBuildReadinessGateTable( ...
        increment, expanded, legacy, variantSummaries)
%LOCALBUILDREADINESSGATETABLE Apply the approved local retraining gate.

gate = [ ...
    "all source files classified"; ...
    "campaign files with usable pairs"; ...
    "sustained turn diversity"; ...
    "sustained acceleration diversity"; ...
    "sustained climb diversity"; ...
    "sustained descent diversity"; ...
    "sparse-update diversity"; ...
    "contributor concentration"; ...
    "aircraft-disjoint split support"; ...
    "chronological split support"; ...
    "expanded independent coverage"; ...
    "no neural retraining"];
observed = strings(numel(gate), 1);
required = strings(numel(gate), 1);
passed = false(numel(gate), 1);

source = increment.sourceSummary;
passed(1) = source.classifiedSourceFileCount == source.sourceFileCount && ...
    source.parseFailureCount == 0 && ...
    source.unselectedSourceFileCount == 0;
observed(1) = sprintf( ...
    "%d/%d classified; %d parse failures", ...
    source.classifiedSourceFileCount, ...
    source.sourceFileCount, ...
    source.parseFailureCount);
required(1) = "all classified; zero failures";

usablePercent = 100 * source.usableSourceFileCount / max(source.sourceFileCount, 1);
passed(2) = usablePercent >= 95;
observed(2) = sprintf( ...
    "%d/%d (%.1f%%)", ...
    source.usableSourceFileCount, ...
    source.sourceFileCount, ...
    usablePercent);
required(2) = ">=95%";

[passed(3), observed(3)] = localEventDiversityGate( ...
    expanded.eventSummary, "sustained_turn", 30, 10, 3);
required(3) = ">=30 events, >=10 ICAO, 3 campaign days";
[passed(4), observed(4)] = localEventDiversityGate( ...
    expanded.eventSummary, "sustained_acceleration", 30, 10, 3);
required(4) = ">=30 events, >=10 ICAO, 3 campaign days";
[passed(5), observed(5)] = localEventDiversityGate( ...
    expanded.eventSummary, "sustained_climb", 50, 15, 3);
required(5) = ">=50 events, >=15 ICAO, 3 campaign days";
[passed(6), observed(6)] = localEventDiversityGate( ...
    expanded.eventSummary, "sustained_descent", 50, 15, 3);
required(6) = ">=50 events, >=15 ICAO, 3 campaign days";
[passed(7), observed(7)] = localSparseDiversityGate(expanded.eventSummary);
required(7) = ">=100 events, >=20 tracks, 3 campaign days";

[passed(8), observed(8)] = localConcentrationGate(expanded.eventSummary);
required(8) = "each critical regime: ICAO <=20%, campaign day <=60%";

eventCoverage = expanded.splitAudit.eventCoverage;
passed(9) = localSplitStrategyPass(eventCoverage, "aircraft_disjoint");
observed(9) = localSplitObservation(eventCoverage, "aircraft_disjoint");
required(9) = "all regimes in train; >=5 each in validation/test";
passed(10) = localSplitStrategyPass(eventCoverage, "chronological_blocked");
observed(10) = localSplitObservation(eventCoverage, "chronological_blocked");
required(10) = "all regimes in train; >=5 each in validation/test";

addedEvents = sum(expanded.eventSummary.eventCount) - ...
    sum(legacy.eventSummary.eventCount);
addedCells = sum(expanded.jointRegimeOccupancy.occupied) - ...
    sum(legacy.jointRegimeOccupancy.occupied);
passed(11) = addedEvents > 0 && addedCells > 0;
observed(11) = sprintf("+%d events; %+d occupied cells", addedEvents, addedCells);
required(11) = "positive events and occupied cells";

retrainingFlags = [ ...
    variantSummaries.legacy_pre3day_v1.retrainingRun; ...
    variantSummaries.campaign_3day_increment_v1.retrainingRun; ...
    variantSummaries.expanded_post3day_v2.retrainingRun];
passed(12) = ~any(retrainingFlags);
observed(12) = sprintf("%d retraining run(s)", sum(retrainingFlags));
required(12) = "0";

gateTable = table(gate, observed, required, passed);

end

function [passed, observation] = localEventDiversityGate( ...
        eventSummary, eventType, minimumEvents, minimumAircraft, minimumBlocks)
%LOCALEVENTDIVERSITYGATE Evaluate one sustained-event threshold.

row = eventSummary(eventSummary.eventType == eventType, :);
passed = row.eventCount >= minimumEvents && ...
    row.aircraftCount >= minimumAircraft && ...
    row.campaignBlockCount >= minimumBlocks;
observation = sprintf( ...
    "%d events, %d ICAO, %d campaign days", ...
    row.eventCount, ...
    row.aircraftCount, ...
    row.campaignBlockCount);

end

function [passed, observation] = localSparseDiversityGate(eventSummary)
%LOCALSPARSEDIVERSITYGATE Evaluate independent sparse-gap support.

row = eventSummary(eventSummary.eventType == "sparse_gap", :);
passed = row.eventCount >= 100 && ...
    row.trackCount >= 20 && ...
    row.campaignBlockCount >= 3;
observation = sprintf( ...
    "%d events, %d tracks, %d campaign days", ...
    row.eventCount, ...
    row.trackCount, ...
    row.campaignBlockCount);

end

function [passed, observation] = localConcentrationGate(eventSummary)
%LOCALCONCENTRATIONGATE Reject dominance by one aircraft or campaign day.

criticalRows = ismember(eventSummary.eventType, [ ...
    "sustained_turn", ...
    "sustained_acceleration", ...
    "sustained_climb", ...
    "sustained_descent", ...
    "sparse_gap"]);
critical = eventSummary(criticalRows, :);
passed = all(critical.largestAircraftSharePercent <= 20) && ...
    all(critical.largestCampaignBlockSharePercent <= 60);
observation = sprintf( ...
    "max ICAO %.1f%%; max campaign day %.1f%%", ...
    max(critical.largestAircraftSharePercent, [], "omitnan"), ...
    max(critical.largestCampaignBlockSharePercent, [], "omitnan"));

end

function passed = localSplitStrategyPass(eventCoverage, strategy)
%LOCALSPLITSTRATEGYPASS Apply train/validation/test event-count minima.

rows = eventCoverage(eventCoverage.splitStrategy == strategy, :);
trainRows = rows.split == "train";
holdoutRows = rows.split == "validation" | rows.split == "test";
passed = all(rows.eventCount(trainRows) >= 1) && ...
    all(rows.eventCount(holdoutRows) >= 5);

end

function observation = localSplitObservation(eventCoverage, strategy)
%LOCALSPLITOBSERVATION Report the weakest train and holdout cells.

rows = eventCoverage(eventCoverage.splitStrategy == strategy, :);
trainMinimum = min(rows.eventCount(rows.split == "train"));
validationMinimum = min(rows.eventCount(rows.split == "validation"));
testMinimum = min(rows.eventCount(rows.split == "test"));
observation = sprintf( ...
    "minimum train/validation/test = %d/%d/%d events", ...
    trainMinimum, ...
    validationMinimum, ...
    testMinimum);

end

function localWriteComparisonTables(outputFolder, comparison)
%LOCALWRITECOMPARISONTABLES Write compact CSV evidence.

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

