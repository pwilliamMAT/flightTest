function comparison = runStage4BPostCampaignMotionDiversityGate(varargin)
%RUNSTAGE4BPOSTCAMPAIGNMOTIONDIVERSITYGATE Compare versioned ADS-B datasets.
% The frozen Stage 3A model and native constvel baseline are evaluated on
% Legacy-16, the 3-Day Campaign Increment, and their Expanded-3Day union.
% This gate measures independent motion diversity and never trains a model.

projectRoot = string(fileparts(mfilename("fullpath")));
parser = inputParser;
parser.FunctionName = mfilename;
addParameter(parser, "ProjectRoot", projectRoot);
addParameter(parser, "OutputFolder", "");
addParameter(parser, "RebuildVariantEvaluations", true);
addParameter(parser, "CreateVariantPlots", true);
addParameter(parser, "CreateComparisonPlots", true);
addParameter(parser, "RefreshStage4A", true);
addParameter(parser, "Verbose", true);
parse(parser, varargin{:});

config = localBuildConfig(parser.Results);
localValidateConfig(config);

variantIDs = [ ...
    "legacy_pre3day_v1"; ...
    "campaign_3day_increment_v1"; ...
    "expanded_post3day_v2"];
displayNames = ["Legacy-16"; "3-Day Campaign Increment"; "Expanded-3Day"];
variantSummaries = struct();
analyses = struct();

for variantIdx = 1:numel(variantIDs)
    variantID = variantIDs(variantIdx);
    fullVariantSummary = localResolveVariantSummary(config, variantID);
    analyses.(variantID) = helperAnalyzeADSBDatasetMotionDiversity( ...
        fullVariantSummary, ...
        variantID);
    analyses.(variantID) = localCompactAnalysis(analyses.(variantID));
    variantSummaries.(variantID) = localCompactVariantSummary(fullVariantSummary);
    clear fullVariantSummary
end

localValidateVariantContracts(variantSummaries, analyses);

variantSummaryTable = localBuildVariantSummaryTable( ...
    variantIDs, ...
    displayNames, ...
    variantSummaries, ...
    analyses);
pairRegimeComparison = localCombineAnalysisTables( ...
    variantIDs, ...
    displayNames, ...
    analyses, ...
    "pairRegimeSummary");
eventComparison = localCombineAnalysisTables( ...
    variantIDs, ...
    displayNames, ...
    analyses, ...
    "eventSummary");
continuousComparison = localCombineAnalysisTables( ...
    variantIDs, ...
    displayNames, ...
    analyses, ...
    "continuousSummary");
continuousHistogramComparison = localCombineAnalysisTables( ...
    variantIDs, ...
    displayNames, ...
    analyses, ...
    "continuousHistogram");
jointRegimeComparison = localCombineAnalysisTables( ...
    variantIDs, ...
    displayNames, ...
    analyses, ...
    "jointRegimeOccupancy");
splitCoverageComparison = localCombineSplitCoverage( ...
    variantIDs, ...
    displayNames, ...
    analyses);
modelComparison = localBuildModelComparison( ...
    variantIDs, ...
    displayNames, ...
    variantSummaries);
differenceSummary = localBuildDifferenceSummary( ...
    analyses.legacy_pre3day_v1, ...
    analyses.expanded_post3day_v2);
variantSummaryTable = localAppendVariantDifference( ...
    variantSummaryTable, ...
    differenceSummary);
pairRegimeComparison = localAppendTableDifference( ...
    pairRegimeComparison, ...
    "dimension", ...
    "regime");
eventDifferenceTable = localBuildEventDifferenceTable( ...
    analyses.legacy_pre3day_v1.eventSummary, ...
    analyses.expanded_post3day_v2.eventSummary);
readinessGateTable = localBuildReadinessGateTable( ...
    analyses.campaign_3day_increment_v1, ...
    analyses.expanded_post3day_v2, ...
    analyses.legacy_pre3day_v1, ...
    variantSummaries);
localRetrainingReady = all(readinessGateTable.passed);
broadGeneralizationReady = false;

comparison = struct();
comparison.generatedAt = datetime("now", "TimeZone", "UTC");
comparison.projectRoot = config.ProjectRoot;
comparison.outputFolder = config.OutputFolder;
comparison.variantOrder = variantIDs;
comparison.variantDisplayNames = displayNames;
comparison.variantSummaries = variantSummaries;
comparison.analyses = analyses;
comparison.variantSummaryTable = variantSummaryTable;
comparison.pairRegimeComparison = pairRegimeComparison;
comparison.eventComparison = eventComparison;
comparison.eventDifferenceTable = eventDifferenceTable;
comparison.continuousComparison = continuousComparison;
comparison.continuousHistogramComparison = continuousHistogramComparison;
comparison.jointRegimeComparison = jointRegimeComparison;
comparison.splitCoverageComparison = splitCoverageComparison;
comparison.modelComparison = modelComparison;
comparison.differenceSummary = differenceSummary;
comparison.readinessGateTable = readinessGateTable;
comparison.localRetrainingReady = localRetrainingReady;
comparison.broadGeneralizationReady = broadGeneralizationReady;
comparison.broadGeneralizationReason = ...
    "The evaluated data use one receiver location and one local ADS-B collection domain; three campaign days cannot establish cross-location or cross-source generalization.";
comparison.retrainingRun = false;
comparison.artifactPath = fullfile( ...
    config.OutputFolder, ...
    "stage4BPostCampaignMotionDiversity.mat");
comparison.reportPath = fullfile( ...
    config.OutputFolder, ...
    "stage4BPostCampaignMotionDiversityReport.md");
comparison.figurePaths = struct();
comparison.stage4ARefresh = struct();

localWriteComparisonTables(config.OutputFolder, comparison);

if config.CreateComparisonPlots
    comparison.figurePaths = helperWriteStage4BPostCampaignFigures( ...
        config.OutputFolder, ...
        comparison);
end

function differenceTable = localBuildEventDifferenceTable(legacy, expanded)
%LOCALBUILDEVENTDIFFERENCETABLE Report additive event gains by type.

differenceTable = table();
differenceTable.eventType = expanded.eventType;
differenceTable.eventCount = expanded.eventCount - legacy.eventCount;
differenceTable.totalDurationSeconds = ...
    expanded.totalDurationSeconds - legacy.totalDurationSeconds;
differenceTable.displayName = repmat( ...
    "Expanded-3Day minus Legacy-16", ...
    height(differenceTable), ...
    1);
differenceTable = movevars(differenceTable, "displayName", "Before", 1);

end

if config.RefreshStage4A
    comparison.stage4ARefresh = localRefreshStage4A( ...
        config, ...
        variantSummaries.expanded_post3day_v2);
end

helperWriteStage4BPostCampaignReport(comparison.reportPath, comparison);
localSaveComparison(comparison);

if config.Verbose
    localPrintSummary(comparison);
end

end

