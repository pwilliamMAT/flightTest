function localValidateConfig(config)
%LOCALVALIDATECONFIG Validate the version manifest and output path.

if ~isfolder(config.ProjectRoot)
    error("Stage4BPost:MissingProjectRoot", ...
        "Project root was not found: %s", config.ProjectRoot);
end

manifestPath = fullfile( ...
    config.ProjectRoot, ...
    "adsb_archive", ...
    "datasetVersions", ...
    "adsbDatasetVariants.csv");

if exist(manifestPath, "file") ~= 2
    error("Stage4BPost:MissingVariantManifest", ...
        "Run integrateStage4BThreeDayArchive before the diversity gate.");
