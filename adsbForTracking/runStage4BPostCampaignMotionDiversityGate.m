function localValidateVariantContracts(variantSummaries, analyses)
%LOCALVALIDATEVARIANTCONTRACTS Verify union and frozen evaluation settings.

legacyFiles = string( ...
    variantSummaries.legacy_pre3day_v1.datasetVariantManifestRows.relativeSourceFile);
incrementFiles = string( ...
    variantSummaries.campaign_3day_increment_v1.datasetVariantManifestRows.relativeSourceFile);
expandedFiles = string( ...
    variantSummaries.expanded_post3day_v2.datasetVariantManifestRows.relativeSourceFile);

if ~isempty(intersect(legacyFiles, incrementFiles))
    error("Stage4BPost:VariantOverlap", ...
        "Legacy-16 and the 3-Day Campaign Increment overlap.");
end

expectedUnion = sort(unique([legacyFiles; incrementFiles]));

if ~isequal(sort(expandedFiles), expectedUnion)
    error("Stage4BPost:InvalidVariantUnion", ...
        "Expanded-3Day is not the exact union of Legacy-16 and the campaign increment.");
end

legacyThresholds = analyses.legacy_pre3day_v1.motionThresholds;
incrementThresholds = analyses.campaign_3day_increment_v1.motionThresholds;
expandedThresholds = analyses.expanded_post3day_v2.motionThresholds;

if ~isequaln(legacyThresholds, incrementThresholds) || ...
        ~isequaln(legacyThresholds, expandedThresholds)
    error("Stage4BPost:ThresholdMismatch", ...
        "All variants must use identical motion thresholds.");
end

stage3APaths = [ ...
    string(variantSummaries.legacy_pre3day_v1.stage3AArtifactPath); ...
    string(variantSummaries.campaign_3day_increment_v1.stage3AArtifactPath); ...
    string(variantSummaries.expanded_post3day_v2.stage3AArtifactPath)];

if numel(unique(stage3APaths)) ~= 1
    error("Stage4BPost:FrozenModelMismatch", ...
        "All variants must use the same frozen Stage 3A artifact.");
end

retrainingFlags = [ ...
    variantSummaries.legacy_pre3day_v1.archiveSummary.retrainingRun; ...
    variantSummaries.campaign_3day_increment_v1.archiveSummary.retrainingRun; ...
    variantSummaries.expanded_post3day_v2.archiveSummary.retrainingRun];

if any(retrainingFlags)
    error("Stage4BPost:UnexpectedRetraining", ...
        "A variant indicates that retraining occurred.");
end

end

