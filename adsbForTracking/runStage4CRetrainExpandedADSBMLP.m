rng(config.Seed, "twister");
iterationsPerEpoch = ceil(size(XTrain, 1) / config.MiniBatchSize);
options = trainingOptions( ...
    "adam", ...
    "MaxEpochs", ...
    config.MaxEpochs, ...
    "MiniBatchSize", ...
    config.MiniBatchSize, ...
    "InitialLearnRate", ...
    config.InitialLearnRate, ...
