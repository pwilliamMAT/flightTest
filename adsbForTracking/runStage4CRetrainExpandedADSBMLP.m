function tiny = localRunTinyOverfit(XTrain, YTrain, config)
%LOCALRUNTINYOVERFIT Fit one deterministic 128-row batch before full runs.

sampleCount = min(config.TinySampleCount, size(XTrain, 1));
rng(config.Seed, "twister");
selection = randperm(size(XTrain, 1), sampleCount);
XTiny = XTrain(selection, :);
YTiny = YTrain(selection, :);
rng(config.Seed, "twister");
tinyNet = dlnetwork(localBuildLayers(config.HiddenUnits));
rng(config.Seed, "twister");
options = trainingOptions( ...
    "adam", ...
    "MaxEpochs", ...
    config.TinyEpochs, ...
    "MiniBatchSize", ...
    sampleCount, ...
    "InitialLearnRate", ...
    config.InitialLearnRate, ...
    "L2Regularization", ...
    config.L2Regularization, ...
    "Shuffle", ...
    "every-epoch", ...
    "ExecutionEnvironment", ...
    config.ExecutionEnvironment, ...
    "Verbose", ...
    false, ...
    "Plots", ...
    "none");
[tinyNet, info] = trainnet(XTiny, YTiny, tinyNet, "mse", options);
prediction = localPredictNormalized( ...
    tinyNet, ...
    XTiny, ...
    config.PredictionMiniBatchSize);
history = info.TrainingHistory;
firstTrainingLoss = history.Loss(1);
finalTrainingLoss = history.Loss(end);
predictionMSE = mean((double(prediction) - double(YTiny)) .^ 2, "all");
lossDecreased = finalTrainingLoss < firstTrainingLoss;
passed = all(isfinite(prediction), "all") && ...
    isfinite(firstTrainingLoss) && ...
    isfinite(finalTrainingLoss) && ...
    isfinite(predictionMSE) && ...
    (lossDecreased || config.TinyEpochs == 1);

tiny = struct();
tiny.sampleCount = sampleCount;
tiny.maxEpochs = config.TinyEpochs;
tiny.firstTrainingLoss = firstTrainingLoss;
tiny.finalTrainingLoss = finalTrainingLoss;
tiny.predictionMSE = predictionMSE;
tiny.lossDecreased = lossDecreased;
tiny.stopReason = string(info.StopReason);
tiny.passed = passed;
tiny.trainingHistory = history;

end

function run = localTrainFullNetwork( ...
        initialNet, ...
        XTrain, ...
        YTrain, ...
        XValidation, ...
        YValidation, ...
        config, ...
