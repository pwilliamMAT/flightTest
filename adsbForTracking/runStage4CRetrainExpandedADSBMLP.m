function membership = localMembershipMask(values)
%LOCALMEMBERSHIPMASK Validate a dataset-variant membership column.

if islogical(values)
    membership = values;
elseif isnumeric(values)
    if any(~isfinite(values), "all") || ...
            any(values ~= 0 & values ~= 1, "all")
        error("Stage4C:InvalidVariantMembership", ...
            "Variant membership must contain only zero or one.");
    end

    membership = logical(values);
else
    text = lower(strtrim(string(values)));
    valid = text == "true" | text == "false" | ...
        text == "1" | text == "0";

    if any(~valid)
        error("Stage4C:InvalidVariantMembership", ...
            "Variant membership must contain only true/false or one/zero.");
    end

    membership = text == "true" | text == "1";
end

membership = membership(:);

end

function keys = localSourceMembershipKey(paths)
%LOCALSOURCEMEMBERSHIPKEY Compare original gzip and fallback text sources.

paths = lower(replace(string(paths), "\", "/"));
keys = strings(numel(paths), 1);
marker = "testing_machine/captures/";

for pathIdx = 1:numel(paths)
    pathValue = paths(pathIdx);
    markerIndex = strfind(pathValue, marker);

    if isempty(markerIndex)
        key = pathValue;
    else
        key = extractAfter(pathValue, markerIndex(end) - 1);
    end

    if endsWith(key, ".gz")
        key = extractBefore(key, strlength(key) - 2);
    end

    keys(pathIdx) = key;
end

end

