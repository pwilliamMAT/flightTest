function predictedState = localPredictPhysicalState( ...
        net, ...
        physicalFeatures, ...
        previousState, ...
        featureNormalization, ...
        targetNormalization, ...
        miniBatchSize)
%LOCALPREDICTPHYSICALSTATE Normalize, infer delta, and reconstruct state.

featuresNormalized = ...
    (double(physicalFeatures) - featureNormalization.featureMean) ./ ...
    featureNormalization.featureStd;
predictedDeltaNormalized = localPredictNormalized( ...
    net, ...
    single(featuresNormalized), ...
    miniBatchSize);
predictedDelta = double(predictedDeltaNormalized) .* ...
    targetNormalization.targetStd + ...
    targetNormalization.targetMean;
predictedState = double(previousState) + predictedDelta;

if any(~isfinite(predictedState), "all")
    error("Stage4C:NonfinitePrediction", ...
        "A Stage 4C model produced nonfinite physical predictions.");
end

end

