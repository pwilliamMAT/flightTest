function provenance = localAuditDatasetProvenance(dataset, config)
%LOCALAUDITDATASETPROVENANCE Verify variant membership and source hashes.

variantManifest = readtable( ...
    config.DatasetVariantManifestPath, ...
    "TextType", ...
    "string");
requiredVariables = [ ...
    "relativeSourceFile", ...
    "sourceFileSHA256", ...
    config.DatasetVariantID];

if any(~ismember(requiredVariables, ...
        string(variantManifest.Properties.VariableNames)))
    error("Stage4C:InvalidVariantManifest", ...
        "Dataset-variant manifest is missing required fields.");
end

membership = localMembershipMask( ...
    variantManifest.(char(config.DatasetVariantID)));
selectedManifest = variantManifest(membership, :);

if height(selectedManifest) ~= 159 || height(dataset.sourceManifest) ~= 159
    error("Stage4C:DatasetMembershipCountMismatch", ...
        "Expanded-3Day must contain exactly 159 source files.");
end

expectedPaths = strings(height(selectedManifest), 1);

for rowIdx = 1:height(selectedManifest)
    expectedPaths(rowIdx) = localCanonicalPath(fullfile( ...
        config.ProjectRoot, ...
        replace( ...
        selectedManifest.relativeSourceFile(rowIdx), ...
        "/", ...
        filesep)));
end

expectedKeys = localSourceMembershipKey(expectedPaths);
datasetKeys = localSourceMembershipKey(dataset.sourceManifest.sourceFile);
membershipPassed = isequal(sort(expectedKeys), sort(datasetKeys));

if ~membershipPassed
    error("Stage4C:DatasetMembershipMismatch", ...
        "Dataset source membership does not match expanded_post3day_v2.");
end

expectedSHA256 = upper(strtrim(string( ...
    selectedManifest.sourceFileSHA256)));
observedSHA256 = repmat("not_verified", height(selectedManifest), 1);
hashPassed = false(height(selectedManifest), 1);

if config.VerifySourceHashes
    for rowIdx = 1:height(selectedManifest)
        observedSHA256(rowIdx) = helperComputeFileSHA256(expectedPaths(rowIdx));
        hashPassed(rowIdx) = strcmpi( ...
            observedSHA256(rowIdx), ...
            expectedSHA256(rowIdx));
    end

    if ~all(hashPassed)
        failedPath = expectedPaths(find(~hashPassed, 1, "first"));
        error("Stage4C:SourceHashMismatch", ...
            "Expanded-3Day source hash mismatch: %s", failedPath);
    end
end

sourceHashTable = table( ...
    selectedManifest.relativeSourceFile, ...
    expectedSHA256, ...
    observedSHA256, ...
    hashPassed, ...
    'VariableNames', [ ...
        "relativeSourceFile", ...
        "expectedSHA256", ...
        "observedSHA256", ...
        "passed"]);

provenance = struct();
provenance.datasetVariantID = config.DatasetVariantID;
provenance.datasetPath = config.DatasetPath;
provenance.datasetSHA256 = helperComputeFileSHA256(config.DatasetPath);
provenance.variantManifestPath = config.DatasetVariantManifestPath;
provenance.variantManifestSHA256 = helperComputeFileSHA256( ...
    config.DatasetVariantManifestPath);
provenance.sourceFileCount = height(selectedManifest);
provenance.datasetMembershipPassed = membershipPassed;
provenance.sourceHashesVerified = config.VerifySourceHashes;
provenance.sourceHashAuditPassed = ...
    config.VerifySourceHashes && all(hashPassed);
provenance.sourceHashTable = sourceHashTable;

end

function [split, audit, provenance] = localLoadAndAuditSplit(metadata, config)
%LOCALLOADANDAUDITSPLIT Apply the frozen global ICAO-disjoint assignment.

manifest = readtable(config.SplitManifestPath, "TextType", "string");
requiredVariables = [ ...
    "icao24", ...
    "split", ...
    "pairCount", ...
    "assignmentOrder", ...
    "datasetVariantID", ...
    "policyVersion"];

if any(~ismember(requiredVariables, string(manifest.Properties.VariableNames)))
    error("Stage4C:InvalidSplitManifest", ...
        "The Stage 4C split manifest is missing required variables.");
end

manifest.icao24 = lower(strtrim(string(manifest.icao24)));
manifest.split = lower(strtrim(string(manifest.split)));
datasetICAO = lower(strtrim(string(metadata.hex)));
uniqueDatasetICAO = sort(unique(datasetICAO));

if height(manifest) ~= numel(uniqueDatasetICAO) || ...
        numel(unique(manifest.icao24)) ~= height(manifest) || ...
        ~isequal(sort(manifest.icao24), uniqueDatasetICAO)
    error("Stage4C:SplitMembershipMismatch", ...
        "Split manifest must assign every Expanded-3Day ICAO exactly once.");
end

if any(~ismember(manifest.split, config.SplitNames)) || ...
        any(manifest.datasetVariantID ~= config.DatasetVariantID) || ...
        numel(unique(manifest.policyVersion)) ~= 1
    error("Stage4C:InvalidSplitAssignment", ...
        "Split assignments, dataset identity, or policy version are invalid.");
end

[found, manifestRow] = ismember(datasetICAO, manifest.icao24);

if ~all(found)
    error("Stage4C:UnassignedDatasetICAO", ...
        "At least one Expanded-3Day ICAO is absent from the split manifest.");
end

split = manifest.split(manifestRow);
actualPairCountByICAO = accumarray( ...
    manifestRow, ...
    1, ...
    [height(manifest), 1]);

if any(actualPairCountByICAO ~= double(manifest.pairCount))
    error("Stage4C:SplitPairCountMismatch", ...
        "Split manifest pair counts do not match the dataset.");
end

pairCount = zeros(numel(config.SplitNames), 1);
aircraftCount = zeros(numel(config.SplitNames), 1);

for splitIdx = 1:numel(config.SplitNames)
    splitName = config.SplitNames(splitIdx);
    pairCount(splitIdx) = sum(split == splitName);
    aircraftCount(splitIdx) = sum(manifest.split == splitName);
end

if any(pairCount(:).' ~= config.ExpectedPairCounts)
    error("Stage4C:UnexpectedSplitCounts", ...
        "Expected train/validation/test pair counts of %s; observed %s.", ...
        mat2str(config.ExpectedPairCounts), ...
        mat2str(pairCount(:).'));
end

[inheritedGroup, ~] = findgroups(datasetICAO);
inheritedSplitCount = splitapply( ...
    @(value) numel(unique(string(value))), ...
    metadata.split, ...
    inheritedGroup);
inheritedOverlappingICAOCount = sum(inheritedSplitCount > 1);

if inheritedOverlappingICAOCount ~= 394
    error("Stage4C:InheritedSplitAuditChanged", ...
        "Expected 394 inherited smoke-split ICAO overlaps; observed %d.", ...
        inheritedOverlappingICAOCount);
end

summaryTable = table( ...
    config.SplitNames(:), ...
    pairCount, ...
    aircraftCount, ...
    'VariableNames', ["split", "pairCount", "aircraftCount"]);
audit = struct();
audit.summary = summaryTable;
audit.everyICAOAssignedOnce = true;
audit.aircraftLeakage = false;
audit.inheritedOverlappingICAOCount = ...
    inheritedOverlappingICAOCount;
audit.inheritedSplitIgnored = true;
audit.icaoUsedOnlyAsPartitionKey = true;

provenance = struct();
provenance.splitManifestPath = config.SplitManifestPath;
provenance.splitManifestSHA256 = helperComputeFileSHA256( ...
    config.SplitManifestPath);
provenance.policyVersion = unique(manifest.policyVersion);
provenance.assignmentCount = height(manifest);
provenance.expectedPairCounts = config.ExpectedPairCounts;

end

