        baseline.velocityRMSEMetersPerSecond;
    beatsConstvelPosition(candidateIdx) = ...
        positionDeltaFromConstvelMeters(candidateIdx) < 0;
    beatsConstvelVelocity(candidateIdx) = ...
        velocityDeltaFromConstvelMetersPerSecond(candidateIdx) < 0;
end

