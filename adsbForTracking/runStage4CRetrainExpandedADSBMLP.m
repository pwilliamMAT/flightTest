        comparison.testPositionRMSEMeters(rowIdx), ...
        comparison.positionDeltaFromConstvelMeters(rowIdx), ...
        velocityResult, ...
        comparison.testVelocityRMSEMetersPerSecond(rowIdx), ...
        comparison.velocityDeltaFromConstvelMetersPerSecond(rowIdx));
