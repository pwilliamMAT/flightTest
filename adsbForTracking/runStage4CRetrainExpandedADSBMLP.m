    candidateIDs, ...
    positionRMSEMeters, ...
    velocityRMSEMetersPerSecond, ...
    positionDeltaFromConstvelMeters, ...
    velocityDeltaFromConstvelMetersPerSecond, ...
    beatsConstvelPosition, ...
    beatsConstvelVelocity, ...
    'VariableNames', [ ...
        "modelID", ...
        "testPositionRMSEMeters", ...
        "testVelocityRMSEMetersPerSecond", ...
        "positionDeltaFromConstvelMeters", ...
        "velocityDeltaFromConstvelMetersPerSecond", ...
        "beatsConstvelPosition", ...
        "beatsConstvelVelocity"]);

end

