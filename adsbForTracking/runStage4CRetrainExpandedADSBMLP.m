function summary = runStage4CRetrainExpandedADSBMLP(varargin)
%RUNSTAGE4CRETRAINEXPANDEDADSBMLP Train two Expanded-3Day mean MLPs.
% The scratch model tests what the unchanged 20-64-64-6 architecture can
% learn from the expanded data. The warm control starts from Stage 3A
% weights after normalization rebasing. Both remain memoryless and predict
% only the six-component state delta with normalized MSE.

projectRoot = string(fileparts(mfilename("fullpath")));
parser = inputParser;
parser.FunctionName = mfilename;
addParameter(parser, "ProjectRoot", projectRoot);
addParameter(parser, "DatasetPath", "");
addParameter(parser, "DatasetVariantManifestPath", "");
addParameter(parser, "SplitManifestPath", "");
addParameter(parser, "Stage3AArtifactPath", "");
addParameter(parser, "OutputFolder", "");
addParameter(parser, "ScratchArtifactPath", "");
addParameter(parser, "WarmArtifactPath", "");
addParameter(parser, "ComparisonArtifactPath", "");
addParameter(parser, "ReportPath", "");
addParameter(parser, "MetricTablePath", "");
addParameter(parser, "Seed", 123);
addParameter(parser, "HiddenUnits", 64);
addParameter(parser, "MiniBatchSize", 1024);
addParameter(parser, "MaxEpochs", 50);
addParameter(parser, "InitialLearnRate", 1e-3);
addParameter(parser, "L2Regularization", 1e-4);
addParameter(parser, "ValidationPatience", 8);
addParameter(parser, "TinySampleCount", 128);
addParameter(parser, "TinyEpochs", 100);
addParameter(parser, "PredictionMiniBatchSize", 8192);
addParameter(parser, "ExecutionEnvironment", "cpu");
addParameter(parser, "VerifySourceHashes", true);
addParameter(parser, "CreatePlots", true);
addParameter(parser, "PreflightOnly", false);
addParameter(parser, "Verbose", true);
parse(parser, varargin{:});

config = localBuildConfig(parser.Results);
localValidateConfig(config);

if config.Verbose
    fprintf("Stage 4C-Retrain Expanded-3Day exploratory mean MLP\n");
    fprintf("Dataset:\t%s\n", config.DatasetPath);
    fprintf("Split manifest:\t%s\n", config.SplitManifestPath);
end

stage3AHashBefore = helperComputeFileSHA256(config.Stage3AArtifactPath);
dataset = localLoadDataset(config.DatasetPath);
stage3A = localLoadStage3A(config.Stage3AArtifactPath);
datasetProvenance = localAuditDatasetProvenance(dataset, config);
[split, splitAudit, splitProvenance] = localLoadAndAuditSplit( ...
    dataset.metadata, ...
    config);

constvelPredictedState = localResolveConstvelPrediction(dataset);
constvelAudit = localAuditConstvelPrediction( ...
    dataset.previousState, ...
    dataset.dtSeconds, ...
    constvelPredictedState);
featureData = helperBuildStage4CFeatures( ...
    dataset.previousState, ...
    dataset.previousCovarianceDiag, ...
    dataset.dtSeconds, ...
    constvelPredictedState);
architectureAudit = localAuditArchitecture( ...
    stage3A.net, ...
    featureData.featureNames, ...
    config.HiddenUnits);

targetDelta = dataset.nextState - dataset.previousState;
normalization = localComputeNormalization( ...
    featureData.features, ...
    featureData.featureNames, ...
    targetDelta, ...
    split);
featuresNormalized = ...
    (featureData.features - normalization.features.featureMean) ./ ...
    normalization.features.featureStd;
targetNormalized = ...
    (targetDelta - normalization.target.targetMean) ./ ...
    normalization.target.targetStd;
localValidateNormalizedData(featuresNormalized, targetNormalized);

trainMask = split == "train";
validationMask = split == "validation";
rebaseRows = localSelectRebaseRows(find(trainMask), 512);
[warmInitialNet, warmStartRebaseAudit] = ...
    helperRebaseStage3ANetworkNormalization( ...
    stage3A.net, ...
    stage3A.normalization.physicsFeatures, ...
    stage3A.normalization.target, ...
    normalization.features, ...
    normalization.target, ...
    featureData.features(rebaseRows, :), ...
    dataset.previousState(rebaseRows, :));

nativeFunctionAudit = localBuildNativeFunctionAudit(constvelAudit);
stage3AIntegrity = struct();
stage3AIntegrity.path = config.Stage3AArtifactPath;
stage3AIntegrity.beforeSHA256 = stage3AHashBefore;
stage3AIntegrity.afterSHA256 = stage3AHashBefore;
stage3AIntegrity.unchanged = true;

summary = localBuildPreflightSummary( ...
    config, ...
    dataset, ...
    datasetProvenance, ...
    splitAudit, ...
    splitProvenance, ...
    normalization, ...
    featureData, ...
    architectureAudit, ...
    warmStartRebaseAudit, ...
    nativeFunctionAudit, ...
    stage3AIntegrity);

if config.PreflightOnly
    if config.Verbose
        fprintf("Preflight complete; neural training was not run.\n");
    end

    return;
end

% The tiny check is deliberately completed before either full-data run.
% Its single batch should become easier to fit, proving that data flow,
% target orientation, gradients, and the six-output reconstruction agree.
tinyOverfit = localRunTinyOverfit( ...
    single(featuresNormalized(trainMask, :)), ...
    single(targetNormalized(trainMask, :)), ...
    config);

if ~tinyOverfit.passed
    error("Stage4C:TinyOverfitFailed", ...
        "The 128-row tiny-overfit check did not produce finite decreasing loss.");
end

XTrain = single(featuresNormalized(trainMask, :));
YTrain = single(targetNormalized(trainMask, :));
XValidation = single(featuresNormalized(validationMask, :));
YValidation = single(targetNormalized(validationMask, :));

if config.Verbose
    fprintf("Training expanded_scratch_mean_v1...\n");
end

scratchRun = localTrainFullNetwork( ...
    [], ...
    XTrain, ...
    YTrain, ...
    XValidation, ...
    YValidation, ...
    config, ...
    "expanded_scratch_mean_v1");

if config.Verbose
    fprintf("Training expanded_warm_mean_v1...\n");
end

warmRun = localTrainFullNetwork( ...
    warmInitialNet, ...
    XTrain, ...
    YTrain, ...
    XValidation, ...
    YValidation, ...
    config, ...
    "expanded_warm_mean_v1");

holdoutMask = split == "validation" | split == "test";
holdoutPreviousState = dataset.previousState(holdoutMask, :);
holdoutNextState = dataset.nextState(holdoutMask, :);
holdoutMetadata = dataset.metadata(holdoutMask, :);
holdoutLabels = helperAssignADSBManeuverLabels( ...
    holdoutPreviousState, ...
    holdoutNextState, ...
    dataset.dtSeconds(holdoutMask));
holdoutSplit = split(holdoutMask);

legacyPredictedState = localPredictPhysicalState( ...
    stage3A.net, ...
    featureData.features(holdoutMask, :), ...
    holdoutPreviousState, ...
    stage3A.normalization.physicsFeatures, ...
    stage3A.normalization.target, ...
    config.PredictionMiniBatchSize);
scratchPredictedState = localPredictPhysicalState( ...
    scratchRun.net, ...
    featureData.features(holdoutMask, :), ...
    holdoutPreviousState, ...
    normalization.features, ...
    normalization.target, ...
    config.PredictionMiniBatchSize);
warmPredictedState = localPredictPhysicalState( ...
    warmRun.net, ...
    featureData.features(holdoutMask, :), ...
    holdoutPreviousState, ...
    normalization.features, ...
    normalization.target, ...
    config.PredictionMiniBatchSize);

modelPredictions = localPackModelPredictions( ...
    constvelPredictedState(holdoutMask, :), ...
    legacyPredictedState, ...
    scratchPredictedState, ...
    warmPredictedState);
metrics = helperScoreStage4CMeanModels( ...
    holdoutNextState, ...
    modelPredictions, ...
    holdoutMetadata, ...
    holdoutLabels, ...
    holdoutSplit);
candidateComparison = localBuildCandidateComparison(metrics.table);
exploratoryVerdict = localBuildExploratoryVerdict(candidateComparison);

if ~isfolder(config.OutputFolder)
    mkdir(config.OutputFolder);
end

writetable(metrics.table, config.MetricTablePath);
figurePaths = struct();

if config.CreatePlots
    figurePaths = helperWriteStage4CRetrainFigures( ...
        config.OutputFolder, ...
        scratchRun.info, ...
        warmRun.info, ...
        holdoutNextState, ...
        modelPredictions, ...
        holdoutMetadata, ...
        holdoutLabels, ...
        holdoutSplit);
end

stage3AHashAfter = helperComputeFileSHA256(config.Stage3AArtifactPath);
stage3AIntegrity.afterSHA256 = stage3AHashAfter;
stage3AIntegrity.unchanged = strcmpi(stage3AHashBefore, stage3AHashAfter);

if ~stage3AIntegrity.unchanged
    error("Stage4C:Stage3AArtifactChanged", ...
        "The frozen Stage 3A artifact hash changed during Stage 4C.");
end

summary.generatedAt = datetime("now", "TimeZone", "UTC");
summary.completed = true;
summary.tinyOverfit = tinyOverfit;
summary.warmStartRebaseAudit = warmStartRebaseAudit;
summary.scratchTraining = localCompactTrainingRun(scratchRun);
summary.warmTraining = localCompactTrainingRun(warmRun);
summary.trainingOptions = localTrainingOptionRecord(config, sum(trainMask));
summary.metrics = metrics;
summary.candidateComparison = candidateComparison;
summary.exploratoryVerdict = exploratoryVerdict;
summary.stage3AIntegrity = stage3AIntegrity;
summary.figurePaths = figurePaths;
summary.scratchArtifactPath = config.ScratchArtifactPath;
summary.warmArtifactPath = config.WarmArtifactPath;
summary.comparisonArtifactPath = config.ComparisonArtifactPath;
summary.reportPath = config.ReportPath;
summary.metricTablePath = config.MetricTablePath;

localSaveModelArtifact( ...
    config.ScratchArtifactPath, ...
    "expanded_scratch_mean_v1", ...
    scratchRun, ...
    "fresh_glorot_initialization", ...
    struct(), ...
    normalization, ...
    summary);
localSaveModelArtifact( ...
    config.WarmArtifactPath, ...
    "expanded_warm_mean_v1", ...
    warmRun, ...
    "legacy_stage3a_v1_rebased_to_expanded_normalization", ...
    warmStartRebaseAudit, ...
    normalization, ...
    summary);
localSaveComparisonArtifact(config.ComparisonArtifactPath, summary);
helperWriteStage4CRetrainReport(config.ReportPath, summary);

if config.Verbose
    localPrintCompletion(summary);
end

end

