    iterationsPerEpoch, ...
    "ValidationPatience", ...
    config.ValidationPatience, ...
    "OutputNetwork", ...
    "best-validation", ...
    "ExecutionEnvironment", ...
    config.ExecutionEnvironment, ...
    "Verbose", ...
    config.Verbose, ...
    "VerboseFrequency", ...
    iterationsPerEpoch, ...
    "Plots", ...
    "none");
