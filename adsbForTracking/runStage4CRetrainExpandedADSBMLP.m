function localValidateConfig(config)
%LOCALVALIDATECONFIG Reject invalid settings and unsafe output collisions.

requiredFiles = [ ...
    config.DatasetPath, ...
    config.DatasetVariantManifestPath, ...
    config.SplitManifestPath, ...
    config.Stage3AArtifactPath];

for pathIdx = 1:numel(requiredFiles)
    if exist(requiredFiles(pathIdx), "file") ~= 2
        error("Stage4C:MissingInputFile", ...
            "Required input file was not found: %s", requiredFiles(pathIdx));
    end
end

validateattributes(config.Seed, ...
    {'numeric'}, {'scalar', 'integer', 'finite'}, mfilename, "Seed");
validateattributes(config.HiddenUnits, ...
    {'numeric'}, {'scalar', 'integer', 'positive'}, mfilename, "HiddenUnits");
validateattributes(config.MiniBatchSize, ...
    {'numeric'}, {'scalar', 'integer', 'positive'}, mfilename, "MiniBatchSize");
validateattributes(config.MaxEpochs, ...
    {'numeric'}, {'scalar', 'integer', 'positive'}, mfilename, "MaxEpochs");
validateattributes(config.InitialLearnRate, ...
    {'numeric'}, {'scalar', 'real', 'finite', 'positive'}, ...
    mfilename, "InitialLearnRate");
validateattributes(config.L2Regularization, ...
    {'numeric'}, {'scalar', 'real', 'finite', 'nonnegative'}, ...
    mfilename, "L2Regularization");
validateattributes(config.ValidationPatience, ...
    {'numeric'}, {'scalar', 'integer', 'positive'}, ...
    mfilename, "ValidationPatience");
validateattributes(config.TinySampleCount, ...
    {'numeric'}, {'scalar', 'integer', 'positive'}, ...
    mfilename, "TinySampleCount");
validateattributes(config.TinyEpochs, ...
    {'numeric'}, {'scalar', 'integer', 'positive'}, ...
    mfilename, "TinyEpochs");
validateattributes(config.PredictionMiniBatchSize, ...
    {'numeric'}, {'scalar', 'integer', 'positive'}, ...
    mfilename, "PredictionMiniBatchSize");

if config.HiddenUnits ~= 64
    error("Stage4C:ArchitectureChanged", ...
        "Stage 4C must retain exactly 64 units in both hidden layers.");
end

if config.ExecutionEnvironment ~= "cpu"
    error("Stage4C:ExecutionEnvironmentChanged", ...
        "Stage 4C defaults and approved runs require CPU execution.");
end

protectedInputPaths = [ ...
    config.DatasetPath, ...
    config.DatasetVariantManifestPath, ...
    config.SplitManifestPath, ...
    config.Stage3AArtifactPath];
outputPaths = [ ...
    config.ScratchArtifactPath, ...
    config.WarmArtifactPath, ...
    config.ComparisonArtifactPath, ...
    config.ReportPath, ...
    config.MetricTablePath];

if numel(unique(lower(outputPaths))) ~= numel(outputPaths)
    error("Stage4C:OutputPathCollision", ...
        "Every Stage 4C output must use a distinct path.");
end

if any(ismember(lower(outputPaths), lower(protectedInputPaths)))
    error("Stage4C:ProtectedArtifactCollision", ...
        "Stage 4C outputs cannot overwrite an input or Stage 3A artifact.");
end

end

function dataset = localLoadDataset(datasetPath)
%LOCALLOADDATASET Load only the fields needed by Stage 4C.

try
    dataset = load( ...
        datasetPath, ...
        "previousState", ...
        "nextState", ...
        "dtSeconds", ...
        "previousCovarianceDiag", ...
        "metadata", ...
        "stateOrder", ...
        "sourceManifest", ...
        "buildSummary", ...
        "baselineConstVelMetrics");
catch err
    error("Stage4C:DatasetLoadFailed", ...
        "Unable to load Expanded-3Day dataset: %s", err.message);
end

requiredFields = [ ...
    "previousState", ...
    "nextState", ...
    "dtSeconds", ...
    "previousCovarianceDiag", ...
    "metadata", ...
    "stateOrder", ...
    "sourceManifest", ...
    "baselineConstVelMetrics"];

if any(~isfield(dataset, requiredFields))
    error("Stage4C:InvalidDatasetArtifact", ...
        "Expanded-3Day dataset is missing a required field.");
end

pairCount = size(dataset.previousState, 1);

if pairCount ~= 457903 || ...
        size(dataset.previousState, 2) ~= 6 || ...
        ~isequal(size(dataset.nextState), [pairCount, 6]) || ...
        ~isequal(size(dataset.previousCovarianceDiag), [pairCount, 6]) || ...
        numel(dataset.dtSeconds) ~= pairCount || ...
        height(dataset.metadata) ~= pairCount
    error("Stage4C:DatasetContractMismatch", ...
        "Expanded-3Day must contain exactly 457,903 aligned N-by-6 pairs.");
end

expectedStateOrder = ["x", "vx", "y", "vy", "z", "vz"];

if any(string(dataset.stateOrder(:).') ~= expectedStateOrder)
    error("Stage4C:StateOrderMismatch", ...
        "Dataset state order must be [x, vx, y, vy, z, vz].");
end

end

