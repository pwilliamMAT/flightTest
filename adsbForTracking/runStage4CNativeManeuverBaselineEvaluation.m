function localAuditFrozenInputs(dataset, split, stage4CSummary, config)
%LOCALAUDITFROZENINPUTS Confirm the extension matches the training run.

datasetSHA256 = helperComputeFileSHA256(config.DatasetPath);
splitSHA256 = helperComputeFileSHA256(config.SplitManifestPath);

if ~strcmpi( ...
        datasetSHA256, ...
        stage4CSummary.datasetProvenance.datasetSHA256) || ...
        ~strcmpi( ...
        splitSHA256, ...
        stage4CSummary.splitProvenance.splitManifestSHA256)
    error("Stage4CNative:FrozenInputHashMismatch", ...
        "Dataset or split hash differs from the completed Stage 4C run.");
end

if size(dataset.previousState, 1) ~= ...
        stage4CSummary.datasetPairCount || ...
        any(~ismember(unique(split), ["train", "validation", "test"]))
    error("Stage4CNative:FrozenInputAlignmentMismatch", ...
        "Dataset rows or split names no longer match Stage 4C.");
end

end

function model = localLoadFrozenModel( ...
        artifactPath, featureNormalizationField, expectedModelID)
%LOCALLOADFROZENMODEL Resolve network and normalization without mutation.

try
    loaded = load(artifactPath, "net", "normalization");
catch err
    error("Stage4CNative:ModelLoadFailed", ...
        "Unable to load frozen model %s: %s", artifactPath, err.message);
end

if ~isfield(loaded, "net") || ...
        ~isfield(loaded, "normalization") || ...
        isempty(loaded.net)
    error("Stage4CNative:InvalidModelArtifact", ...
        "Frozen model artifact lacks its network or normalization: %s", ...
        artifactPath);
end

availableVariables = string(who("-file", artifactPath));

if ismember("modelArtifact", availableVariables)
    identityRecord = load(artifactPath, "modelArtifact");

    if isfield(identityRecord.modelArtifact, "modelID") && ...
            string(identityRecord.modelArtifact.modelID) ~= expectedModelID
        error("Stage4CNative:ModelIdentityMismatch", ...
            "Expected %s in %s.", expectedModelID, artifactPath);
    end
end

if ~isfield(loaded.normalization, featureNormalizationField) || ...
        ~isfield(loaded.normalization, "target")
    error("Stage4CNative:MissingModelNormalization", ...
        "Frozen model normalization is incomplete: %s", artifactPath);
end

model = struct();
model.modelID = string(expectedModelID);
model.net = loaded.net;
model.featureNormalization = ...
    loaded.normalization.(featureNormalizationField);
model.targetNormalization = loaded.normalization.target;

end

function predictedState = localPredictPhysicalState( ...
        net, ...
        physicalFeatures, ...
        previousState, ...
        featureNormalization, ...
        targetNormalization, ...
        miniBatchSize)
%LOCALPREDICTPHYSICALSTATE Run one frozen mean model in physical units.

featuresNormalized = ...
    (double(physicalFeatures) - featureNormalization.featureMean) ./ ...
    featureNormalization.featureStd;
predictedDeltaNormalized = minibatchpredict( ...
    net, ...
    single(featuresNormalized), ...
    "MiniBatchSize", ...
    min(miniBatchSize, size(featuresNormalized, 1)));
predictedDeltaNormalized = gather(extractdata( ...
    predictedDeltaNormalized));

if size(predictedDeltaNormalized, 1) ~= size(featuresNormalized, 1) && ...
        size(predictedDeltaNormalized, 2) == size(featuresNormalized, 1)
    predictedDeltaNormalized = predictedDeltaNormalized.';
end

if ~isequal(size(predictedDeltaNormalized), ...
        [size(featuresNormalized, 1), 6])
    error("Stage4CNative:PredictionShapeMismatch", ...
        "Every frozen mean model must return an N-by-6 prediction.");
end

predictedDelta = double(predictedDeltaNormalized) .* ...
    targetNormalization.targetStd + ...
    targetNormalization.targetMean;
predictedState = double(previousState) + predictedDelta;

if any(~isfinite(predictedState), "all")
    error("Stage4CNative:NonfiniteFrozenPrediction", ...
        "A frozen Stage 4C model produced nonfinite predictions.");
end

end

