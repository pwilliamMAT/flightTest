function value = localTextScalar(value, argumentName)
%LOCALTEXTSCALAR Validate one nonempty text scalar.

if ~(ischar(value) || (isstring(value) && isscalar(value)))
    error("Stage4CNative:InvalidTextArgument", ...
        "%s must be a text scalar.", argumentName);
end

value = string(value);

if strlength(strtrim(value)) == 0
    error("Stage4CNative:EmptyTextArgument", ...
        "%s must not be empty.", argumentName);
end

end

function value = localLogicalScalar(value, argumentName)
%LOCALLOGICALSCALAR Validate one scalar logical setting.

if ~(islogical(value) && isscalar(value))
    error("Stage4CNative:InvalidLogicalArgument", ...
        "%s must be a logical scalar.", argumentName);
end

end

function resolvedPath = localResolvePath(projectRoot, value, defaultValue)
%LOCALRESOLVEPATH Resolve relative paths against the project root.

if isempty(value) || (isstring(value) && isscalar(value) && ...
        strlength(value) == 0)
    value = defaultValue;
end

value = localTextScalar(value, "path");

if localIsAbsolutePath(value)
    resolvedPath = localCanonicalPath(value);
else
    resolvedPath = localCanonicalPath(fullfile(projectRoot, value));
end

end

function canonicalPath = localCanonicalPath(pathValue)
%LOCALCANONICALPATH Normalize one path without requiring it to exist.

pathValue = string(pathValue);
fileObject = java.io.File(char(pathValue));
canonicalPath = string(fileObject.getCanonicalPath());

end

function tf = localIsAbsolutePath(pathValue)
%LOCALISABSOLUTEPATH Recognize Windows and UNC absolute paths.

pathValue = char(string(pathValue));
tf = ~isempty(regexp(pathValue, '^[A-Za-z]:[\\/]', 'once')) || ...
    startsWith(pathValue, "\\") || ...
    startsWith(pathValue, "/");

end
