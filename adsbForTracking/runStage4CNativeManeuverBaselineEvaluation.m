function integrity = localHashFrozenArtifacts(config, phase, integrity)
%LOCALHASHFROZENARTIFACTS Hash all model artifacts before and after.

artifactID = [ ...
    "legacy_stage3a_v1"; ...
    "expanded_scratch_mean_v1"; ...
    "expanded_warm_mean_v1"];
path = [ ...
    config.Stage3AArtifactPath; ...
    config.ScratchArtifactPath; ...
    config.WarmArtifactPath];
hashValue = strings(numel(path), 1);

for artifactIdx = 1:numel(path)
    hashValue(artifactIdx) = helperComputeFileSHA256(path(artifactIdx));
end

if phase == "before"
    integrity = table( ...
        artifactID, ...
        path, ...
        hashValue, ...
        repmat("", numel(path), 1), ...
        false(numel(path), 1), ...
        'VariableNames', [ ...
            "artifactID", ...
            "path", ...
            "beforeSHA256", ...
            "afterSHA256", ...
            "unchanged"]);
    return;
end

integrity.afterSHA256 = hashValue;
integrity.unchanged = strcmpi( ...
    integrity.beforeSHA256, ...
    integrity.afterSHA256);

if ~all(integrity.unchanged)
    error("Stage4CNative:FrozenArtifactChanged", ...
        "A frozen Stage 3A, scratch, or warm artifact changed.");
end

end

