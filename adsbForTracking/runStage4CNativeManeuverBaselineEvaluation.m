    config.ComparisonArtifactPath, ...
    config.MetricTablePath, ...
    config.ReportPath, ...
    config.FigurePath];

if any(ismember(lower(outputPaths), lower(modelPaths)))
    error("Stage4CNative:FrozenArtifactCollision", ...
        "Evaluation outputs cannot overwrite a frozen model artifact.");
end

end

function dataset = localLoadDataset(datasetPath)
%LOCALLOADDATASET Load only fields needed for evaluation.

try
    dataset = load( ...
        datasetPath, ...
        "previousState", ...
        "nextState", ...
        "dtSeconds", ...
        "previousCovarianceDiag", ...
        "metadata", ...
        "stateOrder", ...
        "baselineConstVelMetrics");
catch err
    error("Stage4CNative:DatasetLoadFailed", ...
        "Unable to load the Expanded-3Day dataset: %s", err.message);
end

requiredFields = [ ...
    "previousState", ...
    "nextState", ...
    "dtSeconds", ...
    "previousCovarianceDiag", ...
    "metadata", ...
    "stateOrder", ...
    "baselineConstVelMetrics"];

if any(~isfield(dataset, requiredFields))
    error("Stage4CNative:InvalidDataset", ...
        "The Expanded-3Day dataset is missing required fields.");
end

pairCount = size(dataset.previousState, 1);
expectedStateOrder = ["x", "vx", "y", "vy", "z", "vz"];

if pairCount ~= 457903 || ...
        ~isequal(size(dataset.previousState), [pairCount, 6]) || ...
        ~isequal(size(dataset.nextState), [pairCount, 6]) || ...
        ~isequal(size(dataset.previousCovarianceDiag), [pairCount, 6]) || ...
        numel(dataset.dtSeconds) ~= pairCount || ...
        height(dataset.metadata) ~= pairCount || ...
        any(string(dataset.stateOrder(:).') ~= expectedStateOrder)
    error("Stage4CNative:DatasetContractMismatch", ...
        "The frozen Expanded-3Day dataset contract has changed.");
end

if ~isfield(dataset.baselineConstVelMetrics, "predictedState") || ...
        ~isequal(size(dataset.baselineConstVelMetrics.predictedState), ...
        [pairCount, 6])
    error("Stage4CNative:MissingConstvelPrediction", ...
        "The dataset lacks aligned native constvel predictions.");
end

end

function split = localLoadSplit(metadata, splitManifestPath)
%LOCALLOADSPLIT Apply the frozen global ICAO-disjoint split.

manifest = readtable(splitManifestPath, "TextType", "string");
manifest.icao24 = lower(strtrim(string(manifest.icao24)));
manifest.split = lower(strtrim(string(manifest.split)));
[found, manifestRow] = ismember( ...
    lower(strtrim(string(metadata.hex))), ...
    manifest.icao24);

if ~all(found)
    error("Stage4CNative:SplitMembershipMismatch", ...
        "Every dataset ICAO must occur in the frozen split manifest.");
end

split = manifest.split(manifestRow);

if ~isequal( ...
        [sum(split == "train"), ...
        sum(split == "validation"), ...
        sum(split == "test")], ...
        [277959, 86420, 93524])
    error("Stage4CNative:SplitCountMismatch", ...
        "The frozen train/validation/test pair counts have changed.");
end

end

