function summary = runStage4CNativeManeuverBaselineEvaluation(varargin)
%RUNSTAGE4CNATIVEMANEUVERBASELINEEVALUATION Extend Stage 4C evaluation.
% This function does not train or modify a network. It builds causal raw
% finite-difference initialization values, propagates native constacc and
% constturn states, and compares them with the four frozen Stage 4C models
% on matched untouched validation/test maneuver slices.

projectRoot = string(fileparts(mfilename("fullpath")));
parser = inputParser;
parser.FunctionName = mfilename;
addParameter(parser, "ProjectRoot", projectRoot);
addParameter(parser, "DatasetPath", "");
addParameter(parser, "SplitManifestPath", "");
addParameter(parser, "Stage3AArtifactPath", "");
addParameter(parser, "ScratchArtifactPath", "");
addParameter(parser, "WarmArtifactPath", "");
addParameter(parser, "ComparisonArtifactPath", "");
addParameter(parser, "MetricTablePath", "");
addParameter(parser, "ReportPath", "");
addParameter(parser, "FigurePath", "");
addParameter(parser, "PredictionMiniBatchSize", 8192);
addParameter(parser, "CreatePlots", true);
addParameter(parser, "Verbose", true);
parse(parser, varargin{:});

config = localBuildConfig(parser.Results);
localValidateConfig(config);

if config.Verbose
    fprintf("Stage 4C native maneuver-baseline evaluation\n");
    fprintf("Policy:\traw_causal_finite_difference_v1\n");
    fprintf("Dataset:\t%s\n", config.DatasetPath);
end

frozenIntegrity = localHashFrozenArtifacts(config, "before");
dataset = localLoadDataset(config.DatasetPath);
split = localLoadSplit(dataset.metadata, config.SplitManifestPath);
stage4CSummary = localLoadComparisonSummary(config.ComparisonArtifactPath);
localAuditFrozenInputs(dataset, split, stage4CSummary, config);

% Keep only grouping and timing metadata after loading. The source-file
% string column is large and is not needed for causal predecessor matching.
metadata = dataset.metadata(:, ...
    ["sessionID", "hex", "timeUtcK", "timeUtcNext"]);
nativeBaseline = helperBuildStage4CNativeManeuverBaselines( ...
    dataset.previousState, ...
    dataset.dtSeconds, ...
    metadata, ...
    split);

% Maneuver labels are truth-derived retrospective slices. They are created
% only after native predictions exist and are never passed into the causal
% initialization helper.
maneuverPairTable = helperAssignADSBManeuverLabels( ...
    dataset.previousState, ...
    dataset.nextState, ...
    dataset.dtSeconds);
holdoutMask = (split == "validation") | (split == "test");
holdoutDatasetRows = find(holdoutMask);
holdoutMetadata = metadata(holdoutMask, :);
holdoutSplit = split(holdoutMask);
holdoutLabels = maneuverPairTable(holdoutMask, :);
holdoutNativeBaseline = localSubsetNativeBaseline( ...
    nativeBaseline, ...
    holdoutMask);

featureData = helperBuildStage4CFeatures( ...
    dataset.previousState, ...
    dataset.previousCovarianceDiag, ...
    dataset.dtSeconds, ...
    dataset.baselineConstVelMetrics.predictedState);
holdoutFeatures = featureData.features(holdoutMask, :);
holdoutPreviousState = dataset.previousState(holdoutMask, :);

legacy = localLoadFrozenModel( ...
    config.Stage3AArtifactPath, ...
    "physicsFeatures", ...
    "legacy_stage3a_v1");
scratch = localLoadFrozenModel( ...
    config.ScratchArtifactPath, ...
    "features", ...
    "expanded_scratch_mean_v1");
warm = localLoadFrozenModel( ...
    config.WarmArtifactPath, ...
    "features", ...
    "expanded_warm_mean_v1");

comparatorPredictions = localBuildComparatorPredictions( ...
    double(dataset.baselineConstVelMetrics.predictedState(holdoutMask, :)), ...
    localPredictPhysicalState( ...
        legacy.net, ...
        holdoutFeatures, ...
        holdoutPreviousState, ...
        legacy.featureNormalization, ...
        legacy.targetNormalization, ...
        config.PredictionMiniBatchSize), ...
    localPredictPhysicalState( ...
        scratch.net, ...
        holdoutFeatures, ...
        holdoutPreviousState, ...
        scratch.featureNormalization, ...
        scratch.targetNormalization, ...
        config.PredictionMiniBatchSize), ...
    localPredictPhysicalState( ...
        warm.net, ...
        holdoutFeatures, ...
        holdoutPreviousState, ...
        warm.featureNormalization, ...
        warm.targetNormalization, ...
        config.PredictionMiniBatchSize));

nativeMetrics = helperScoreStage4CNativeManeuverModels( ...
    dataset.nextState(holdoutMask, :), ...
    comparatorPredictions, ...
    holdoutNativeBaseline, ...
    holdoutMetadata, ...
    holdoutLabels, ...
    holdoutSplit);
localAuditExpectedCoverage(nativeMetrics.coverageTable);
nativeMetrics.selectionTable = localMapSelectionToDatasetRows( ...
    nativeMetrics.selectionTable, ...
    holdoutDatasetRows);
initializationDiagnostics = localBuildInitializationDiagnostics( ...
    holdoutNativeBaseline, ...
    holdoutLabels, ...
    holdoutSplit);

baseMetricTable = stage4CSummary.metrics.table( ...
    stage4CSummary.metrics.table.groupDimension ~= ...
    "native_maneuver_baseline", :);
stage4CSummary.metrics.table = [ ...
    baseMetricTable; ...
    nativeMetrics.table];

if config.CreatePlots
    figurePath = helperWriteStage4CNativeManeuverFigure( ...
        config.FigurePath, ...
        nativeMetrics.table);
else
    figurePath = "";
end

frozenIntegrity = localHashFrozenArtifacts( ...
    config, ...
    "after", ...
    frozenIntegrity);

extension = struct();
extension.generatedAt = datetime("now", "TimeZone", "UTC");
extension.completed = true;
extension.evaluationOnly = true;
extension.policy = localBuildPolicyRecord(nativeBaseline);
extension.nativeFunctionAudit = localBuildNativeFunctionAudit();
extension.coverageTable = nativeMetrics.coverageTable;
extension.exclusionTable = nativeMetrics.exclusionTable;
extension.selectionTable = nativeMetrics.selectionTable;
extension.initializationDiagnostics = initializationDiagnostics;
extension.metrics = rmfield(nativeMetrics, ...
    ["coverageTable", "exclusionTable", "selectionTable"]);
extension.figurePath = figurePath;
extension.frozenArtifactIntegrity = frozenIntegrity;
extension.trainingPerformed = false;
extension.modelPromoted = false;
extension.retrospectiveLabelPolicy = ...
    "Truth-derived maneuver labels select evaluation rows only; they do not initialize or enter predictions.";
extension.icaoPolicy = ...
    "ICAO is used only for split assignment and same-track predecessor grouping.";
extension.deferredSensitivityStudy = ...
    "Bounded or smoothed causal acceleration/turn-rate initialization.";

stage4CSummary.nativeManeuverBaseline = extension;

if ~isfield(stage4CSummary, "figurePaths") || ...
        ~isstruct(stage4CSummary.figurePaths)
    stage4CSummary.figurePaths = struct();
end

stage4CSummary.figurePaths.nativeManeuverBaseline = figurePath;
stage4CSummary.metricTablePath = config.MetricTablePath;
stage4CSummary.reportPath = config.ReportPath;
stage4CSummary.comparisonArtifactPath = config.ComparisonArtifactPath;

writetable(stage4CSummary.metrics.table, config.MetricTablePath);
localSaveComparisonSummary(config.ComparisonArtifactPath, stage4CSummary);
helperWriteStage4CRetrainReport(config.ReportPath, stage4CSummary);

summary = stage4CSummary;

if config.Verbose
    localPrintCompletion(extension, config);
end

end

