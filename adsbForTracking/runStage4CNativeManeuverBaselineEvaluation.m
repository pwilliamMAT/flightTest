function diagnostics = localBuildInitializationDiagnostics( ...
        nativeBaseline, maneuverPairTable, split)
%LOCALBUILDINITIALIZATIONDIAGNOSTICS Quantify raw finite-difference tails.

splitNames = ["validation", "test"];
sliceNames = ["constacc_like", "constturn_like"];
quantityNames = [ ...
    "acceleration_magnitude"; ...
    "absolute_turn_rate"];
units = ["m/s^2"; "deg/s"];
rowCount = numel(splitNames) * numel(sliceNames);
splitColumn = strings(rowCount, 1);
sliceColumn = strings(rowCount, 1);
quantityColumn = strings(rowCount, 1);
unitsColumn = strings(rowCount, 1);
sampleCount = zeros(rowCount, 1);
p50 = NaN(rowCount, 1);
p90 = NaN(rowCount, 1);
p95 = NaN(rowCount, 1);
p99 = NaN(rowCount, 1);
p999 = NaN(rowCount, 1);
maximum = NaN(rowCount, 1);
signedMinimum = NaN(rowCount, 1);
signedMaximum = NaN(rowCount, 1);
outlierUpperFence = NaN(rowCount, 1);
outlierCount = zeros(rowCount, 1);
outlierFraction = NaN(rowCount, 1);
outputRow = 0;

for splitIdx = 1:numel(splitNames)
    for sliceIdx = 1:numel(sliceNames)
        outputRow = outputRow + 1;
        rowMask = ...
            (split == splitNames(splitIdx)) & ...
            (string(maneuverPairTable.maneuverClass) == ...
            sliceNames(sliceIdx)) & ...
            nativeBaseline.eligibleMask;

        if sliceIdx == 1
            rawSignedValues = NaN(sum(rowMask), 1);
            values = vecnorm( ...
                nativeBaseline.rawAccelerationMetersPerSecondSquared( ...
                rowMask, :), ...
                2, ...
                2);
        else
            rawSignedValues = ...
                nativeBaseline.rawTurnRateDegreesPerSecond(rowMask);
            values = abs(rawSignedValues);
        end

        probability = [0.50, 0.90, 0.95, 0.99, 0.999];
        quantiles = quantile(values, probability);
        quartiles = quantile(values, [0.25, 0.75]);
        upperFence = quartiles(2) + 1.5 * ...
            (quartiles(2) - quartiles(1));
        highOutlierMask = values > upperFence;

        if sliceIdx == 2
            signedMinimum(outputRow) = min(rawSignedValues);
            signedMaximum(outputRow) = max(rawSignedValues);
        end

        splitColumn(outputRow) = splitNames(splitIdx);
        sliceColumn(outputRow) = sliceNames(sliceIdx);
        quantityColumn(outputRow) = quantityNames(sliceIdx);
        unitsColumn(outputRow) = units(sliceIdx);
        sampleCount(outputRow) = numel(values);
        p50(outputRow) = quantiles(1);
        p90(outputRow) = quantiles(2);
        p95(outputRow) = quantiles(3);
        p99(outputRow) = quantiles(4);
        p999(outputRow) = quantiles(5);
        maximum(outputRow) = max(values);
        outlierUpperFence(outputRow) = upperFence;
        outlierCount(outputRow) = sum(highOutlierMask);
        outlierFraction(outputRow) = mean(highOutlierMask);
    end
end

diagnostics = table( ...
    splitColumn, ...
    sliceColumn, ...
    quantityColumn, ...
    unitsColumn, ...
    sampleCount, ...
    p50, ...
    p90, ...
    p95, ...
    p99, ...
    p999, ...
    maximum, ...
    signedMinimum, ...
    signedMaximum, ...
    outlierUpperFence, ...
    outlierCount, ...
    outlierFraction, ...
    'VariableNames', [ ...
        "split", ...
        "maneuverSlice", ...
        "quantity", ...
        "units", ...
        "sampleCount", ...
        "p50", ...
        "p90", ...
        "p95", ...
        "p99", ...
        "p999", ...
        "maximum", ...
        "signedMinimum", ...
        "signedMaximum", ...
        "outlierUpperFence", ...
        "outlierCount", ...
        "outlierFraction"]);

end

