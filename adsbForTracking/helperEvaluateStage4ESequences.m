function signature = localSequenceSignature(sequence)
%LOCALSEQUENCESIGNATURE Hash timestamps, measurements, and score/update masks.

numericPayload = [ ...
    double(sequence.timeSeconds(:)); ...
    double(sequence.measurementState(:)); ...
    double(sequence.updateMask(:)); ...
    double(sequence.scoringMask(:)); ...
    double(sequence.referenceState(:))];
signature = localNumericSignature(numericPayload);

end

function signature = localNumericSignature(values)
%LOCALNUMERICSIGNATURE Compute a deterministic SHA-256 for numeric values.

digest = java.security.MessageDigest.getInstance("SHA-256");
bytes = typecast(double(values(:)), "int8");
digest.update(bytes);
hashBytes = uint8(mod(double(digest.digest()), 256));
signature = string(reshape(dec2hex(hashBytes, 2).', 1, []));

end

function tableOut = localBuildMetricTable(parts)
%LOCALBUILDMETRICTABLE Aggregate sample errors by benchmark condition.

metadata = localPartMetadata(parts, false);
[groupIndex, groupTable] = findgroups( ...
    metadata(:, [ ...
        "domain", ...
        "profile", ...
        "modelID", ...
        "estimateStage", ...
        "targetReference"]));
rows = cell(height(groupTable), 1);

for groupIdx = 1:height(groupTable)
    selectedParts = [parts{groupIndex == groupIdx}];
    positionError = vertcat(selectedParts.positionError);
    velocityError = vertcat(selectedParts.velocityError);
    nees = vertcat(selectedParts.nees);
    stateCoverage = vertcat(selectedParts.stateCoverage95);
    coverage = vertcat(selectedParts.positionCoverage95);
    rows{groupIdx} = localMetricRow( ...
        groupTable(groupIdx, :), ...
        positionError, ...
        velocityError, ...
        nees, ...
        stateCoverage, ...
        coverage, ...
        numel(selectedParts), ...
        sum([selectedParts.divergenceCount]), ...
        sum([selectedParts.invalidCovarianceCount]));
end

tableOut = vertcat(rows{:});

end

