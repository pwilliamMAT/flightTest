function evaluation = helperEvaluateStage4ESequences( ...
        sequences, tuning, varargin)
%HELPEREVALUATESTAGE4ESEQUENCES Run recursive filters on matched sequences.
% Each estimator receives identical timestamps, position measurements,
% update masks, scoring rows, and physical six-state initialization.

parser = inputParser;
parser.FunctionName = mfilename;
addRequired(parser, "sequences");
addRequired(parser, "tuning");
addParameter(parser, "Verbose", true);
parse(parser, sequences, tuning, varargin{:});

verbose = logical(parser.Results.Verbose);
localValidateInputs(sequences, tuning);
modelIDs = [ ...
    "cv_ekf"; ...
    "ca_ekf"; ...
    "ct_ekf"; ...
    "native_imm"; ...
    "warm_ukf"];
maximumPartCount = numel(sequences)*numel(modelIDs)*2;
scoreParts = cell(maximumPartCount, 1);
runtimeRows = cell(numel(sequences)*numel(modelIDs), 1);
consistencyRows = cell(numel(sequences)*numel(modelIDs), 1);
inputAuditRows = cell(numel(sequences)*numel(modelIDs), 1);
partIndex = 0;
runIndex = 0;
representativePaths = struct("synthetic", [], "real", []);

for sequenceIdx = 1:numel(sequences)
    sequence = sequences(sequenceIdx);
    inputSignature = localSequenceSignature(sequence);

    if verbose
        fprintf( ...
            "Stage 4E sequence %d/%d:\t%s\n", ...
            sequenceIdx, ...
            numel(sequences), ...
            sequence.caseID);
    end

    for modelIdx = 1:numel(modelIDs)
        modelID = modelIDs(modelIdx);
        runIndex = runIndex + 1;
        runOutput = localRunOneFilter(sequence, modelID, tuning);
        partIndex = partIndex + 1;
        scoreParts{partIndex} = runOutput.priorScores;
        partIndex = partIndex + 1;
        scoreParts{partIndex} = runOutput.posteriorScores;
        runtimeRows{runIndex} = runOutput.runtimeRow;
        consistencyRows{runIndex} = runOutput.consistencyRow;
        inputAuditRows{runIndex} = localInputAuditRow( ...
            sequence, ...
            modelID, ...
            inputSignature, ...
            runOutput);
        representativePaths = localCaptureRepresentative( ...
            representativePaths, ...
            sequence, ...
            modelID, ...
            runOutput.posteriorState);
    end
end

scoreParts = scoreParts(1:partIndex);
evaluation = struct();
evaluation.modelIDs = modelIDs;
evaluation.metricTable = localBuildMetricTable(scoreParts);
evaluation.eventMetricTable = localBuildEventMetricTable(scoreParts);
evaluation.motionMetricTable = localBuildMotionMetricTable(scoreParts);
evaluation.outageAgeMetricTable = localBuildOutageMetricTable(scoreParts);
evaluation.eventWinRateTable = localBuildEventWinRateTable( ...
    evaluation.eventMetricTable);
evaluation.consistencyTable = localSummarizeConsistency( ...
    vertcat(consistencyRows{:}));
evaluation.runtimeTable = localSummarizeRuntime(vertcat(runtimeRows{:}));
evaluation.inputAuditTable = vertcat(inputAuditRows{:});
evaluation.representativePaths = representativePaths;
evaluation.audit = localBuildAudit( ...
    sequences, ...
    evaluation.inputAuditTable, ...
    evaluation.eventMetricTable);

end

function output = localRunOneFilter(sequence, modelID, tuning)
%LOCALRUNONEFILTER Execute predict-score-correct recursion for one model.

initialDetection = localInitialDetection(sequence);
filter = localCreateFilter(initialDetection, modelID, tuning);
[initialState, initialCovariance] = localPhysicalDistribution(filter, modelID);
sampleCount = numel(sequence.timeSeconds);
priorState = NaN(sampleCount, 6);
posteriorState = NaN(sampleCount, 6);
priorCovariance = NaN(6, 6, sampleCount);
posteriorCovariance = NaN(6, 6, sampleCount);
priorState(1, :) = initialState;
posteriorState(1, :) = initialState;
priorCovariance(:, :, 1) = initialCovariance;
posteriorCovariance(:, :, 1) = initialCovariance;
priorOutageAge = NaN(sampleCount, 1);
posteriorOutageAge = NaN(sampleCount, 1);
priorOutageAge(1) = 0;
posteriorOutageAge(1) = 0;
nisValues = NaN(sampleCount, 1);
correctionCount = 1;
divergenceCount = 0;
invalidCovarianceCount = 0;
errorIdentifier = "";
errorMessage = "";
lastCorrectionTime = sequence.timeSeconds(1);
runTimer = tic;

for sampleIdx = 2:sampleCount
    dtSeconds = sequence.timeSeconds(sampleIdx) - ...
        sequence.timeSeconds(sampleIdx - 1);

    try
        predict(filter, dtSeconds);
        [priorState(sampleIdx, :), priorCovariance(:, :, sampleIdx)] = ...
            localPhysicalDistribution(filter, modelID);
        priorOutageAge(sampleIdx) = ...
            sequence.timeSeconds(sampleIdx) - lastCorrectionTime;
        invalidCovarianceCount = invalidCovarianceCount + ...
            ~localIsPositiveDefinite(priorCovariance(:, :, sampleIdx));

        if sequence.updateMask(sampleIdx)
            measurement = sequence.measurementState( ...
                sampleIdx, ...
                [1, 3, 5]).';
            innovation = measurement - ...
                priorState(sampleIdx, [1, 3, 5]).';
            measurementCovariance = ...
                priorCovariance([1, 3, 5], [1, 3, 5], sampleIdx) + ...
                sequence.measurementNoise;
            nisValues(sampleIdx) = ...
                innovation.'*(measurementCovariance\innovation);
            filter.MeasurementNoise = sequence.measurementNoise;
            correct(filter, measurement);
            correctionCount = correctionCount + 1;
            lastCorrectionTime = sequence.timeSeconds(sampleIdx);
        end

        [posteriorState(sampleIdx, :), ...
            posteriorCovariance(:, :, sampleIdx)] = ...
            localPhysicalDistribution(filter, modelID);
        posteriorOutageAge(sampleIdx) = ...
            sequence.timeSeconds(sampleIdx) - lastCorrectionTime;
        invalidCovarianceCount = invalidCovarianceCount + ...
            ~localIsPositiveDefinite(posteriorCovariance(:, :, sampleIdx));

        if any(~isfinite(priorState(sampleIdx, :))) || ...
                any(~isfinite(posteriorState(sampleIdx, :))) || ...
                any(~isfinite(priorCovariance(:, :, sampleIdx)), "all") || ...
                any(~isfinite(posteriorCovariance(:, :, sampleIdx)), "all")
            divergenceCount = divergenceCount + 1;
            break;
        end
    catch err
        divergenceCount = divergenceCount + 1;
        errorIdentifier = string(err.identifier);
        errorMessage = string(err.message);
        break;
    end
end

elapsedSeconds = toc(runTimer);
output = struct();
output.priorScores = localBuildScorePart( ...
    sequence, ...
    modelID, ...
    "prior", ...
    priorState, ...
    priorCovariance, ...
    priorOutageAge, ...
    divergenceCount, ...
    invalidCovarianceCount);
output.posteriorScores = localBuildScorePart( ...
    sequence, ...
    modelID, ...
    "posterior", ...
    posteriorState, ...
    posteriorCovariance, ...
    posteriorOutageAge, ...
    divergenceCount, ...
    invalidCovarianceCount);
validNIS = nisValues(isfinite(nisValues));
output.consistencyRow = table( ...
    sequence.domain, ...
    sequence.profile, ...
    sequence.caseID, ...
    sequence.eventID, ...
    modelID, ...
    numel(validNIS), ...
    {validNIS}, ...
    'VariableNames', [ ...
        "domain", ...
        "profile", ...
        "caseID", ...
        "eventID", ...
        "modelID", ...
        "measurementCount", ...
        "nisValues"]);
output.runtimeRow = table( ...
    sequence.domain, ...
    sequence.profile, ...
    modelID, ...
    sampleCount - 1, ...
    correctionCount, ...
    elapsedSeconds, ...
    errorIdentifier, ...
    errorMessage, ...
    'VariableNames', [ ...
        "domain", ...
        "profile", ...
        "modelID", ...
        "predictionCount", ...
        "correctionCount", ...
        "elapsedSeconds", ...
        "errorIdentifier", ...
        "errorMessage"]);
output.posteriorState = posteriorState;
output.initialState = initialState;
output.initialCovariance = initialCovariance;
output.correctionCount = correctionCount;
output.divergenceCount = divergenceCount;
output.invalidCovarianceCount = invalidCovarianceCount;
output.errorIdentifier = errorIdentifier;
output.errorMessage = errorMessage;

end

