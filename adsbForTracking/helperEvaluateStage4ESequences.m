function filter = localCreateFilter(detection, modelID, tuning)
%LOCALCREATEFILTER Initialize and apply frozen validation-only parameters.

filter = helperInitializeStage4EFilter(detection, modelID);
parameterField = matlab.lang.makeValidName(modelID);

if ~isfield(tuning.parameters, parameterField)
    error("Stage4E:MissingTunedParameters", ...
        "Tuning does not contain parameters for %s.", modelID);
end

setTunedProperties(filter, tuning.parameters.(parameterField));

end

function [state, covariance] = localPhysicalDistribution(filter, modelID)
%LOCALPHYSICALDISTRIBUTION Convert each filter to common six-state output.

switch modelID
    case {"cv_ekf", "native_imm", "warm_ukf"}
        stateIndices = 1:6;
    case "ca_ekf"
        stateIndices = [1, 2, 4, 5, 7, 8];
    case "ct_ekf"
        stateIndices = [1, 2, 3, 4, 6, 7];
    otherwise
        error("Stage4E:UnknownFilterModel", ...
            "Unknown Stage 4E filter model: %s", modelID);
end

state = double(filter.State(stateIndices).');
covariance = double(filter.StateCovariance(stateIndices, stateIndices));
covariance = 0.5*(covariance + covariance.');

end

function scorePart = localBuildScorePart( ...
        sequence, ...
        modelID, ...
        estimateStage, ...
        estimatedState, ...
        covariance, ...
        outageAge, ...
        divergenceCount, ...
        invalidCovarianceCount)
%LOCALBUILDSCOREPART Compute physical errors on reserved scoring rows.

scoreRows = find(sequence.scoringMask);
referenceState = sequence.referenceState(scoreRows, :);
selectedEstimate = estimatedState(scoreRows, :);
positionError = vecnorm( ...
    selectedEstimate(:, [1, 3, 5]) - ...
    referenceState(:, [1, 3, 5]), ...
    2, ...
    2);
velocityError = vecnorm( ...
    selectedEstimate(:, [2, 4, 6]) - ...
    referenceState(:, [2, 4, 6]), ...
    2, ...
    2);
nees = NaN(numel(scoreRows), 1);
stateCoverage95 = NaN(numel(scoreRows), 1);
positionCoverage95 = NaN(numel(scoreRows), 1);

if sequence.targetReference == "latent_kinematic_truth"
    fullThreshold = chi2inv(0.95, 6);
    positionThreshold = chi2inv(0.95, 3);

    for scoreIdx = 1:numel(scoreRows)
        sourceIdx = scoreRows(scoreIdx);
        stateError = ...
            selectedEstimate(scoreIdx, :) - referenceState(scoreIdx, :);
        stateCovariance = covariance(:, :, sourceIdx);
        positionCovariance = ...
            stateCovariance([1, 3, 5], [1, 3, 5]);
        positionDifference = ...
            stateError([1, 3, 5]);

        if localIsPositiveDefinite(stateCovariance)
            nees(scoreIdx) = stateError/stateCovariance*stateError.';
            stateCoverage95(scoreIdx) = nees(scoreIdx) <= fullThreshold;
        end

        if localIsPositiveDefinite(positionCovariance)
            positionNEES = ...
                positionDifference/positionCovariance*positionDifference.';
            positionCoverage95(scoreIdx) = positionNEES <= positionThreshold;
        end
    end
else
    fullThreshold = NaN;
end

scorePart = struct();
scorePart.domain = sequence.domain;
scorePart.profile = sequence.profile;
scorePart.caseID = sequence.caseID;
scorePart.eventID = sequence.eventID;
scorePart.motionScenario = sequence.motionScenario;
scorePart.targetReference = sequence.targetReference;
scorePart.modelID = modelID;
scorePart.estimateStage = estimateStage;
scorePart.positionError = positionError;
scorePart.velocityError = velocityError;
scorePart.nees = nees;
scorePart.nees95Threshold = fullThreshold;
scorePart.stateCoverage95 = stateCoverage95;
scorePart.positionCoverage95 = positionCoverage95;
scorePart.outageAgeSeconds = outageAge(scoreRows);
scorePart.motionMode = sequence.motionMode(scoreRows);
scorePart.sampleCount = numel(scoreRows);
scorePart.divergenceCount = divergenceCount;
scorePart.invalidCovarianceCount = invalidCovarianceCount;

end

