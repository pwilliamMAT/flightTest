function tableOut = localBuildMotionMetricTable(parts)
%LOCALBUILDMOTIONMETRICTABLE Summarize synthetic error by truth motion mode.

maximumRowCount = sum(cellfun( ...
    @(part) numel(unique(part.motionMode)), ...
    parts));
rows = cell(maximumRowCount, 1);
rowIndex = 0;

for partIdx = 1:numel(parts)
    part = parts{partIdx};

    if part.targetReference ~= "latent_kinematic_truth"
        continue;
    end

    motionModes = unique(part.motionMode, "stable");

    for modeIdx = 1:numel(motionModes)
        rowMask = part.motionMode == motionModes(modeIdx);
        rowIndex = rowIndex + 1;
        rows{rowIndex} = localDistributionRow( ...
            part, ...
            "motionMode", ...
            motionModes(modeIdx), ...
            rowMask);
    end
end

tableOut = vertcat(rows{1:rowIndex});

end

function tableOut = localBuildOutageMetricTable(parts)
%LOCALBUILDOUTAGEMETRICTABLE Summarize error as correction age increases.

maximumRowCount = numel(parts)*5;
rows = cell(maximumRowCount, 1);
rowIndex = 0;

for partIdx = 1:numel(parts)
    part = parts{partIdx};
    [outageBin, outageOrder] = localOutageBins(part.outageAgeSeconds);

    for binIdx = 1:numel(outageOrder)
        rowMask = outageBin == outageOrder(binIdx);

        if any(rowMask)
            rowIndex = rowIndex + 1;
            rows{rowIndex} = localDistributionRow( ...
                part, ...
                "outageAgeBin", ...
                outageOrder(binIdx), ...
                rowMask);
        end
    end
end

tableOut = vertcat(rows{1:rowIndex});

end

