function tableOut = localBuildEventWinRateTable(eventMetrics)
%LOCALBUILDEVENTWINRATETABLE Count posterior event-level RMSE wins.

posteriorRows = eventMetrics(eventMetrics.estimateStage == "posterior", :);
[conditionIndex, conditions] = findgroups( ...
    posteriorRows(:, ["domain", "profile"]));
maximumModelCount = numel(unique(posteriorRows.modelID));
rows = cell(height(conditions)*maximumModelCount, 1);
rowIndex = 0;

for conditionIdx = 1:height(conditions)
    conditionRows = posteriorRows(conditionIndex == conditionIdx, :);
    eventKeys = unique(conditionRows.caseID, "stable");
    modelIDs = unique(conditionRows.modelID, "stable");
    winCount = zeros(numel(modelIDs), 1);

    for eventIdx = 1:numel(eventKeys)
        eventRows = conditionRows(conditionRows.caseID == eventKeys(eventIdx), :);
        finiteError = eventRows.positionRMSEMeters;
        finiteError = finiteError(isfinite(finiteError));

        if isempty(finiteError)
            continue;
        end

        bestError = min(finiteError);
        winners = eventRows.modelID( ...
            abs(eventRows.positionRMSEMeters - bestError) <= 1e-9);
        winCount(ismember(modelIDs, winners)) = ...
            winCount(ismember(modelIDs, winners)) + 1/numel(winners);
    end

    for modelIdx = 1:numel(modelIDs)
        rowIndex = rowIndex + 1;
        rows{rowIndex} = table( ...
            conditions.domain(conditionIdx), ...
            conditions.profile(conditionIdx), ...
            modelIDs(modelIdx), ...
            numel(eventKeys), ...
            winCount(modelIdx), ...
            winCount(modelIdx)/numel(eventKeys), ...
            'VariableNames', [ ...
                "domain", ...
                "profile", ...
                "modelID", ...
                "eventCount", ...
                "eventWinCount", ...
                "eventWinRate"]);
    end
end

tableOut = vertcat(rows{1:rowIndex});

end

function tableOut = localSummarizeConsistency(eventRows)
%LOCALSUMMARIZECONSISTENCY Aggregate NIS by condition and model.

[groupIndex, groupTable] = findgroups( ...
    eventRows(:, ["domain", "profile", "modelID"]));
rows = cell(height(groupTable), 1);
threshold = chi2inv(0.95, 3);

for groupIdx = 1:height(groupTable)
    values = vertcat(eventRows.nisValues{groupIndex == groupIdx});
    rows{groupIdx} = [ ...
        groupTable(groupIdx, :), ...
        table( ...
            numel(values), ...
            mean(values, "omitnan"), ...
            median(values, "omitnan"), ...
            prctile(values, 95), ...
            mean(values <= threshold, "omitnan"), ...
            threshold, ...
            'VariableNames', [ ...
                "measurementCount", ...
                "meanNIS", ...
                "medianNIS", ...
                "p95NIS", ...
                "nisCoverage95", ...
                "nis95Threshold"])];
end

tableOut = vertcat(rows{:});

end

function tableOut = localSummarizeRuntime(eventRows)
%LOCALSUMMARIZERUNTIME Aggregate elapsed time by condition and model.

[groupIndex, groupTable] = findgroups( ...
    eventRows(:, ["domain", "profile", "modelID"]));
rows = cell(height(groupTable), 1);

for groupIdx = 1:height(groupTable)
    rowMask = groupIndex == groupIdx;
    predictionCount = sum(eventRows.predictionCount(rowMask));
    correctionCount = sum(eventRows.correctionCount(rowMask));
    elapsedSeconds = sum(eventRows.elapsedSeconds(rowMask));
    rows{groupIdx} = [ ...
        groupTable(groupIdx, :), ...
        table( ...
            predictionCount, ...
            correctionCount, ...
            elapsedSeconds, ...
            1e6*elapsedSeconds/max(1, predictionCount), ...
            'VariableNames', [ ...
                "predictionCount", ...
                "correctionCount", ...
                "elapsedSeconds", ...
                "microsecondsPerPrediction"])];
end

tableOut = vertcat(rows{:});

end

function [outageBin, order] = localOutageBins(outageAgeSeconds)
%LOCALOUTAGEBINS Assign correction-age ranges used by coasting plots.

order = [ ...
    "corrected_now"; ...
    "0_to_5_s"; ...
    "5_to_15_s"; ...
    "15_to_30_s"; ...
    "over_30_s"];
outageBin = repmat("over_30_s", numel(outageAgeSeconds), 1);
outageBin(outageAgeSeconds <= 0) = "corrected_now";
outageBin(outageAgeSeconds > 0 & outageAgeSeconds <= 5) = "0_to_5_s";
outageBin(outageAgeSeconds > 5 & outageAgeSeconds <= 15) = "5_to_15_s";
outageBin(outageAgeSeconds > 15 & outageAgeSeconds <= 30) = "15_to_30_s";

end

function value = localRMSE(errorMagnitude)
%LOCALRMSE Compute root-mean-square magnitude while omitting failures.

value = sqrt(mean(errorMagnitude.^2, "omitnan"));

end

function representativePaths = localCaptureRepresentative( ...
        representativePaths, sequence, modelID, posteriorState)
%LOCALCAPTUREREPRESENTATIVE Keep one synthetic and one real path.

isSyntheticRepresentative = ...
    sequence.domain == "synthetic_canonical" && ...
    sequence.profile == "degraded" && ...
    sequence.motionScenario == "motion_transitions";
isRealRepresentative = ...
    sequence.domain == "real_adsb" && ...
    sequence.profile == "burst_outage" && ...
    (isempty(representativePaths.real) || ...
    sequence.caseID == representativePaths.real.caseID);

if isSyntheticRepresentative
    fieldName = "synthetic";
elseif isRealRepresentative
    fieldName = "real";
else
    return;
end

if isempty(representativePaths.(fieldName))
    path = struct();
    path.domain = sequence.domain;
    path.profile = sequence.profile;
    path.caseID = sequence.caseID;
    path.targetReference = sequence.targetReference;
    path.receiverOriginLLA = sequence.receiverOriginLLA;
    path.timeSeconds = sequence.timeSeconds;
    path.referenceState = sequence.referenceState;
    path.measurementTimeSeconds = ...
        sequence.timeSeconds(sequence.updateMask);
    path.measurementState = ...
        sequence.measurementState(sequence.updateMask, :);
    path.modelState = struct();
    representativePaths.(fieldName) = path;
end

modelField = matlab.lang.makeValidName(modelID);
representativePaths.(fieldName).modelState.(modelField) = posteriorState;

end

function audit = localBuildAudit(sequences, inputAuditTable, eventMetricTable)
%LOCALBUILDAUDIT Consolidate recursive execution invariants.

[sequenceGroup, ~] = findgroups( ...
    inputAuditTable(:, ["domain", "profile", "caseID"]));
identicalInputs = splitapply( ...
    @(value) isscalar(unique(value)), ...
    inputAuditTable.inputSignature, ...
    sequenceGroup);
identicalInitialization = splitapply( ...
    @(value) isscalar(unique(value)), ...
    inputAuditTable.initializationSignature, ...
    sequenceGroup);
realMask = string({sequences.domain}).' == "real_adsb";
realSequences = sequences(realMask);
scoringNeverCorrected = true;
sameRealScoringRows = true;

if ~isempty(realSequences)
    for sequenceIdx = 1:numel(realSequences)
        scoringNeverCorrected = scoringNeverCorrected && ...
            ~any(realSequences(sequenceIdx).scoringMask & ...
            realSequences(sequenceIdx).updateMask);
    end

    eventIDs = unique(string({realSequences.eventID}), "stable");

    for eventIdx = 1:numel(eventIDs)
        selected = realSequences( ...
            string({realSequences.eventID}) == eventIDs(eventIdx));
        referenceMask = selected(1).scoringMask;

        for profileIdx = 2:numel(selected)
            sameRealScoringRows = sameRealScoringRows && ...
                isequal(selected(profileIdx).scoringMask, referenceMask);
        end
    end
end

audit = struct();
audit.identicalInputsAcrossFilters = all(identicalInputs);
audit.identicalInitializationAcrossFilters = all(identicalInitialization);
audit.scheduledCorrectionsApplied = all( ...
    inputAuditTable.actualCorrectionCount == ...
    inputAuditTable.scheduledCorrectionCount);
audit.scoringReportsNeverCorrected = scoringNeverCorrected;
audit.sameRealScoringRowsAcrossProfiles = sameRealScoringRows;
audit.monotonicTime = all(arrayfun( ...
    @(sequence) all(diff(sequence.timeSeconds) > 0), ...
    sequences));
audit.finiteStates = ...
    all(eventMetricTable.divergenceCount == 0) && ...
    all(strlength(inputAuditTable.errorIdentifier) == 0) && ...
    all(isfinite(eventMetricTable.positionRMSEMeters)) && ...
    all(isfinite(eventMetricTable.velocityRMSEMetersPerSecond));
audit.positiveDefiniteCovariance = ...
    all(eventMetricTable.invalidCovarianceCount == 0);
audit.coastingOccurred = any(arrayfun( ...
    @(sequence) any(~sequence.updateMask(2:end)), ...
    sequences));

end

function tf = localIsPositiveDefinite(covariance)
%LOCALISPOSITIVEDEFINITE Check finite symmetric positive definiteness.

if any(~isfinite(covariance), "all")
    tf = false;
    return;
end

covariance = 0.5*(covariance + covariance.');
[~, flag] = chol(covariance);
tf = flag == 0;

end

function localValidateInputs(sequences, tuning)
%LOCALVALIDATEINPUTS Enforce the recursive-sequence and tuning contracts.

requiredFields = [ ...
    "domain", ...
    "profile", ...
    "caseID", ...
    "eventID", ...
    "timeSeconds", ...
    "referenceState", ...
    "measurementState", ...
    "updateMask", ...
    "scoringMask", ...
    "measurementNoise", ...
    "initialCovarianceDiag", ...
    "motionMode", ...
    "motionScenario", ...
    "targetReference", ...
    "receiverOriginLLA"];

if ~isstruct(sequences) || ...
        isempty(sequences) || ...
        any(~isfield(sequences, requiredFields))
    error("Stage4E:InvalidSequences", ...
        "Recursive sequences are missing required fields.");
end

if ~isstruct(tuning) || ...
        ~isfield(tuning, "completed") || ...
        ~tuning.completed || ...
        ~isfield(tuning, "parameters")
    error("Stage4E:InvalidTuning", ...
        "Completed frozen Stage 4E tuning parameters are required.");
end

end
