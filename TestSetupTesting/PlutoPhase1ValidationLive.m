jointDelta = double(localFieldOrDefault(block.result, {'joint_metrics', 'channel_frequency_delta_hz'}, NaN));
line = block.label + ": REF=" + string(refToneFound) + ", SURV=" + string(survToneFound) + ", margins " + compose("%.1f", refDetect) + "/" + compose("%.1f", survDetect) + " dB, channel delta " + compose("%.1f", jointDelta) + " Hz.";
