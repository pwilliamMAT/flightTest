    block.notes = notes;
    block.result = result;
catch me
    block.status = "ERROR";
    block.summary_table = table();
    block.notes = [ ...
        "The full wrapper stopped on an execution error."; ...
        "Review the error details below and confirm the baseline plus Pluto runtime are valid on this machine."];
    block.error_report = string(getReport(me, 'extended', 'hyperlinks', 'off'));
    block.result = struct();
end
end
