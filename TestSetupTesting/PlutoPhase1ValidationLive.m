function line = localUnitSummaryLine(unitBlock)
if unitBlock.status == "SKIPPED"
    line = "Unit tests were skipped.";
    return
end
if unitBlock.status == "ERROR"
    line = "Unit tests stopped on an execution error.";
    return
end
results = unitBlock.result;
line = "Unit tests: " + string(nnz([results.Passed])) + " passed, " + string(nnz([results.Failed])) + " failed, " + string(nnz([results.Incomplete])) + " incomplete.";
end
function line = localSmokeSummaryLine(block)
if block.status == "SKIPPED"
    line = block.label + ": skipped.";
    return
end
if block.status == "ERROR"
    line = block.label + ": execution error.";
    return
end
refToneFound = logical(localFieldOrDefault(block.result, {'reference_metrics', 'tone_found'}, false));
survToneFound = logical(localFieldOrDefault(block.result, {'surveillance_metrics', 'tone_found'}, false));
refDetect = double(localFieldOrDefault(block.result, {'reference_metrics', 'detect_margin_db'}, NaN));
