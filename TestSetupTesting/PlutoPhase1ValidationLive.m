end
function value = localFieldOrDefault(source, fieldPath, defaultValue)
value = defaultValue;
current = source;
for idx = 1:numel(fieldPath)
    fieldName = fieldPath{idx};
    if ~(isstruct(current) && isfield(current, fieldName))
        return
    end
    current = current.(fieldName);
end
value = current;
end
