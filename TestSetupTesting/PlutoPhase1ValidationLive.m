    disp(block.summary_table);
end
if ~isempty(block.notes)
    disp(string(block.notes));
end
if strlength(string(block.error_report)) > 0
    disp("Error details:");
    disp(string(block.error_report));
end
end
function [summaryTable, notes] = localSummarizeUnitResults(results)
if isempty(results)
    summaryTable = table();
    notes = "No unit-test results were available.";
    return
end
summaryTable = table( ...
    string({results.Name})', ...
    [results.Passed]', ...
    [results.Failed]', ...
    [results.Incomplete]', ...
    [results.Duration]', ...
    'VariableNames', ["Name", "Passed", "Failed", "Incomplete", "Duration_s"]);
failedNames = string({results([results.Failed]).Name})';
incompleteNames = string({results([results.Incomplete]).Name})';
notes = strings(0, 1);
notes(end + 1) = "Unit-test summary:";
notes(end + 1) = "Passed: " + string(nnz([results.Passed]));
notes(end + 1) = "Failed: " + string(nnz([results.Failed]));
notes(end + 1) = "Incomplete: " + string(nnz([results.Incomplete]));
if ~isempty(failedNames)
    notes(end + 1) = "Failed cases: " + join(failedNames, ", ");
else
    notes(end + 1) = "No hard unit-test failures were reported.";
end
if ~isempty(incompleteNames)
    notes(end + 1) = "Incomplete cases: " + join(incompleteNames, ", ");
end
missingRuntimeTest = contains(incompleteNames, "testWrapperFailsGracefullyWhenPlutoRuntimeMissing");
if any(missingRuntimeTest)
    notes(end + 1) = "The missing-runtime wrapper case is expected to be incomplete on machines where the Pluto support package is already installed.";
end
end
function [summaryTable, notes] = localSummarizeSmokeResult(label, result)
summaryTable = table( ...
    string(label), ...
    logical(localFieldOrDefault(result, {'reference_metrics', 'tone_found'}, false)), ...
    logical(localFieldOrDefault(result, {'surveillance_metrics', 'tone_found'}, false)), ...
    double(localFieldOrDefault(result, {'reference_metrics', 'detect_margin_db'}, NaN)), ...
    double(localFieldOrDefault(result, {'surveillance_metrics', 'detect_margin_db'}, NaN)), ...
    double(localFieldOrDefault(result, {'reference_metrics', 'frequency_error_hz'}, NaN)), ...
    double(localFieldOrDefault(result, {'surveillance_metrics', 'frequency_error_hz'}, NaN)), ...
    double(localFieldOrDefault(result, {'joint_metrics', 'channel_frequency_delta_hz'}, NaN)), ...
    double(localFieldOrDefault(result, {'joint_metrics', 'xcorr_peak_db'}, NaN)), ...
    'VariableNames', ["RunLabel", "RefToneFound", "SurvToneFound", "RefDetectMargin_dB", "SurvDetectMargin_dB", "RefFreqErr_Hz", "SurvFreqErr_Hz", "ChannelFreqDelta_Hz", "XcorrPeak_dB"]);
refToneFound = summaryTable.RefToneFound;
survToneFound = summaryTable.SurvToneFound;
refDetect = summaryTable.RefDetectMargin_dB;
survDetect = summaryTable.SurvDetectMargin_dB;
jointDelta = summaryTable.ChannelFreqDelta_Hz;
xcorrPeak = summaryTable.XcorrPeak_dB;
notes = strings(0, 1);
notes(end + 1) = string(label) + " summary:";
if refToneFound && survToneFound
    notes(end + 1) = "Both channels found the injected tone.";
else
    notes(end + 1) = "At least one channel did not find the injected tone.";
end
if isfinite(refDetect) && isfinite(survDetect) && refDetect > 6 && survDetect > 6
    notes(end + 1) = "The tone stands clearly above the local floor on both channels.";
elseif isfinite(refDetect) && isfinite(survDetect) && refDetect > 0 && survDetect > 0
    notes(end + 1) = "The tone is visible on both channels, but the margin is still modest.";
else
    notes(end + 1) = "At least one channel has weak or negative detect margin, so this is not yet a strong commissioning candidate.";
end
if isfinite(jointDelta) && jointDelta < 1e3
    notes(end + 1) = "Inter-channel frequency agreement is strong.";
elseif isfinite(jointDelta) && jointDelta < 3e3
    notes(end + 1) = "Inter-channel frequency agreement is usable but still worth watching.";
else
    notes(end + 1) = "Inter-channel frequency agreement is weak; common RF offset or poor tone prominence is likely.";
end
if isfinite(xcorrPeak) && xcorrPeak > -10
    notes(end + 1) = "Advisory cross-correlation looks reasonably coherent.";
else
    notes(end + 1) = "Advisory cross-correlation is weak.";
end
if contains(string(label), "250 kHz") && (refDetect <= 0 || survDetect <= 0)
    notes(end + 1) = "Because this run uses a 250 kHz offset inside the broadcast band, weak detect margin can reflect occupied ATSC content rather than a broken capture path.";
end
if contains(string(label), "3.2 MHz") && refToneFound && survToneFound
    notes(end + 1) = "The wider tone offset separates the injected tone from the strongest broadcast energy and should be easier to interpret than the 250 kHz runs.";
end
end
function [summaryTable, notes] = localSummarizeWrapperResult(result)
summaryTable = table( ...
    string(localFieldOrDefault(result, {'status'}, "")), ...
    logical(localFieldOrDefault(result, {'overall_pass'}, false)), ...
    string(strjoin(localFieldOrDefault(result, {'fail_codes'}, cell(0, 1)), ", ")), ...
    string(strjoin(localFieldOrDefault(result, {'warn_codes'}, cell(0, 1)), ", ")), ...
    'VariableNames', ["Status", "OverallPass", "FailCodes", "WarnCodes"]);
notes = strings(0, 1);
notes(end + 1) = "Full wrapper summary:";
notes(end + 1) = "Status: " + string(localFieldOrDefault(result, {'status'}, ""));
if summaryTable.OverallPass
    notes(end + 1) = "The baseline-backed wrapper completed without fail codes.";
else
    notes(end + 1) = "Review the wrapper fail or warn codes before treating this run as commissionable.";
end
if isfield(result, 'precheck_summary') && isstruct(result.precheck_summary) && isfield(result.precheck_summary, 'reason_line')
    notes(end + 1) = "Wrapper reason line: " + string(result.precheck_summary.reason_line);
end
end
function smokeComparison = localBuildSmokeComparisonTable(smokeBlocks)
rows = struct( ...
    'RunLabel', {}, ...
    'RefToneFound', {}, ...
    'SurvToneFound', {}, ...
    'RefDetectMargin_dB', {}, ...
    'SurvDetectMargin_dB', {}, ...
    'RefFreqErr_Hz', {}, ...
    'SurvFreqErr_Hz', {}, ...
    'ChannelFreqDelta_Hz', {}, ...
    'XcorrPeak_dB', {});
for idx = 1:numel(smokeBlocks)
    block = smokeBlocks{idx};
    if ~isstruct(block.result) || isempty(fieldnames(block.result))
        continue
    end
    rows(end + 1).RunLabel = char(block.label); %#ok<AGROW>
    rows(end).RefToneFound = logical(localFieldOrDefault(block.result, {'reference_metrics', 'tone_found'}, false));
    rows(end).SurvToneFound = logical(localFieldOrDefault(block.result, {'surveillance_metrics', 'tone_found'}, false));
    rows(end).RefDetectMargin_dB = double(localFieldOrDefault(block.result, {'reference_metrics', 'detect_margin_db'}, NaN));
    rows(end).SurvDetectMargin_dB = double(localFieldOrDefault(block.result, {'surveillance_metrics', 'detect_margin_db'}, NaN));
    rows(end).RefFreqErr_Hz = double(localFieldOrDefault(block.result, {'reference_metrics', 'frequency_error_hz'}, NaN));
    rows(end).SurvFreqErr_Hz = double(localFieldOrDefault(block.result, {'surveillance_metrics', 'frequency_error_hz'}, NaN));
    rows(end).ChannelFreqDelta_Hz = double(localFieldOrDefault(block.result, {'joint_metrics', 'channel_frequency_delta_hz'}, NaN));
    rows(end).XcorrPeak_dB = double(localFieldOrDefault(block.result, {'joint_metrics', 'xcorr_peak_db'}, NaN));
end
if isempty(rows)
    smokeComparison = table();
else
    smokeComparison = struct2table(rows);
end
end
