classdef CaptureProvenanceTest < matlab.unittest.TestCase
    %CAPTUREPROVENANCETEST Offline tests for capture setup provenance.

    properties (Access = private)
        TestSetupRoot string
        RepositoryRoot string
    end

    methods (TestClassSetup)
        function addProjectPaths(testCase)
            testCase.TestSetupRoot = string(fileparts(mfilename('fullpath')));
            testCase.RepositoryRoot = string(fileparts(testCase.TestSetupRoot));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                char(testCase.TestSetupRoot)));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                char(fullfile(testCase.RepositoryRoot, 'TriggerAcquisition'))));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                char(fullfile(testCase.RepositoryRoot, 'BistaticDataAnalysis'))));
        end
    end

    methods (Test)
        function testProvidedSetupNotesArePreservedVerbatim(testCase)
            provided_notes = "CH1 RF0:RX2 surveillance Yagi; CH2 RF1:RX2 reference dipole.";

            notes = helperResolveOperatorSetupNotes(provided_notes, ...
                'Interactive', false);

            testCase.verifyEqual(notes, provided_notes);
        end

        function testEmptyInteractiveSetupNotesPromptOnce(testCase)
            prompted_notes = "CH1 proof: disconnect; CH2 proof: pilot stimulus.";

            notes = helperResolveOperatorSetupNotes("", ...
                'Interactive', true, ...
                'PromptFunction', @(~) prompted_notes);

            testCase.verifyEqual(notes, prompted_notes);
        end

        function testHeadlessMissingSetupNotesRefusesCapture(testCase)
            testCase.verifyError( ...
                @() helperResolveOperatorSetupNotes("", 'Interactive', false), ...
                'helperResolveOperatorSetupNotes:missingOperatorSetupNotes');
        end

        function testLocalWrapperCarriesProvidedNotesAndMapping(testCase)
            provided_notes = "CH1 RF0:RX2 surveillance Yagi; CH2 RF1:RX2 reference dipole.";

            capture_info = runLocalHDTVCapture( ...
                'SessionID', "provenance_local_test", ...
                'OperatorSetupNotes', provided_notes, ...
                'Gain', [12 18], ...
                'AntennaPorts', ["RF0:RX2", "RF1:RX2"], ...
                'ChannelRoles', ["surveillance", "reference"], ...
                'CaptureFunction', @localLoggerStub);

            testCase.verifyEqual(capture_info.operator_setup_notes, provided_notes);
            testCase.verifyEqual(capture_info.manifest_version, 3);
            testCase.verifyEqual(capture_info.channel_mapping(1).stored_channel_index, 1);
            testCase.verifyEqual(capture_info.channel_mapping(1).n320_port, "RF0:RX2");
            testCase.verifyEqual(capture_info.channel_mapping(1).semantic_role, "surveillance");
            testCase.verifyEqual(capture_info.channel_mapping(1).gain_db, 12);
            testCase.verifyEqual(capture_info.channel_mapping(2).stored_channel_index, 2);
            testCase.verifyEqual(capture_info.channel_mapping(2).n320_port, "RF1:RX2");
            testCase.verifyEqual(capture_info.channel_mapping(2).semantic_role, "reference");
            testCase.verifyEqual(capture_info.channel_mapping(2).gain_db, 18);
        end

        function testManifestV3RoundTripPreservesSetupAndMapping(testCase)
            [session_result, package_info, config] = localManifestInputs(testCase);

            manifest_path = helperTriggerWriteManifest(session_result, package_info, config);
            manifest = helperLoadSessionManifest(manifest_path);

            testCase.verifyEqual(manifest.manifest_version, 3);
            testCase.verifyEqual(string(manifest.operator_setup_notes), ...
                config.OperatorSetupNotes);
            testCase.verifyEqual(manifest.channel_mapping(1).stored_channel_index, 1);
            testCase.verifyEqual(string(manifest.channel_mapping(1).n320_port), "RF0:RX2");
            testCase.verifyEqual(string(manifest.channel_mapping(1).semantic_role), ...
                "surveillance");
            testCase.verifyEqual(manifest.channel_mapping(1).gain_db, 12);
            testCase.verifyEqual(manifest.channel_mapping(2).stored_channel_index, 2);
            testCase.verifyEqual(string(manifest.channel_mapping(2).n320_port), "RF1:RX2");
            testCase.verifyEqual(string(manifest.channel_mapping(2).semantic_role), ...
                "reference");
            testCase.verifyEqual(manifest.channel_mapping(2).gain_db, 18);
        end

        function testLegacyManifestRemainsReadable(testCase)
            manifest_path = localWriteLegacyManifest(testCase);

            manifest = helperLoadSessionManifest(manifest_path);

            testCase.verifyEqual(manifest.manifest_version, 1);
            testCase.verifyEqual(manifest.session_id, 'legacy_session');
            testCase.verifyEqual(manifest.radar_files, {'radar/legacy.bb'});
            testCase.verifyEmpty(manifest.adsb_files);
            testCase.verifyEmpty(manifest.log_files);
        end
    end
end

function [session_id, written_files] = localLoggerStub(varargin)
arguments_struct = localNameValueStruct(varargin);
session_id = string(arguments_struct.session_id);
written_files = strings(0, 1);
end

function values = localNameValueStruct(arguments_in)
values = struct;
for index = 1:2:numel(arguments_in)
    field_name = char(string(arguments_in{index}));
    values.(field_name) = arguments_in{index + 1};
end
end

