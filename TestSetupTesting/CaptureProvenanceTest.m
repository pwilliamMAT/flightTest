session_dir = string(tempname(char(testCase.TestSetupRoot)));
mkdir(session_dir);
testCase.addTeardown(@() localSafeRemoveFolder(session_dir));

channel_mapping = helperBuildChannelMapping( ...
    ["RF0:RX2", "RF1:RX2"], ...
    ["surveillance", "reference"], ...
    [12, 18]);

capture_info = struct( ...
    'recording_utc', 1.0, ...
    'header_center_frequency_hz', 599e6, ...
    'header_sample_rate_hz', 6.144e6, ...
    'header_lo_offset_hz', 0, ...
    'header_tune_frequency_hz', 599e6, ...
    'channel_mapping', channel_mapping);
session_result = struct( ...
    'session_id', "provenance_manifest_test", ...
    'capture_info', capture_info, ...
    'mode', "live", ...
    'opportunity_policy', "single", ...
    'trigger_fired', true, ...
    'trigger_reason', "offline manifest test", ...
    'proxy_label', "test", ...
    'watch_started_utc', datetime('now', 'TimeZone', 'UTC'), ...
    'watch_stopped_utc', datetime('now', 'TimeZone', 'UTC'), ...
    'candidate_table', table);
package_info = struct( ...
    'session_dir', session_dir, ...
    'packaged_radar_rel', "radar/capture.bb", ...
    'packaged_adsb_rel', strings(0, 1), ...
    'packaged_log_rel', strings(0, 1));
config = struct( ...
    'CaptureDuration_s', 30, ...
    'Repetitions', 1, ...
    'RepetitionSpacing_s', 0, ...
    'TailSeconds_s', 5, ...
    'ADSBRotation_s', 5, ...
    'PollPeriod_s', 5, ...
    'CaptureFile', "capture", ...
    'Gain', [12, 18], ...
    'OperatorSetupNotes', "CH1 proven; CH2 proven.", ...
    'ChannelMapping', channel_mapping, ...
    'PiHost', "pi.example", ...
    'PiUser', "pi", ...
    'RemoteLogFile', "adsb.log", ...
    'RadioName', "test radio", ...
    'CenterFrequency_Hz', 599e6, ...
    'SampleRate_Hz', 6.144e6, ...
    'LOOffset_Hz', 0, ...
    'ReferenceChainPenalty_dB', NaN);
end

function manifest_path = localWriteLegacyManifest(testCase)
session_dir = string(tempname(char(testCase.TestSetupRoot)));
mkdir(session_dir);
testCase.addTeardown(@() localSafeRemoveFolder(session_dir));
manifest_path = fullfile(session_dir, 'session_manifest.json');

file_id = fopen(manifest_path, 'w');
cleanup_file = onCleanup(@() fclose(file_id));
fprintf(file_id, ['{"manifest_version":1,"session_id":"legacy_session",' ...
    '"radar_files":["radar/legacy.bb"]}']);
clear cleanup_file
end

function localSafeRemoveFolder(folder_path)
folder_path = char(string(folder_path));
if isfolder(folder_path)
    rmdir(folder_path, 's');
end
end
