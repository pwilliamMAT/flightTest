classdef PlutoToneWrapperTest < matlab.unittest.TestCase
    %PLUTOTONEWRAPPERTEST Regression coverage for the live wrapper's safe paths.

    properties (Access = private)
        SourceRoot string
    end

    methods (TestClassSetup)
        function addSourcePath(testCase)
            sourceRoot = string(fileparts(mfilename('fullpath')));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture(char(sourceRoot)));
            testCase.SourceRoot = sourceRoot;
        end
    end

    methods (TestMethodSetup)
        function resetRandomState(testCase)
            original_rng = rng;
            testCase.addTeardown(@() rng(original_rng));
            rng(11, 'twister');
        end
    end

    methods (Test)
        function testWrapperFailsBeforeHardwareOnBaselineSettingsMismatch(testCase)
            [baseline_path, wrapper_settings] = localCreateBaseline(testCase);
            capture_root = string(tempname(char(testCase.SourceRoot)));
            testCase.addTeardown(@() localSafeRemoveFolder(capture_root));

            result = runPlutoTonePrecheck( ...
                'BaselinePath', baseline_path, ...
                'CaptureRoot', capture_root, ...
                'RadioName', wrapper_settings.RadioName, ...
                'CaptureFileBase', wrapper_settings.CaptureFileBase, ...
                'CenterFrequency_Hz', wrapper_settings.CenterFrequency_Hz, ...
                'SampleRate_Hz', wrapper_settings.SampleRate_Hz, ...
                'LOOffset_Hz', wrapper_settings.LOOffset_Hz, ...
                'Gain', wrapper_settings.Gain, ...
                'ToneOffset_Hz', wrapper_settings.ToneOffset_Hz + 10e3, ...
                'ToneAmplitude', wrapper_settings.ToneAmplitude, ...
                'CaptureDuration_s', wrapper_settings.CaptureDuration_s, ...
                'PlotFigures', false, ...
                'Verbose', false);
            testCase.addTeardown(@() localSafeRemoveFolder(string(result.artifact_paths.run_folder)));

            testCase.verifyEqual(result.status, 'FAIL');
            testCase.verifyTrue(any(strcmp(result.fail_codes, 'BASELINE_SETTINGS_MISMATCH')));
            testCase.verifyFalse(any(strcmp(result.fail_codes, 'PLUTO_CONNECT_FAILED')));
            testCase.verifyFalse(result.baseline_comparison.settings_match);
            testCase.verifyTrue(any(strcmp(result.baseline_comparison.settings_mismatch_fields, 'tone_offset_hz')));
            testCase.verifyTrue(isfile(char(result.artifact_paths.result_mat)));
            testCase.verifyTrue(contains(string(result.precheck_summary.reason_line), "BASELINE_SETTINGS_MISMATCH"));
        end

        function testWrapperFailsGracefullyWhenPlutoRuntimeMissing(testCase)
            testCase.assumeTrue(localPlutoRuntimeMissing(), ...
                'Pluto support-package runtime is installed; missing-runtime regression is not applicable.');

            [baseline_path, wrapper_settings] = localCreateBaseline(testCase);
            capture_root = string(tempname(char(testCase.SourceRoot)));
            testCase.addTeardown(@() localSafeRemoveFolder(capture_root));

            result = runPlutoTonePrecheck( ...
                'BaselinePath', baseline_path, ...
                'CaptureRoot', capture_root, ...
                'RadioName', wrapper_settings.RadioName, ...
                'CaptureFileBase', wrapper_settings.CaptureFileBase, ...
                'CenterFrequency_Hz', wrapper_settings.CenterFrequency_Hz, ...
                'SampleRate_Hz', wrapper_settings.SampleRate_Hz, ...
                'LOOffset_Hz', wrapper_settings.LOOffset_Hz, ...
                'Gain', wrapper_settings.Gain, ...
                'ToneOffset_Hz', wrapper_settings.ToneOffset_Hz, ...
                'ToneAmplitude', wrapper_settings.ToneAmplitude, ...
                'CaptureDuration_s', wrapper_settings.CaptureDuration_s, ...
                'PlotFigures', false, ...
                'Verbose', false);
            testCase.addTeardown(@() localSafeRemoveFolder(string(result.artifact_paths.run_folder)));

            testCase.verifyEqual(result.status, 'FAIL');
            testCase.verifyTrue(any(strcmp(result.fail_codes, 'PLUTO_CONNECT_FAILED')));
            testCase.verifyTrue(result.baseline_comparison.settings_match);
            testCase.verifyFalse(result.overall_pass);
            testCase.verifyEmpty(result.capture_info.capture_file_path);
            testCase.verifyTrue(isfile(char(result.artifact_paths.result_mat)));
            testCase.verifyTrue(isfile(char(result.artifact_paths.result_json)));
            testCase.verifyTrue(isfile(char(result.artifact_paths.summary_txt)));
            testCase.verifyTrue(isfile(char(result.artifact_paths.summary_png)));
            testCase.verifyTrue(contains(string(result.precheck_summary.reason_line), "PLUTO_CONNECT_FAILED"));
        end
    end
end

function [baseline_path, wrapper_settings] = localCreateBaseline(testCase)
wrapper_settings = localWrapperSettings();
result = localBuildStandaloneResult(wrapper_settings);

run_folder = string(tempname(char(testCase.SourceRoot)));
baseline_root = string(tempname(char(testCase.SourceRoot)));
testCase.addTeardown(@() localSafeRemoveFolder(run_folder));
testCase.addTeardown(@() localSafeRemoveFolder(baseline_root));

helperPlutoToneWriteArtifacts( ...
    result, ...
    'RunFolder', run_folder, ...
    'CopyCaptureFile', false, ...
    'FigureVisibility', 'off', ...
    'Verbose', false);

baseline = commissionPlutoToneBaseline( ...
    'BaselineRoot', baseline_root, ...
    'BaselineID', 'wrapper_test_baseline', ...
    'SiteID', 'test_site', ...
    'PlacementID', 'bench_1', ...
    'PlacementNotes', 'wrapper test baseline', ...
    'Thresholds', localThresholds(), ...
    'RadioName', wrapper_settings.RadioName, ...
    'CaptureFileBase', wrapper_settings.CaptureFileBase, ...
    'CenterFrequency_Hz', wrapper_settings.CenterFrequency_Hz, ...
    'SampleRate_Hz', wrapper_settings.SampleRate_Hz, ...
    'LOOffset_Hz', wrapper_settings.LOOffset_Hz, ...
    'Gain', wrapper_settings.Gain, ...
    'ToneOffset_Hz', wrapper_settings.ToneOffset_Hz, ...
    'ToneAmplitude', wrapper_settings.ToneAmplitude, ...
    'CaptureDuration_s', wrapper_settings.CaptureDuration_s, ...
    'RunSources', {char(run_folder)}, ...
    'PlotFigures', false, ...
    'Verbose', false);

baseline_path = string(baseline.provenance.baseline_mat_path);
end

