    'run_id', char("run_" + string(tempname)), ...
    'created_utc', char(string(datetime('now', 'TimeZone', 'UTC', 'Format', 'yyyy-MM-dd''T''HH:mm:ss''Z'''))), ...
    'overall_pass', strcmp(status, 'PASS'), ...
    'status', status, ...
    'fail_codes', {fail_codes}, ...
    'warn_codes', {warn_codes}, ...
    'settings', struct( ...
        'baseline_path', 'demo_baseline.mat', ...
        'capture_root', 'demo_capture_root', ...
        'radio_name', 'Unit Test Radio', ...
        'capture_file_base', 'demo_capture', ...
        'center_frequency_hz', 540e6, ...
        'sample_rate_hz', 1e6, ...
        'lo_offset_hz', 200e3, ...
        'capture_tune_frequency_hz', 540.2e6, ...
        'gain', [30, 50], ...
        'tone_offset_hz', 250e3, ...
        'tone_rf_frequency_hz', 540.45e6, ...
        'tone_amplitude', 0.14, ...
        'capture_duration_s', 0.065536, ...
        'plot_figures', false, ...
        'verbose', false), ...
    'capture_info', struct( ...
        'capture_session_id', 'demo_capture', ...
        'capture_file_path', '', ...
        'local_capture_files', strings(0, 1), ...
        'recording_utc', posixtime(datetime('now', 'TimeZone', 'UTC')), ...
        'header_center_frequency_hz', 540e6, ...
        'header_lo_offset_hz', 200e3, ...
        'header_tune_frequency_hz', 540.2e6, ...
        'header_sample_rate_hz', 1e6, ...
        'samples_per_channel', 65536, ...
        'samples_scored', 65536, ...
        'slice_duration_s', 0.065536, ...
        'reader_metadata', struct()), ...
    'channel_map', struct( ...
        'reference_label', 'REF', ...
        'reference_channel_index', 2, ...
        'reference_rx_label', 'CH2/RX2', ...
        'surveillance_label', 'SURV', ...
        'surveillance_channel_index', 1, ...
