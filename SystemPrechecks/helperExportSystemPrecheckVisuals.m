function annotateGroupedBars(barSeries)
for seriesIndex = 1:numel(barSeries)
    xValues = barSeries(seriesIndex).XEndPoints;
    yValues = barSeries(seriesIndex).YEndPoints;
    labels = compose("%.1f", yValues);
    text( ...
        xValues, ...
        yValues, ...
        labels, ...
        "HorizontalAlignment", "center", ...
        "VerticalAlignment", "bottom", ...
        "Color", "k", ...
        "FontSize", 11);
end
end

function annotateSingleBars(barSeries)
xValues = barSeries.XEndPoints;
yValues = barSeries.YEndPoints;
labels = compose("%.1f", yValues);
verticalAlignment = repmat("bottom", size(yValues));
verticalAlignment(yValues < 0) = "top";

for labelIndex = 1:numel(labels)
    text( ...
        xValues(labelIndex), ...
        yValues(labelIndex), ...
        labels(labelIndex), ...
        "HorizontalAlignment", "center", ...
        "VerticalAlignment", verticalAlignment(labelIndex), ...
        "Color", "k", ...
        "FontSize", 11);
end
end

