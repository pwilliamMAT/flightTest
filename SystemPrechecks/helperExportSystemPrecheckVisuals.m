function [latitudeLimits_deg, longitudeLimits_deg] = getFullGeometryLimits( ...
    stationSummary, ...
    coverageResults, ...
    analysisNames, ...
    showBoresight)
analysisNames = string(analysisNames);
analysisMask = ismember(string({coverageResults.Analyses.Name}).', analysisNames);
selectedAnalyses = coverageResults.Analyses(analysisMask);

latitudeValues_deg = [stationSummary.TowerLatitude_deg; coverageResults.Analyses(1).ReceiverLatitude_deg];
longitudeValues_deg = [stationSummary.TowerLongitude_deg; coverageResults.Analyses(1).ReceiverLongitude_deg];

if ~isempty(selectedAnalyses)
    roiLatitudeCells = {selectedAnalyses.RoiLatitude_deg}.';
    roiLongitudeCells = {selectedAnalyses.RoiLongitude_deg}.';
    latitudeValues_deg = [latitudeValues_deg; vertcat(roiLatitudeCells{:})];
    longitudeValues_deg = [longitudeValues_deg; vertcat(roiLongitudeCells{:})];
end

if showBoresight
    boresightAnalyses = coverageResults.Analyses([coverageResults.Analyses.ShowBoresight]);

    if ~isempty(boresightAnalyses)
        boresightLatitudeCells = {boresightAnalyses.BoresightLatitude_deg}.';
        boresightLongitudeCells = {boresightAnalyses.BoresightLongitude_deg}.';
        latitudeValues_deg = [latitudeValues_deg; vertcat(boresightLatitudeCells{:})];
        longitudeValues_deg = [longitudeValues_deg; vertcat(boresightLongitudeCells{:})];
    end
end

latitudePadding_deg = 0.025;
longitudePadding_deg = 0.03;
latitudeLimits_deg = [min(latitudeValues_deg) - latitudePadding_deg max(latitudeValues_deg) + latitudePadding_deg];
longitudeLimits_deg = [min(longitudeValues_deg) - longitudePadding_deg max(longitudeValues_deg) + longitudePadding_deg];
end

function [latitudeLimits_deg, longitudeLimits_deg] = getRegionalLimits(stationSummary, coverageResults, analysisName)
switch string(analysisName)
    case "RecoveredRoi"
        analysis = getCoverageAnalysis(coverageResults, analysisName);
        southernLatitude_deg = min([analysis.ReceiverLatitude_deg; stationSummary.TowerLatitude_deg]);
        northernLatitude_deg = min(analysis.RoiMaxLatitude_deg, max(stationSummary.TowerLatitude_deg) + 0.08);
        westernLongitude_deg = min([analysis.ReceiverLongitude_deg; stationSummary.TowerLongitude_deg]) - 0.08;
        easternLongitude_deg = max([analysis.ReceiverLongitude_deg; stationSummary.TowerLongitude_deg]) + 0.08;
        latitudeLimits_deg = [southernLatitude_deg - 0.02 northernLatitude_deg];
        longitudeLimits_deg = [westernLongitude_deg easternLongitude_deg];
    case "WestCorridor"
        analysis = getCoverageAnalysis(coverageResults, analysisName);
        latitudeLimits_deg = [analysis.RoiMinLatitude_deg - 0.02 analysis.RoiMaxLatitude_deg + 0.02];
        longitudeLimits_deg = [analysis.RoiMinLongitude_deg - 0.03 analysis.ReceiverLongitude_deg + 0.05];
    otherwise
        error("Unsupported analysis name '%s' for regional limits.", analysisName);
end
end

