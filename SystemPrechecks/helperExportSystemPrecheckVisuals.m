function coverageLevels_dB = buildCoverageLevels(coverageResults)
allSNR_dB = [];

for analysisIndex = 1:numel(coverageResults.Analyses)
    allSNR_dB = [allSNR_dB; vertcat(coverageResults.Analyses(analysisIndex).PathData.BistaticSNR_dB)]; %#ok<AGROW>
end

lowerLevel_dB = 5 * floor(min(allSNR_dB) / 5);
upperLevel_dB = 5 * ceil(max(allSNR_dB) / 5);
coverageLevels_dB = lowerLevel_dB:5:upperLevel_dB;

if numel(coverageLevels_dB) < 5
    coverageLevels_dB = linspace(lowerLevel_dB, upperLevel_dB, 6);
end
end

