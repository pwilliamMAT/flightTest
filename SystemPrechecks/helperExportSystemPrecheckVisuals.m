pathNames = categorical(sourceLinkTable.Path, sourceLinkTable.Path, sourceLinkTable.Path);

powerAxes = nexttile;
bar(powerAxes, pathNames, sourceLinkTable.DirectPathPowerAfterAntenna_dBm);
hold(powerAxes, "on");
yline(powerAxes, -25, "--", "Preferred low edge", "LineWidth", 1.25);
yline(powerAxes, -15, "--", "Recommended max input", "LineWidth", 1.25);
