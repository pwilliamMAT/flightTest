function figurePaths = helperExportSystemPrecheckVisuals( ...
    stationSummary, ...
    sourceLinkTable, ...
    rfSummaryTable, ...
    rfResults, ...
    coverageResults, ...
    westCorridorRfResults, ...
    integrationTimes_s, ...
    figuresDir)
%helperExportSystemPrecheckVisuals Export slide-ready visuals for the technical deck.
%
% Plain-language concept:
% The PowerPoint should now show two deterministic geometry branches without
% duplicating the shared direct-path and RF-chain story. This helper exports
% one shared geometry/RF section, the recovered-ROI baseline coverage set,
% and the additive due-west corridor coverage set with explicit naming.

figurePaths = struct;
figurePaths.GeometryOverview = fullfile(figuresDir, "SystemPrecheck_GeometryOverview.png");
figurePaths.SourceViability = fullfile(figuresDir, "SystemPrecheck_SourceViability.png");
figurePaths.RFChainOverview = fullfile(figuresDir, "SystemPrecheck_RFChainOverview.png");
figurePaths.RFLevelsAndHeadroom = fullfile(figuresDir, "SystemPrecheck_RFLevelsAndHeadroom.png");
figurePaths.RecoveredRoiSetup = fullfile(figuresDir, "SystemPrecheck_RoiTargetGridContext.png");
figurePaths.RecoveredRoiNewtonCoverage = fullfile(figuresDir, "SystemPrecheck_NewtonDeterministicSNRCoverage.png");
figurePaths.RecoveredRoiHudsonCoverage = fullfile(figuresDir, "SystemPrecheck_HudsonDeterministicSNRCoverage.png");
figurePaths.RecoveredRoiCombinedCoverage = fullfile(figuresDir, "SystemPrecheck_CombinedDeterministicSNRCoverage.png");
figurePaths.RecoveredRoiRegionalCoverage = fullfile(figuresDir, "SystemPrecheck_RegionalSNRCoverage.png");
figurePaths.RecoveredRoiDetectability = fullfile(figuresDir, "SystemPrecheck_DetectabilityPlausibility.png");
figurePaths.WestCorridorSetup = fullfile(figuresDir, "SystemPrecheck_WestCorridorSetup.png");
figurePaths.WestCorridorNewtonCoverage = fullfile(figuresDir, "SystemPrecheck_WestCorridor_NewtonSNRCoverage.png");
figurePaths.WestCorridorHudsonCoverage = fullfile(figuresDir, "SystemPrecheck_WestCorridor_HudsonSNRCoverage.png");
figurePaths.WestCorridorCombinedCoverage = fullfile(figuresDir, "SystemPrecheck_WestCorridor_CombinedSNRCoverage.png");
figurePaths.WestCorridorRegionalCoverage = fullfile(figuresDir, "SystemPrecheck_WestCorridor_RegionalSNRCoverage.png");
figurePaths.WestCorridorDetectability = fullfile(figuresDir, "SystemPrecheck_WestCorridor_Detectability.png");
figurePaths.RFBudgetAnalyzerScreenshot = fullfile(figuresDir, "SystemPrecheck_RFBudgetAnalyzer_Newton.png");

% Legacy aliases retained for downstream consumers that still expect the
% original recovered-ROI baseline field names.
figurePaths.RoiTargetGridContext = figurePaths.RecoveredRoiSetup;
figurePaths.NewtonCoverage = figurePaths.RecoveredRoiNewtonCoverage;
figurePaths.HudsonCoverage = figurePaths.RecoveredRoiHudsonCoverage;
figurePaths.CombinedCoverage = figurePaths.RecoveredRoiCombinedCoverage;
figurePaths.RegionalCoverage = figurePaths.RecoveredRoiRegionalCoverage;
figurePaths.Detectability = figurePaths.RecoveredRoiDetectability;

coverageLevels_dB = buildCoverageLevels(coverageResults);

createGeometryOverviewFigure(stationSummary, coverageResults, figurePaths.GeometryOverview);
createSourceViabilityFigure(sourceLinkTable, figurePaths.SourceViability);
createRFChainOverviewFigure(rfResults, figurePaths.RFChainOverview);
createRFLevelsFigure(rfSummaryTable, figurePaths.RFLevelsAndHeadroom);

createAnalysisSetupFigure(stationSummary, coverageResults, "RecoveredRoi", figurePaths.RecoveredRoiSetup);
createCoverageFigure( ...
    stationSummary, ...
    coverageResults, ...
    "RecoveredRoi", ...
    "Newton", ...
    coverageLevels_dB, ...
    figurePaths.RecoveredRoiNewtonCoverage);
createCoverageFigure( ...
    stationSummary, ...
    coverageResults, ...
    "RecoveredRoi", ...
    "Hudson", ...
    coverageLevels_dB, ...
    figurePaths.RecoveredRoiHudsonCoverage);
createCombinedCoverageFigure( ...
    stationSummary, ...
    coverageResults, ...
    "RecoveredRoi", ...
    coverageLevels_dB, ...
    figurePaths.RecoveredRoiCombinedCoverage);
createRegionalCoverageFigure( ...
    stationSummary, ...
    coverageResults, ...
    "RecoveredRoi", ...
    coverageLevels_dB, ...
    figurePaths.RecoveredRoiRegionalCoverage);
createDetectabilityFigure( ...
    stationSummary, ...
    rfResults, ...
    integrationTimes_s, ...
    "Recovered-ROI Baseline", ...
    figurePaths.RecoveredRoiDetectability);

createAnalysisSetupFigure(stationSummary, coverageResults, "WestCorridor", figurePaths.WestCorridorSetup);
createCoverageFigure( ...
    stationSummary, ...
    coverageResults, ...
    "WestCorridor", ...
    "Newton", ...
    coverageLevels_dB, ...
    figurePaths.WestCorridorNewtonCoverage);
createCoverageFigure( ...
    stationSummary, ...
    coverageResults, ...
    "WestCorridor", ...
    "Hudson", ...
    coverageLevels_dB, ...
    figurePaths.WestCorridorHudsonCoverage);
createCombinedCoverageFigure( ...
    stationSummary, ...
    coverageResults, ...
    "WestCorridor", ...
    coverageLevels_dB, ...
    figurePaths.WestCorridorCombinedCoverage);
createRegionalCoverageFigure( ...
    stationSummary, ...
    coverageResults, ...
    "WestCorridor", ...
    coverageLevels_dB, ...
    figurePaths.WestCorridorRegionalCoverage);
createDetectabilityFigure( ...
    stationSummary, ...
    westCorridorRfResults, ...
    integrationTimes_s, ...
    "West Corridor Due-West Check", ...
    figurePaths.WestCorridorDetectability);
end

function createGeometryOverviewFigure(stationSummary, coverageResults, outputPath)
recoveredAnalysis = getCoverageAnalysis(coverageResults, "RecoveredRoi");
westCorridorAnalysis = getCoverageAnalysis(coverageResults, "WestCorridor");

figureHandle = createSlideFigure();
tiledlayout(1, 2, "TileSpacing", "compact", "Padding", "compact");

mapAxes = nexttile;
plotGeometryContext( ...
    mapAxes, ...
    stationSummary, ...
    coverageResults, ...
    coverageResults.AnalysisOrder, ...
    true, ...
    true);
title(mapAxes, ...
    "Receiver, candidate transmitters, recovered ROI, and due-west corridor", ...
    "FontSize", 18, ...
    "FontWeight", "bold");
geometryLegend = legend(mapAxes, "Location", "southoutside", "Orientation", "horizontal");
geometryLegend.NumColumns = 2;
styleLegend(geometryLegend);

detailAxes = nexttile;
axis(detailAxes, "off");
summaryLines = [ ...
    "ASSUMPTIONS SNAPSHOT"; ...
    compose("Receiver: %s", recoveredAnalysis.ReceiverName); ...
    compose("Newton RF35: %.0f MHz, %.0f kW horizontal ERP, status %s.", ...
        stationSummary.CenterFrequency_MHz(1), ...
        stationSummary.ERPHorizontal_kW(1), ...
        stationSummary.CurrentOperationalStatus(1)); ...
    compose("Hudson RF27: %.0f MHz, %.0f kW horizontal ERP, status %s.", ...
        stationSummary.CenterFrequency_MHz(2), ...
        stationSummary.ERPHorizontal_kW(2), ...
        stationSummary.CurrentOperationalStatus(2)); ...
    compose("Recovered-ROI baseline: %.4f to %.4f deg lat and %.4f to %.4f deg lon.", ...
        recoveredAnalysis.RoiMinLatitude_deg, ...
        recoveredAnalysis.RoiMaxLatitude_deg, ...
        recoveredAnalysis.RoiMinLongitude_deg, ...
        recoveredAnalysis.RoiMaxLongitude_deg); ...
    compose("Due-west corridor: %.6f to %.6f deg lat and %.6f to %.6f deg lon.", ...
        westCorridorAnalysis.RoiMinLatitude_deg, ...
        westCorridorAnalysis.RoiMaxLatitude_deg, ...
        westCorridorAnalysis.RoiMinLongitude_deg, ...
        westCorridorAnalysis.RoiMaxLongitude_deg); ...
    compose("West corridor east edge is fixed at receiver longitude %.6f deg.", ...
        westCorridorAnalysis.ReceiverLongitude_deg); ...
    "Due-west boresight marker is visual only; no directional receive gain is applied."; ...
    "These figures are regenerated from the cleaned deterministic rerun workflow."];
text( ...
    detailAxes, ...
    0, ...
    1, ...
    cellstr(summaryLines), ...
    "Color", "k", ...
    "FontSize", 15, ...
    "VerticalAlignment", "top", ...
    "Interpreter", "none");

exportFigure(figureHandle, outputPath);
end

function createSourceViabilityFigure(sourceLinkTable, outputPath)
