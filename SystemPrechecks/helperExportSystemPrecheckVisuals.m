        roiLatitude_deg, ...
        "LineStyle", getAnalysisLineStyle(selectedAnalyses(analysisIndex).Name), ...
        "Color", getAnalysisColor(selectedAnalyses(analysisIndex).Name), ...
        "LineWidth", 1.8, ...
        "DisplayName", formatAnalysisLegendLabel(selectedAnalyses(analysisIndex).Name));
end

if includePathLines
    for pathIndex = 1:height(stationSummary)
        plot( ...
            ax, ...
            [stationSummary.TowerLongitude_deg(pathIndex) coverageResults.Analyses(1).ReceiverLongitude_deg], ...
            [stationSummary.TowerLatitude_deg(pathIndex) coverageResults.Analyses(1).ReceiverLatitude_deg], ...
            "--", ...
            "Color", colors(pathIndex, :), ...
            "LineWidth", 1.5, ...
            "DisplayName", stationSummary.Path(pathIndex) + " direct path");
    end
end

for pathIndex = 1:height(stationSummary)
    plot( ...
        ax, ...
        stationSummary.TowerLongitude_deg(pathIndex), ...
        stationSummary.TowerLatitude_deg(pathIndex), ...
        "^", ...
