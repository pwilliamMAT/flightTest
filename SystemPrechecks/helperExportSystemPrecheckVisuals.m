function createCoverageFigure(stationSummary, coverageResults, analysisName, pathName, coverageLevels_dB, outputPath)
analysis = getCoverageAnalysis(coverageResults, analysisName);
analysisTitleText = formatAnalysisTitle(analysis.Name);
pathIndex = find(stationSummary.Path == pathName, 1, "first");
pathData = analysis.PathData(pathIndex);
summaryRow = analysis.TargetPathSummary(pathIndex, :);

figureHandle = createSlideFigure();
tiledlayout(1, 2, "TileSpacing", "compact", "Padding", "compact");

mapAxes = nexttile;
drawCoverageMap( ...
    mapAxes, ...
    stationSummary, ...
    coverageResults, ...
    analysis.Name, ...
    pathData.BistaticSNRGrid_dB, ...
    coverageLevels_dB, ...
    pathName + " " + analysisTitleText + " bistatic SNR coverage", ...
    false);

detailAxes = nexttile;
axis(detailAxes, "off");
detailLines = [ ...
    compose("%s | %s", upper(pathName), upper(analysisTitleText)); ...
    compose("Center frequency: %.0f MHz", stationSummary.CenterFrequency_MHz(pathIndex)); ...
    compose("Effective transmit power: %.0f kW horizontal ERP", stationSummary.ERPHorizontal_kW(pathIndex)); ...
    compose("Mean bistatic SNR: %.2f dB", summaryRow.MeanBistaticSNR_dB); ...
    compose("Median bistatic SNR: %.2f dB", summaryRow.MedianBistaticSNR_dB); ...
    compose("Mean target-path power: %.2f dBm", summaryRow.MeanTargetPathPower_dBm); ...
    compose("Min / max target-path power: %.2f / %.2f dBm", ...
        summaryRow.MinTargetPathPower_dBm, ...
        summaryRow.MaxTargetPathPower_dBm); ...
    compose("Map source: cleaned deterministic Longley-Rice rerun over the %s.", analysis.DisplayName); ...
    "These values are model-based precheck evidence, not field measurements."];

if analysis.ShowBoresight
    detailLines = [ ...
        detailLines; ...
        "The due-west boresight marker is shown on the setup and regional west-corridor views only."];
end

text( ...
    detailAxes, ...
    0, ...
    1, ...
    cellstr(detailLines), ...
    "Color", "k", ...
    "FontSize", 15, ...
    "VerticalAlignment", "top", ...
    "Interpreter", "none");

exportFigure(figureHandle, outputPath);
end

