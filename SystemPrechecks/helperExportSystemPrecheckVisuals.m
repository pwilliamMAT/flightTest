function createDetectabilityFigure(stationSummary, rfResults, integrationTimes_s, analysisTitleText, outputPath)
figureHandle = createSlideFigure();
tiledlayout(1, 2, "TileSpacing", "compact", "Padding", "compact");
colors = lines(numel(rfResults));

curveAxes = nexttile;
hold(curveAxes, "on");

for resultIndex = 1:numel(rfResults)
    signalBandwidth_Hz = stationSummary.SignalBandwidth_MHz(resultIndex) * 1e6;
    integrationGain_dB = 10 * log10(integrationTimes_s * signalBandwidth_Hz);
    postProcessingSNR_dB = rfResults(resultIndex).TargetPreProcessingSNR_dB + integrationGain_dB;
    plot( ...
        curveAxes, ...
        integrationTimes_s, ...
        postProcessingSNR_dB, ...
        "-o", ...
        "Color", colors(resultIndex, :), ...
        "LineWidth", 2, ...
        "MarkerSize", 7, ...
        "DisplayName", stationSummary.Path(resultIndex));
end

yline(curveAxes, 13, "--", "Illustrative detection threshold", "LineWidth", 1.25);
hold(curveAxes, "off");
grid(curveAxes, "on");
xlabel(curveAxes, "Integration time [s]", "FontSize", 15);
ylabel(curveAxes, "Post-processing SNR [dB]", "FontSize", 15);
title(curveAxes, analysisTitleText + " detectability versus coherent integration time", "FontSize", 18, "FontWeight", "bold");
curveLegend = legend(curveAxes, "Location", "southeast");
styleLegend(curveLegend);
styleAxes(curveAxes);

barAxes = nexttile;
pathNames = categorical(string({rfResults.Path}), string({rfResults.Path}), string({rfResults.Path}));
barSeries = bar( ...
    barAxes, ...
    pathNames, ...
    [[rfResults.TargetPreProcessingSNR_dB].' [rfResults.TargetPostProcessing1sSNR_dB].'], ...
    "grouped");
hold(barAxes, "on");
yline(barAxes, 13, "--", "Illustrative detection threshold", "LineWidth", 1.25);
hold(barAxes, "off");
grid(barAxes, "on");
xlabel(barAxes, "Source path", "FontSize", 15);
ylabel(barAxes, "SNR [dB]", "FontSize", 15);
title(barAxes, analysisTitleText + " pre-processing and 1 s post-processing SNR", "FontSize", 18, "FontWeight", "bold");
barLegend = legend(barAxes, ["Pre-processing" "1 s post-processing"], "Location", "northwest");
styleLegend(barLegend);
styleAxes(barAxes);
annotateGroupedBars(barSeries);

exportFigure(figureHandle, outputPath);
end

function figureHandle = createSlideFigure()
figureHandle = figure( ...
    "Visible", "off", ...
    "Color", "w", ...
    "Position", [100 100 1600 900]);
